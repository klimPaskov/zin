// Companion of the shared_b focus trees (docs/design/stage2/focus_shared_b.md). The focus compiler names the opinion
// modifiers of a tree `zin_<tree>_<key>`, but the Triton's Islands spec fixes two ids that the tier B island trees
// already use (`zin_tritons_banks_quarrel`, `zin_tritons_mediation_refused`), so this module writes them.
// Staged: common/opinion_modifiers/zin_tritons_pupor.txt and localisation/english/zin_tritons_pupor_l_english.yml.
// Call it before buildFocusTrees so the compiler finds both names in the staged files.
export const TRITONS_OPINIONS = {
  zin_tritons_banks_quarrel: { value: -20, decay: 0.5, name: 'The Quarrel over the Banks' },
  zin_tritons_mediation_refused: { value: -10, decay: 1, name: 'Mediation Refused' },
};

const HEADER = '# Generated by the ZIN content builder (modules/focus_shared_b.mjs). Do not edit.';

export function tritonsOpinionText(table = TRITONS_OPINIONS) {
  const body = Object.entries(table).map(([id, m]) => [`\t${id} = {`, `\t\tvalue = ${m.value}`, ...(m.decay ? [`\t\tdecay = ${m.decay}`] : []), '\t}'].join('\n'));
  return `${HEADER}\nopinion_modifiers = {\n${body.join('\n')}\n}\n`;
}

export async function buildSharedBCompanion(staged) {
  staged.text('common/opinion_modifiers/zin_tritons_pupor.txt', tritonsOpinionText());
  staged.loc('zin_tritons_pupor', Object.fromEntries(Object.entries(TRITONS_OPINIONS).map(([id, m]) => [id, m.name])));
  return { opinionModifiers: Object.keys(TRITONS_OPINIONS).length, files: 2 };
}
