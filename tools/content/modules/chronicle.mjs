export const sectionOf = (note, s) => s.section ?? (note ? [...note.sections.keys()][0] : undefined);

// ---------------------------------------------------------------------------------------------------- pages
// Whole paragraphs packed into pages of at most `lines` lines (a blank line between paragraphs counts); a paragraph longer than a page
// is an error.
export function packPages(paragraphs, font, { width = CHR_LAYOUT.lineW - CHR_LAYOUT.margin, lines = LIMITS.pageLines } = {}) {
  const pages = [], errors = [];
  let cur = [], used = 0;
  for (const p of paragraphs) {
    const n = font.wrap(p, width).length;
    if (n > lines) { errors.push(`a paragraph of ${n} lines (${p.slice(0, 50)}…)`); continue; }
    const need = cur.length ? used + 1 + n : n;
    if (need > lines) { pages.push(cur); cur = [p]; used = n; } else { cur.push(p); used = need; }
  }
  if (cur.length) pages.push(cur);
  return { pages: pages.map(ps => ps.join('\n\n')), errors };
}

// ---------------------------------------------------------------------------------------------------- checks (spec section 12)
const FORBIDDEN_CHARS = /["$£§\[\]\n\r\t]/;
export async function chronicleProblems(data, { vault = null, kl = knowledgeRules(), banned = null, font = null, fonts = null, only = null } = {}) {
  const errors = [], warnings = [];
  const E = (e, m) => errors.push(`${e.id ?? '?'} ${e.key ?? ''}: ${m}`), W = (e, m) => warnings.push(`${e.id ?? '?'} ${e.key ?? ''}: ${m}`);
  const axioms = compileAxioms(data.axioms);
  const ctx = { axioms, futureTerms: data.futureTerms, kl };
  const body = font ?? await loadFont('garamond_16');
  const f24 = fonts?.title ?? await loadFont('hoi_24header'), f16 = fonts?.label ?? await loadFont('hoi_16mbs');
  const compiled = banned ?? compileBanned(await loadBanned());
  for (const d of screenRealms(data, { kl, compiled })) warnings.push(d);
  const cats = new Map(data.categories.map(c => [c.key, c]));
  const keys = new Map(), ids = new Map();
  for (const e of data.entries) { keys.set(e.key, (keys.get(e.key) ?? 0) + 1); ids.set(e.id, (ids.get(e.id) ?? 0) + 1); }
  for (const [k, n] of keys) if (n > 1) errors.push(`key ${k} is used ${n} times`);
  for (const [k, n] of ids) if (n > 1) errors.push(`id ${k} is used ${n} times`);
  for (const m of data.realmMissing ?? []) errors.push(`realm ${m} has no id in realm_ids.json (node tools/content/chronicle.mjs ids)`);
  const authored = data.entries.filter(e => !e.generated);
  if (authored.length < 120 || authored.length > 200) errors.push(`${authored.length} authored entries (the spec asks 120 to 180, the lane allows 200 with the added categories)`);
  for (const c of data.categories) { const n = data.entries.filter(e => e.category === c.key).length; if (n < 5) errors.push(`category ${c.key} has ${n} entries (at least 5)`); }
  const checkWords = (e, where, text, cond) => {
    if (FORBIDDEN_CHARS.test(text)) E(e, `${where}: a forbidden character (straight double quote, $, £, §, [, ], tab or line break)`);
    for (const ch of text) if (cp1252(ch) === null) { E(e, `${where}: "${ch}" is not a Windows-1252 character`); break; }
    const meta = META_WORDS.exec(text); if (meta) E(e, `${where}: the meta word "${meta[0]}"`);
    for (const h of findBanned(text, compiled, ['error'])) {
      // a year written with its age ("2A 1900") is the world's own date, not a real-world year
      if (/year/i.test(h.class ?? '') && new RegExp(`\\b\\dA ${h.word}\\b`).test(text)) continue;
      E(e, `${where}: banned word "${h.word}" (${h.id})`);
    }
    for (const f of secrecyFindings(text, cond, ctx)) E(e, `${where}: ${f}`);
  };
  for (const e of data.entries) {
    if (only && !only(e)) continue;
    const cat = cats.get(e.category);
    if (!cat) { E(e, `unknown category ${e.category}`); continue; }
    if (!e.generated && Math.floor(e.id / 100) !== cat.n) E(e, `id outside the range of category ${cat.n}`);
    for (const k of ['title', 'subtitle', 'unlock']) if (!e[k]) E(e, `no ${k}`);
    let unlock;
    try { unlock = parseCond(e.unlock); } catch (x) { E(e, x.message); continue; }
    if (!e.parts?.length) { E(e, 'no parts'); continue; }
    // conditions
    const partConds = [];
    for (const [i, p] of e.parts.entries()) {
      let c;
      try { c = parseCond(p.when); } catch (x) { E(e, `part ${i + 1}: ${x.message}`); continue; }
      if (i === 0 && condText(c) !== condText(unlock)) E(e, `the first part's condition ${p.when} differs from the unlock ${e.unlock}`);
      if (!implies(c, unlock, axioms)) E(e, `part ${i + 1} (${p.when}) does not imply the unlock ${e.unlock}`);
      partConds.push(c);
      for (const [j, q] of (p.paragraphs ?? []).entries()) {
        if (!['established', 'proposed', 'mixed'].includes(q.status)) E(e, `part ${i + 1} paragraph ${j + 1}: status ${q.status}`);
        if (!e.generated && !q.sources?.length) E(e, `part ${i + 1} paragraph ${j + 1}: no sources`);
        checkWords(e, `part ${i + 1} paragraph ${j + 1}`, q.text, c);
        if (vault && !e.generated) for (const s0 of q.sources ?? []) {
          const note = vault.get(s0.note), s = { ...s0, section: sectionOf(note, s0) };
          if (!note) E(e, `part ${i + 1}: the vault has no note ${s.note}`);
          else if (!note.sections.has(s.section)) E(e, `part ${i + 1}: ${s.note} has no section "${s.section}"`);
          else if (s.sha256 && s.sha256 !== note.sections.get(s.section).sha256) W(e, `part ${i + 1}: ${s.note} § ${s.section} changed since the paragraph was written (stale)`);
          else if (!s.sha256) W(e, `part ${i + 1}: ${s.note} § ${s.section} carries no hash (node tools/content/chronicle.mjs stamp)`);
        }
      }
      const packed = packPages((p.paragraphs ?? []).map(q => q.text), body);
      for (const m of packed.errors) E(e, `part ${i + 1}: ${m}`);
      const lim = e.generated ? LIMITS.realmPages : i === 0 ? LIMITS.firstPartPages : LIMITS.laterPartPages;
      if (packed.pages.length > lim) E(e, `part ${i + 1}: ${packed.pages.length} pages (at most ${lim})`);
      p.pages = packed.pages;
    }
    const total = e.parts.reduce((n, p) => n + (p.pages?.length ?? 0), 0);
    if (total > (e.generated ? LIMITS.realmPages : LIMITS.entryPages)) E(e, `${total} pages in all`);
    // titles and fit
    const titleCond = unlock;
    checkWords(e, 'title', e.title, titleCond); checkWords(e, 'subtitle', e.subtitle, titleCond);
    if (f24.width(e.title) > LIMITS.titlePx) E(e, `the title is ${f24.width(e.title)} px wide (at most ${LIMITS.titlePx})`);
    const listTitle = e.short ?? e.title;
    if (e.short) checkWords(e, 'short title', e.short, titleCond);
    if (f16.width(listTitle) > LIMITS.shortPx) E(e, `the list title "${listTitle}" is ${f16.width(listTitle)} px wide (at most ${LIMITS.shortPx})`);
    if (f16.width(e.subtitle) > LIMITS.subPx) E(e, `the subtitle is ${f16.width(e.subtitle)} px wide`);
    if (e.title_after) {
      let c; try { c = parseCond(e.title_after.when); } catch (x) { E(e, `title_after: ${x.message}`); c = null; }
      if (c) {
        if (!implies(c, unlock, axioms)) E(e, `title_after (${e.title_after.when}) does not imply the unlock`);
        checkWords(e, 'title_after', e.title_after.text, c);
        if (f24.width(e.title_after.text) > LIMITS.titlePx) E(e, 'title_after is too wide');
        if (f16.width(e.title_after.text) > LIMITS.shortPx && !e.short) W(e, `the list shows the first title (title_after "${e.title_after.text}" is wider than a slot)`);
      }
    }
    for (const pa of e.plate_after ?? []) { try { parseCond(pa.when); } catch (x) { E(e, `plate_after: ${x.message}`); } }
    if ((e.related ?? []).length > LIMITS.links) E(e, `${e.related.length} related entries (at most ${LIMITS.links})`);
    for (const r of e.related ?? []) if (!keys.has(r)) E(e, `related ${r} does not exist`);
  }
  // coverage: every in-scope vault section is cited or excluded with a reason
  if (vault) {
    const cited = new Set();
    for (const e of data.entries) for (const p of e.parts ?? []) for (const q of p.paragraphs ?? []) for (const s of q.sources ?? []) cited.add(`${s.note}§${sectionOf(vault.get(s.note), s)}`);
    const excluded = new Map((data.coverage.exclusions ?? []).map(x => [`${x.note}§${x.section ?? '*'}`, x.reason]));
    let uncovered = 0;
    for (const [rel, note] of vault) {
      if (!IN_SCOPE.test(rel)) continue;
      for (const [h, sec] of note.sections) {
        if (!sec.length) continue;   // a heading with no text of its own (a note's title above its sections)
        if (cited.has(`${rel}§${h}`) || excluded.has(`${rel}§${h}`) || excluded.has(`${rel}§*`)) continue;
        uncovered++; warnings.push(`coverage: ${rel} § ${h} is neither cited nor excluded`);
      }
    }
    data.uncovered = uncovered;
  }
  return { errors, warnings };
}

// ---------------------------------------------------------------------------------------------------- emit
const ind = (s, k) => s.split('\n').map(l => `${'\t'.repeat(k)}${l}`).join('\n');
const block = (name, body, k = 0) => `${'\t'.repeat(k)}${name} = {\n${ind(body, k + 1)}\n${'\t'.repeat(k)}}`;
const eq = (v, n) => `check_variable = { ${v} = ${n} }`;

// The ordered entries of each category as the window lists them; realms by region, then as the history lists them.
export function ordered(data) {
  const by = new Map(data.categories.map(c => [c.key, []]));
  for (const e of data.entries) by.get(e.category)?.push(e);
  for (const [k, list] of by) if (k !== 'realms') list.sort((a, b) => a.id - b.id);
  return by;
}

