// Art (gpt-6-luna, art/chronicle-jobs.mjs): the Chronicle theme sheet (cut by lib/zin_chrome.mjs) and the plates (tracked bands
// art/source/chronicle/plates/<plate>.png, 864 x 324, fitted to 432 x 160). Every picture needs an accepted review line; the
// owner-approval plates also need the owner's line and show their category plate until then. The window is not built while the theme
// sheet or a category plate is pending (named in the build log), so nothing undefined is loaded.
export const PLATE_W = 432, PLATE_H = 160;
const definedNames = (staged, dir) => { const out = new Set(); for (const [rel, buf] of staged.files) if (rel.startsWith(dir) && rel.endsWith('.txt')) for (const m of buf.toString('utf8').matchAll(/^([A-Za-z_][A-Za-z0-9_]*)\s*=\s*\{/gm)) out.add(m[1]); return out; };
// The named branch of each fallen realm's category title (modules/deep_past.mjs): the viewer's own knowledge gate.
export function deepGatesFrom(staged) {
  const LOOPS = { low_country: 'LowCountry', two_shores: 'TwoShores', kalioth: 'Kalioth', sea_doors: 'SeaDoors', sea_roads: 'SeaRoads', ice: 'Ice' };
  const text = [...staged.files].filter(([r]) => r.startsWith('common/scripted_localisation/')).map(([, b]) => b.toString('utf8')).join('\n');
  const out = {};
  for (const [loop, name] of Object.entries(LOOPS)) {
    const at = text.indexOf(`name = GetDeep${name}Title`);
    if (at < 0) { out[loop] = null; continue; }
    const t = text.indexOf('trigger', at), i = text.indexOf('{', t);
    let depth = 0, end = i;
    for (; end < text.length; end++) { if (text[end] === '{') depth++; else if (text[end] === '}' && --depth === 0) break; }
    out[loop] = text.slice(i + 1, end).split('\n').map(l => l.trim()).filter(Boolean).join('\n');
  }
  return out;
}

export async function buildChronicle(staged, { provenance = null, log = s => process.stderr.write(`${s}\n`), panelFlags = [] } = {}) {
  const { rawFile, provenanceFile } = await import('../lib/paths.mjs');
  const { acceptance } = await import('./presentation.mjs');
  const { loadZinChrome } = await import('../lib/zin_chrome.mjs');
  const { loadImage, cover } = await import('../lib/fit.mjs');
  const { dds, fromRaw } = await import('../lib/raster.mjs');
  const jobsMod = await import('../art/chronicle-jobs.mjs');
  const data = loadChronicle();
  const vault = indexVault(vaultFilesFrom(staged));
  const { errors, warnings } = await chronicleProblems(data, { vault });
  for (const w of warnings) if (!/carries no hash|left out/.test(w)) log(`Chronicle: ${w}`);
  const stale = warnings.filter(w => /\(stale\)/.test(w));
  if (process.env.ZIN_RELEASE === '1' && stale.length) errors.push(...stale);
  if (errors.length) throw new Error(`The Chronicle breaks its rules (${errors.length}):\n  ${errors.slice(0, 40).join('\n  ')}`);

  // art
  const lines = provenance ?? (existsSync(provenanceFile()) ? readFileSync(provenanceFile(), 'utf8').split('\n').filter(Boolean).map(l => { try { return JSON.parse(l); } catch { return {}; } }) : []);
  const spec = readJson(path.join(CHR_DATA, 'codex_sheet.json'));
  const pending = [];
  const sheetRel = spec.sheet.raw, sheetFile = rawFile(sheetRel);
  let chrome = null;
  if (!existsSync(sheetFile)) pending.push(`no theme sheet ${sheetRel}`);
  else {
    const bytes = readFileSync(sheetFile), acc = acceptance(lines, sheetRel, bytes);
    if (!acc.ok) pending.push(`theme sheet: ${acc.why}`);
    else { chrome = await loadZinChrome(rawFile, spec); staged.add(`art/source/${sheetRel}`, bytes); }
  }
  const plates = new Map(), ownerPending = [];
  for (const p of jobsMod.plateList(data)) {
    const file = jobsMod.trackedPlate(p.plate), rel = `art/source/chronicle/plates/${p.plate}.png`;
    if (!existsSync(file)) { pending.push(`no plate ${p.plate}`); continue; }
    const bytes = readFileSync(file), acc = acceptance(lines, rel, bytes);
    if (!acc.ok) { pending.push(`plate ${p.plate}: ${acc.why}`); continue; }
    staged.add(rel, bytes);
    if (p.owner && !lines.some(l => l.sha256 === acc.sha && l.reviewer === 'owner' && l.accepted === true)) { ownerPending.push(p.plate); continue; }
    plates.set(p.plate, { file, bytes });
  }
  const catPending = pending.filter(s => /cat_|theme sheet/.test(s));
  if (catPending.length) { log(`Chronicle: not built, art pending (${catPending.slice(0, 8).join('; ')}${catPending.length > 8 ? '; …' : ''})`); return { built: false, pending, entries: data.entries.length }; }
  if (pending.length) log(`Chronicle: ${pending.length} entry plates pending; those entries show their category plate (${pending.slice(0, 6).join('; ')}${pending.length > 6 ? '; …' : ''})`);
  if (ownerPending.length) log(`Chronicle: ${ownerPending.length} plates wait for the owner and show their category plate (${ownerPending.join(', ')})`);
  for (const s of data.realmDropped ?? []) log(`Chronicle: ${s}`);

  const gfx = [];
  const tex = (rel, img) => { staged.add(rel, dds(fromRaw(img.data, img.w, img.h))); return rel; };
  for (const s of chrome.sprites) {
    tex(s.texture, s.img);
    const [bx, by] = Array.isArray(s.border) ? s.border : [s.border, s.border];
    if (s.kind === 'cornered') gfx.push(`\tcorneredTileSpriteType = {\n\t\tname = "${s.name}"\n\t\tsize = { x = ${s.size[0]} y = ${s.size[1]} }\n\t\ttexturefile = "${s.texture}"\n\t\tborderSize = { x = ${bx} y = ${by} }\n\t\ttilingCenter = no\n\t}`);
    else gfx.push(`\tspriteType = {\n\t\tname = "${s.name}"\n\t\ttexturefile = "${s.texture}"${s.frames > 1 ? `\n\t\tnoOfFrames = ${s.frames}` : ''}${s.button ? '\n\t\teffectFile = "gfx/FX/buttonstate.lua"' : ''}\n\t}`);
  }
  const plateSprite = p => `GFX_zin_chr_plate_${p}`;
  for (const [p, { file }] of [...plates].sort(([a], [b]) => a.localeCompare(b))) {
    const img = await loadImage(file), { img: fitted } = await cover(img, PLATE_W, PLATE_H);
    gfx.push(`\tspriteType = {\n\t\tname = "${plateSprite(p)}"\n\t\ttexturefile = "${tex(`gfx/interface/zin/chronicle/plates/${p}.dds`, fitted)}"\n\t}`);
  }
  staged.text('interface/zin_chronicle.gfx', `${HDR}\n# Sprites of the Chronicle of Aoaz: the Chronicle theme (codex_sheet.json) and the plates.\nspriteTypes = {\n${gfx.join('\n')}\n}\n`);

  // text, triggers, effects, scripted localisation, scripted GUI
  const trig = definedNames(staged, 'common/scripted_triggers/');
  const names = { hubTrigger: trig.has('zin_afrit_is_hub') ? 'zin_afrit_is_hub' : null, hostTrigger: trig.has('zin_eindil_is_host') ? 'zin_eindil_is_host' : null, panelFlags };
  if (!names.hubTrigger) log('Chronicle: zin_afrit_is_hub is not defined; the Worshipdom reads no private record');
  const deepGates = deepGatesFrom(staged);
  for (const [l, b] of Object.entries(deepGates)) if (!b) log(`Chronicle: no knowledge gate for the fallen realm ${l}; its named part stays hidden`);
  const plateOf = (pl, e) => { const key = typeof pl === 'string' ? pl : pl ? e.key : null; return key && plates.has(key) ? plateSprite(key) : null; };
  const out = await emitChronicle(data, { names, deepGates, plateOf, catPlate: k => plateSprite(`cat_${k}`) });
  staged.loc('zin_chronicle', out.loc);
  staged.text('common/scripted_triggers/zin_chronicle.txt', out.triggers);
  staged.text('common/scripted_effects/zin_chronicle.txt', out.effects);
  staged.text('common/scripted_localisation/zin_chronicle.txt', out.sloc);
  staged.text('common/scripted_guis/zin_chronicle.txt', out.sgui);
  staged.text('interface/zin_chronicle.gui', chronicleGui(data));
  const n = k => data.entries.filter(e => e.category === k).length;
  return { built: true, entries: data.entries.length, authored: data.entries.filter(e => !e.generated).length, open: data.entries.filter(e => e.unlock === 'start').length, byCategory: Object.fromEntries(data.categories.map(c => [c.key, n(c.key)])), plates: plates.size, ownerPending, platesPending: pending.length, realmDropped: (data.realmDropped ?? []).length, keys: Object.keys(out.loc).length };
}

