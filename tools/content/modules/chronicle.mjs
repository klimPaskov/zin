// ---------------------------------------------------------------------------------------------------- secrecy (spec 12.4, 12.5)
const AFRIT_TERMS = /\b(Afrit|Hidden Council|Kingdom Behind the Throne|Sevrin|Ring of Doors|Crown of Witnesses|Bracelet of the First Seal)\b/;
const DELIV = /\b(Deliverer|Aurevan)\b/;
// Meta words (spec voice rule 1). "Flag", "owner", "campaign", "proposed" and "established" have plain in-world senses (a realm's flag, a
// ship's owner, a war's campaign, a treaty proposed), so only their meta uses are caught.
export const META_WORDS = /\b(canon|canonical|lore|vault|players?|game|games|mod|spec|ZIN|mechanics?|unlock(?:ed|s)?|version|faction)\b|\((?:proposed|established|open)\)|\b(?:proposed|established) (?:lore|canon|name|date|figure|chronology|fact)\b/i;
const sentencesOf = p => sentences(p);
// An open question said as open (voice rule 3) answers nothing; an attributed warning is a claim, not a fact (register 4.6, kl_gated_019).
const OPEN_MARKER = /\b(no chronicle|not known|do not agree|does not agree|cannot say|can say|nobody knows|no one knows|is not told|are not told|whether)\b/i;
const ATTRIBUTED = /\b(spoke of|warned|warnings?|said|says|told|claimed|feared|rumou?rs?)\b/i;
// The knowledge-layer register (docs/lore/references/knowledge_layers.md section 4): its sealed and mystery rules hold for every text;
// its gated rules hold for text whose condition does not imply their gate. Rules the Chronicle spec settles otherwise are skipped
// (kl_gated_013 and _015: Glo and Glernaen's crystal are open from the start as "a crystal of old and holy power", spec section 6.4;
// kl_mystery_001 to _003: the vault's New Gods note names the twelve gods, owner 24 October 2026; place rules and belief and dispute
// rules need a reviewer, not a pattern).
const KL_SKIP = new Set(['kl_gated_012', 'kl_gated_013', 'kl_gated_015', 'kl_gated_016', 'kl_mystery_001', 'kl_mystery_002', 'kl_mystery_003', 'kl_mystery_009']);
const KL_GATES = { zin_afrit_revealed: 'rev | hub', zin_eindil_named: 'heir', zin_horos_dead: 'F:zin_horos_dead | hub', zin_eindil_returned: 'F:zin_eindil_returned', zin_volgan_marches: 'F:zin_volgan_marches' };
const KL_MANIFEST = { kl_gated_008: 'rev | hub', kl_gated_017: 'F:zin_afrit_dead', kl_gated_018: 'F:zin_kusven_forth' };
export function knowledgeRules(file = path.join(ZIN_ROOT, 'docs/lore/references/knowledge_layers.md')) {
  if (!existsSync(file)) return [];
  const out = [];
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    if (!/^\| `kl_(sealed|gated|mystery)_\d+`/.test(line)) continue;
    const cells = line.split(/(?<!\\)\|/).map(c => c.trim()).slice(1, -1).map(c => c.replace(/\\\|/g, '|'));
    const id = cells[0].replace(/`/g, ''), kind = cells[2], pat = cells[3], gate = cells[4] ?? '';
    if (KL_SKIP.has(id) || !['term', 'phrase', 'answer'].includes(kind)) continue;
    const ticks = [...pat.matchAll(/`([^`]+)`/g)].map(m => m[1]);
    if (!ticks.length) continue;
    // a pattern that names a proper noun by its capital ([A-Z][a-z]+) is matched case-sensitively, and never by an article or a particle
    const cs = /case-sensitive/i.test(cells.slice(4).join(' ')) || ticks.some(t => t.includes('[A-Z]'));
    const fix = s => s.replace(/\[A-Z\]\[a-z\]\+/g, '(?!(?:The|A|An|And|Of|For|To|In|By|With|As|Then|When|There|It)\\b)[A-Z][a-z]+');
    const re = s => new RegExp(`(?<![\\p{L}\\p{N}])(?:${fix(s)})(?![\\p{L}\\p{N}])`, cs ? 'u' : 'iu');
    let rx;
    try { rx = kind === 'phrase' ? ticks.map(re) : [re(ticks[0])]; } catch { continue; }
    const layer = id.split('_')[1];
    const need = layer === 'gated' ? (KL_MANIFEST[id] ?? KL_GATES[/`(zin_[a-z_]+)`/.exec(gate)?.[1]] ?? null) : null;
    if (layer === 'gated' && !need) continue;
    out.push({ id, layer, kind, rx, need: need ? parseCond(need) : null });
  }
  return out;
}

// Findings for one text variant (a paragraph, a title or a page) under its condition.
export function secrecyFindings(text, cond, ctx) {
  const { axioms, futureTerms, kl = [] } = ctx;
  const out = [];
  const needs = (need, what) => { if (!implies(cond, parseCond(need), axioms)) out.push(`${what} needs ${need}`); };
  const sents = sentencesOf(text);
  if (AFRIT_TERMS.test(text)) needs('rev | hub', `"${AFRIT_TERMS.exec(text)[0]}"`);
  for (const s of sents) {
    if (DELIV.test(s) && /\bdemon/i.test(s)) needs('rev | hub', '"demon" beside the Deliverer');
    if (/\b(Deliverer|Aurevan|Council)\b/.test(s) && /\bmurder/i.test(s)) needs('rev | hub', '"murder" beside the Deliverer or the Council');
    if (/\bGlo\b/.test(s) && /\bheart\b/i.test(s)) needs('F:zin_horos_dead, S>=8', 'Glo called a heart');
  }
  if (DELIV.test(text) && /\bfalse gods?\b/i.test(text)) needs('rev | hub', '"false god" beside the Deliverer');
  if (/\bEindil\b/.test(text)) needs('heir', '"Eindil"');
  // "son of Ein" (or "grandson of Aen") names the heir, or Afrit's descent when the sentence names Afrit or the Deliverer
  for (const s of sents) if (/\b(son of Ein|grandson of Aen)\b/i.test(s)) needs(/\b(Afrit|Deliverer|Aurevan)\b/.test(s) ? 'rev | hub' : 'heir', '"son of Ein"');
  if (/\b(Horos(['’]s)? (own )?heart|heart of Horos)\b/i.test(text)) needs('F:zin_horos_dead, S>=8', 'Horos’s heart');
  for (const [loop, names] of Object.entries(DEEP_NAMES)) for (const n of names) if (new RegExp(`\\b${n}`).test(text)) needs(`D:${loop}`, `"${n}"`);
  if (/\b\d[\d,]*\s+years before Aen\b|\b\d+\s*BA\b/.test(text)) out.push('a count of years before Aen');
  if (cond.atom === 'start') for (const t of futureTerms) if (new RegExp(`\\b${t}\\b`, 'i').test(text)) out.push(`"${t}" in text open at the start`);
  for (const r of kl) {
    // ...and a plot against the King is public once it is exposed (zin_golden_king_plot_exposed), though who made it and any murder are not
    const passes = s => (r.layer === 'mystery' && OPEN_MARKER.test(s)) || (r.id === 'kl_gated_019' && ATTRIBUTED.test(s))
      || (r.id === 'kl_gated_005' && !/murder|poison|assassin|killed by/i.test(s) && implies(cond, parseCond('F:zin_golden_king_plot_exposed'), axioms));
    const hit = r.kind === 'phrase' ? sents.some(s => r.rx.every(x => x.test(s)) && !passes(s)) : (sents.length ? sents : [text]).some(s => r.rx[0].test(s) && !passes(s));
    if (!hit) continue;
    if (r.layer !== 'gated') out.push(`${r.id} (${r.layer})`);
    else if (!implies(cond, r.need, axioms)) out.push(`${r.id} needs ${condText(r.need)}`);
  }
  return out;
}

// The regional histories were written for other surfaces; a sentence of theirs that a secrecy rule, a banned word or a meta word catches
// under its part's condition is left out of the Chronicle (and listed in the build log), never rewritten here.
// The world's own words for the few modern ones the histories use (the banned-word rules' own replacements).
const REALM_WORDS = [[/\ba coal\b/g, 'an ember'], [/\bcoals\b/g, 'embers'], [/\bcoal\b/g, 'ember'], [/\bconvoys\b/g, 'merchant fleets'], [/\bconvoy\b/g, 'merchant fleet']];
export function screenRealms(data, { kl, compiled }) {
  if (data.realmsScreened) return data.realmDropped;
  const axioms = compileAxioms(data.axioms), ctx = { axioms, futureTerms: data.futureTerms, kl };
  const dropped = [];
  for (const e of data.entries.filter(x => x.generated)) {
    for (const p of e.parts) {
      const cond = parseCond(p.when), keep = [], src = p.paragraphs[0]?.sources ?? [];
      for (const q of p.paragraphs) {
        const ok = sentences(q.text).map(s => REALM_WORDS.reduce((t, [a, b]) => t.replace(a, b), s)).filter(s => {
          const why = [...secrecyFindings(s, cond, ctx), ...findBanned(s, compiled, ['error']).map(h => `banned "${h.word}"`), ...(META_WORDS.test(s) ? ['a meta word'] : [])];
          if (why.length) dropped.push(`${e.id} ${e.key}: left out "${s.slice(0, 60)}…" (${why.join('; ')})`);
          return !why.length;
        });
        if (ok.length) keep.push({ ...q, text: ok.join(' ') });
      }
      p.paragraphs = keep.length ? keep : [{ text: `The chroniclers of ${e.title} keep this part of its history to themselves.`, status: 'proposed', sources: src }];
    }
  }
  data.realmsScreened = true; data.realmDropped = dropped;
  return dropped;
}

// A source without a section cites the note's title section (its first heading): a title that names a person or a place is left out of
