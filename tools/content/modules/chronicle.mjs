export function realmEntries(ids = readJson(path.join(CHR_DATA, 'realm_ids.json')).ids, histDir = HISTORY) {
  const out = [], missing = [];
  for (const [file, landKey, region] of REGIONS) {
    const h = readJson(path.join(histDir, `${file}.json`));
    for (const c of h.countries) {
      const idKey = `${file}/${c.name}`, id = ids[idKey];
      if (!id) { missing.push(idKey); continue; }
      const status = c.roots?.canon === 'established' ? 'established' : 'proposed';
      const src = [{ note: `07 - History/Roots of the ${region.replace('’', '')}.md`, section: `Roots of the ${region.replace('’', '')}` }];
      // the sentences of the roots and the sign, each with the extra condition it needs
      const items = [];
      for (const s of sentences(c.roots?.story ?? '')) items.push({ s, block: 'roots' });
      const sign = [c.sign?.device, c.sign?.origin].filter(Boolean).join(' ');
      for (const s of sentences(sign)) items.push({ s, block: 'sign' });
      for (const it of items) { const loops = deepLoopOf(it.s); it.when = loops.length ? loops.map(l => `D:${l}`).join(', ') : null; }
      const groups = new Map();
      for (const it of items) { const k = it.when ?? 'start'; if (!groups.has(k)) groups.set(k, []); groups.get(k).push(it); }
      const parts = [...groups].map(([when, its]) => ({ when, paragraphs: paragraphsOf(its).map(text => ({ text, status, sources: src })) }));
      if (parts[0].when !== 'start') parts.unshift({ when: 'start', paragraphs: [{ text: `The histories of ${c.name} are kept by its own chroniclers.`, status, sources: src }] });
      out.push({ id, key: `realm_${keyOf(c.name)}`, title: c.name, short: null, title_after: null, subtitle: `${region} · Realm`, plate: null, unlock: 'start', parts, related: [landKey], secrets: [], generated: true, region: file });
    }
  }
  return { entries: out, missing };
}
// Sentences into paragraphs of at most about 480 characters; the sign starts its own paragraph.
function paragraphsOf(items, max = 470) {
  const paras = [];
  let cur = '', block = null;
  for (const { s, block: b } of items) {
    if (cur && (b !== block || cur.length + 1 + s.length > max)) { paras.push(cur); cur = ''; }
    cur = cur ? `${cur} ${s}` : s; block = b;
  }
  if (cur) paras.push(cur);
  return paras;
}

// ---------------------------------------------------------------------------------------------------- data
export function loadChronicle({ dir = CHR_DATA, withRealms = true } = {}) {
  const categories = readJson(path.join(dir, 'categories.json')).categories;
  const entries = [];
  for (const f of readdirSync(path.join(dir, 'entries')).filter(f => f.endsWith('.json')).sort()) {
    const j = readJson(path.join(dir, 'entries', f));
    for (const e of j.entries) entries.push({ ...e, category: j.category, file: `entries/${f}` });
  }
  const realms = withRealms ? realmEntries() : { entries: [], missing: [] };
  for (const e of realms.entries) entries.push({ ...e, category: 'realms', file: 'realm_ids.json' });
  return {
    categories, entries, realmMissing: realms.missing,
    foreword: readJson(path.join(dir, 'foreword.json')),
    axioms: readJson(path.join(dir, 'axioms.json')).axioms,
    futureTerms: readJson(path.join(dir, 'future_terms.json')).terms,
    coverage: existsSync(path.join(dir, 'coverage.json')) ? readJson(path.join(dir, 'coverage.json')) : { exclusions: [] },
  };
}

// ---------------------------------------------------------------------------------------------------- vault index (spec section 11)
// Notes of the staged vault (or the repo copy) parsed into sections: heading path, normalised text, sha256.
export const VAULT_EXCLUDED = /^(Sources\/|Maps\/|ZIN Lore Master Compendium\.md$)/;
export const normalise = s => s.replace(/\r/g, '').replace(/\s+/g, ' ').trim();
export function indexVault(files) {
  const notes = new Map();
  for (const [rel, text] of files) {
    if (!rel.endsWith('.md') || VAULT_EXCLUDED.test(rel)) continue;
    const sections = new Map();
    let cur = null;
    for (const line of String(text).replace(/\r/g, '').split('\n')) {
      const m = /^(#{1,6})\s+(.+?)\s*#*\s*$/.exec(line);
      if (m) { cur = { heading: m[2].trim(), level: m[1].length, lines: [] }; if (!sections.has(cur.heading)) sections.set(cur.heading, cur); continue; }
      if (cur) cur.lines.push(line);
    }
    const out = new Map();
    for (const [h, s] of sections) { const t = normalise(s.lines.join('\n')); out.set(h, { heading: h, level: s.level, sha256: sha(t), length: t.length }); }
    const status = /^status:\s*(\S+)/m.exec(String(text))?.[1] ?? null;
    notes.set(rel, { path: rel, status, sections: out });
  }
  return notes;
}
