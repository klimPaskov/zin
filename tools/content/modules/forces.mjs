// ------------------------------------------------------------------------------------------------ layout and apportionment
// Regiments in columns of one group each (the engine refuses a column that mixes groups): three rows to a column, five when
// the template would need more than five columns.
export function layoutRegiments(regs, groupOf) {
  const list = regs.flatMap(([s, n]) => Array.from({ length: n }, () => s));
  const order = [];
  for (const s of list) { const g = groupOf(s); if (!order.includes(g)) order.push(g); }
  const sorted = list.map((s, i) => ({ s, i })).sort((a, b) => order.indexOf(groupOf(a.s)) - order.indexOf(groupOf(b.s)) || a.i - b.i).map(x => x.s);
  for (const rows of [3, 5]) {
    const out = []; let col = -1, row = 0, last = null;
    for (const s of sorted) {
      const g = groupOf(s);
      if (g !== last || row >= rows) { col++; row = 0; last = g; }
      out.push({ sub: s, x: col, y: row++ });
    }
    if (col + 1 <= 5) return out;
  }
  return err(`A template of ${list.length} battalions does not fit the five columns of the division designer`);
}

// Largest-remainder apportionment of `total` over weights [[key, w]]; ties go to the earlier key. Deterministic.
export function apportion(total, weights) {
  const pos = weights.filter(([, w]) => w > 0), sum = pos.reduce((s, [, w]) => s + w, 0);
  const out = new Map(weights.map(([k]) => [k, 0]));
  if (total <= 0 || sum <= 0) return out;
  const rows = pos.map(([k, w], i) => ({ k, i, exact: total * w / sum }));
  for (const r of rows) out.set(r.k, Math.floor(r.exact));
  let left = total - rows.reduce((s, r) => s + Math.floor(r.exact), 0);
  for (const r of [...rows].sort((a, b) => (b.exact - Math.floor(b.exact)) - (a.exact - Math.floor(a.exact)) || a.i - b.i)) { if (left <= 0) break; out.set(r.k, out.get(r.k) + 1); left--; }
  return out;
}

