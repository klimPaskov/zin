export function divisionCount(model, c) {
  const F = model.raw.templates.formula, named = model.raw.templates.named[c.name];
  if (named) return named.divisions;
  const states = model.raw.geography.countries[c.tag].length, tier = model.tierOf(c.tag);
  const key = model.profileKey(c), pop = model.popOf.get(c.tag) ?? 0;
  const character = model.raw.templates.cultureCharacter[model.cultureOf.get(c.tag)] ?? model.raw.templates.cultureCharacter.default;
  if (states <= F.villageStates && pop < F.villagePeople) return 1;
  let d = clamp(F.base + Math.round(states * F.perState), F.min, F.max);
  if (tier === 'b') d = Math.round(d * F.tierB);
  d = Math.max(1, Math.round(d * (character.martial ?? 1)));
  const manpower = pop * (model.share[key] ?? model.share[key.replace('country:', '')] ?? 0.05);
  return clamp(Math.min(d, Math.max(1, Math.ceil(manpower / F.popPerDivision))), 1, 24);
}

// The option of a template a country can field with what it has unlocked, or null.
function chooseOption(model, tmpl, unlocked) {
  if (!(tmpl.needs ?? []).every(n => unlocked.subs.has(n))) return null;
  for (const o of tmpl.options) if (o.regiments.every(([s]) => unlocked.subs.has(s))) return { regiments: o.regiments, support: o.support.filter(s => unlocked.subs.has(s)) };
  return null;
}
function bestType(model, archetype, unlocked) {
  const have = [...unlocked.eq].filter(t => archetypeOfType(t, model.archetypes) === archetype).sort((a, b) => Number(b.match(/(\d+)$/)[1]) - Number(a.match(/(\d+)$/)[1]));
  if (have.length) return { type: have[0], unlocked: true };
  const all = [...model.eqTypes].filter(t => archetypeOfType(t, model.archetypes) === archetype).sort((a, b) => Number(a.match(/(\d+)$/)[1]) - Number(b.match(/(\d+)$/)[1]));
  return all.length ? { type: all[0], unlocked: false } : null;
}

export function planCountry(model, c) {
  const TDm = model.raw.templates, F = TDm.formula, geo = model.raw.geography.countries[c.tag];
  const key = model.profileKey(c), prof = TDm.profiles[key], named = TDm.named[c.name], tier = model.tierOf(c.tag);
  const unlocked = model.unlockedOf.get(c.tag), r = rng(`forces:${c.tag}`);
  const character = TDm.cultureCharacter[model.cultureOf.get(c.tag)] ?? TDm.cultureCharacter.default;
  const ranked = [...geo].sort((a, b) => (a.id === c.capitalState ? -1 : 0) - (b.id === c.capitalState ? -1 : 0) || b.vp - a.vp || a.id - b.id);
  const ports = ranked.filter(s => s.port);
  const notes = [];
  const total = divisionCount(model, c);
  const options = new Map();
  const usable = id => { if (!options.has(id)) options.set(id, chooseOption(model, model.templates.get(id), unlocked)); return options.get(id); };

  // which templates, how many
  const plan = []; // { template, reserve, xp, province, wall? }
  const wallRow = named?.wall;
  let wallStates = [];
  if (wallRow) {
    const [w, h] = TDm.wall.frame, forts = TDm.wall.forts.map(f => [f.x * w, (1 - f.y) * h]);
    wallStates = geo.filter(s => s.centre).map(s => ({ s, d: Math.min(...forts.map(f => Math.hypot(f[0] - s.centre[0], f[1] - s.centre[1]))) })).filter(x => x.d <= TDm.wall.maxDistance).sort((a, b) => a.d - b.d || a.s.id - b.s.id).map(x => x.s);
    if (!wallStates.length) notes.push('no state near the Great Wall: the wall divisions stand in the capital state');
  }
  const counts = new Map();
  if (named) {
    for (const [id, n] of Object.entries(named.mix)) counts.set(id, n);
  } else if (total > 0) {
    const village = geo.length <= F.villageStates && (model.popOf.get(c.tag) ?? 0) < F.villagePeople;
    const delta = (model.raw.ai.tierGarrison[tier] ?? 0) / 100;
    let g = prof.garrison ? (total <= 2 ? 1 : Math.max(1, Math.round(total * (prof.garrisonShare + delta)))) : 0;
    if (village || geo.length < F.fieldMinStates) g = total;
    g = Math.min(g, total);
    if (prof.garrison && g > 0) counts.set(prof.garrison, g);
    const field = total - g;
    if (field > 0) {
      const cm = character.mult ?? {};
      const weights = prof.mix.map(m => {
        let w = m.w > 0 ? m.w : (m.base ?? 0);
        if (m.mult) w *= cm[m.mult] ?? (m.w > 0 ? 1 : 0);
        if (m.port && !ports.length) w = 0;
        if (!usable(m.t)) w = 0;
        return [m.t, w];
      });
      if (!weights.some(([, w]) => w > 0)) notes.push('no field template is available: the divisions are garrisons');
      const got = weights.some(([, w]) => w > 0) ? apportion(field, weights) : new Map([[prof.garrison, field]]);
      for (const [t, n] of got) if (n > 0) counts.set(t, (counts.get(t) ?? 0) + n);
    }
  }
  // a template the country cannot field becomes its people's first usable field template (or garrison)
  const fallbackFor = id => { for (const m of prof.mix) if (usable(m.t)) return m.t; return prof.garrison && usable(prof.garrison) ? prof.garrison : null; };
  const final = new Map();
  for (const [id, n] of counts) {
    let use = id;
    if (!usable(id)) { use = fallbackFor(id); notes.push(`${id} is not unlocked: ${n} division(s) use ${use ?? 'nothing'}`); }
    if (!use) continue;
    final.set(use, (final.get(use) ?? 0) + n);
  }
  // placement
  const xpBase = named ? named.xp : prof.xp;
  const jitter = () => named ? 0 : (r() - 0.5) * 2 * F.experienceJitter;
  const stateAt = i => ranked[i % ranked.length];
  const capitalState = ranked[0];
  let fieldIndex = 0, garrisonIndex = 0, wallIndex = 0;
  const reserveIds = [...final.keys()].filter(id => model.templates.get(id).reserve);
  const entries = [...final].sort((a, b) => (reserveIds.includes(a[0]) ? 1 : 0) - (reserveIds.includes(b[0]) ? 1 : 0));
  const fieldTotal = entries.filter(([id]) => !reserveIds.includes(id)).reduce((a, [, n]) => a + n, 0);
  const spread = Math.max(1, Math.min(ranked.length, Math.ceil(fieldTotal / 2)));
  const wallNeed = wallRow ? wallRow.n : 0;
  const ordered = [];
  if (wallRow) {
    const t = wallRow.template;
    if (!usable(t)) notes.push(`${t} is not unlocked: the wall divisions use the line host`);
    const use = usable(t) ? t : fallbackFor(t);
    for (let i = 0; i < wallNeed; i++) { const st = wallStates.length ? wallStates[i % wallStates.length] : capitalState; ordered.push({ template: use, reserve: false, xp: wallRow.xp ?? xpBase, province: st.province, state: st.id, wall: true }); }
  }
  for (const [id, n] of entries) {
    const reserve = reserveIds.includes(id);
    for (let i = 0; i < n; i++) {
      const st = reserve ? stateAt(garrisonIndex++) : stateAt(fieldIndex++ % spread);
      const xp = clamp(Math.round(((reserve ? xpBase * 0.5 : xpBase) + jitter()) * 100) / 100, 0, 1);
      ordered.push({ template: id, reserve, xp, province: st.province, state: st.id });
    }
  }
  plan.push(...ordered);
  // ships
  const ships = [];
  const wantShips = named ? (named.navy ?? {}) : null;
  const hullOf = { zin_ship_galley: 'zin_hull_galley', zin_ship_warship: 'zin_hull_warship', zin_ship_great_warship: 'zin_hull_great_warship', zin_ship_raider: 'zin_hull_raider' };
  const shipCounts = new Map();
  if (wantShips) for (const [s, n] of Object.entries(wantShips)) shipCounts.set(s, n);
  else if (ports.length) shipCounts.set('zin_ship_galley', Math.min(F.galleysMax, Math.ceil(ports.length / 2 * (character.sea ?? 1))));
  for (const [s, n] of shipCounts) {
    const hull = bestType(model, hullOf[s], unlocked);
    if (!unlocked.subs.has(s) || !hull?.unlocked) { if (named) notes.push(`${s} (${n}) is not unlocked by the start technologies: no such ship at the start`); continue; }
    if (!ports.length) { if (named) notes.push(`${s} (${n}): the country has no port`); continue; }
    for (let i = 0; i < n; i++) ships.push({ sub: s, hull: hull.type, port: ports[Math.floor(i * Math.min(ports.length, Math.max(1, Math.ceil(n / 4))) / n) % ports.length] });
  }
  // equipment
  const need = new Map();
  const tally = (optionRegs, optionSupport, n) => {
    for (const [s, k] of optionRegs) for (const [a, v] of Object.entries(model.needOf.get(s) ?? {})) need.set(a, (need.get(a) ?? 0) + v * k * n);
    for (const s of optionSupport) for (const [a, v] of Object.entries(model.needOf.get(s) ?? {})) need.set(a, (need.get(a) ?? 0) + v * n);
  };
  const perTemplate = new Map();
  for (const d of plan) perTemplate.set(d.template, (perTemplate.get(d.template) ?? 0) + 1);
  for (const [id, n] of perTemplate) { const o = usable(id); if (o) tally(o.regiments, o.support, n); }
  const stock = [];
  const factor = prof.stockFactor ?? F.stockFactor;
  for (const a of [...need.keys()].sort(byEn)) {
    const t = bestType(model, a, unlocked);
    if (!t) continue;
    if (!t.unlocked) notes.push(`${a} is not unlocked by the start technologies: the stock is ${t.type}`);
    stock.push({ type: t.type, archetype: a, amount: Math.ceil(need.get(a) * factor / 10) * 10, unlocked: t.unlocked });
  }
  const production = prof.arms && plan.length ? bestType(model, prof.arms, unlocked) : null;
  const logistics = [];
  if (plan.length) {
    const trains = bestType(model, 'train_equipment', unlocked);
    if (trains) logistics.push({ type: trains.type, amount: clamp(F.trainsMin + plan.length * F.trainsPerDivision, F.trainsMin, F.trainsMax) });
  }
  if (ships.length || ports.length && plan.length) {
    const convoy = bestType(model, 'convoy', unlocked);
    if (convoy && convoy.unlocked) logistics.push({ type: convoy.type, amount: clamp(F.convoysBase + ships.length * F.convoysPerGalley, F.convoysBase, F.convoysMax) });
  }
  return { tag: c.tag, name: c.name, key, tier, divisions: plan, ships, stock, production, logistics, notes, usable, ranked, ports, total };
}

