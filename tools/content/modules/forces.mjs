// ------------------------------------------------------------------------------------------------ the builder
export async function buildForces(staged, ctx) {
  const model = await prepareModel(ctx, ctx.raw ?? null, staged);
  ctx.model = model;
  const names = groupNames(staged), shipGroups = shipNames(staged);
  const hostGroups = model.raw.ids.hostGroupByCountry;
  const compiled = compileBanned(model.raw.banned);
  const report = { countries: {}, divisions: 0 };
  let divisions = 0, ships = 0, stockLines = 0;
  for (const c of [...model.countries].sort((a, b) => byEn(a.tag, b.tag))) {
    const plan = planCountry(model, c);
    plan.ships = nameShips(model, plan, shipGroups);
    const oobText = writeOob(model, plan, names, plan.ships, hostGroups[c.name], !!ctx.splitNaval);
    staged.text(`history/units/${c.tag}_world.txt`, oobText.land);
    if (ctx.splitNaval && oobText.naval) staged.text(`history/units/${c.tag}_world_naval.txt`, oobText.naval);
    divisions += plan.divisions.length; ships += plan.ships.length; stockLines += plan.stock.length;
    const tmpl = {}; for (const d of plan.divisions) { const n = model.templates.get(d.template).name; tmpl[n] = (tmpl[n] ?? 0) + 1; }
    const shipsBy = {}; for (const s of plan.ships) shipsBy[s.sub] = (shipsBy[s.sub] ?? 0) + 1;
    report.countries[c.tag] = { name: c.name, people: plan.key, tier: plan.tier, divisions: plan.divisions.length, garrisons: plan.divisions.filter(d => d.reserve).length, templates: tmpl, ships: shipsBy, stock: Object.fromEntries(plan.stock.map(s => [s.type, s.amount])), production: plan.production?.type ?? null, notes: plan.notes };
  }
  report.divisions = divisions;
  staged.text(FILES.tiers, tierTriggers(model));
  staged.text(FILES.eras, eraTriggers());
  staged.text(FILES.aiTemplates, aiTemplates(model));
  staged.text(FILES.aiEquipment, aiEquipment(model));
  staged.text(FILES.taskforce, aiTaskforces(model));
  staged.text(FILES.fleet, aiFleets(model));
  staged.text(FILES.goals, aiGoals(model));
  staged.text(FILES.land, landStrategies(model));
  staged.text(FILES.production, productionStrategies(model));
  staged.text(FILES.navy, navyStrategies(model));
  staged.text(FILES.doctrines, doctrineStrategies(model));
  staged.text(FILES.plans, plans(model));
  staged.text(FILES.graphicDb, graphicDb(model));
  staged.text(FILES.designerGui, designerGui(model));
  staged.text(FILES.designerGfx, designerGfx(model));
  // player-visible words: the displayed names of templates and fleets contain nothing modern
  const shown = [...new Set([...model.templates.values()].map(t => t.name))];
  for (const s of shown) { const hits = findBanned(s, compiled); if (hits.length) err(`forces: template name "${s}" contains a banned word (${hits.map(h => h.word).join(', ')})`); }
  const coverage = {};
  for (const e of model.raw.ai.entries) (coverage[e.people] ??= {})[e.role] = `zin_ai_${slugOf(e.people)}_${e.role}`;
  report.aiTemplateCoverage = coverage;
  report.designGroups = model.raw.ai.designs.groups.map(g => g.id);
  staged.text(FILES.report, canonicalJson(report));
  return { countries: model.countries.length, divisions, ships, stockLines, templates: model.templates.size, aiEntries: model.raw.ai.entries.length, aiTargets: model.raw.ai.entries.reduce((a, e) => a + e.targets.length, 0), taskforces: model.raw.ai.navy.taskforces.length, fleets: model.raw.ai.navy.fleets.length, goals: model.raw.ai.navy.goals.length, designGroups: model.raw.ai.designs.groups.length };
}
