// ------------------------------------------------------------------------------------------------ AI: strategies
const strat = (type, id, value, depth = 1) => `${T(depth)}ai_strategy = {\n${T(depth + 1)}type = ${type}\n${id ? `${T(depth + 1)}id = ${id}\n` : ''}${T(depth + 1)}value = ${num(value)}\n${T(depth)}}`;
const stratBlock = (name, enable, strategies, comment) => `${comment ? `# ${comment}\n` : ''}${name} = {\n${T(1)}allowed = {\n${T(2)}always = yes\n${T(1)}}\n${T(1)}enable = {\n${enable.map(e => `${T(2)}${e}`).join('\n')}\n${T(1)}}\n${T(1)}abort_when_not_enabled = yes\n${strategies.join('\n')}\n}`;
const peopleEnable = (model, key) => key.startsWith('country:') ? [`original_tag = ${model.tagOfName.get(key.slice(8))}`] : [`has_country_flag = zin_people_${key}`];
const presentKeys = model => [...new Set(model.countries.map(c => model.profileKey(c)))].sort(byEn);

function landStrategies(model) {
  const ai = model.raw.ai, out = [HEADER, '# Generic land strategies (L1 of docs/specs/09_validation/02_ai_defaults.md): role ratios by people, tier shifts of the garrison share, and the peace-first army size. Values are weights; probe AI-P1 calibrates the scale.'];
  for (const key of presentKeys(model)) {
    const r = ai.ratios[key], marines = r.marines;
    out.push(stratBlock(`zin_default_land_${slugOf(key)}`, peopleEnable(model, key), ai.roles.filter(role => role !== 'marines').map(role => strat('role_ratio', role, r[role])), `Role ratios of ${labelOf(key)}`));
    if (marines > 0) out.push(stratBlock(`zin_default_land_${slugOf(key)}_coast`, [...peopleEnable(model, key), 'any_owned_state = { is_coastal = yes }'], [strat('role_ratio', 'marines', marines)], `Sea soldiers of ${labelOf(key)}, for realms with a coast`));
  }
  // A role whose every target waits for tiers A and B has no target for tier C: its ratio is cancelled there.
  for (const key of presentKeys(model)) {
    const cancel = ai.entries.filter(e => e.people === key && ai.ratios[key][e.role] > 0 && e.targets.every(t => (t.enable ?? []).includes('not_tier_c')));
    if (cancel.length) out.push(stratBlock(`zin_default_land_${slugOf(key)}_tier_c`, [...peopleEnable(model, key), 'zin_ai_is_tier_c = yes'], cancel.map(e => strat('role_ratio', e.role, -ai.ratios[key][e.role])), `Tier C of ${labelOf(key)} has no ${cancel.map(e => e.role).join(', ')} target`));
  }
  for (const [t, v] of Object.entries(ai.tierGarrison)) {
    if (v === 0) { out.push(stratBlock(`zin_default_land_tier_${t}`, [`zin_ai_is_tier_${t} = yes`], [strat('garrison_reinforcement_priority', null, 0)], `Tier ${t.toUpperCase()}: no change to the garrison share`)); continue; }
    out.push(stratBlock(`zin_default_land_tier_${t}`, [`zin_ai_is_tier_${t} = yes`], [strat('role_ratio', 'garrison', v), strat('role_ratio', 'infantry', -v), strat('garrison_reinforcement_priority', null, 25)], `Tier ${t.toUpperCase()}: ${v} more garrison, the same less infantry`));
  }
  out.push(stratBlock(PEACE_FIRST, ['zin_ai_era_peace = yes'], [strat('ai_wanted_divisions_factor', null, -50)], 'Peace first: the AI builds no more than a little beyond its start army while the Golden King reigns'));
  return out.join('\n\n');
}

function productionStrategies(model) {
  const ai = model.raw.ai, P = ai.production, out = [HEADER, '# Generic production strategies (L1): factory mix, which equipment lines, how many, minimum lines, surplus. Granted equipment is never produced.'];
  for (const key of presentKeys(model)) {
    const L = [strat('added_military_to_civilian_factory_ratio', null, P.militaryToCivilian[key])];
    const v = P.variants[key] ?? {};
    for (const a of Object.keys(v).sort(byEn)) L.push(strat('equipment_variant_production_factor', a, v[a] - 100));
    out.push(stratBlock(`zin_default_production_${slugOf(key)}`, peopleEnable(model, key), L, `Factory mix and equipment lines of ${labelOf(key)}`));
  }
  out.push(stratBlock('zin_default_production_never', ['always = yes'], P.never.slice().sort(byEn).map(a => strat('equipment_variant_production_factor', a, -100)), 'Granted and unproducible equipment is never produced'));
  out.push(stratBlock('zin_default_production_types', ['always = yes'], Object.entries(P.types).map(([t, w]) => strat('equipment_production_factor', t, w - 100)), 'How many of each equipment type'));
  out.push(stratBlock('zin_default_production_no_skies', ['NOT = { zin_rules_skies_present = yes }'], [strat('equipment_production_factor', 'anti_air', -100)], 'No scorpions when the sky rule is none'));
  out.push(stratBlock('zin_default_production_war', ['has_war = yes'], [strat('added_military_to_civilian_factory_ratio', null, P.warBoost / 2)], 'More armouries at war'));
  out.push(stratBlock('zin_default_production_surplus', ['always = yes'], Object.entries(P.surplus).sort(([a], [b]) => byEn(a, b)).map(([a, v]) => strat('equipment_production_surplus_management', a, v)), 'What to keep making once the need is met'));
  out.push(stratBlock('zin_default_production_lines', ['always = yes'], [strat('equipment_production_min_factories_archetype', 'train_equipment', P.minFactories.train_equipment)], 'One line of pack trains for the roads'));
  out.push(stratBlock('zin_default_production_convoys', ['any_owned_state = { is_coastal = yes }'], [strat('equipment_production_min_factories_archetype', 'convoy', P.minFactories.convoy)], 'One line of cogs for a coastal realm'));
  out.push(stratBlock('zin_default_production_pack_trains', [`num_of_military_factories > ${P.minArmouries - 1}`], [strat('equipment_production_min_factories_archetype', 'motorized_equipment', P.minFactories.motorized_equipment)], 'One line of pack trains once the realm has twelve armouries'));
  return out.join('\n\n');
}

function navyStrategies(model) {
  const N = model.raw.ai.navy, seaTags = [...new Set([...N.seaPower.names.map(n => model.tagOfName.get(n)), ...model.countries.filter(c => N.seaPower.scans.includes(c.scan)).map(c => c.tag)])].filter(Boolean).sort(byEn);
  const zol = model.tagOfName.get('Zol');
  const out = [HEADER, '# Generic navy strategies (L1): ratios of galleys, warships, raiders and cogs by sea drive; no dragons are ever produced, and under the griffin rule men with war keep a few griffin riders.'];
  const ratios = r => Object.entries(r).map(([id, v]) => strat('unit_ratio', id, v));
  out.push(stratBlock('zin_default_navy_sea_power', [`OR = {\n${seaTags.map(t => `${T(3)}original_tag = ${t}`).join('\n')}\n${T(2)}}`], [...ratios(N.seaPower.ratios), ...Object.entries(N.roleRatios.seaPower).map(([id, v]) => strat('role_ratio', id, v)), strat('dockyard_to_military_factory_ratio', null, model.raw.ai.production.dockyards.seaPower)], 'Sea powers'));
  out.push(stratBlock('zin_default_navy_coastal', ['any_owned_state = { is_coastal = yes }', `NOT = { original_tag = ${zol} }`, `NOT = {\n${T(3)}OR = {\n${seaTags.map(t => `${T(4)}original_tag = ${t}`).join('\n')}\n${T(3)}}\n${T(2)}}`], [...ratios(N.coastal.ratios), ...Object.entries(N.roleRatios.coastal).map(([id, v]) => strat('role_ratio', id, v)), strat('dockyard_to_military_factory_ratio', null, model.raw.ai.production.dockyards.coastal)], 'Coastal land powers'));
  out.push(stratBlock('zin_default_navy_zol', [`original_tag = ${zol}`], Object.entries(N.zol.ratios).map(([id, v]) => strat('unit_ratio', id, v - 100)), 'The Mistake builds no ships: its three black ships are scripted'));
  out.push(stratBlock('zin_default_air_dragons', ['always = yes'], [strat('unit_ratio', 'cas', 0), strat('unit_ratio', 'fighter', 0)], 'Dragons are granted and never built'));
  out.push(stratBlock('zin_default_air_griffins', ['has_country_flag = zin_people_men', 'zin_rules_skies_beasts = yes', 'has_war = yes'], [strat('unit_ratio', 'fighter', 10)], 'Under the griffin rule, men at war keep griffin riders at a tenth of the arms'));
  return out.join('\n\n');
}

function doctrineStrategies(model) {
  const Dd = model.raw.ai.doctrines, out = [HEADER, '# Ratios that follow the doctrines (L1): one block per grand doctrine of the technology module, four for completed tracks, and the concentration of force by command doctrine.'];
  const body = r => Object.entries(r).map(([id, v]) => strat(['capital_ship', 'screen_ship', 'submarine', 'convoy'].includes(id) ? 'unit_ratio' : 'role_ratio', id, v));
  for (const [k, r] of Object.entries(Dd.land)) out.push(stratBlock(`zin_default_doctrine_${k.replace(/^zin_gd_/, '')}`, [`has_doctrine = ${k}`], body(r), `Grand doctrine ${k}`));
  for (const [k, r] of Object.entries(Dd.naval)) out.push(stratBlock(`zin_default_doctrine_${k.replace(/^zin_gd_/, '')}`, [`has_doctrine = ${k}`], body(r), `Grand doctrine ${k}`));
  for (const [k, r] of Object.entries(Dd.air)) out.push(stratBlock(`zin_default_doctrine_${k.replace(/^zin_gd_/, '')}`, [`has_doctrine = ${k}`], [strat('unit_ratio', 'cas', 0)], `Grand doctrine ${k}: dragons are granted, not built`));
  for (const [k, r] of Object.entries(Dd.tracks)) {
    const s = body(r);
    if (Dd.forceConcentration[k] !== undefined) s.push(strat('force_concentration_factor', null, Dd.forceConcentration[k]));
    if (s.length) out.push(stratBlock(`zin_default_track_${k.replace(/^zin_track_/, '')}`, [`has_completed_track = ${k}`], s, `Track ${k} completed`));
  }
  for (const [k, v] of Object.entries(Dd.forceConcentration)) if (k.startsWith('zin_gd_')) out.push(stratBlock(`zin_default_concentration_${k.replace(/^zin_gd_/, '')}`, [`has_doctrine = ${k}`], [strat('force_concentration_factor', null, v)], `Grand doctrine ${k}: pushes in force`));
  return out.join('\n\n');
}

function plans(model) {
  const R = model.raw.ai.research, out = [HEADER, '# Generic AI strategy plans, one per people and tier present in the roster: research multipliers by category. They carry no focus order (the focus trees and the historical path own it).'];
  const pairs = new Map();
  for (const c of model.countries) pairs.set(`${model.profileKey(c)}|${model.tierOf(c.tag)}`, [model.profileKey(c), model.tierOf(c.tag)]);
  for (const [, [key, tier]] of [...pairs].sort(([a], [b]) => byEn(a, b))) {
    const cats = { ...(R.base[key] ?? {}) };
    for (const [k, v] of Object.entries(tier === 'c' ? R.tierC : tier === 'b' ? R.tierB : {})) cats[k] = Math.round((cats[k] ?? 1) * v * 100) / 100;
    const name = `zin_default_plan_${slugOf(key)}_${tier}`;
    out.push([`${name} = {`, `${T(1)}name = ${q(name)}`, `${T(1)}desc = ""`, `${T(1)}allowed = {\n${T(2)}always = yes\n${T(1)}}`, `${T(1)}enable = {\n${[...peopleEnable(model, key), `zin_ai_is_tier_${tier} = yes`].map(e => `${T(2)}${e}`).join('\n')}\n${T(1)}}`, `${T(1)}abort = {\n${T(2)}always = no\n${T(1)}}`, `${T(1)}research = {`, ...Object.keys(cats).sort(byEn).map(k => `${T(2)}${k} = ${num(cats[k])}`), `${T(1)}}`, `${T(1)}weight = {\n${T(2)}factor = 1\n${T(1)}}`, '}'].join('\n'));
  }
  return out.join('\n\n');
}

