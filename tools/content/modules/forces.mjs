      L.push(`${T(2)}upgrade_prio = {\n${T(3)}factor = ${t.prio ?? 1}\n${T(2)}}`);
      if (t.enable?.length) L.push(`${T(2)}enable = {`, ...t.enable.map(tok => `${T(3)}${condText(model, tok)}`), `${T(2)}}`);
      L.push(`${T(2)}target_template = {`);
