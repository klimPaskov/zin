// The battalion that names the division: the most numerous one that is not a siege engine.
function mainUnit(regs, groupOf) {
  const front = regs.filter(([s]) => groupOf(s) !== 'combat_support');
  return [...(front.length ? front : regs)].sort((a, b) => b[1] - a[1])[0][0];
}

function writeOob(model, plan, names, ships, hostGroup, splitNaval = false) {
  const c = model.byTag.get(plan.tag), L = [HEADER];
  const groupOf = s => model.groupOf.get(s) ?? 'infantry';
  L.push(`# ${c.name}: ${plan.divisions.length} division(s), ${plan.ships.length} ship(s). People ${plan.key}, tier ${plan.tier}.`);
  const used = [...new Set(plan.divisions.map(d => d.template))];
  const group = hostGroup && names.get(hostGroup);
  const chosen = new Map();
  for (const id of used) {
    const t = model.templates.get(id), o = plan.usable(id);
    chosen.set(id, o);
    const main = mainUnit(o.regiments, groupOf);
    const useGroup = group && group.types.has(main) && (group.countries.size === 0 || group.countries.has(c.tag)) ? hostGroup : null;
    const lines = [`division_template = {`, `${T(1)}name = ${q(t.name)}`];
    if (useGroup) lines.push(`${T(1)}division_names_group = ${useGroup}`);
    if (t.reserve) lines.push(`${T(1)}priority = 0`);
    lines.push(`${T(1)}regiments = {`, ...layoutRegiments(o.regiments, groupOf).map(p => `${T(2)}${p.sub} = { x = ${p.x} y = ${p.y} }`), `${T(1)}}`);
    if (o.support.length) lines.push(`${T(1)}support = {`, ...o.support.map((s, i) => `${T(2)}${s} = { x = 0 y = ${i} }`), `${T(1)}}`);
    lines.push('}');
    L.push(lines.join('\n'));
  }
  L.push('units = {');
  let order = 0;
  for (const d of plan.divisions) {
    const t = model.templates.get(d.template);
    const o = chosen.get(d.template), main = mainUnit(o.regiments, groupOf);
    const named = group && group.types.has(main) && (group.countries.size === 0 || group.countries.has(c.tag));
    L.push(`${T(1)}division = { ${named ? `division_name = { is_name_ordered = yes name_order = ${++order} } ` : `name = ${q(`${ordinal(++order)} ${t.name}`)} `}location = ${d.province} division_template = ${q(t.name)} start_experience_factor = ${num(d.xp)} start_equipment_factor = 1 }`);
  }
  const fleetLines = [];
  if (ships.length) {
    const fleet = `${plan.name} Fleet`, home = ships[0].port.port;
    fleetLines.push(`${T(1)}fleet = {`, `${T(2)}name = ${q(fleet)}`, `${T(2)}naval_base = ${home}`);
    const byPort = new Map();
    for (const s of ships) (byPort.get(s.port.port) ?? byPort.set(s.port.port, []).get(s.port.port)).push(s);
    let tf = 0;
    for (const [port, list] of byPort) {
      tf++;
      fleetLines.push(`${T(2)}task_force = {`, `${T(3)}name = ${q(byPort.size > 1 ? `${plan.name} ${ordinal(tf)} Squadron` : `${plan.name} Squadron`)}`, `${T(3)}location = ${port}`);
      for (const s of list) fleetLines.push(`${T(3)}ship = { name = ${q(s.name)}${s.pride ? ' pride_of_the_fleet = yes' : ''} definition = ${s.sub} equipment = { ${s.hull} = { amount = 1 owner = ${plan.tag} } } }`);
      fleetLines.push(`${T(2)}}`);
    }
    fleetLines.push(`${T(1)}}`);
  }
  if (!splitNaval) L.push(...fleetLines);
  L.push('}');
  const eff = [];
  for (const s of plan.stock) eff.push(`${T(1)}add_equipment_to_stockpile = { type = ${s.type} amount = ${s.amount} producer = ${plan.tag} }`);
  for (const l of plan.logistics) eff.push(`${T(1)}add_equipment_to_stockpile = { type = ${l.type} amount = ${l.amount} producer = ${plan.tag} }`);
  const F = model.raw.templates.formula;
  if (plan.production) eff.push(`${T(1)}add_equipment_production = { equipment = { type = ${plan.production.type} creator = ${plan.tag} } requested_factories = ${F.factories} progress = ${F.progress} efficiency = ${F.efficiency} }`);
  if (eff.length) L.push('instant_effect = {', ...eff, '}');
  const naval = fleetLines.length ? [HEADER, `# ${c.name}: the fleet, loaded by set_naval_oob = "${plan.tag}_world_naval" in the country history.`, 'units = {', ...fleetLines, '}'].join('\n') : null;
  return { land: L.join('\n'), naval };
}

function nameShips(model, plan, groups) {
  const used = new Set(), r = rng(`ships:${plan.tag}`);
  const out = [];
  let black = 0;
  for (const s of plan.ships) {
    const hullArch = s.hull.replace(/_\d+$/, '');
    const g = groups.find(x => x.countries.has(plan.tag) && x.hulls.has(hullArch));
    let name = null;
    if (g && g.names.length) {
      const start = Math.floor(r() * g.names.length);
      for (let i = 0; i < g.names.length; i++) { const n = g.names[(start + i) % g.names.length]; if (!used.has(n)) { name = n; break; } }
    }
    if (!name) name = (g?.fallback ?? 'Ship %d').replace('%d', String(++black));
    used.add(name);
    out.push({ ...s, name });
  }
  if (out.length) { const i = out.findIndex(s => s.sub === 'zin_ship_great_warship' || s.sub === 'zin_ship_warship'); if (i >= 0) out[i].pride = true; }
  return out;
}

