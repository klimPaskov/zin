export async function prepareModel(ctx, raw0 = null, staged = null) {
  const raw = raw0 ?? await loadRaw();
  const problems = [];
  const P = m => { problems.push(m); };
  const countries = ctx.countries;
  const table = ctx.table ?? await loadCountryTable(countries, `${ZIN}/docs/design/countries.csv`);
  const assignment = ctx.assignment ?? new Map([...table].map(([t, v]) => [t, v.people]));
  const { templates: TD, ai, geography, ids, units, techs, institutions, cultures, demography } = raw;
  const subIds = new Set(ids.subUnits), landIds = new Set(ids.landSubUnits), archetypes = new Set(ids.archetypes), eqTypes = new Set(ids.equipmentTypes);
  const groupOf = new Map(units.land.map(u => [u.id, u.grp]));
  const tagOfName = new Map(countries.map(c => [c.name, c.tag]));
  const byTag = new Map(countries.map(c => [c.tag, c]));

  // unlock indexes
  const unitTech = new Map(), eqTech = new Map(), techByKey = new Map();
  for (const t of techs.technologies) {
    techByKey.set(t.key, t);
    for (const s of t.unlocks?.subunits ?? []) if (!unitTech.has(s)) unitTech.set(s, t.key);
    for (const e of t.unlocks?.equipment ?? []) if (!eqTech.has(e)) eqTech.set(e, t.key);
  }

  // profile keys, tiers, cultures, populations
  const profileKey = c => (c.name === 'Volgan' || c.name === 'Zol') ? `country:${c.name}` : (assignment.get(c.tag) ?? err(`No people for ${c.tag}`));
  const tierA = new Set(institutions.tiers.a.map(n => { const t = tagOfName.get(n); if (!t) P(`tier A names ${n}, which is not in the roster`); return t; }).filter(Boolean)), tierB = new Set(institutions.tiers.b.map(n => tagOfName.get(n)).filter(Boolean));
  const tierOf = tag => tierA.has(tag) ? 'a' : tierB.has(tag) ? 'b' : 'c';
  const cultureOf = new Map(cultures.countries.map(c => [c.tag, c.culture]));
  const popOf = new Map(demography.countries.map(c => [c.tag, c.population]));
  const share = demography.game_numbers.manpower_share_by_people;

  // start technologies
  let packs = ctx.startPackages;
  if (!packs && staged?.files.has('docs/design/technology/start_packages.json')) packs = JSON.parse(staged.files.get('docs/design/technology/start_packages.json').toString('utf8'));
  if (!packs) {
    const tm = await prepareTech({ countries, assignment }), pk = technologyPackages(tm);
    packs = { packages: pk, countries: Object.fromEntries(countries.map(c => [c.name, { people: assignment.get(c.tag), ...startFor(tm, pk, c, assignment.get(c.tag)) }])) };
  }
  const unlockedOf = new Map();
  for (const c of countries) {
    const row = packs.countries[c.name];
    if (!row) { P(`${c.name}: no start package`); continue; }
    const subs = new Set(), eq = new Set();
    for (const k of row.technologies) {
      const t = techByKey.get(k);
      if (!t) continue; // the technologies of the craft and scholarship rows unlock neither units nor equipment
      for (const s of t.unlocks?.subunits ?? []) subs.add(s);
      for (const e of t.unlocks?.equipment ?? []) eq.add(e);
    }
    unlockedOf.set(c.tag, { subs, eq, technologies: new Set(row.technologies) });
  }

  // templates
  const templates = new Map(Object.entries(TD.templates));
  const roles = new Set(TD.roles);
  const profiles = TD.profiles;
  const peopleOk = (people, key, name) => people.includes(key) || people.includes(`country:${name}`);
  for (const [id, t] of templates) {
    if (!roles.has(t.role)) P(`template ${id}: unknown role ${t.role}`);
    if (!t.name || /["\\]/.test(t.name)) P(`template ${id}: bad name`);
    if (!t.options?.length) P(`template ${id}: no option`);
    for (const n of t.needs ?? []) if (!landIds.has(n)) P(`template ${id}: needs unknown sub-unit ${n}`);
    for (const o of t.options ?? []) {
      for (const [s, n] of o.regiments) {
        if (!subIds.has(s)) P(`template ${id}: unknown sub-unit ${s}`); else if (!landIds.has(s)) P(`template ${id}: ${s} is not a land sub-unit`);
        else if (groupOf.get(s) === 'support') P(`template ${id}: support company ${s} listed among the regiments`);
        if (!(n >= 1)) P(`template ${id}: count ${n} of ${s}`);
        if (s === 'zin_abyss_folk' || ids.unlock?.[s] === 'grant') P(`template ${id}: ${s} is not recruited at the start`);
      }
      for (const s of o.support) if (!landIds.has(s) || groupOf.get(s) !== 'support') P(`template ${id}: ${s} is not a support company`);
      if (o.support.length > 5) P(`template ${id}: more than five support companies`);
      if (o.regiments.reduce((a, [, n]) => a + n, 0) > 25) P(`template ${id}: more than 25 battalions`);
      try { layoutRegiments(o.regiments, s => groupOf.get(s) ?? 'infantry'); } catch (e) { P(`template ${id}: ${e.message}`); }
    }
  }
  for (const [key, prof] of Object.entries(profiles)) {
    if (!templates.has(prof.garrison) && prof.garrison) P(`profile ${key}: unknown garrison template ${prof.garrison}`);
    for (const m of prof.mix) if (!templates.has(m.t)) P(`profile ${key}: unknown template ${m.t}`);
    if (prof.arms && !archetypes.has(prof.arms)) P(`profile ${key}: unknown archetype ${prof.arms}`);
  }
  // named countries
  for (const [name, row] of Object.entries(TD.named)) {
    const c = countries.find(x => x.name === name);
    if (!c) { P(`named country ${name} is not in the roster`); continue; }
    const key = profileKey(c);
    const ids2 = Object.keys(row.mix);
    const sum = ids2.reduce((a, k) => a + row.mix[k], 0) + (row.wall?.n ?? 0);
    if (sum !== row.divisions) P(`${name}: the mix names ${sum} divisions, not ${row.divisions}`);
    for (const k of [...ids2, ...(row.wall ? [row.wall.template] : [])]) {
      const t = templates.get(k);
      if (!t) { P(`${name}: unknown template ${k}`); continue; }
      if (!peopleOk(t.people, key, name)) P(`${name}: template ${k} is not for ${key}`);
    }
    for (const s of Object.keys(row.navy ?? {})) if (!['zin_ship_galley', 'zin_ship_warship', 'zin_ship_great_warship', 'zin_ship_raider'].includes(s)) P(`${name}: unknown ship ${s}`);
  }
  for (const [k, cc] of Object.entries(TD.cultureCharacter)) if (k !== 'default' && ![...cultureOf.values()].includes(k)) P(`culture character ${k} is not a culture of the roster`);

  // AI entries
  const aiRoles = new Set(ai.roles);
  for (const r of ai.roles) if (!roles.has(r)) P(`AI role ${r} is not a template role`);
  const entryKeys = new Set();
  for (const e of ai.entries) {
    const k = `${e.people}/${e.role}`;
    if (entryKeys.has(k)) P(`AI entry ${k} is declared twice`);
    entryKeys.add(k);
    if (!aiRoles.has(e.role)) P(`AI entry ${k}: unknown role ${e.role}`);
    if (!profiles[e.people]) P(`AI entry ${k}: unknown people ${e.people}`);
    const tids = new Set(e.targets.map(t => t.id));
    if (tids.size !== e.targets.length) P(`AI entry ${k}: duplicate target id`);
    for (const t of e.targets) {
      for (const s of [...Object.keys(t.regiments), ...Object.keys(t.support)]) if (!landIds.has(s)) P(`AI entry ${k}: unknown sub-unit ${s}`);
      for (const s of Object.keys(t.support)) if (groupOf.get(s) !== 'support') P(`AI entry ${k}: ${s} is not a support company`);
      for (const s of Object.keys(t.regiments)) if (groupOf.get(s) === 'support') P(`AI entry ${k}: support company ${s} among the regiments`);
      if (t.replace && !tids.has(t.replace)) P(`AI entry ${k}: replace_with ${t.replace} is not a target of the entry`);
      for (const tok of t.enable ?? []) {
        if (tok.startsWith('tech:')) { if (!unitTech.has(tok.slice(5))) P(`AI entry ${k}: no technology unlocks ${tok.slice(5)}`); }
        else if (!(tok === 'not_tier_c' || tok.startsWith('flag:'))) P(`AI entry ${k}: unknown condition ${tok}`);
      }
    }
  }
  for (const [key] of Object.entries(profiles)) {
    if (!ai.ratios[key]) P(`no role ratios for ${key}`);
    else for (const [role, v] of Object.entries(ai.ratios[key])) {
      if (!aiRoles.has(role)) P(`ratios ${key}: unknown role ${role}`);
      if (v > 0 && !entryKeys.has(`${key}/${role}`)) P(`ratios ${key}: role ${role} has a ratio but no template entry (spec AIC1)`);
      if (['infantry', 'garrison'].includes(role) && !entryKeys.has(`${key}/${role}`)) P(`${key}: no ${role} entry (spec AIC1)`);
    }
  }
  for (const [pk, row] of Object.entries(ai.production.variants)) {
    if (!profiles[pk]) P(`production ${pk}: unknown people`);
    for (const a of Object.keys(row)) if (!archetypes.has(a)) P(`production ${pk}: unknown archetype ${a}`);
  }
  for (const a of ai.production.never) if (!archetypes.has(a)) P(`production: unknown archetype ${a} in never`);
  for (const a of Object.keys(ai.production.surplus)) if (!archetypes.has(a)) P(`production: unknown archetype ${a} in surplus`);
  for (const a of Object.keys(ai.production.minFactories)) if (!archetypes.has(a)) P(`production: unknown archetype ${a} in minFactories`);
  const shipIds = ['zin_ship_galley', 'zin_ship_warship', 'zin_ship_great_warship', 'zin_ship_raider'];
  const tfIds = new Set(ai.navy.taskforces.map(t => t.id));
  for (const t of ai.navy.taskforces) for (const s of [...Object.keys(t.min), ...Object.keys(t.optimal)]) if (!shipIds.includes(s)) P(`task force ${t.id}: ${s} is not a ZIN ship sub-unit`);
  for (const f of ai.navy.fleets) for (const s of [...Object.keys(f.required), ...Object.keys(f.optional)]) if (!tfIds.has(s)) P(`fleet ${f.id}: unknown task force ${s}`);
  const objectiveTypes = new Set(['naval_invasion_support', 'naval_invasion_defense', 'coast_defense', 'convoy_protection', 'convoy_raiding', 'naval_dominance', 'training', 'naval_blockade']);
  for (const g of ai.navy.goals) { if (!objectiveTypes.has(g.type)) P(`goal ${g.id}: unknown objective type ${g.type}`); if (!(g.min <= g.max)) P(`goal ${g.id}: min above max`); }
  for (const t of [...Object.keys(ai.research.base)]) if (!profiles[t]) P(`research ${t}: unknown people`);
  for (const f of Object.values(ai.designs.armament)) for (const l of Object.values(f)) for (const m of l) if (!naval_modules(raw).has(m)) P(`designs: unknown module ${m}`);

  // doctrines and research categories named by the strategies and plans exist
  const doctrineKeys = new Set([...raw.doctrines.grand.map(g => g.key), ...raw.doctrines.tracks.map(t => t.key)]);
  const categoryKeys = new Set(raw.civil.categories.map(c => c.key));
  for (const group of ['land', 'naval', 'air', 'tracks', 'forceConcentration']) for (const k of Object.keys(ai.doctrines[group])) if (!doctrineKeys.has(k)) P(`doctrine strategy ${group}: unknown doctrine or track ${k}`);
  for (const [p, row] of Object.entries(ai.research.base)) for (const k of Object.keys(row)) if (!categoryKeys.has(k)) P(`research ${p}: unknown research category ${k}`);
  for (const row of [ai.research.tierB, ai.research.tierC]) for (const k of Object.keys(row)) if (!categoryKeys.has(k)) P(`research tier shift: unknown research category ${k}`);
  const needOf = new Map(units.land.map(u => [u.id, u.needs]));
  const portsOf = tag => (geography.countries[tag] ?? []).filter(s => s.port);
  for (const c of countries) if (!geography.countries[c.tag]?.length) P(`${c.tag} ${c.name}: no state in the geography file (regenerate it)`);

  if (problems.length) throw new Error(`Forces data is invalid:\n  ${problems.slice(0, 40).join('\n  ')}${problems.length > 40 ? `\n  (${problems.length - 40} more)` : ''}`);
  return { raw, countries, table, assignment, packs, unlockedOf, templates, roles, profiles, groupOf, unitTech, eqTech, techByKey, needOf, profileKey, tierOf, tierA, tierB, cultureOf, popOf, share, byTag, tagOfName, portsOf, ids, eqTypes, archetypes };
}
