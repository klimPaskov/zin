const HULL_CLASS = { galley: { role: 'naval_screen', hull: 'zin_hull_galley', icon: 2 }, warship: { role: 'naval_capital', hull: 'zin_hull_warship', icon: 4 }, great: { role: 'naval_capital', hull: 'zin_hull_great_warship', icon: 5 }, raider: { role: 'naval_raider', hull: 'zin_hull_raider', icon: 3 } };
function techOfType(model, type) { return model.eqTech.get(type); }

function aiEquipment(model) {
  const ai = model.raw.ai, D = ai.designs, out = [HEADER, '# Ship designs of the AI, one default design per hull and group of peoples (docs/specs/03_gameplay/09_naval_air_doctrines.md section 10). Roles: naval_screen (galleys), naval_capital (warships and great warships), naval_raider (corsairs and black ships).'];
  const hulls = model.raw.naval.hulls;
  const mods = new Map(model.raw.naval.modules.map(m => [m.id, m]));
  const groupKey = id => id.replace('zin_ai_ships_', '');
  for (const g of D.groups) {
    const gk = groupKey(g.id), prop = D.propulsion[gk], arm = D.armament[gk];
    const forTags = g.defaultGroup ? model.countries.filter(c => !g.people.includes(model.profileKey(c)) && !g.people.includes(`country:${c.name}`)).map(c => c.tag) : model.countries.filter(c => g.people.includes(model.profileKey(c))).map(c => c.tag);
    for (const cls of ['galley', 'warship', 'great', 'raider']) {
      if (cls === 'great' && gk === 'mistake') continue;
      const hc = HULL_CLASS[cls], hull = hulls.find(h => h.id === hc.hull);
      const L = [`${g.id}_${cls} = {`, `${T(1)}category = naval`, listBlock(g.defaultGroup ? 'blocked_for' : 'available_for', forTags.sort(byEn), 1), `${T(1)}roles = {\n${T(2)}${hc.role}\n${T(1)}}`, `${T(1)}priority = {\n${T(2)}factor = ${cls === 'great' ? 2000 : 2500}\n${T(1)}}`];
      for (const v of hull.variants) {
        const type = `${hc.hull}_${v.n}`, next = hull.variants.find(x => x.n === v.n + 1);
        const nextTech = next ? techOfType(model, `${hc.hull}_${next.n}`) : null;
        const slots = [], armament = arm[cls] ?? arm.galley;
        slots.push(`${T(4)}fixed_propulsion_slot = ${v.n === 0 && cls === 'galley' ? 'zin_mod_oars' : prop[cls === 'great' ? 'warship' : cls]}`);
        for (let i = 0; i < hull.slots; i++) slots.push(`${T(4)}fixed_armament_slot_${i + 1} = ${v.n === 0 ? (gk === 'elves' ? 'zin_mod_archers_deck' : cls === 'galley' || cls === 'raider' ? 'zin_mod_ram' : 'zin_armament') : armament[i] ?? armament[armament.length - 1]}`);
        slots.push(`${T(4)}fixed_protection_slot = ${v.n === 0 ? 'zin_mod_planking' : 'zin_protection'}`);
        if (v.n > 0 && D.crew[cls]) slots.push(`${T(4)}fixed_crew_slot = ${D.crew[cls]}`);
        const allowed = [...new Set([...slots.map(s => s.split(' = ')[1]), ...[...mods.values()].filter(m => m.fits.includes(hc.hull) && !(gk !== 'elves' && m.id === 'zin_mod_elven_sails') && !(gk !== 'mistake' && m.id === 'zin_mod_black_sails')).map(m => m.id)])].filter(x => mods.has(x) || x.startsWith('zin_') && !x.startsWith('zin_mod_'));
        const designName = `${g.id}_${cls}_${v.n}`;
        L.push('', `${T(1)}${designName} = {`, `${T(2)}priority = {\n${T(3)}factor = ${10 * (v.n + 1)}${nextTech ? `\n${T(3)}modifier = {\n${T(4)}factor = 0\n${T(4)}has_tech = zin_tech_${nextTech}\n${T(3)}}` : ''}\n${T(2)}}`, `${T(2)}role_icon_index = ${hc.icon}`, `${T(2)}history = yes`, `${T(2)}target_variant = {\n${T(3)}match_value = ${1000 * (v.n + 1)}.0\n${T(3)}type = ${type}\n${T(3)}modules = {`, ...slots, `${T(3)}}`, `${T(2)}}`);
        L.push(`${T(2)}allowed_modules = {`, ...allowed.map(m => `${T(3)}${m}`), `${T(2)}}`, `${T(1)}}`);
      }
      L.push('}');
      out.push(L.join('\n'));
    }
  }
  return out.join('\n\n');
}

