// The declared pending names (docs/design/stage2/integration_r3.md, section "Pending names"): names that ZIN files use and that a module
// not yet written will define. tools/content/data/pending_names.json lists each one under its owner and spec. The final C3 pass of
// build.mjs gives each declared name that still dangles an inert stand-in (triggers false, effects empty, events hidden, ideas never
// allowed, characters unnamed, opinion modifiers worth nothing), and stops the build on:
//   - a name that dangles and is not declared (C3 stays strict: nothing is stubbed without an owner on record);
//   - a declared name that a module now defines (the owner landed: remove the row);
//   - a declared name that no ZIN file uses any more (the row is stale).
import { readFile } from 'node:fs/promises';

export const PENDING_FILE = new URL('../data/pending_names.json', import.meta.url);
const CATS = ['trigger', 'effect', 'scripted', 'event', 'character', 'idea', 'opinion_modifier', 'dynamic_modifier'];
const HEADER = '# Generated by the ZIN content builder (modules/pending_names.mjs). Inert stand-ins for names that a module not yet written will define;\n# each is declared with its owner and spec in tools/content/data/pending_names.json and vanishes when the owner lands.';

export async function loadPending(file = PENDING_FILE) {
  const data = JSON.parse(await readFile(file, 'utf8'));
  const entries = [], seen = new Map(), problems = [];
  for (const o of data.owners ?? []) {
    if (!o.id || !o.owner || !o.spec) problems.push(`an owner row lacks id, owner or spec: ${JSON.stringify(o).slice(0, 80)}`);
    for (const [cat, names] of Object.entries(o.names ?? {})) {
      if (!CATS.includes(cat)) { problems.push(`${o.id}: unknown kind ${cat}`); continue; }
      for (const name of names) {
        if (seen.has(name)) problems.push(`${name} is declared twice (${seen.get(name)}, ${o.id})`);
        seen.set(name, o.id);
        entries.push({ cat, name, owner: o.id });
      }
    }
  }
  if (problems.length) throw new Error(`data/pending_names.json:\n  ${problems.join('\n  ')}`);
  return { data, entries };
}

// A dangling reference matches a declared row of the same kind. The scan reports `scripted` for a call it cannot tell apart, and a row of
// kind trigger, effect or scripted answers it.
const matches = (row, g) => row.name === g.name && (row.cat === g.cat || (['trigger', 'effect', 'scripted'].includes(row.cat) && ['trigger', 'effect', 'scripted'].includes(g.cat)));

// dangling: groupDangling output of the final scan; defined: (cat, name) => boolean over the ZIN definitions.
export function resolvePending(pending, dangling, defined) {
  const undeclared = dangling.filter(g => g.gameFiles.size || !pending.entries.some(r => matches(r, g)));
  const landed = pending.entries.filter(r => (r.cat === 'scripted' ? defined('trigger', r.name) || defined('effect', r.name) : defined(r.cat, r.name)));
  const unused = pending.entries.filter(r => !landed.includes(r) && !dangling.some(g => matches(r, g)));
  const used = pending.entries.filter(r => !landed.includes(r) && !unused.includes(r)).map(r => ({ ...r, via: dangling.find(g => matches(r, g))?.via }));
  return { undeclared, landed, unused, used };
}

export function writePendingStandIns(staged, used, pending) {
  const owners = new Map(pending.data.owners.map(o => [o.id, o]));
  const mark = r => `# pending: ${owners.get(r.owner).owner}`;
  const by = (...cats) => used.filter(r => cats.includes(r.cat)).sort((a, b) => a.name.localeCompare(b.name, 'en'));
  const loc = {};
  const trig = by('trigger', 'scripted');
  if (trig.length) staged.text('common/scripted_triggers/zz_zin_pending_triggers.txt', `${HEADER}\n${trig.map(r => `${r.name} = { ${mark(r)}\n\talways = no\n}`).join('\n')}\n`);
  const eff = by('effect', 'scripted');
  if (eff.length) staged.text('common/scripted_effects/zz_zin_pending_effects.txt', `${HEADER}\n${eff.map(r => `${r.name} = { } ${mark(r)}`).join('\n')}\n`);
  const events = by('event');
  if (events.length) {
    loc.zin_pending_event_option = 'Continue';
    const spaces = [...new Set(events.map(r => r.name.split('.')[0]))].sort();
    staged.text('events/zz_zin_pending_events.txt', `${HEADER}\n${spaces.map(s => `add_namespace = ${s}`).join('\n')}\n${events.map(r => `${r.via ?? 'country_event'} = { ${mark(r)}\n\tid = ${r.name}\n\thidden = yes\n\tis_triggered_only = yes\n\toption = { name = zin_pending_event_option }\n}`).join('\n')}\n`);
  }
  const ideas = by('idea');
  if (ideas.length) staged.text('common/ideas/zz_zin_pending_ideas.txt', `${HEADER}\nideas = {\n\thidden_ideas = {\n${ideas.map(r => `\t\t${r.name} = { allowed = { always = no } } ${mark(r)}`).join('\n')}\n\t}\n}\n`);
  const chars = by('character');
  if (chars.length) {
    loc.ZIN_PENDING_CHARACTER = 'Unnamed';
    staged.text('common/characters/zz_zin_pending_characters.txt', `${HEADER}\ncharacters = {\n${chars.map(r => `\t${r.name} = { ${mark(r)}\n\t\tname = ZIN_PENDING_CHARACTER\n\t\tportraits = { civilian = { large = GFX_zin_portrait_men_male_1 } }\n\t}`).join('\n')}\n}\n`);
  }
  const opinions = by('opinion_modifier');
  if (opinions.length) staged.text('common/opinion_modifiers/zz_zin_pending_opinion_modifiers.txt', `${HEADER}\nopinion_modifiers = {\n${opinions.map(r => `\t${r.name} = { value = 0 } ${mark(r)}`).join('\n')}\n}\n`);
  const dyn = by('dynamic_modifier');
  if (dyn.length) staged.text('common/dynamic_modifiers/zz_zin_pending_dynamic_modifiers.txt', `${HEADER}\n${dyn.map(r => `${r.name} = { enable = { always = no } } ${mark(r)}`).join('\n')}\n`);
  if (Object.keys(loc).length) staged.loc('zin_pending', loc);
  return Object.fromEntries(CATS.map(c => [c, used.filter(r => r.cat === c).length]).filter(([, n]) => n));
}
