// The Reckoning of the Twelve and the local reckonings (docs/lore/references/calendar.md, decisions K28 and K30; how to use the
// reckonings in text: docs/design/calendar_localisation.md).
// 1. The god-months in every language folder: the engine's month keys take the names of pantheon.json through the
//    per-language formula (lib/calendar.mjs monthKeys). The start date itself is a define (modules/defines.mjs) and the
//    bookmark date comes from the same constant (lib/calendar.mjs), so the bookmark reads 1 Lumae 1748.
// 2. The local reckonings of the realms whose roster calendar is not the twelve (data/world/reckonings.json): a start-up
//    flag per realm, the scripted effect zin_reckoning_refresh that works out the month and the local year, and the scripted
//    localisation zin_reckoning_date that writes the date as that realm counts it, in the same ten language folders.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { yml } from '../lib/core.mjs';
import { GAME } from '../lib/paths.mjs';
import { MONTHS, monthKeys, START_DATE, CALENDARS, SEASON_WORDS, ORDINAL_WORDS, eraOffset, risingDay, firstRisingYear, fillForm } from '../lib/calendar.mjs';

export const LANGUAGES = ['english', 'braz_por', 'french', 'german', 'japanese', 'korean', 'polish', 'russian', 'simp_chinese', 'spanish'];
const here = path.dirname(fileURLToPath(import.meta.url));
const HEADER = '# Generated by the ZIN content builder (modules/calendar.mjs, docs/design/calendar_localisation.md). Do not edit; change tools/content/data/world/reckonings.json or pantheon.json.';

// Every month key must exist in the installed game's localisation, or the replacement would silently do nothing.
export async function assertKeysExist(keys) {
  const text = (await readFile(`${GAME}/localisation/english/core_l_english.yml`, 'utf8')) + (await readFile(`${GAME}/localisation/english/combat_l_english.yml`, 'utf8'));
  const missing = Object.keys(keys).filter(k => !new RegExp(`^ ${k}:`, 'm').test(text));
  if (missing.length) throw new Error(`Calendar keys the game does not define: ${missing.join(', ')}`);
}

// ------------------------------------------------------------------------------------------------ realms
/**
 * The game country of every roster realm that keeps its own reckoning. A realm resolves by its roster tag, then by its name,
 * then by the tag of its first former label (the realm's own entry before the roster renamed it): the roster migration moves
 * tags while this module runs. Realms the country table does not hold yet are returned as unresolved.
 */
export function resolveReckoningRealms(roster, countries) {
  const byTag = new Map(countries.map(c => [c.tag, c])), byName = new Map(countries.map(c => [c.name, c]));
  const resolved = [], unresolved = [], taken = new Map();
  for (const r of roster.realms) {
    if (!CALENDARS[r.calendar]) throw new Error(`The roster gives ${r.name} the calendar ${r.calendar}, which reckonings.json does not define`);
    if (r.calendar === 'twelve') continue;
    const former = /\(([A-Z][A-Z0-9]{2})\)$/.exec(r.formerLabels?.[0] ?? '')?.[1];
    const c = byTag.get(r.tag) ?? byName.get(r.name) ?? (former ? byTag.get(former) : undefined);
    if (!c) { unresolved.push(r.key); continue; }
    if (taken.has(c.tag)) throw new Error(`${r.name} and ${taken.get(c.tag)} both resolve to ${c.tag}`);
    taken.set(c.tag, r.name);
    resolved.push({ key: r.key, name: r.name, calendar: r.calendar, tag: c.tag });
  }
  return { resolved, unresolved };
}

// ------------------------------------------------------------------------------------------------ script
const tab = (n, s) => s.split('\n').map(l => '\t'.repeat(n) + l).join('\n');
const block = (head, lines) => `${head} = {\n${lines.map(l => tab(1, l)).join('\n')}\n}`;
const flagOf = id => `zin_calendar_${id}`;
const own = () => Object.keys(CALENDARS).filter(id => id !== 'twelve');

function risingMonth() {
  const r = risingDay();
  // The script counts whole months: the Rising must fall on the first day of its month.
  if (r.day !== 1) throw new Error(`reckonings.json puts the Rising on day ${r.day}; the scripted reckoning needs day 1`);
  return r.month;
}

export function constantsFile() {
  const lines = [HEADER, '# Tuning of the local reckonings (tools/content/data/world/reckonings.json): era offsets turn the 4A year into the local year.', 'zin_calendar = {', '\tschema = {', '\t\tany_key = yes', '\t\tdata = int', '\t}', ''];
  for (const [id, c] of Object.entries(CALENDARS)) if (c.kind === 'era') lines.push(`\t${id}_offset = ${eraOffset(id)}`);
  lines.push(`\trising_month = ${risingMonth()}`, '}');
  return lines.join('\n') + '\n';
}

export function effectsFile() {
  const month = ['set_variable = { zin_reckoning_month = 1 }'];
  for (const m of MONTHS.slice(1)) month.push(`if = { limit = { meta_trigger = { text = { NOT = { date < [Y].${m.index}.1 } } Y = "[?global.year|0]" } } set_variable = { zin_reckoning_month = ${m.index} } }`);
  const year = ['set_variable = { zin_reckoning_year = global.year }'];
  for (const [id, c] of Object.entries(CALENDARS)) {
    if (c.kind === 'era') year.push(block('if', [`limit = { has_country_flag = ${flagOf(id)} }`, `set_temp_variable = { zin_reckoning_offset = constant:zin_calendar.${id}_offset }`, 'add_to_variable = { zin_reckoning_year = zin_reckoning_offset }']));
    if (c.kind === 'reign') year.push(block('if', [`limit = { has_country_flag = ${flagOf(id)} }`,
      block('if', ['limit = { has_variable = zin_reckoning_first_rising }', 'subtract_from_variable = { zin_reckoning_year = zin_reckoning_first_rising }', 'set_temp_variable = { zin_reckoning_rising = constant:zin_calendar.rising_month }',
        'if = { limit = { NOT = { check_variable = { zin_reckoning_month < zin_reckoning_rising } } } add_to_variable = { zin_reckoning_year = 1 } }', 'clamp_variable = { var = zin_reckoning_year min = 0 }']),
      'else = { set_variable = { zin_reckoning_year = 0 } }']));
  }
  const digits = ['set_variable = { zin_reckoning_mod100 = zin_reckoning_year }', 'modulo_variable = { var = zin_reckoning_mod100 value = 100 }', 'set_variable = { zin_reckoning_units = zin_reckoning_year }', 'modulo_variable = { var = zin_reckoning_units value = 10 }',
    'set_variable = { zin_reckoning_tens = zin_reckoning_mod100 }', 'subtract_from_variable = { zin_reckoning_tens = zin_reckoning_units }', 'divide_variable = { zin_reckoning_tens = 10 }'];
  const refresh = block('zin_reckoning_refresh', ['# The month of the current date (1-12): the last month whose first day has come.', ...month,
    '# The local year: the 4A year, an era year (the Wells, the Ledger) or the Rising of the reign (0 before the first Rising or when it is not known).', ...year,
    '# The digits the ordinal texts read.', ...digits]);
  const reign = block('zin_reckoning_new_reign', [`if = { limit = { has_country_flag = ${flagOf('flood_count')} }`, '\tzin_reckoning_refresh = yes', '\tset_temp_variable = { zin_reckoning_rising = constant:zin_calendar.rising_month }', '\tset_variable = { zin_reckoning_first_rising = global.year }',
    '\tif = { limit = { check_variable = { zin_reckoning_month > zin_reckoning_rising } } add_to_variable = { zin_reckoning_first_rising = 1 } }', '\tzin_reckoning_refresh = yes', '}']);
  return [HEADER,
    '# zin_reckoning_refresh (country scope): sets zin_reckoning_month, zin_reckoning_year, zin_reckoning_mod100, zin_reckoning_units and zin_reckoning_tens',
    '# for the current date in the scope country\'s reckoning, which [This.zin_reckoning_date] then writes. Call it in the immediate block of an event',
    '# (or before any text that shows the date); it changes no game state.',
    refresh, '',
    '# zin_reckoning_new_reign (country scope): a river-king of the Count of the Floods begins his reign. He is crowned standing in the Rising: his first',
    '# Rising is this year\'s until the month of the Rising has passed, otherwise next year\'s. Call it where a flood_count realm gets a new leader.',
    reign, ''].join('\n');
}

export function triggersFile() {
  return [HEADER, '# zin_keeps_own_reckoning (country scope): the country dates by its own reckoning, not by the twelve months (decision K30).',
    block('zin_keeps_own_reckoning', [block('OR', own().filter(id => CALENDARS[id].kind !== 'twelve').map(id => `has_country_flag = ${flagOf(id)}`))]),
    ...own().map(id => `${block(`zin_keeps_reckoning_${id}`, [`has_country_flag = ${flagOf(id)}`])}`), ''].join('\n');
}

const text = (trigger, key) => `text = { ${trigger ? `trigger = { ${trigger} } ` : ''}localization_key = ${key} }`;
const defined = (name, texts) => block('defined_text', [`name = ${name}`, ...texts]);
const eq = (v, n) => `check_variable = { ${v} = ${n} }`;

export function scriptedLocFile() {
  const dateTexts = [];
  for (const id of own()) {
    const c = CALENDARS[id], flag = `has_country_flag = ${flagOf(id)}`;
    if (c.kind === 'era') dateTexts.push(text(`${flag} check_variable = { zin_reckoning_year < 1 }`, `zin_reckoning_${id}_before`));
    if (c.kind === 'reign') dateTexts.push(text(`${flag} check_variable = { zin_reckoning_year < 1 }`, `zin_reckoning_${id}_no_reign`));
    dateTexts.push(text(flag, `zin_reckoning_${id}`));
  }
  dateTexts.push(text(null, 'zin_reckoning_twelve'));
  const nameTexts = [...own().map(id => text(`has_country_flag = ${flagOf(id)}`, `zin_reckoning_${id}_name`)), text(null, 'zin_reckoning_twelve_name')];
  const seasons = Object.keys(SEASON_WORDS);
  const seasonTexts = seasons.map((s, i) => {
    const months = MONTHS.filter(m => m.season === s);
    return text(i === seasons.length - 1 ? null : `OR = { ${months.map(m => eq('zin_reckoning_month', m.index)).join(' ')} }`, `zin_reckoning_season_${s}`);
  });
  const ordinal = [text('check_variable = { zin_reckoning_year > 99 }', 'zin_reckoning_ordinal_digits')];
  for (let n = 1; n < 20; n++) ordinal.push(text(eq('zin_reckoning_year', n), `zin_reckoning_ordinal_${n}`));
  for (let t = 2; t < 10; t++) ordinal.push(text(eq('zin_reckoning_year', t * 10), `zin_reckoning_ordinal_${t * 10}`));
  ordinal.push(text(null, 'zin_reckoning_ordinal_compound'));
  return [HEADER,
    '# [This.zin_reckoning_date] writes the current date as the scope country reckons it, after zin_reckoning_refresh has run on that country;',
    '# [This.zin_reckoning_name] names the reckoning. The other texts are the parts the date is made of.',
    defined('zin_reckoning_date', dateTexts),
    defined('zin_reckoning_name', nameTexts),
    defined('zin_reckoning_month_name', [...MONTHS.slice(1).map(m => text(eq('zin_reckoning_month', m.index), m.key)), text(null, MONTHS[0].key)]),
    defined('zin_reckoning_season', seasonTexts),
    defined('zin_reckoning_muster', [...MONTHS.slice(1).map(m => text(eq('zin_reckoning_month', m.index), `zin_reckoning_muster_${m.index}`)), text(null, 'zin_reckoning_muster_1')]),
    defined('zin_reckoning_ordinal_suffix', [text('check_variable = { zin_reckoning_mod100 > 10 } check_variable = { zin_reckoning_mod100 < 14 }', 'zin_reckoning_suffix_th'),
      text(eq('zin_reckoning_units', 1), 'zin_reckoning_suffix_st'), text(eq('zin_reckoning_units', 2), 'zin_reckoning_suffix_nd'), text(eq('zin_reckoning_units', 3), 'zin_reckoning_suffix_rd'), text(null, 'zin_reckoning_suffix_th')]),
    defined('zin_reckoning_ordinal_word', ordinal),
    defined('zin_reckoning_tens_word', [...[3, 4, 5, 6, 7, 8, 9].map(t => text(eq('zin_reckoning_tens', t), `zin_reckoning_tens_${t}`)), text(null, 'zin_reckoning_tens_2')]),
    defined('zin_reckoning_units_ordinal', [...[2, 3, 4, 5, 6, 7, 8, 9].map(u => text(eq('zin_reckoning_units', u), `zin_reckoning_ordinal_${u}`)), text(null, 'zin_reckoning_ordinal_1')]),
    ''].join('\n');
}

// The loc fragment each form token becomes.
const TOKENS = {
  year: '[?global.year|0]', month: '[This.zin_reckoning_month_name]', season: '[This.zin_reckoning_season]', muster: '[This.zin_reckoning_muster]',
  leader: '[This.GetLeader]', yearOrdinal: '[?This.zin_reckoning_year|0][This.zin_reckoning_ordinal_suffix]', reignOrdinal: '[This.zin_reckoning_ordinal_word]',
};
const cap = s => s[0].toUpperCase() + s.slice(1);

/** The reckoning texts (one set, written identically in every language folder, as ZIN writes every proper name). */
export function reckoningLoc() {
  const loc = {};
  for (const [id, c] of Object.entries(CALENDARS)) {
    loc[`zin_reckoning_${id}`] = fillForm(c.form, TOKENS);
    loc[`zin_reckoning_${id}_name`] = c.name;
    if (c.formBefore) loc[`zin_reckoning_${id}_before`] = fillForm(c.formBefore, TOKENS);
    if (c.formNoReign) loc[`zin_reckoning_${id}_no_reign`] = fillForm(c.formNoReign, TOKENS);
  }
  for (const [s, w] of Object.entries(SEASON_WORDS)) loc[`zin_reckoning_season_${s}`] = w;
  const { ones, tens, tenths } = ORDINAL_WORDS;
  for (const m of MONTHS) loc[`zin_reckoning_muster_${m.index}`] = cap(ones[m.index]);
  for (let n = 1; n < 20; n++) loc[`zin_reckoning_ordinal_${n}`] = ones[n];
  for (let t = 2; t < 10; t++) { loc[`zin_reckoning_ordinal_${t * 10}`] = tenths[t]; loc[`zin_reckoning_tens_${t}`] = tens[t]; }
  loc.zin_reckoning_ordinal_compound = '[This.zin_reckoning_tens_word]-[This.zin_reckoning_units_ordinal]';
  loc.zin_reckoning_ordinal_digits = '[?This.zin_reckoning_year|0][This.zin_reckoning_ordinal_suffix]';
  for (const s of ['st', 'nd', 'rd', 'th']) loc[`zin_reckoning_suffix_${s}`] = s;
  return loc;
}

/** The start-up block: each realm's reckoning flag, the first Rising of each river-king whose Risings are written, a first refresh. */
export function startupFile(resolved) {
  const [y, m, d] = START_DATE.split('.').map(Number);
  const reigns = CALENDARS.flood_count.reigns;
  const lines = [];
  for (const r of resolved) {
    const parts = [`set_country_flag = ${flagOf(r.calendar)}`];
    if (r.calendar === 'flood_count') {
      if (!(r.key in reigns)) throw new Error(`reckonings.json gives no reign for the river-crown ${r.key}`);
      const rising = reigns[r.key].rising;
      if (rising !== null) parts.push(`set_variable = { zin_reckoning_first_rising = ${firstRisingYear(rising, { year: y, month: m, day: d })} }`);
    }
    parts.push('zin_reckoning_refresh = yes');
    lines.push(`${r.tag} = { ${parts.join(' ')} }`);
  }
  return `${HEADER}\n# The realms that keep their own reckoning (roster.json calendar), resolved to their game tags.\non_actions = {\n\ton_startup = {\n\t\teffect = {\n${lines.map(l => `\t\t\t${l}`).join('\n')}\n\t\t}\n\t}\n}\n`;
}

export async function buildCalendar(staged, ctx = {}) {
  const keyCount = Object.keys(monthKeys('english')).length;
  await assertKeysExist(monthKeys('english'));
  // The engine's month keys, per language formula; `replace` wins over the vanilla files.
  for (const lang of LANGUAGES) staged.add(`localisation/replace/zin_calendar_l_${lang}.yml`, yml(monthKeys(lang), lang));

  const roster = ctx.roster ?? JSON.parse(await readFile(path.join(here, '../data/world/roster.json'), 'utf8'));
  const countries = ctx.countries ?? JSON.parse(await readFile(path.join(here, '../data/countries.json'), 'utf8')).countries;
  const { resolved, unresolved } = resolveReckoningRealms(roster, countries);
  staged.text('common/script_constants/zin_calendar_constants.txt', constantsFile());
  staged.text('common/scripted_effects/zin_calendar.txt', effectsFile());
  staged.text('common/scripted_triggers/zin_calendar.txt', triggersFile());
  staged.text('common/scripted_localisation/zin_calendar.txt', scriptedLocFile());
  staged.text('common/on_actions/zin_calendar.txt', startupFile(resolved));
  const loc = reckoningLoc();
  for (const lang of LANGUAGES) staged.add(`localisation/${lang}/zin_reckoning_l_${lang}.yml`, yml(loc, lang));
  const byCalendar = {};
  for (const r of resolved) byCalendar[r.calendar] = (byCalendar[r.calendar] ?? 0) + 1;
  return { months: MONTHS.length, keys: keyCount, languages: LANGUAGES.length, reckonings: Object.keys(CALENDARS).length, realms: resolved.length, byCalendar, unresolved };
}
