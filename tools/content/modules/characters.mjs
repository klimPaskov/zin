// The characters of Aoaz (requirement R-65): the rulers, heirs, advisors, commanders and named figures of every realm of the roster, from
// tools/content/data/world/characters/<region>.json (conventions: docs/design/characters_part1.md and characters_part2.md), and the new
// leader and advisor traits of tools/content/data/world/character_traits.json.
//
//   const characters = await buildCharacters(staged, { countries, table })
//     stages common/characters/zin_realm_characters.txt, common/country_leader/zin_character_traits.txt and their localisation, and
//     returns { recruits: Map(tag -> [ids recruited at the start]), leaders: Map(tag -> ruler id), counts, defined, skipped }.
//
// A character another module already defines (a mechanic's court, the Dark Lands chiefs, the Afrit council) is left to that module and
// recruited by it; the data only mirrors it. Characters that a focus or an event brings into play (`recruit`) and heirs are defined but not
// recruited at the start. Design notes (`note`, `secret`, `formerName`, `definedBy`, `recruit`, `canon`) are never localised. Portraits are
// the generic portraits of the character's people (the named portraits are pending, docs/plans/zin-art/pending_from_integration.md).
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { rng, assertModifiers } from '../lib/core.mjs';
import { KIT_PEOPLE, gamePeopleOf } from '../lib/roster.mjs';
import { stanceIdeology } from './ideologies.mjs';
import { spriteName, VARIANTS } from './portraits.mjs';
import { TRAITS as GENERAL_TRAITS } from './vanilla_removal.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const CHARACTERS_DIR = path.join(here, '../data/world/characters');
export const TRAITS_FILE = path.join(here, '../data/world/character_traits.json');
const HEADER = '# Generated by the ZIN content builder (modules/characters.mjs). Do not edit by hand.';

export function rulerId(tag) { return `${tag}_zin_ruler`; }

// Every realm's court, in file order (regions alphabetically, realms as written).
export function loadCharacterData(dir = CHARACTERS_DIR) {
  return readdirSync(dir).filter(f => f.endsWith('.json')).sort().flatMap(f => JSON.parse(readFileSync(path.join(dir, f), 'utf8')).map(r => ({ ...r, region: path.basename(f, '.json') })));
}
export const loadTraitData = (file = TRAITS_FILE) => JSON.parse(readFileSync(file, 'utf8')).traits;

// The kit people of a character's portrait: the game people (lib/roster.mjs) of the character's own people. Spirits and a being of unknown
// kind take the men's portraits until their named portraits exist.
const PORTRAIT_PEOPLE = { spirits: 'men', unknown: 'men' };
export const portraitPeople = people => PORTRAIT_PEOPLE[people] ?? (KIT_PEOPLE.includes(people) ? people : gamePeopleOf(people));
// The generic portraits of a pool are shared evenly (the asset check's uniqueness rule): each character takes the least used variant of
// its people and sex, counting the characters other modules have staged; ties go to the seeded draw of the character's id.
function portraitChooser(staged) {
  const used = new Map();
  // A character counts once per portrait, however many portrait states or roles show it (as the asset check counts).
  for (const [rel, bytes] of staged.files) if (/^common\/characters\//.test(rel)) for (const block of bytes.toString('utf8').split(/^\t(?=[A-Za-z0-9_]+\s*=\s*\{)/m)) {
    for (const s of new Set([...block.matchAll(/large = "?(GFX_zin_portrait_[a-z_]+_\d+)/g)].map(m => m[1]))) used.set(s, (used.get(s) ?? 0) + 1);
  }
  return c => {
    const people = portraitPeople(c.people ?? 'men'), female = c.gender === 'female', first = Math.floor(rng(`portrait:${c.id}`)() * VARIANTS);
    const options = Array.from({ length: VARIANTS }, (_, i) => spriteName(people, female, 1 + ((first + i) % VARIANTS)));
    const pick = options.reduce((best, s) => ((used.get(s) ?? 0) < (used.get(best) ?? 0) ? s : best), options[0]);
    used.set(pick, (used.get(pick) ?? 0) + 1);
    return pick;
  };
}

const SLOTS = new Set(['political_advisor', 'theorist', 'army_chief', 'navy_chief', 'air_chief', 'high_command']);
const MILITARY_SLOTS = new Set(['army_chief', 'navy_chief', 'air_chief', 'high_command']);
const COMMANDERS = new Set(['field_marshal', 'corps_commander', 'navy_leader']);

// The ids every staged character file defines (`characters = { id = { ... } }`).
export function stagedCharacterIds(staged) {
  const ids = new Map();
  for (const [rel, bytes] of staged.files) {
    if (!/^common\/characters\/.*\.txt$/.test(rel)) continue;
    for (const m of bytes.toString('utf8').matchAll(/^\t([A-Za-z0-9_]+)\s*=\s*\{/gm)) ids.set(m[1], rel);
  }
  return ids;
}
// Trait names the staged files define, by the folder that holds them.
function stagedTraits(staged, folder) {
  const out = new Set();
  for (const [rel, bytes] of staged.files) if (rel.startsWith(`common/${folder}/`)) for (const m of bytes.toString('utf8').matchAll(/^\t{1,2}([A-Za-z0-9_]+)\s*=\s*\{/gm)) out.add(m[1]);
  return out;
}

const list = xs => `{ ${xs.join(' ')} }`;

function leaderBlock(c, ideology, descKey) {
  return [`\t\tcountry_leader = {`, `\t\t\tideology = ${ideology}`, ...(c.traits?.length ? [`\t\t\ttraits = ${list(c.traits)}`] : []), ...(descKey ? [`\t\t\tdesc = ${descKey}`] : []), `\t\t\texpire = "2000.1.1.1"`, `\t\t\tid = -1`, `\t\t}`];
}
function advisorBlock(c, tag) {
  return [`\t\tadvisor = {`, `\t\t\tslot = ${c.slot}`, `\t\t\tidea_token = ${c.id}_adv`, `\t\t\tallowed = { original_tag = ${tag} }`, ...(c.traits?.length ? [`\t\t\ttraits = ${list(c.traits)}`] : []), `\t\t\tcost = 150`, `\t\t\tai_will_do = { factor = 1 }`, `\t\t}`];
}
function commanderBlock(c) {
  const s = c.skill ?? {}, navy = c.type === 'navy_leader';
  const skills = navy ? [['skill', s.level], ['attack_skill', s.attack], ['defense_skill', s.defense], ['maneuvering_skill', s.maneuvering], ['coordination_skill', s.coordination]]
    : [['skill', s.level], ['attack_skill', s.attack], ['defense_skill', s.defense], ['planning_skill', s.planning], ['logistics_skill', s.logistics]];
  return [`\t\t${c.type} = {`, `\t\t\ttraits = ${list(c.traits ?? [])}`, ...skills.map(([k, v]) => `\t\t\t${k} = ${v ?? 1}`), `\t\t}`];
}

export async function buildCharacters(staged, { countries, data = loadCharacterData(), traits = loadTraitData() }) {
  const problems = [];
  const byKey = new Map(countries.map(c => [c.key, c]));
  const seenRealm = new Set(), seenId = new Set();
  for (const r of data) {
    const c = byKey.get(r.key);
    if (!c) { problems.push(`characters/${r.region}.json: ${r.key} is not a realm of the roster`); continue; }
    if (r.tag !== c.tag) problems.push(`${r.key}: the characters give the tag ${r.tag}, the roster ${c.tag}`);
    if (seenRealm.has(r.key)) problems.push(`${r.key} has two courts`); seenRealm.add(r.key);
  }
  for (const c of countries) if (!seenRealm.has(c.key)) problems.push(`${c.name} (${c.tag}) has no court in data/world/characters`);

  // ---- traits: the new ones are defined here; every trait a character carries must exist
  // The general leader traits of modules/vanilla_removal.mjs are staged after this module; they count as defined.
  const definedLeader = new Set([...stagedTraits(staged, 'country_leader'), ...Object.keys(GENERAL_TRAITS)]), definedUnit = stagedTraits(staged, 'unit_leader');
  const traitLines = [], loc = {};
  for (const [id, t] of Object.entries(traits)) {
    if (definedLeader.has(id)) { problems.push(`trait ${id} is defined by another module already`); continue; }
    await assertModifiers(`trait ${id}`, t.modifier);
    loc[id] = t.name;
    traitLines.push(`\t${id} = {\n\t\trandom = no\n${Object.entries(t.modifier).map(([k, v]) => `\t\t${k} = ${v}`).join('\n')}\n\t}`);
    definedLeader.add(id);
  }

  const existing = stagedCharacterIds(staged), portraitOf = portraitChooser(staged);
  const blocks = [], recruits = new Map(), leaders = new Map(), skipped = [], withAdvisors = new Set();
  const counts = { realms: 0, characters: 0, defined: 0, mirrored: 0, recruited: 0, rulers: 0, heirs: 0, advisors: 0, commanders: 0, figures: 0 };
  for (const r of data) {
    const realm = byKey.get(r.key);
    if (!realm) continue;
    counts.realms++;
    const tag = realm.tag, mine = [];
    // A court with named advisors, or one that keeps none on purpose (an open court: nothing about its counsel is invented).
    if (r.advisors.length || r.court === 'open') withAdvisors.add(tag);
    const entries = [['ruler', r.ruler], ['heir', r.heir?.id ? r.heir : null], ...r.advisors.map(a => ['advisor', a]), ...r.commanders.map(a => ['commander', a]), ...(r.figures ?? []).map(a => ['figure', a])].filter(([, c]) => c);
    for (const [role, c] of entries) {
      counts.characters++; counts[`${role}s`]++;
      if (seenId.has(c.id)) problems.push(`${c.id} is given twice`); seenId.add(c.id);
      if (!c.name) problems.push(`${c.id} has no name`);
      for (const t of c.traits ?? []) {
        if (role === 'commander' ? !definedUnit.has(t) : !definedLeader.has(t)) problems.push(`${c.id} (${r.key}) carries the trait ${t}, which no file defines`);
      }
      if (role === 'ruler') leaders.set(tag, c.id);
      if (existing.has(c.id)) { counts.mirrored++; skipped.push({ id: c.id, file: existing.get(c.id) }); continue; }
      const lines = [`\t${c.id} = {`, `\t\tname = ${c.id}`];
      const military = role === 'commander' || (role === 'advisor' && MILITARY_SLOTS.has(c.slot));
      lines.push(`\t\tportraits = {`, `\t\t\t${military ? 'army' : 'civilian'} = {`, `\t\t\t\tlarge = ${portraitOf(c)}`, `\t\t\t}`, `\t\t}`);
      loc[c.id] = c.name;
      if (role === 'ruler' || role === 'heir') {
        const stance = c.stance ?? r.stance ?? realm.stance;
        if (!stanceIdeology[stance]) problems.push(`${c.id}: the stance ${stance} is not an Aoaz stance`);
        const bio = role === 'ruler' ? c.bio : c.role ?? c.succession;
        if (role === 'ruler' && !bio) problems.push(`${c.id}: a ruler needs a biography`);
        if (bio) loc[`${c.id}_desc`] = bio;
        lines.push(...leaderBlock(c, stance, bio ? `${c.id}_desc` : null));
      } else if (role === 'advisor') {
        if (!SLOTS.has(c.slot)) problems.push(`${c.id}: unknown advisor slot ${c.slot}`);
        lines.push(...advisorBlock(c, tag));
      } else if (role === 'commander') {
        if (!COMMANDERS.has(c.type)) problems.push(`${c.id}: unknown commander type ${c.type}`);
        lines.push(...commanderBlock(c));
      }
      lines.push('\t}');
      blocks.push(lines.join('\n'));
      counts.defined++;
      if (['ruler', 'advisor', 'commander'].includes(role) && !c.recruit) mine.push(c.id);
    }
    counts.recruited += mine.length;
    recruits.set(tag, mine);
  }
  if (problems.length) throw new Error(`Characters data is invalid (${problems.length}):\n  ${problems.slice(0, 50).join('\n  ')}`);
  staged.text('common/characters/zin_realm_characters.txt', `${HEADER}\n# The courts of the realms of Aoaz (data/world/characters). Rulers and heirs carry the realm's stance; advisors may be hired only by their realm.\ncharacters = {\n${blocks.join('\n')}\n}\n`);
  staged.text('common/country_leader/zin_character_traits.txt', `${HEADER}\n# Leader and advisor traits of the characters of Aoaz (data/world/character_traits.json).\nleader_traits = {\n${traitLines.join('\n')}\n}\n`);
  staged.loc('zin_realm_characters', loc);
  return { recruits, leaders, withAdvisors, counts, skipped, traits: Object.keys(traits).length };
}
