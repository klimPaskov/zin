// A ruler character for every ZIN country, recruited by the politics step's country history
// (`recruit_character = <TAG>_zin_ruler`). Names come from the regional name pools; portraits from the people.
import { rng, cw } from '../lib/core.mjs';
import { spriteName, VARIANTS } from './portraits.mjs';

// Rulers the canon names. Everyone else gets a generated regional name.
const NAMED = { Aenor: ['The Golden King', false], Volgan: ['Volgan', false], Zol: ['The Will of Zol', false], Worshipdom: ['Aurevan the Deliverer', false], Yeldenne: ['Horos', false], 'Gala Elves': ['King Lorien', false] };

export function rulerId(tag) { return `${tag}_zin_ruler`; }

export function buildCharacters(staged, countries, table, pools) {
  const chars = {}, loc = {};
  for (const c of countries) {
    const t = table.get(c.tag), r = rng(`ruler:${c.tag}`), pool = pools.get(c.tag) ?? pools.get(c.scan);
    const female = NAMED[c.name] ? NAMED[c.name][1] : r() < 0.3;
    const given = female ? pool.female[Math.floor(r() * pool.female.length)] : pool.male[Math.floor(r() * pool.male.length)];
    const name = NAMED[c.name]?.[0] ?? `${given} ${pool.surnames[Math.floor(r() * pool.surnames.length)]}`;
    const id = rulerId(c.tag);
    loc[id] = name;
    chars[id] = { name: id, portraits: { civilian: { large: spriteName(t.people, female, 1 + Math.floor(r() * VARIANTS)) } }, country_leader: { ideology: t.stance, expire: '2000.1.1.1', id: -1 } };
  }
  staged.text('common/characters/zin_rulers.txt', `# Generated by the ZIN content builder: rulers of Erdae.\ncharacters = {\n${cw(chars, 1)}}\n`);
  staged.loc('zin_rulers', loc);
}
