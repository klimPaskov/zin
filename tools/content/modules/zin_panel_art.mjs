// Header pictures of ZIN's panels (UI overhaul lane W7; design system section 6.4; spec 01 sections 4 and 12): one 600 x 96 picture
// per panel under its title band, plus the broken-host variant of the Southern Dominion. The pictures are painted by gpt-6-luna from
// tools/content/data/ui/zin_headers.json (art/zin-header-jobs.mjs); this module only reads the tracked bands
// (art/source/ui/headers/<id>.png, 1536 x 246), fits them to the header size (cover, scale 0.39, never enlarged) and writes:
//   gfx/interface/zin/headers/<id>.dds          the textures
//   interface/zin_panels.gfx                    the sprites GFX_zin_header_<id>
//   art/source/ui/headers/<id>.png              the sources, staged for the asset provenance check
//
//   const r = await stagePanelHeaders(staged)   -> { sprites: [names], scales: { id: scale } }
import { readFile } from 'node:fs/promises';
import { dds, fromRaw } from '../lib/raster.mjs';
import { loadImage, cover, scaleOf } from '../lib/fit.mjs';
import { loadHeaderSpec, trackedHeader } from '../art/zin-header-jobs.mjs';

export const HEADER_TEXTURE = id => `gfx/interface/zin/headers/${id}.dds`;

export async function stagePanelHeaders(staged, spec = loadHeaderSpec()) {
  const [w, h] = spec.size, sprites = [], scales = {};
  for (const hd of spec.headers) {
    const file = trackedHeader(hd.id), img = await loadImage(file);
    const s = scaleOf('cover', img, w, h);
    scales[hd.id] = Math.round(s * 1000) / 1000;
    if (s > 1) throw new Error(`header ${hd.id}: the band ${img.w} x ${img.h} is smaller than ${w} x ${h}`);
    const { img: fitted } = await cover(img, w, h);
    staged.add(HEADER_TEXTURE(hd.id), dds(fromRaw(fitted.data, fitted.w, fitted.h)));
    staged.add(`art/source/ui/headers/${hd.id}.png`, await readFile(file));
    sprites.push(`\tspriteType = {\n\t\tname = "${hd.sprite}"\n\t\ttexturefile = "${HEADER_TEXTURE(hd.id)}"\n\t}`);
  }
  staged.text('interface/zin_panels.gfx', `# Generated by the ZIN content builder (tools/content/modules/zin_panel_art.mjs, data/ui/zin_headers.json). Do not edit by hand.\n# Header pictures of the ZIN panels (design system section 6.4), 600 x 96 each.\nspriteTypes = {\n${sprites.join('\n')}\n}\n`);
  return { sprites: spec.headers.map(hd => hd.sprite), scales };
}
