// Dynamic modifiers of the Noris and Stabilo trees (docs/specs/05_focus_trees/major/noris.md and stabilo.md,
// "Dynamic modifier"). The focus compiler has no block for them, so the two files are written here. The values come
// from variables the trees' scripted effects keep: zin_noris_accord_stab and zin_noris_accord_cons on Noris,
// zin_stabilo_ledger_pp and zin_stabilo_ledger_trade on Stabilo. Run it anywhere in the build; it reads nothing.
import { assertModifiers } from '../lib/core.mjs';

const HEADER = '# Generated by the ZIN content builder (modules/focus_major_c.mjs). Do not edit.';
export const DYNAMIC_MODIFIERS = {
  zin_noris_clans: {
    file: 'common/dynamic_modifiers/zin_noris.txt', icon: 'GFX_idea_zin_banner_league', name: 'The Clans of Noris',
    modifiers: { stability_factor: 'zin_noris_accord_stab', conscription_factor: 'zin_noris_accord_cons' },
  },
  zin_stabilo_ledger_income: {
    file: 'common/dynamic_modifiers/zin_stabilo.txt', icon: 'GFX_idea_zin_ledger_coins', name: 'The Ledger of the East',
    modifiers: { political_power_gain: 'zin_stabilo_ledger_pp', trade_opinion_factor: 'zin_stabilo_ledger_trade' },
  },
};

export function dynamicModifierText(id, def) {
  return [HEADER, `${id} = {`, `\ticon = ${def.icon}`, ...Object.entries(def.modifiers).map(([k, v]) => `\t${k} = ${v}`), '}', ''].join('\n');
}

export async function buildFocusMajorC(staged) {
  const loc = {};
  for (const [id, def] of Object.entries(DYNAMIC_MODIFIERS)) {
    await assertModifiers(`dynamic modifier ${id}`, def.modifiers);
    staged.text(def.file, dynamicModifierText(id, def));
    loc[id] = def.name;
  }
  staged.loc('zin_focus_major_c', loc);
  return { dynamicModifiers: Object.keys(DYNAMIC_MODIFIERS).length, files: Object.keys(DYNAMIC_MODIFIERS).length + 1 };
}
