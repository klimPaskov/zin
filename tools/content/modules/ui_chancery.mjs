const sha256 = b => createHash('sha256').update(b).digest('hex');
const ord = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const pair = v => (Array.isArray(v) ? v : [v, v]);

// ==================================================================================================== sprites
export function chanceryGfx(sprites) {
  const blocks = sprites.map(s => {
    if (s.kind === 'cornered') { const [bx, by] = pair(s.border); return `\tcorneredTileSpriteType = {\n\t\tname = "${s.name}"\n\t\tsize = { x = ${s.size[0]} y = ${s.size[1]} }\n\t\ttexturefile = "${s.texture}"\n\t\tborderSize = { x = ${bx} y = ${by} }\n\t\ttilingCenter = yes\n\t}`; }
    const n = s.cells.length;
    const extra = s.kind === 'button' ? `\n\t\tnoOfFrames = ${n}\n\t\teffectFile = "gfx/FX/buttonstate.lua"` : s.kind === 'strip' ? `\n\t\tnoOfFrames = ${n}` : '';
    return `\tspriteType = {\n\t\tname = "${s.name}"\n\t\ttexturefile = "${s.texture}"${extra}\n\t}`;
  });
  return `# Generated by the ZIN content builder (modules/ui_chancery.mjs, UI overhaul lane W2): the Chancery sprites of the politics, diplomacy,\n# decision and peace conference windows and the standard diplomatic popup, cut from the accepted chrome sheets (data/ui/chancery.json).\nspriteTypes = {\n${blocks.join('\n')}\n}\n`;
}

// ==================================================================================================== overrides
// Swaps whole sprite names (spriteType / quadTextureSprite values) inside the named top-level windows, or the whole file. A name is
// matched only as a whole word, so GFX_tiled_window never rewrites the start of GFX_tiled_window2_1b_border.
export function swapSpriteNames(text, swaps, windows) {
  const keys = Object.keys(swaps).sort((a, b) => b.length - a.length);
  const re = new RegExp(`((?:spriteType|quadTextureSprite)\\s*=\\s*"?)(${keys.join('|')})(?![A-Za-z0-9_])`, 'gi');
  const counts = {};
  const sub = s => s.replace(re, (_, a, name) => { const k = keys.find(x => x.toLowerCase() === name.toLowerCase()); counts[k] = (counts[k] ?? 0) + 1; return `${a}${swaps[k]}`; });
  if (!windows) return { text: sub(text), counts };
  const wins = topWindows(text).filter(w => windows.includes(w.name)).sort((a, b) => b.start - a.start);
  if (wins.length !== windows.length) throw new Error(`chancery: windows ${windows.join(', ')} not all found`);
  let out = text;
  for (const w of wins) out = out.slice(0, w.start) + sub(out.slice(w.start, w.end)) + out.slice(w.end);
  return { text: out, counts };
}
const HEAD = file => `# ${file}: generated by the ZIN content builder (modules/ui_chancery.mjs, UI overhaul lane W2) from the installed vanilla file.\n# Shared chrome sprites are swapped for the Chancery sprites of interface/zin_chancery.gfx; every element name and position is vanilla.\n`;

export function chanceryOverrides(spec = loadChancery(), read = f => readFileSync(`${GAME}/${f}`, 'latin1')) {
  const files = new Map(), counts = {};
  for (const [rel, o] of Object.entries(spec.overrides)) {
    const r = swapSpriteNames(read(rel), spec.swaps, o.windows);
    const n = Object.values(r.counts).reduce((a, b) => a + b, 0);
    if (n < o.min) throw new Error(`chancery: ${rel} swapped ${n} sprites, expected at least ${o.min}`);
    files.set(rel, HEAD(rel) + r.text);
    counts[rel] = r.counts;
  }
  return { files, counts };
}

// ==================================================================================================== roots and sign
// The realms of the history data with their roster tags. Only a realm whose roots and sign are established canon is shown.
export function realmLore(countries, dir = HISTORY_DIR) {
  const tagOf = new Map(countries.map(c => [c.name, c.tag]));
  const out = [];
  for (const f of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) {
    const h = JSON.parse(readFileSync(`${dir}/${f}`, 'utf8'));
    for (const c of h.countries ?? []) {
      const tag = tagOf.get(c.name);
      if (!tag) throw new Error(`chancery: realm ${c.name} (${f}) is not in the roster`);
      if (c.roots?.canon !== 'established' || c.sign?.canon !== 'established') continue;
      const text = [c.roots.story, c.sign.device, c.sign.origin, c.sign.meaning].join(' ');
      if (/[$§£@[\]]/.test(text)) throw new Error(`chancery: the lore of ${c.name} holds a localisation control character`);
      out.push({ tag, name: c.name, device: c.sign.device, origin: c.sign.origin, meaning: c.sign.meaning, roots: c.roots.story });
    }
  }
  return out.sort((a, b) => ord(a.tag, b.tag));
}
export const loreKey = tag => `zin_realm_lore_${tag}`;
// History data written before the god-months (K28) may still name a month by its former name (pantheon.json calendar.oldNames). Shown
// to the player, a former name used as a month becomes its god-month; Thaw, Sowing and Harvest stay when they are season words (the
// same reading as calendar.test.mjs: as a month after a day number or a preposition, or before a year).
const SEASONAL = new Set(['Thaw', 'Sowing', 'Harvest']);
const godMonth = name => MONTHS[FORMER_MONTHS.get(name) - 1].name;
export function currentMonths(text) {
  const coined = [...FORMER_MONTHS.keys()].filter(n => !SEASONAL.has(n));
  let out = coined.length ? text.replace(new RegExp(`\\b(${coined.join('|')})\\b`, 'g'), n => godMonth(n)) : text;
  out = out.replace(/\b(\d{1,2}|in|each|every|from|to|until|since|before|after|at|of) (Thaw|Sowing|Harvest)\b/g, (_, p, n) => `${p} ${godMonth(n)}`);
  return out.replace(/\b(Thaw|Sowing|Harvest)(,? (?:4A )?\d{3,4})\b/g, (_, n, y) => `${godMonth(n)}${y}`);
}
export const loreText = r => currentMonths(`The Sign\n${r.device}\n\n${r.origin}\n\n${r.meaning}\n\nThe Roots\n${r.roots}`);

