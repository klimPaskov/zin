// News reach (owner decision K61, 25 October 2026: "most things remain unheard"). World news is kept only for what the whole world would
// truly learn: the great wars and their fronts, the fall of great capitals, the death or crowning of the great kings and gods, the false
// god's reveal, the meter of the Gathering Dark and the endings. Every other news event of the story is shown only to the realms of the
// lands where it happens, the realms that border those lands, and the realms it involves.
//
//   applyNewsReach(staged, { countries })   build.mjs, over the finished event tree (after the focus trees and the regional decisions,
//                                            before the late characters, whose presence rewrite then covers the audiences too)
//     1. stages common/scripted_triggers/zin_news_reach.txt: zin_hears_in_<land> for every land of the roster and zin_realm_hears_of;
//     2. checks that every major news event the tree stages is classified in data/news_reach.json (world, owned by a mechanic that
//        writes its own show_major, or regional); an unclassified one stops the build, so a new world news event is a decision;
//     3. gives every regional news event its show_major (the lands and the involved realms of the data).
//     Returns { counts, regional: [{ id, file, was, now }] }.
//
// The lands are the realm-life land flags (zin_realm_land_<land>, modules/realm_life.mjs on_startup, every roster realm).
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse, scriptText } from '../lib/clausewitz.mjs';
import { DATA } from '../lib/mech_court_lib.mjs';

export const DATA_FILE = 'news_reach.json';
export const FILE = 'common/scripted_triggers/zin_news_reach.txt';
const HEADER = '# Generated by the ZIN content builder (modules/news_reach.mjs, owner decision K61). Do not edit; change tools/content/data/news_reach.json.';

export const loadNewsReach = async () => JSON.parse(await readFile(path.join(DATA, DATA_FILE), 'utf8'));
export const landTrigger = land => `zin_hears_in_${land}`;

// The triggers (pure): one per land and the general one.
export function newsReachTriggers(lands) {
  const out = [];
  for (const land of lands) out.push(`# K61: a realm of the ${land.replace(/_/g, ' ')} or a realm that borders one hears what happens there.\n${landTrigger(land)} = {\n\tOR = {\n\t\thas_country_flag = zin_realm_land_${land}\n\t\tany_neighbor_country = { has_country_flag = zin_realm_land_${land} }\n\t}\n}`);
  out.push(['# K61: the realms that would hear of what befell ROOT (the realm the news is sent to, where it happened): ROOT itself, its neighbours,',
    '# the realms of its own land, its enemies, its leaguemates, its overlord and its sworn realms. Scope: the realm that would hear (THIS);',
    '# for show_major, whose ROOT is the original recipient (Kaiserreich precedent: show_major = { is_in_faction_with = ROOT }).',
    'zin_realm_hears_of = {', '\tOR = {', '\t\ttag = ROOT', '\t\tis_neighbor_of = ROOT', '\t\thas_war_with = ROOT', '\t\tis_in_faction_with = ROOT', '\t\tis_subject_of = ROOT',
    '\t\tROOT = { is_subject_of = PREV }',
    ...lands.map(l => `\t\tAND = {\n\t\t\thas_country_flag = zin_realm_land_${l}\n\t\t\tROOT = { has_country_flag = zin_realm_land_${l} }\n\t\t}`), '\t}', '}'].join('\n'));
  return out.join('\n');
}

// The show_major body of a regional news event (pure).
export function audienceOf(row) {
  const parts = [...row.regions.map(l => `${landTrigger(l)} = yes`), ...(row.also ?? [])];
  return parts.length === 1 ? parts[0] : `OR = {\n\t${parts.join('\n\t')}\n}`;
}

// Every major news event of a staged event file: { id, start, end, showMajor } (end is the block's closing brace).
export function majorNews(text) {
  const out = [];
  for (const m of text.matchAll(/^(news_event|country_event)\s*=\s*\{/gm)) {
    let d = 0, j = m.index + m[0].length - 1;
    for (; j < text.length; j++) { if (text[j] === '{') d++; else if (text[j] === '}' && --d === 0) break; }
    const body = text.slice(m.index, j + 1);
    const top = parse(body)[0]?.v ?? [];
    if (top.find(x => x.k === 'major')?.v !== 'yes') continue;
    out.push({ id: top.find(x => x.k === 'id')?.v, start: m.index, end: j, showMajor: top.some(x => x.k === 'show_major') });
  }
  return out;
}

export async function applyNewsReach(staged, { countries, data } = {}) {
  const D = data ?? await loadNewsReach();
  const lands = [...new Set(countries.map(c => c.region))].sort();
  const problems = [];
  for (const [id, row] of Object.entries(D.regional)) for (const l of row.regions) if (!lands.includes(l)) problems.push(`${id}: ${l} is not a land of the roster`);
  staged.text(FILE, `${HEADER}\n${newsReachTriggers(lands)}\n`);
  const seen = new Set(), regional = [];
  for (const [rel, bytes] of [...staged.files]) {
    if (!/^events\/.*\.txt$/.test(rel)) continue;
    // scriptText reads the bytes as latin1 (lib/clausewitz.mjs); they are written back the same way, after a BOM if the file had one.
    const bom = bytes[0] === 0xef && bytes[1] === 0xbb && bytes[2] === 0xbf;
    let text = scriptText(bytes);
    const news = majorNews(text), before = text;
    if (!news.length) continue;
    // Insert from the last block back, so the earlier offsets hold.
    for (const n of news.sort((a, b) => b.start - a.start)) {
      seen.add(n.id);
      const row = D.regional[n.id];
      if (D.world[n.id] || D.owned[n.id]) {
        if (D.owned[n.id] && !n.showMajor) problems.push(`${n.id} (${rel}) is listed as owned but its owner writes no show_major`);
        continue;
      }
      if (!row) { problems.push(`${n.id} (${rel}) is world news that data/news_reach.json does not classify (K61: world, owned or regional)`); continue; }
      if (n.showMajor) { problems.push(`${n.id} (${rel}) already has a show_major; list it as owned`); continue; }
      const block = text.slice(n.start, n.end + 1);
      const at = block.search(/\n\s*major = yes[^\n]*/);
      const line = block.slice(at).match(/^\n\s*major = yes[^\n]*/)[0];
      const indent = line.match(/^\n(\s*)/)[1];
      const show = `${line}\n${indent}# K61: shown to the lands where it happens and the realms it involves (data/news_reach.json).\n${indent}show_major = {\n${audienceOf(row).split('\n').map(l => `${indent}\t${l}`).join('\n')}\n${indent}}`;
      text = text.slice(0, n.start) + block.slice(0, at) + show + block.slice(at + line.length) + text.slice(n.end + 1);
      regional.push({ id: n.id, file: rel, was: row.was, now: audienceOf(row).replace(/\n/g, ' ') });
    }
    if (text !== before) staged.files.set(rel, Buffer.concat([bom ? Buffer.from([0xef, 0xbb, 0xbf]) : Buffer.alloc(0), Buffer.from(text, 'latin1')]));
  }
  for (const id of [...Object.keys(D.world), ...Object.keys(D.owned), ...Object.keys(D.regional)]) if (!seen.has(id)) problems.push(`${id} is classified in data/news_reach.json but no staged event defines it as major news`);
  if (problems.length) throw new Error(`News reach (K61, data/news_reach.json):\n  ${problems.join('\n  ')}`);
  return { counts: { world: Object.keys(D.world).length, owned: Object.keys(D.owned).length, regional: regional.length, lands: lands.length }, regional: regional.sort((a, b) => a.id.localeCompare(b.id, 'en')) };
}
