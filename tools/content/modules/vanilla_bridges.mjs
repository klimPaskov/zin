// Bridges for vanilla files that stay loaded after stage 1 (spec section 5, stage 1 step 4).
// Check C3 lists every name a kept vanilla file uses that no loaded file defines any more. Each one gets a bridge:
// an inert definition of the same name (triggers always = no, effects empty, ideas and decisions never allowed,
// focuses never available, dynamic modifiers never enabled, events hidden), marked
// "# bridge: remove in stage N", where N is the stage that removes the last kept file using it. Check C4 fails a
// build whose bridges are due. Bridges carry identifiers only: no vanilla text, conditions or values, except the
// special-project constants (identifiers and numbers), which go with special projects in stage 2 (spec 3.2).
// A name used by a file that is never removed is not a bridge: it must have a permanent ZIN definition, so the
// build stops and names it. A ZIN file that names something undefined also stops the build.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse, scriptText } from '../lib/clausewitz.mjs';
import { GAME, ZIN } from '../lib/paths.mjs';
import { allGameScripts, definitions, danglingReferences, groupDangling, loadedScripts, rowsInEffect } from '../checks/vanilla_refs.mjs';

const HEADER = '# Generated by the ZIN content builder (vanilla removal bridges). Identifiers only; never shown, never fire.';

// The stage that unloads a vanilla file, or null when the file stays loaded for good.
export function removalStage(disp, rel) {
  const later = disp.rows.filter(r => r.stage > disp.currentStage);
  const stages = later.filter(r => (r.action === 'replace' && r.kind === 'folder' && r.path === path.posix.dirname(rel)) || (r.action === 'override' && r.kind === 'file' && r.path === rel)).map(r => r.stage);
  return stages.length ? Math.min(...stages) : null;
}

// The mod as the game will load it after this build: the repository's world-owned files with the staged tree on top.
export async function modFilesAfterBuild(staged, zin = ZIN) {
  const world = JSON.parse(await readFile(`${zin}/.hoi4-agent-world.json`, 'utf8'));
  const files = new Map();
  for (const f of world.files) if (/^(common|events|history)\//.test(f.relativePath) && f.relativePath.endsWith('.txt')) files.set(f.relativePath, await readFile(`${zin}/${f.relativePath}`));
  for (const [rel, bytes] of staged.files) files.set(rel, bytes);
  return files;
}

let gameScriptsCache;
const gameScripts = async () => gameScriptsCache ??= await allGameScripts();

export async function scanStaged(disp, staged) {
  const modFiles = await modFilesAfterBuild(staged);
  const loaded = await loadedScripts(disp, modFiles);
  const universe = definitions([...(await gameScripts()), ...loaded.filter(f => f.source === 'mod')]);
  return { modFiles, loaded, universe, dangling: groupDangling(danglingReferences(loaded, universe)) };
}

const serialize = (entries, depth = 0) => entries.map(e => {
  const pad = '\t'.repeat(depth);
  if (Array.isArray(e.v)) return `${pad}${e.k === null ? '' : `${e.k} = `}{\n${serialize(e.v, depth + 1)}${pad}}\n`;
  return `${pad}${e.k === null ? '' : `${e.k} ${e.op} `}${e.quoted ? JSON.stringify(e.v) : e.v}\n`;
}).join('');

export async function computeBridges(disp, staged) {
  const { dangling } = await scanStaged(disp, staged);
  const bridges = { triggers: [], effects: [], dynamicModifiers: [], other: [] }, permanent = [], zinBroken = [];
  for (const g of dangling) {
    const stages = [...g.gameFiles].map(f => removalStage(disp, f));
    if (g.modFiles.size) { zinBroken.push(`${g.cat} ${g.name} (${[...g.modFiles].slice(0, 3).join(', ')})`); continue; }
    if (stages.includes(null)) { permanent.push(`${g.cat} ${g.name} (${g.uses.slice(0, 3).join(', ')})`); continue; }
    const b = { cat: g.cat, name: g.name, stage: Math.max(...stages), via: g.via, uses: g.uses.length };
    if (g.cat === 'trigger') bridges.triggers.push(b);
    else if (g.cat === 'effect') bridges.effects.push(b);
    else if (g.cat === 'scripted') { bridges.triggers.push(b); bridges.effects.push(b); }
    else if (g.cat === 'dynamic_modifier') bridges.dynamicModifiers.push(b);
    else bridges.other.push(b);
  }
  if (zinBroken.length) throw new Error(`ZIN files name undefined definitions:\n  ${zinBroken.join('\n  ')}`);
  if (permanent.length) throw new Error(`Files that stay loaded for good name removed definitions; give each a permanent ZIN definition:\n  ${permanent.join('\n  ')}`);
  for (const k of Object.keys(bridges)) bridges[k].sort((a, b) => a.cat.localeCompare(b.cat) || a.name.localeCompare(b.name, 'en'));
  return bridges;
}
// Writes the non-script-hook bridge files; trigger, effect and dynamic modifier bridges go into the engine files.
export async function writeBridgeFiles(staged, bridges, loc) {
  const by = cat => bridges.other.filter(b => b.cat === cat);
  const mark = b => `# bridge: remove in stage ${b.stage}`;
  const ideas = by('idea');
  if (ideas.length) staged.text('common/ideas/zz_zin_bridge_ideas.txt', `${HEADER}\nideas = {\n\thidden_ideas = {\n${ideas.map(b => `\t\t${b.name} = { allowed = { always = no } } ${mark(b)}`).join('\n')}\n\t}\n}\n`);
  const focuses = by('focus'), trees = by('focus_tree');
  if (focuses.length || trees.length) staged.text('common/national_focus/zz_zin_bridge_focuses.txt', `${HEADER}\n${focuses.map(b => `shared_focus = { id = ${b.name} icon = GFX_idea_zin_people_men x = 0 y = 0 cost = 1 available = { always = no } } ${mark(b)}`).join('\n')}\n${trees.map((b, i) => `focus_tree = { ${mark(b)}\n\tid = ${b.name}\n\tcountry = { factor = 0 }\n\tdefault = no\n\tfocus = { id = zin_bridge_tree_focus_${i + 1} icon = GFX_idea_zin_people_men x = 0 y = 0 cost = 1 available = { always = no } }\n}`).join('\n')}\n`);
  const chars = by('character');
  if (chars.length) { loc.text.ZIN_BRIDGE_CHARACTER = 'Unnamed'; staged.text('common/characters/zz_zin_bridge_characters.txt', `${HEADER}\ncharacters = {\n${chars.map(b => `\t${b.name} = { name = ZIN_BRIDGE_CHARACTER portraits = { civilian = { large = GFX_zin_portrait_men_male_1 } } } ${mark(b)}`).join('\n')}\n}\n`); }
  const traits = by('trait');
  if (traits.length) staged.text('common/country_leader/zz_zin_bridge_traits.txt', `${HEADER}\nleader_traits = {\n${traits.map(b => `\t${b.name} = { random = no } ${mark(b)}`).join('\n')}\n}\n`);
  const opinion = by('opinion_modifier');
  if (opinion.length) staged.text('common/opinion_modifiers/zz_zin_bridge_opinion_modifiers.txt', `${HEADER}\nopinion_modifiers = {\n${opinion.map(b => `\t${b.name} = { value = 0 } ${mark(b)}`).join('\n')}\n}\n`);
  const cats = by('decision_category'), decisions = by('decision');
  if (cats.length || decisions.length) staged.text('common/decisions/categories/zz_zin_bridge_categories.txt', `${HEADER}\n${[...cats, ...(decisions.length ? [{ name: 'zin_bridge_category', stage: Math.max(...decisions.map(d => d.stage)) }] : [])].map(b => `${b.name} = { allowed = { always = no } visible = { always = no } } ${mark(b)}`).join('\n')}\n`);
  if (decisions.length) staged.text('common/decisions/zz_zin_bridge_decisions.txt', `${HEADER}\nzin_bridge_category = {\n${decisions.map(b => `\t${b.name} = { allowed = { always = no } visible = { always = no } available = { always = no } cost = 0 ai_will_do = { factor = 0 } } ${mark(b)}`).join('\n')}\n}\n`);
  const events = by('event');
  if (events.length) {
    loc.text.zin_bridge_event_option = 'Continue';
    const spaces = [...new Set(events.map(b => b.name.split('.')[0]))].sort();
    staged.text('events/zz_zin_bridge_events.txt', `${HEADER}\n${spaces.map(s => `add_namespace = ${s}`).join('\n')}\n${events.map(b => `${b.via ?? 'country_event'} = { id = ${b.name} hidden = yes is_triggered_only = yes option = { name = zin_bridge_event_option } } ${mark(b)}`).join('\n')}\n`);
  }
  const theaters = by('theater');
  if (theaters.length) { loc.text.ZIN_BRIDGE_THEATER = 'Unclaimed Marches'; staged.text('common/ai_faction_theaters/zz_zin_bridge_theaters.txt', `${HEADER}\n${theaters.map(b => `${b.name} = { name = ZIN_BRIDGE_THEATER regions = { 1 } ai_will_do = { base = 0 } } ${mark(b)}`).join('\n')}\n`); }
  const collections = by('collection');
  if (collections.length) {
    loc.text.ZIN_BRIDGE_COLLECTION = 'Nothing';
    const inputs = await collectionInputs();
    staged.text('common/collections/zz_zin_bridge_collections.txt', `${HEADER}\n${collections.map(b => `${b.name} = { input = ${inputs.get(b.name) ?? 'game:all_countries'} operators = { limit = { always = no } } name = ZIN_BRIDGE_COLLECTION } ${mark(b)}`).join('\n')}\n`);
  }
  await writeConstants(staged, by('constant'));
  const known = new Set(['idea', 'focus', 'focus_tree', 'character', 'trait', 'opinion_modifier', 'decision_category', 'decision', 'event', 'theater', 'collection', 'constant']);
  const unknown = bridges.other.filter(b => !known.has(b.cat));
  if (unknown.length) throw new Error(`No bridge form for ${unknown.map(b => `${b.cat} ${b.name}`).join(', ')}`);
}

// A bridged collection keeps the kind of its vanilla input (countries, states, scope), resolved through chains.
async function collectionInputs() {
  const defs = new Map();
  for (const f of (await gameScripts()).filter(f => path.posix.dirname(f.rel) === 'common/collections')) for (const e of (f.parsed ??= parse(f.text))) if (e.k && Array.isArray(e.v)) defs.set(e.k, e.v.find(x => x.k === 'input')?.v);
  const resolve = (n, depth = 0) => { const i = defs.get(n); if (!i || depth > 10) return undefined; const m = /^collection:(\w+)$/.exec(i); if (m) return resolve(m[1], depth + 1); if (i.startsWith('constant:state_groups')) return 'game:all_states'; if (i.startsWith('constant:')) return 'game:all_countries'; return /^game:\w+$/.test(i) ? i : undefined; };
  return new Map([...defs.keys()].map(n => [n, resolve(n)]));
}

// Script constants: the ZIN groups (none yet), every group of the installed special_project_constants.txt (the
// engine reads them; they go with special projects in stage 2), and empty entries for other bridged keys.
async function writeConstants(staged, constants) {
  const sp = parse(scriptText(await readFile(`${GAME}/common/script_constants/special_project_constants.txt`)));
  const spGroups = new Set(sp.map(e => e.k));
  const other = new Map();
  for (const b of constants) { const [g, k] = b.name.split('.'); if (spGroups.has(g)) continue; (other.get(g) ?? other.set(g, []).get(g)).push({ k, stage: b.stage }); }
  const vanillaSchemas = new Map();
  for (const f of (await gameScripts()).filter(f => path.posix.dirname(f.rel) === 'common/script_constants')) for (const e of (f.parsed ??= parse(f.text))) if (e.k && Array.isArray(e.v)) vanillaSchemas.set(e.k, e.v.find(x => x.k === 'schema'));
  const parts = [];
  for (const [g, keys] of [...other].sort(([a], [b]) => a.localeCompare(b))) {
    const schema = vanillaSchemas.get(g);
    parts.push(`${g} = {\n${schema ? serialize([schema], 1) : ''}${keys.sort((a, b) => a.k.localeCompare(b.k)).map(x => `\t${x.k} = { } # bridge: remove in stage ${x.stage}`).join('\n')}\n}`);
  }
  for (const e of sp) parts.push(`# bridge: remove in stage 2 (special projects)\n${serialize([e])}`.trimEnd());
  staged.text('common/script_constants/zin_constants.txt', `${HEADER.replace('Identifiers only; never shown, never fire.', 'ZIN groups and bridged groups.')}\n# The ZIN state and country groups of the mechanic specs join this file when they ship.\n${parts.join('\n')}\n`);
}
