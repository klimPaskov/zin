const STATE_CATEGORY_FILES = ['wasteland', 'enclave', 'tiny_island', 'small_island', 'pastoral', 'rural', 'large_island', 'town', 'large_town', 'city', 'large_city', 'metropolis', 'megalopolis'];
// The engine keys this module renames or defines must exist in the installed game (an unknown key is ignored silently).
export async function assertEngineKeys(data, game = GAME) {
  const bad = [];
  const res = parse(scriptText(await readFile(`${game}/common/resources/00_resources.txt`))).find(e => e.k === 'resources')?.v ?? [];
  const vanillaRes = new Map(res.filter(e => e.k && Array.isArray(e.v)).map(e => [e.k, Number(e.v.find(x => x.k === 'icon_frame')?.v)]));
  for (const r of data.resources) {
    if (!vanillaRes.has(r.key)) bad.push(`resource ${r.key}`);
    else if (vanillaRes.get(r.key) !== r.frame) bad.push(`resource ${r.key} frame ${r.frame} (the game's strip has ${vanillaRes.get(r.key)})`);
  }
  if (new Set(data.resources.map(r => r.key)).size !== vanillaRes.size) bad.push('the resource list differs from the installed game');
  const types = new Set(await buildingTypes(game));
  for (const b of data.buildings) if (!types.has(b.key)) bad.push(`building ${b.key}`);
  const cats = new Map();
  for (const f of STATE_CATEGORY_FILES) {
    const e = parse(scriptText(await readFile(`${game}/common/state_category/${f}.txt`))).find(x => x.k === 'state_categories');
    for (const c of e?.v ?? []) if (c.k) cats.set(c.k, Number(c.v.find(x => x.k === 'local_building_slots')?.v));
  }
  for (const c of data.stateCategories) {
    if (!cats.has(c.key)) bad.push(`state category ${c.key}`);
    else if (cats.get(c.key) !== c.slots) bad.push(`state category ${c.key} slots ${c.slots} (the game has ${cats.get(c.key)})`);
  }
  if (data.energy.engineResource !== 'coal' || data.energy.fuelResource !== 'oil') bad.push('energy and fuel resources (the installed defines use coal and oil)');
  if (bad.length) throw new Error(`Engine keys the game does not define: ${bad.join(', ')}`);
}

// The vanilla text sweep (modules/text_sweep.mjs, data/text/*.json) writes the interface families it owns. A key it already
// writes is left to it, so that no key is defined twice in localisation/replace.
export async function textSweepKeys() {
  const dir = path.join(here, '../data/text'), keys = new Set();
  if (!existsSync(dir)) return keys;
  for (const n of (await readdir(dir)).filter(n => n.endsWith('.json') && !/^(families|frames|banned_extra)/.test(n)).sort()) {
    const d = JSON.parse(await readFile(path.join(dir, n), 'utf8'));
    for (const k of Object.keys(d.lit ?? {})) keys.add(k);
    for (const x of [...(d.neutral ?? []), ...(d.engine ?? [])]) keys.add(typeof x === 'string' ? x : x.key);
  }
  return keys;
}

// ------------------------------------------------------------------------------------------------ the builder
export async function buildEconomy(staged, ctx = {}) {
  const { countries } = ctx, game = ctx.game ?? GAME, skip = new Set(ctx.skipLoc ?? []);
  if (!Array.isArray(countries) || !countries.length) throw new Error('buildEconomy needs the roster (ctx.countries)');
  const { data, groups } = await loadEconomy();
  await assertEngineKeys(data, game);

  const vanillaEnums = await readFile(`${game}/common/script_enums.txt`, 'utf8');
  const equipment = [...new Set([...stagedEquipmentKeys(staged), ...(ctx.equipmentKeys ?? [])])].sort();
  staged.text('common/resources/00_resources.txt', resourcesFile(data));
  staged.text('common/buildings/01_landmark_buildings.txt', landmarksFile(data));
  staged.text('common/script_enums.txt', scriptEnumsFile(vanillaEnums, equipment));
  staged.text('common/synchronized_dynamic_tokens/zin_tokens.txt', tokensFile(data, [...equipment, ...(ctx.extraTokens ?? [])]));
  staged.text('common/script_constants/zin_economy_constants.txt', constantsFile(data));
  staged.text('common/ideas/zin_economy.txt', await spiritsFile(data, game));
  staged.text('common/on_actions/zin_economy.txt', onActionsFile(data, countries));
  staged.text('common/scripted_effects/zin_economy.txt', scriptedEffectsFile(data));
  staged.text('common/scripted_triggers/zin_economy.txt', scriptedTriggersFile());
  staged.text('common/opinion_modifiers/zin_economy.txt', opinionModifiersFile());
  staged.text('common/ai_strategy/zin_economy.txt', aiStrategyFile());

  const replace = {};
  const merge = (g, entries) => {
    if (skip.has(g)) return;
    for (const [k, v] of Object.entries(entries)) { if (k in replace) throw new Error(`Text key ${k} is written twice (group ${g})`); replace[k] = v; }
  };
  for (const [g, entries] of Object.entries(generatedGroups(data))) merge(g, entries);
  for (const [g, entries] of Object.entries(groups)) merge(g, entries);
  const yielded = [];
  if (ctx.yieldToTextSweep !== false) { const sweep = await textSweepKeys(); for (const k of Object.keys(replace)) if (sweep.has(k)) { yielded.push(k); delete replace[k]; } }
  const added = newText(data);
  // Keys of ZIN's own objects (the interim landmark) are new keys, not replacements.
  for (const k of Object.keys(replace)) if (/^zin_/i.test(k)) { if (k in added) throw new Error(`Text key ${k} is written twice`); added[k] = replace[k]; delete replace[k]; }
  await assertPlayerText({ ...replace, ...added });
  staged.add('localisation/replace/zin_economy_l_english.yml', yml(replace));
  staged.add('localisation/english/zin_economy_l_english.yml', yml(added));
  return { resources: data.resources.length, buildings: data.buildings.length, stateCategories: data.stateCategories.length, spirits: data.spirits.regional.length + data.spirits.timed.length, equipmentKeys: equipment.length, replaceKeys: Object.keys(replace).length, newKeys: Object.keys(added).length, yielded: yielded.sort() };
}
