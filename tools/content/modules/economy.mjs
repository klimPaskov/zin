// Keys the installed game defines go to localisation/replace; new ZIN keys go to localisation/english. Text is kept in
// named groups so that a module that writes the same keys can switch one off (ctx.skipLoc).
export function generatedGroups(data) {
  const g = { resources: {}, buildings: {}, facilities: {}, building_modifiers: {}, state_categories: {}, landmark: {} };
  const put = (group, k, v) => { if (k in g[group]) throw new Error(`Generated text key ${k} twice`); g[group][k] = v; };
  for (const r of data.resources) {
    put('resources', `PRODUCTION_MATERIALS_${upper(r.key)}`, r.name);
    for (const p of ['state_resource_', 'temporary_state_resource_', 'country_resource_']) put('resources', `${p}${r.key}`, r.name);
    for (const p of ['state_resource_cost_', 'country_resource_cost_']) put('resources', `${p}${r.key}`, `${r.name} Use`);
    put('resources', `local_resources_${r.key}_factor`, `${r.name} Yield`);
    put('resources', `local_resources_${r.key}_factor_desc`, `Changes how much ${r.name} the state yields.`);
    put('resources', `state_resources_${r.key}_factor`, `Local Available £resources_strip|${r.frame} ${r.name}`);
    put('resources', `sabotage_${r.key}`, `Sabotage ${r.name} Stores`);
  }
  for (const b of data.buildings) {
    const group = b.owner ? 'facilities' : 'buildings';
    put(group, b.key, b.name); put(group, `${b.key}_plural`, b.plural); put(group, `${b.key}_desc`, b.desc);
  }
  for (const b of data.buildings) {
    put('building_modifiers', `modifier_production_speed_${b.key}_factor`, `§Y${b.name}§! building speed`);
    put('building_modifiers', `modifier_production_speed_${b.key}_factor_desc`, `Changes the speed at which ${b.plural} are built.`);
  }
  for (const k of ['infrastructure', 'industrial_complex', 'arms_factory', 'rail_way', 'bunker']) {
    put('building_modifiers', `modifier_repair_speed_${k}_factor`, `${data.buildings.find(x => x.key === k).name} Repair Speed`);
  }
  for (const c of data.stateCategories) { put('state_categories', `STATE_CATEGORY_${c.key}`, c.name); put('state_categories', c.key, c.name); }
  const l = data.interimLandmark;
  put('landmark', l.key, l.name); put('landmark', `${l.key}_plural`, l.name); put('landmark', `${l.key}_desc`, l.desc);
  return g;
}

