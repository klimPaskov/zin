// The text data files, merged by group. A key may be written once only.
export const TEXT_FILES = ['economy_text_core.json', 'economy_text_ui.json', 'economy_text_supply.json', 'economy_text_modifiers.json'];

export async function loadEconomy() {
  const data = await readJson('economy.json'), groups = {};
  for (const f of TEXT_FILES) {
    const t = await readJson(f);
    for (const [g, entries] of Object.entries(t.groups)) {
      if (groups[g]) throw new Error(`Text group ${g} is defined twice (${f})`);
      groups[g] = entries;
    }
  }
  return { data, groups };
}

// ---------------------------------------------------------------------------------------------- modifier checks
// The modifier documentation lists plain modifiers as '## name' and templated ones as '## <span ...></span>name_<X>_s'
// followed by 'Modified types'. Both are checked; a template instance needs a type from its list (or a building type
// the game or this module defines).
let modifierDocCache;
export async function modifierDoc(game = GAME) {
  if (modifierDocCache?.game === game) return modifierDocCache.doc;
  const text = await readFile(`${game}/documentation/modifiers_documentation.md`, 'utf8');
  const plain = new Set([...text.matchAll(/^## ([a-z0-9_]+)$/gm)].map(m => m[1])), templates = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const m = /^##\s+<span id="[^"]*"><\/span>([a-z0-9_]*)<[A-Za-z]+>([a-z0-9_]*)$/.exec(lines[i]);
    if (!m) continue;
    for (let j = i + 1; j < Math.min(lines.length, i + 14); j++) {
      const t = /\*\*Modified types\*\*: (.*)$/.exec(lines[j]);
      if (t) { templates.push({ prefix: m[1], suffix: m[2], types: new Set(t[1].split(',').map(s => s.trim())) }); break; }
      if (lines[j].startsWith('## ')) break;
    }
  }
  modifierDocCache = { game, doc: { plain, templates } };
  return modifierDocCache.doc;
}
export async function assertEconomyModifiers(where, modifiers, extraTypes = [], game = GAME) {
  const { plain, templates } = await modifierDoc(game), bad = [];
  for (const k of Object.keys(modifiers)) {
    if (plain.has(k)) continue;
    const ok = templates.some(t => k.startsWith(t.prefix) && k.endsWith(t.suffix) && k.length > t.prefix.length + t.suffix.length && (t.types.has(k.slice(t.prefix.length, k.length - t.suffix.length)) || extraTypes.includes(k.slice(t.prefix.length, k.length - t.suffix.length))));
    if (!ok) bad.push(k);
  }
  if (bad.length) throw new Error(`Unknown modifier ${bad.join(', ')} in ${where}`);
}

// ------------------------------------------------------------------------------------------------ banned words
// The text scan of the text sweep spec (data/banned_words.json): whole words, colour codes, icon codes, $VARIABLES$ and
// [calls] removed first. Error rules fail the build; review rules are reported by the tests.
let bannedCache;
export async function bannedRules() {
  if (bannedCache) return bannedCache;
  const b = await readJson('banned_words.json');
  bannedCache = b.rules.map(r => ({ id: r.id, severity: r.severity, re: new RegExp(`(?<![\\p{L}\\p{N}'])(?:${r.pattern})(?![\\p{L}\\p{N}'])`, r.caseSensitive ? 'u' : 'iu') }));
  return bannedCache;
}
export const playerText = s => s.normalize('NFKC').replace(/§./g, '').replace(/£[A-Za-z0-9_]+(?:\|\d+)?/g, '').replace(/\$[^$]*\$/g, '').replace(/\[[^\]]*\]/g, '').replace(/\\n/g, ' ');
export async function bannedHits(value, severity = 'error') {
  const t = playerText(value);
  return (await bannedRules()).filter(r => r.severity === severity && r.re.test(t)).map(r => r.id);
}

// Every value a player can read must pass the error rules of the banned list.
export async function assertPlayerText(entries) {
  const banned = [];
  for (const [k, v] of Object.entries(entries)) {
    const hits = await bannedHits(v);
    if (hits.length) banned.push(`${k}: "${v.split('\n').join(' ').slice(0, 90)}" (${hits.join(', ')})`);
  }
  if (banned.length) throw new Error(`Banned words in player text:\n  ${banned.join('\n  ')}`);
}

