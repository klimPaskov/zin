// The culture and faith layer (docs/specs/02_lore/05_world_bible.md, 08_world_in_game.md): one culture idea and one
// faith spirit per culture and faith, the people-aware trigger family, the hooks of the faiths, scripted
// localisation, the localisation, the per-state culture data and the mappings other modules read.
//
//   const culture = await buildCultures(staged, { countries });      // build.mjs, after buildPeoples
//   // culture.startup is a block of `\t\t\t<TAG> = { ... }` lines for the on_startup effect, as buildPeoples returns.
//
// A country carries its culture the way it carries its people (modules/peoples.mjs): an idea and a flag of the same name,
// set once in on_startup (P9: the value lives on the country, never in a list of tags). Flags:
//   zin_culture_<key>   dominant culture (idea of the same name)        zin_language_<id>   the language of the country
//   zin_culture2_<key>  second culture, where mixed (idea, half strength)   zin_faith_<key>     the faith (idea of the same name)
// plus the country variables zin_culture_id, zin_culture2_id, zin_faith_id and zin_language_id (the numbers of
// data/cultures_game.json) that the state triggers compare. States carry zin_state_culture, zin_state_culture2 and
// zin_state_faith, set from `resolveStateCulture` by the politics step.
import { existsSync } from 'node:fs';
