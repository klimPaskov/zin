const HEADER = '# Generated by the ZIN content builder (modules/cultures.mjs). Do not edit by hand.';
const block = (name, lines, indent = '\t') => `${name} = {\n${lines.map(l => (l === '' ? '' : indent + l)).join('\n')}\n}\n`;
const clamp = s => s.replace(/\n{3,}/g, '\n\n');

// ----------------------------------------------------------------------------------------------------- the ideas
// The picture of an idea: its own sprite when the art track has shipped one, otherwise the emblem of the people.
export const defaultPicture = (name, fallback) => (existsSync(`${ZIN}/gfx/interface/ideas/${name}.dds`) ? name : fallback);

export function ideasFile(model, pictureOf = defaultPicture) {
  const buckets = { country: {}, hidden_ideas: {} };
  const body = (mods, picture) => ({ ...(picture ? { picture } : {}), allowed: raw('{ always = no }'), allowed_civil_war: raw('{ always = yes }'), removal_cost: -1, modifier: mods });
  const put = (cat, id, idea) => { if (!buckets[cat]) throw new Error(`Unknown idea category ${cat} for ${id}`); buckets[cat][id] = idea; };
  for (const k of model.cultureKeys) {
    const cat = M.ideaCategory(model, k), people = M.peopleOf(model, k);
    put(cat, M.cultureIdea(k), body(model.game.cultures[k].modifier, cat === 'country' ? pictureOf(M.cultureIdea(k), `zin_people_${people}`) : null));
    put(M.ideaCategory(model, k, true), M.cultureIdea2(k), body(M.secondaryModifiers(model, k), null));
  }
  for (const k of model.faithKeys) {
    const f = model.game.faiths[k];
    if (!f.spirit_desc) continue;
    const firstCulture = model.cultureKeys.find(c => M.faithOfCulture(model, c) === k || model.world.cultures[c].faith_secondary === k);
    const cat = model.game.idea_category.faith;
    put(cat, M.faithIdea(k), body(f.modifier, cat === 'country' ? pictureOf(M.faithIdea(k), `zin_people_${firstCulture ? M.peopleOf(model, firstCulture) : 'men'}`) : null));
  }
  const section = (name, ideas) => (Object.keys(ideas).length ? `\t${name} = {\n${cw(ideas, 2)}\t}\n` : '');
  return `${HEADER}\n# Culture ideas (zin_culture_<key>, second culture zin_culture2_<key> at half strength) and faith spirits (zin_faith_<key>).\nideas = {\n${section('country', buckets.country)}${section('hidden_ideas', buckets.hidden_ideas)}}\n`;
}

// ------------------------------------------------------------------------------------------------- the triggers
// Country scope reads the flags; state scope reads the variables. All are generated from the data.
export function cultureTriggersFile(model) {
  const out = [HEADER, '# Country scope: zin_is_culture_<key>, zin_includes_culture_<key> (dominant or second), zin_is_language_<id>, zin_is_faith_<key>.', '# State scope: zin_state_is_culture_<key>, zin_state_includes_culture_<key>, zin_state_is_faith_<key>, and the owner comparisons.', ''];
  for (const k of model.cultureKeys) {
    out.push(block(`zin_is_culture_${k}`, [`has_country_flag = ${M.cultureFlag(k)}`]));
    out.push(block(`zin_includes_culture_${k}`, ['OR = {', `\thas_country_flag = ${M.cultureFlag(k)}`, `\thas_country_flag = ${M.culture2Flag(k)}`, '}']));
  }
  for (const id of model.languageKeys) out.push(block(`zin_is_language_${id}`, [`has_country_flag = ${M.languageFlag(id)}`]));
  for (const k of model.faithKeys) out.push(block(`zin_is_faith_${k}`, [`has_country_flag = ${M.faithFlag(k)}`]));
  for (const k of model.cultureKeys) {
    const n = M.cultureNumber(model, k);
    out.push(block(`zin_state_is_culture_${k}`, [`check_variable = { zin_state_culture = ${n} }`]));
    out.push(block(`zin_state_includes_culture_${k}`, ['OR = {', `\tcheck_variable = { zin_state_culture = ${n} }`, `\tcheck_variable = { zin_state_culture2 = ${n} }`, '}']));
  }
  for (const k of model.faithKeys) out.push(block(`zin_state_is_faith_${k}`, [`check_variable = { zin_state_faith = ${M.faithNumber(model, k)} }`]));
  // Owner comparisons (demography spec section 6): the Wall-Folk and Lake Aenorans count as one culture.
  out.push(block('zin_state_culture_matches_owner', ['owner = { check_variable = { var = zin_culture_id value = PREV.zin_state_culture compare = equals } }']));
  const kin = model.game.kin.flatMap(([a, b]) => [[a, b], [b, a]]).map(([s, o]) => `AND = { check_variable = { zin_state_culture = ${M.cultureNumber(model, s)} } owner = { check_variable = { zin_culture_id = ${M.cultureNumber(model, o)} } } }`);
  out.push(block('zin_state_culture_same_kin_as_owner', ['OR = {', '\tzin_state_culture_matches_owner = yes', ...kin.map(l => '\t' + l), '}']));
  out.push(block('zin_state_culture_foreign_to_owner', ['NOT = { zin_state_culture_same_kin_as_owner = yes }']));
  out.push(block('zin_state_faith_matches_owner', ['owner = { check_variable = { var = zin_faith_id value = PREV.zin_state_faith compare = equals } }']));
  out.push(block('zin_state_has_minority_culture', ['check_variable = { zin_state_culture2 > 0 }']));
  return clamp(out.join('\n'));
}

// Faith hooks (triggers). A festival is a timed country flag; the content tracks fire the effect on the right day.
export const festivalDays = (model, fest) => fest.days ?? model.game.limits.festival_days;
export const festivalFlag = (faith, fest) => `zin_festival_${faith}_${fest.id}`;
export function faithTriggersFile(model) {
  const out = [HEADER, '# Hooks of the faiths. zin_faith_<key>_festival_active is true while any festival of the faith runs; zin_faith_<key>_<festival>_active', '# while one does. zin_state_has_holy_site_<key> is true for a state the politics step marked with zin_holy_site_<key>.', ''];
  for (const k of model.faithKeys) {
    const f = model.game.faiths[k];
    if (f.festivals.length) {
      out.push(block(`zin_faith_${k}_festival_active`, [`has_country_flag = zin_festival_${k}_any`]));
      for (const fest of f.festivals) out.push(block(`zin_faith_${k}_${fest.id}_active`, [`has_country_flag = ${festivalFlag(k, fest)}`]));
    }
    if (f.holy_sites.length) out.push(block(`zin_state_has_holy_site_${k}`, [`has_state_flag = zin_holy_site_${k}`]));
  }
  return clamp(out.join('\n'));
}

// ------------------------------------------------------------------------------------------------- the effects
// Effects take no parameters (decision E1): the caller sets the temporary variables first.
//   set_temp_variable = { zin_arg_culture = 5 }  set_temp_variable = { zin_arg_culture2 = 0 }
//   set_temp_variable = { zin_arg_faith = 2 }    set_temp_variable = { zin_arg_language = 1 }    zin_culture_set = yes
export function cultureEffectsFile(model) {
  const { game } = model, out = [HEADER, '# zin_culture_clear removes the culture, second culture, faith and language of the country in scope.',
    '# zin_culture_set (arguments zin_arg_culture, zin_arg_culture2 (0 = none), zin_arg_faith, zin_arg_language (0 = none); numbers from data/cultures_game.json)', '# clears them and sets the new ones, for countries made at run time (civil wars, releases).', ''];
  const clear = [];
  for (const k of model.cultureKeys) clear.push(`if = { limit = { has_idea = ${M.cultureIdea(k)} } remove_ideas = ${M.cultureIdea(k)} }`, `if = { limit = { has_idea = ${M.cultureIdea2(k)} } remove_ideas = ${M.cultureIdea2(k)} }`, `clr_country_flag = ${M.cultureFlag(k)}`, `clr_country_flag = ${M.culture2Flag(k)}`);
  for (const k of model.faithKeys) { if (game.faiths[k].spirit_desc) clear.push(`if = { limit = { has_idea = ${M.faithIdea(k)} } remove_ideas = ${M.faithIdea(k)} }`); clear.push(`clr_country_flag = ${M.faithFlag(k)}`); }
  for (const id of model.languageKeys) clear.push(`clr_country_flag = ${M.languageFlag(id)}`);
  clear.push('clear_variable = zin_culture_id', 'clear_variable = zin_culture2_id', 'clear_variable = zin_faith_id', 'clear_variable = zin_language_id');
  out.push(block('zin_culture_clear', clear));
  const set = ['zin_culture_clear = yes'];
  for (const k of model.cultureKeys) {
    const n = M.cultureNumber(model, k);
    set.push(`if = { limit = { check_variable = { zin_arg_culture = ${n} } } set_country_flag = ${M.cultureFlag(k)} add_ideas = ${M.cultureIdea(k)} set_variable = { zin_culture_id = ${n} } }`);
  }
  for (const k of model.cultureKeys) {
    const n = M.cultureNumber(model, k);
    set.push(`if = { limit = { check_variable = { zin_arg_culture2 = ${n} } } set_country_flag = ${M.culture2Flag(k)} add_ideas = ${M.cultureIdea2(k)} set_variable = { zin_culture2_id = ${n} } }`);
  }
  for (const k of model.faithKeys) {
    const n = M.faithNumber(model, k), idea = game.faiths[k].spirit_desc ? ` add_ideas = ${M.faithIdea(k)}` : '';
    set.push(`if = { limit = { check_variable = { zin_arg_faith = ${n} } } set_country_flag = ${M.faithFlag(k)}${idea} set_variable = { zin_faith_id = ${n} } }`);
  }
  for (const id of model.languageKeys) {
    const n = M.languageNumber(model, id);
    set.push(`if = { limit = { check_variable = { zin_arg_language = ${n} } } set_country_flag = ${M.languageFlag(id)} set_variable = { zin_language_id = ${n} } }`);
  }
  out.push(block('zin_culture_set', set));
  return clamp(out.join('\n'));
}

// zin_faith_<key>_hold_festival (argument zin_arg_festival = the festival's position in data, from 1) opens a festival:
// a timed flag for the festival and one for the faith, both for the festival's days.
export function faithEffectsFile(model) {
  const out = [HEADER, '# zin_faith_<key>_hold_festival: set_temp_variable = { zin_arg_festival = <1..n> } first. The flags run for the festival days; content events', '# react to zin_faith_<key>_festival_active and zin_faith_<key>_<festival>_active. No effect here fires an event.', ''];
  for (const k of model.faithKeys) {
    const f = model.game.faiths[k];
    if (!f.festivals.length) continue;
    const lines = [];
    f.festivals.forEach((fest, i) => {
      const days = festivalDays(model, fest);
      lines.push(`if = { limit = { check_variable = { zin_arg_festival = ${i + 1} } } set_country_flag = { flag = ${festivalFlag(k, fest)} days = ${days} } set_country_flag = { flag = zin_festival_${k}_any days = ${days} } }`);
    });
    out.push(block(`zin_faith_${k}_hold_festival`, lines));
  }
  return clamp(out.join('\n'));
}

// ------------------------------------------------------------------------------- scripted localisation of the names
// [ROOT.zin_culture_name] in a country, [<state scope>.zin_state_culture_name] in a state. The last text of each is the fallback.
export function scriptedLocFile(model) {
  const out = [HEADER, '# Names of the culture, faith and language of a country (flags) or a state (variables).', ''];
  const def = (name, rows, fallback) => out.push(`defined_text = {\n\tname = ${name}\n${rows.map(([trig, key]) => `\ttext = { trigger = { ${trig} } localization_key = ${key} }`).join('\n')}\n\ttext = { localization_key = ${fallback} }\n}\n`);
  const C = model.cultureKeys, F = model.faithKeys, L = model.languageKeys;
  def('zin_culture_name', C.map(k => [`has_country_flag = ${M.cultureFlag(k)}`, `zin_cname_${k}`]), 'zin_cname_unknown');
  def('zin_culture_adjective', C.map(k => [`has_country_flag = ${M.cultureFlag(k)}`, `zin_cadj_${k}`]), 'zin_cadj_unknown');
  def('zin_culture_text', C.map(k => [`has_country_flag = ${M.cultureFlag(k)}`, `zin_ctext_${k}`]), 'zin_ctext_unknown');
  def('zin_culture2_name', C.map(k => [`has_country_flag = ${M.culture2Flag(k)}`, `zin_cname_${k}`]), 'zin_cname_second_none');
  def('zin_faith_name', F.map(k => [`has_country_flag = ${M.faithFlag(k)}`, `zin_fname_${k}`]), 'zin_fname_unknown');
  def('zin_faith_text', F.map(k => [`has_country_flag = ${M.faithFlag(k)}`, `zin_ftext_${k}`]), 'zin_ftext_unknown');
  def('zin_language_name', L.map(id => [`has_country_flag = ${M.languageFlag(id)}`, `zin_lname_${id}`]), 'zin_lname_unknown');
  def('zin_state_culture_name', C.map(k => [`check_variable = { zin_state_culture = ${M.cultureNumber(model, k)} }`, `zin_cname_${k}`]), 'zin_cname_unknown');
  def('zin_state_culture_adjective', C.map(k => [`check_variable = { zin_state_culture = ${M.cultureNumber(model, k)} }`, `zin_cadj_${k}`]), 'zin_cadj_unknown');
  def('zin_state_culture2_name', C.map(k => [`check_variable = { zin_state_culture2 = ${M.cultureNumber(model, k)} }`, `zin_cname_${k}`]), 'zin_cname_second_none');
  def('zin_state_faith_name', F.map(k => [`check_variable = { zin_state_faith = ${M.faithNumber(model, k)} }`, `zin_fname_${k}`]), 'zin_fname_unknown');
  return out.join('\n');
}

const countDefs = text => (text.match(/^[a-z0-9_]+ = \{$/gm) ?? []).length;

// ---------------------------------------------------------------------------------------- on_startup lines per country
// One line per country, in the layout of buildPeoples: `\t\t\t<TAG> = { ... }`.
export function startupLines(model, countries, rows) {
  return countries.map(c => {
    const r = rows.get(c.tag), ideas = [M.cultureIdea(r.culture)], parts = [];
    parts.push(`set_country_flag = ${M.cultureFlag(r.culture)}`, `set_variable = { zin_culture_id = ${M.cultureNumber(model, r.culture)} }`);
    if (r.culture2) { ideas.push(M.cultureIdea2(r.culture2)); parts.push(`set_country_flag = ${M.culture2Flag(r.culture2)}`, `set_variable = { zin_culture2_id = ${M.cultureNumber(model, r.culture2)} }`); }
    if (r.language) parts.push(`set_country_flag = ${M.languageFlag(r.language)}`, `set_variable = { zin_language_id = ${M.languageNumber(model, r.language)} }`);
    parts.push(`set_country_flag = ${M.faithFlag(r.faith)}`, `set_variable = { zin_faith_id = ${M.faithNumber(model, r.faith)} }`);
    if (model.game.faiths[r.faith].spirit_desc) ideas.push(M.faithIdea(r.faith));
    return `\t\t\t${c.tag} = { add_ideas = { ${ideas.join(' ')} } ${parts.join(' ')} }`;
  }).join('\n');
}

// ------------------------------------------------------------------------------------------------------- the build
// ctx: { countries, table?: Map of owner overrides, model?, geography?: Set of ids, pictureOf?, files? }.
export async function buildCultures(staged, ctx = {}) {
  const model = ctx.model ?? await M.loadCultureModel();
  const countries = ctx.countries ?? [];
  const geography = ctx.geography === undefined ? await loadGeographyIds() : ctx.geography;
  const result = await runCultureChecks(model, { countries, table: ctx.table ?? new Map(), geography, files: ctx.files ?? {}, modifierDocs: ctx.modifierDocs !== false });
  assertCultureChecks(result);
  if (result.warnings.length && !ctx.quiet) console.error(`Culture checks, ${result.warnings.length} warnings:\n${formatFindings(result.warnings)}`);

  staged.text('common/ideas/zin_cultures.txt', ideasFile(model, ctx.pictureOf));
  staged.text('common/scripted_triggers/zin_cultures.txt', cultureTriggersFile(model));
  staged.text('common/scripted_triggers/zin_faiths.txt', faithTriggersFile(model));
  staged.text('common/scripted_effects/zin_cultures.txt', cultureEffectsFile(model));
  staged.text('common/scripted_effects/zin_faiths.txt', faithEffectsFile(model));
  staged.text('common/scripted_localisation/zin_cultures.txt', scriptedLocFile(model));
  staged.loc('zin_cultures', M.cultureLocEntries(model));
  const mappings = M.cultureMappings(model);
  staged.text(M.STATE_CULTURES_FILE, M.keepOrderJson(model.state));
  staged.text(M.COVERAGE_FILE, M.canonicalJson(result.coverage));
  staged.text(M.MAPPINGS_FILE, M.canonicalJson({ schema: 'zin-culture-mappings/1', status: 'Generated by tools/content/modules/cultures.mjs; do not edit', cultures: mappings, chronicle: M.chronicleNames(model) }));

  const startup = startupLines(model, countries, result.resolved.rows);
  const faiths = Object.values(model.game.faiths).filter(f => f.spirit_desc).length;
  const festivals = Object.values(model.game.faiths).reduce((n, f) => n + f.festivals.length, 0);
  return {
    startup, model, mappings, coverage: result.coverage, warnings: result.warnings,
    counts: {
      countries: result.resolved.rows.size, cultures: model.cultureKeys.length, cultureIdeas: model.cultureKeys.length * 2, faithSpirits: faiths, festivals,
      triggers: countDefs(staged.files.get('common/scripted_triggers/zin_cultures.txt').toString()) + countDefs(staged.files.get('common/scripted_triggers/zin_faiths.txt').toString()),
      scriptedEffects: countDefs(staged.files.get('common/scripted_effects/zin_cultures.txt').toString()) + countDefs(staged.files.get('common/scripted_effects/zin_faiths.txt').toString()),
    },
  };
}
