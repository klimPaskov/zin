// The vanilla text sweep (docs/specs/07_interface/05_text_sweep.md). It writes ZIN text for the interface keys the
// installed game still defines: one family at a time, from data (data/text/<family>.json), the master glossary
// (data/glossary.json) and the sentence frames (data/text/frames.json). It reads the VANILLA key set and each key's
// placeholder signature (variables, scope calls, colour codes, icon codes), never its words, and refuses a row whose
// text would lose or add a placeholder. Output, waves 1 to 3: localisation/replace/zin_<family>_l_<language>.yml in all
// ten languages (the other nine copy the English values) and the people variants of the terms
// (common/scripted_localisation/zin_terms.txt, localisation/replace/zin_terms_l_<language>.yml).
//   build.mjs: const sweep = await buildTextSweep(staged);   // after buildCalendar and writeLocalisation
import { readFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { yml } from '../lib/core.mjs';
import { GAME } from '../lib/paths.mjs';
import { monthKeys } from '../lib/calendar.mjs';
import { LANGUAGES, parseLocText, readLocFile, signature, orderedVarsOf } from '../lib/loc_parse.mjs';
import { loadRuleSet, compileBanned } from '../lib/banned.mjs';
import { TextError, loadGlossary, loadFrames, makeEngine, renderFamily, termForm, indexGlossary } from '../lib/text_engine.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TEXT_DATA = path.join(here, '../data/text');
export const FAMILIES_FILE = path.join(TEXT_DATA, 'families.json');
const HEADER = '# Generated by the ZIN content builder (vanilla text sweep, docs/specs/07_interface/05_text_sweep.md).';

export async function loadFamilyTable(file = FAMILIES_FILE) { return JSON.parse(await readFile(file, 'utf8')); }

// A family's data: <family>.json plus any <family>.<part>.json (a part is another engineer's section, for example
// alerts.energy.json). Parts merge; a key written by two parts is an error.
export async function loadFamilyDef(dataDir, family) {
  if (!existsSync(dataDir)) return null;
  const names = (await readdir(dataDir)).filter(n => n === `${family}.json` || (n.startsWith(`${family}.`) && n.endsWith('.json'))).sort();
  if (!names.length) return null;
  const merged = { family, lit: {}, rows: [], neutral: [], engine: [], tokenMap: {}, phrases: {}, parts: names };
  for (const n of names) {
    const d = JSON.parse(await readFile(path.join(dataDir, n), 'utf8'));
    for (const [k, v] of Object.entries(d.lit ?? {})) {
      if (k in merged.lit) throw new TextError(`${family}: the key ${k} is written by two parts (${n} and an earlier one)`);
      merged.lit[k] = v;
    }
    merged.rows.push(...(d.rows ?? [])); merged.neutral.push(...(d.neutral ?? [])); merged.engine.push(...(d.engine ?? []));
    Object.assign(merged.tokenMap, d.tokenMap ?? {}); Object.assign(merged.phrases, d.phrases ?? {});
    if (d.drop) merged.drop = [...(merged.drop ?? []), ...d.drop];
  }
  return merged;
}

// The vanilla key table of the swept files: Map<key, { file, family, sig, vars, value? }>. `value` is kept only when
// the caller needs the installed text for a comparison (the scan) and is never written anywhere.
export async function loadVanillaTable({ dir = `${GAME}/localisation`, language = 'english', families, withValues = false }) {
  const table = new Map(), fileFamily = new Map(), perFile = new Map();
  for (const [family, def] of Object.entries(families)) {
    for (const stem of def.files) {
      const name = `${stem}_l_${language}.yml`;
      fileFamily.set(name, family);
      const file = path.join(dir, language, name);
      if (!existsSync(file)) { perFile.set(name, null); continue; }
      const entries = await readLocFile(file);
      perFile.set(name, entries.length);
      for (const { key, value } of entries) {
        if (table.has(key)) { table.get(key).alsoIn.push(name); continue; }
        const v = { key, file: name, family, sig: signature(value), vars: orderedVarsOf(value), alsoIn: [] };
        if (withValues) v.value = value;
        table.set(key, v);
      }
    }
  }
  const owner = claimsOf(families);
  for (const v of table.values()) v.family = owner(v.key, v.family);
  return { table, fileFamily, perFile };
}

// Families may claim keys by pattern whatever file they sit in (spec 05, section 5: "ownership is by key"). The
// first family that claims a key wins; every other key keeps the family its file is swept by.
export function claimsOf(families) {
  const claims = [];
  for (const [name, def] of Object.entries(families)) for (const c of def.claims ?? []) claims.push([name, new RegExp(c)]);
  return (key, fileFamily) => claims.find(([, re]) => re.test(key))?.[0] ?? fileFamily;
}

// Keys already defined by other ZIN localisation files of the staged tree (owned by other modules).
export function stagedLocKeys(staged) {
  const keys = new Map();
  for (const [rel, bytes] of staged.files) {
    if (!/^localisation\/.*_l_english\.yml$/.test(rel)) continue;
    for (const { key } of parseLocText(bytes.toString('utf8'))) if (!keys.has(key)) keys.set(key, rel);
  }
  return keys;
}

// The people variants of the glossary: scripted localisation names zin_term_<id>[_p|_lc|_lcp] and their keys.
export function peopleTerms(idx) {
  const script = [HEADER, '# One text per people flag, then the default. Used by families whose text is drawn with a country in scope.'];
  const entries = new Map();
  const suffix = { s: '', p: '_p', lc: '_lc', lcp: '_lcp' };
  let count = 0;
  for (const e of idx.glossary.entries) {
    if (!e.people || !Object.keys(e.people).length) continue;
    for (const p of Object.keys(e.people)) if (!idx.peoples.includes(p)) throw new TextError(`Glossary entry ${e.id} has a variant for the unknown people ${p}`);
    for (const form of ['s', 'p', 'lc', 'lcp']) {
      const name = `zin_term_${e.id}${suffix[form]}`;
      const blocks = Object.keys(e.people).map(p => `\ttext = {\n\t\ttrigger = { has_country_flag = zin_people_${p} }\n\t\tlocalization_key = ${name}_${p}\n\t}`);
      blocks.push(`\ttext = {\n\t\tlocalization_key = ${name}_default\n\t}`);
      script.push(`defined_text = {\n\tname = ${name}\n${blocks.join('\n')}\n}`);
      for (const p of Object.keys(e.people)) entries.set(`${name}_${p}`, termForm(e, form, p));
      entries.set(`${name}_default`, termForm(e, form));
      count++;
    }
  }
  return { script: script.join('\n') + '\n', entries, count };
}

// ------------------------------------------------------------------------------------------------ the build
// ctx (all optional; tests pass their own):
//   vanillaDir   the installed game's localisation folder (default HOI4_GAME/localisation)
//   dataDir      folder of the family files (default data/text); defs: { family: def } replaces the files
//   families     the family table (default data/text/families.json); only: ['core', ...] restricts the run
//   glossary     an indexed glossary (default data/glossary.json); frames, names: likewise
//   languages    the language list (default all ten)
//   stage        the vanilla removal stage; the whole-file conversion of stage 4 is not written here
export async function buildTextSweep(staged, ctx = {}) {
  if ((ctx.stage ?? 1) >= 4) throw new TextError('The stage 4 whole-file conversion is not implemented; the sweep writes replace files (waves 1 to 3).');
  const table = ctx.familyTable ?? await loadFamilyTable();
  const idx = ctx.glossary ?? await loadGlossary();
  const frames = ctx.frames ?? await loadFrames();
  const namesFile = path.join(path.dirname(TEXT_DATA), 'proper_names.json');
  const names = ctx.names ?? (existsSync(namesFile) ? JSON.parse(await readFile(namesFile, 'utf8')).names : null);
  const engine = makeEngine({ glossary: idx, frames, names });
  const banned = ctx.compiledBanned ?? compileBanned(await loadRuleSet({ banned: ctx.banned, extra: ctx.bannedExtra, glossary: idx }));
  const languages = ctx.languages ?? LANGUAGES;
  const dataDir = ctx.dataDir ?? TEXT_DATA;
  const wanted = Object.keys(table.families).filter(f => !ctx.only || ctx.only.includes(f));
  const defs = {};
  for (const f of wanted) {
    if (ctx.defs?.[f]) defs[f] = ctx.defs[f];
    else { const d = await loadFamilyDef(dataDir, f); if (d) defs[f] = d; }
  }
  const { table: vanilla } = await loadVanillaTable({ dir: ctx.vanillaDir ?? `${GAME}/localisation`, families: table.families });
  // Keys owned elsewhere: the months (calendar.mjs) and whatever other modules already staged.
  const owned = new Map(Object.keys(monthKeys()).map(k => [k, 'calendar.mjs']));
  for (const [k, rel] of stagedLocKeys(staged)) owned.set(k, rel);
  for (const o of table.ownership ?? []) if (o.match) { const re = new RegExp(o.match); for (const k of vanilla.keys()) if (re.test(k)) owned.set(k, o.owner); }
  for (const k of ctx.skipKeys ?? []) owned.set(k, 'caller');
  const problems = [], out = {}, claimed = new Map();
  const summary = { families: {}, files: 0, entries: 0, languages: languages.length };
  for (const family of wanted) {
    const def = defs[family];
    if (!def) { summary.families[family] = { data: false }; continue; }
    const fdef = table.families[family];
    const res = renderFamily({ ...def, family }, vanilla, engine, { scope: fdef.scope === true, family, skip: k => owned.has(k), banned });
    problems.push(...res.problems);
    const entries = {};
    for (const [k, v] of res.entries) {
      if (claimed.has(k)) { problems.push({ family, key: k, kind: 'owned_twice', detail: `already written by the ${claimed.get(k)} family (check X14)` }); continue; }
      claimed.set(k, family); entries[k] = v;
    }
    out[family] = entries;
    summary.families[family] = { data: true, written: Object.keys(entries).length, neutral: res.neutral.size, engine: res.engineKept.size, skipped: res.skipped.length, ownedElsewhere: res.skipped.filter(s => s.reason === 'owned_elsewhere').length, unresolved: res.skipped.filter(s => s.reason !== 'owned_elsewhere' && !s.reason.startsWith('unchanged')).length, unchanged: res.skipped.filter(s => s.reason.startsWith('unchanged')).length, glossaryIds: [...res.used].sort(), ...(ctx.detail ? { unresolvedList: res.skipped.filter(s => s.reason !== 'owned_elsewhere' && !s.reason.startsWith('unchanged')), written_: Object.fromEntries(Object.entries(entries)) } : {}) };
  }
  if (problems.length) {
    const lines = problems.slice(0, 25).map(p => `${p.family} ${p.key || '-'} [${p.kind}] ${p.detail}`);
    throw new TextError(`The text sweep refuses ${problems.length} rows:\n${lines.join('\n')}${problems.length > 25 ? `\n... and ${problems.length - 25} more` : ''}`);
  }
  for (const [family, entries] of Object.entries(out)) {
    if (!Object.keys(entries).length) continue;
    for (const lang of languages) staged.add(`localisation/replace/zin_${family}_l_${lang}.yml`, yml(entries, lang));
    summary.files += languages.length; summary.entries += Object.keys(entries).length;
  }
  const people = peopleTerms(idx);
  if (people.count) {
    staged.text('common/scripted_localisation/zin_terms.txt', people.script);
    for (const lang of languages) staged.add(`localisation/replace/zin_terms_l_${lang}.yml`, yml(Object.fromEntries(people.entries), lang));
    summary.files += languages.length + 1;
  }
  summary.peopleTerms = people.count;
  return summary;
}

