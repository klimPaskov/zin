//   buildUiFrontend(staged, { sheets, provenance, read })  -> { sprites, overrides, manifest, counts }
//
// Sprites: data/ui/frontend_sprites.json, cut from the accepted Banner Hall chrome sheet by the lane W5 cutter (modules/ui_dialogs.mjs
// buildDialogSprites): code crops, reduces, repeats and places generated pixels; nothing is painted. Written to interface/zin_frontend_ui.gfx,
// lineage to art/source/frontend_ui_manifest.json. Every other texture of these windows is already a Banner Hall texture of the reskin.
//
// Overrides (closed list of lib/ui_plan.mjs OVERRIDE_FILES), each the installed vanilla file with named top-level windows replaced or
// patched; every vanilla element name is kept (builder check 8), so the engine binds each control:
//   interface/frontendmainview.gui        the ZIN title plate under the emblem; Tutorial, the store and DLC list, the subscription offer,
//                                         the achievements and the career profile hidden (ZIN has no tutorial, achievements or
//                                         subscription content); the button stacks closed up
//   interface/frontendgamesetupview.gui   ten land filters on narrow Banner Hall tabs; the realm description given the room its
//                                         situation, founding and banner need, in light faces on the woad body; one name per
//                                         difficulty button (vanilla draws two)
// A hidden control keeps its name and its vanilla parent, carries `hide = yes` and sits below its window (y 2000), whose clipping cuts it
// even if the engine shows it again (the lane W5 rule).
