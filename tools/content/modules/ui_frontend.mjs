// The difficulty row of gamesetup_gameplay_settings_window: vanilla gives each of the five checkboxes a buttonText (the first one the
// wrong key) and also draws a centred label over it, so two names overlap; the checkboxes keep no text and the labels name the difficulty.
export const SETTINGS_PATCHES = [
  ['difficulty checkbox text', /(checkboxType = \{\s*name = "(?:very_easy|easy|normal|hard|very_hard)_cb"(?:(?!checkboxType)[\s\S])*?buttonText = )"FE_DIFFICULTY_[A-Z_]+"/, '$1""', 5],
];
// Applies [what, regex, replacement, count] patches inside one top-level window; each must match exactly its count.
function patchWindow(text, name, patches) {
  const win = topWindows(text).find(x => x.name === name);
  if (!win) throw new Error(`frontend: no ${name}`);
  let block = text.slice(win.start, win.end);
  for (const [what, re, rep, count = 1] of patches) {
    const g = new RegExp(re.source, 'g');
    if ((block.match(g) ?? []).length !== count) throw new Error(`frontend: the ${what} patch does not match ${name} ${count} times`);
    block = block.replace(g, rep);
  }
  return text.slice(0, win.start) + block + text.slice(win.end);
}

export function frontendOverrides(read = f => readFileSync(`${GAME}/${f}`, 'latin1')) {
  const files = new Map();
  let menu = replaceWindows(read('interface/frontendmainview.gui'), { mainmenu_panel_upperleft: MENU_UPPERLEFT, mainmenu_panel_upperright: MENU_UPPERRIGHT, mainmenu_single_player: MENU_SINGLE_PLAYER, mainmenu_panel_bottom: MENU_BOTTOM });
  for (const name of ['mainmenu_dlc_ownership', 'mainmenu_achievement_button']) {
    const w = topWindows(menu).filter(x => x.name === name);
    if (w.length !== 1) throw new Error(`frontend: ${w.length} top-level windows named ${name}`);
    menu = menu.slice(0, w[0].start) + hideWindow(menu.slice(w[0].start, w[0].end)) + menu.slice(w[0].end);
  }
  files.set('interface/frontendmainview.gui', HEAD('interface/frontendmainview.gui') + menu);
  let setup = replaceWindows(read('interface/frontendgamesetupview.gui'), { country_filter: COUNTRY_FILTER });
  setup = patchWindow(setup, 'gamesetup_interesting_countries_window', SELECTION_PATCHES);
  setup = patchWindow(setup, 'gamesetup_gameplay_settings_window', SETTINGS_PATCHES);
  files.set('interface/frontendgamesetupview.gui', HEAD('interface/frontendgamesetupview.gui') + setup);
  return files;
}

// ---------------------------------------------------------------------------------------------------- build
export async function buildUiFrontend(staged, { sheets, provenance, read, rawPath } = {}) {
  const spec = JSON.parse(readFileSync(FRONTEND_SPRITES_FILE, 'utf8'));
  const { sprites, sources } = await buildDialogSprites({ spec, sheets, provenance, ...(rawPath ? { rawPath } : {}) });
  const manifest = [];
  for (const s of sprites) {
    const bytes = dds(fromRaw(s.img.data, s.img.w, s.img.h));
    staged.add(s.texture, bytes);
    manifest.push({ out: s.texture, source: s.source, sourceSha256: s.sourceSha256, cells: [...new Set(s.cellKeys)].sort(ord), sheets: [s.sheetId], ops: [...s.ops, 'dds a8r8g8b8'], sha256: sha256(bytes) });
  }
  staged.add(FRONTEND_GFX, Buffer.from(frontendGfx(sprites)));
  const overrides = frontendOverrides(read);
  for (const [rel, text] of overrides) staged.add(rel, Buffer.from(text, 'latin1'));
  staged.add(FRONTEND_MANIFEST, Buffer.from(JSON.stringify({ generator: 'tools/content/modules/ui_frontend.mjs', files: manifest.sort((a, b) => ord(a.out, b.out)) }, null, 1) + '\n'));
  return { sprites, sources, overrides: [...overrides.keys()], manifest, counts: { sprites: sprites.length, overrides: overrides.size } };
}
