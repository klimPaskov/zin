const sha256 = b => createHash('sha256').update(b).digest('hex');
const ord = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const HIDDEN_Y = 2000;
const HEAD = file => `# ${file}: generated by the ZIN content builder (modules/ui_frontend.mjs, UI overhaul lane W6) from the installed vanilla file.\n# The windows named in the module are ZIN layouts or patches; every vanilla element name is kept so the engine binds each control.\n`;

export function frontendGfx(sprites) {
  const blocks = sprites.map(s => {
    if (s.kind === 'cornered') { const [bx, by] = Array.isArray(s.border) ? s.border : [s.border, s.border]; return `\tcorneredTileSpriteType = {\n\t\tname = "${s.name}"\n\t\tsize = { x = ${s.size[0]} y = ${s.size[1]} }\n\t\ttexturefile = "${s.texture}"\n\t\tborderSize = { x = ${bx} y = ${by} }\n\t\ttilingCenter = yes\n\t}`; }
    const extra = s.kind === 'button' ? `\n\t\tnoOfFrames = ${s.frames}\n\t\teffectFile = "gfx/FX/buttonstate.lua"` : '';
    return `\tspriteType = {\n\t\tname = "${s.name}"\n\t\ttexturefile = "${s.texture}"${extra}\n\t}`;
  });
  return `# Generated by the ZIN content builder (modules/ui_frontend.mjs, UI overhaul lane W6): sprites of the main menu and the country\n# selection, cut from the accepted Banner Hall chrome sheet (data/ui/frontend_sprites.json).\nspriteTypes = {\n${blocks.join('\n')}\n}\n`;
}

