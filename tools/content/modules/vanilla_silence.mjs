// Interim silencing of vanilla files written for single vanilla countries (data/vanilla/silenced.json). The vanilla
// tags left in stage 1, so these files name tags that no longer exist. Each one is overridden by a comment-only ZIN
// file of the same relative path, which unloads the base-game and DLC copies alike. Nothing here copies vanilla text.
import { readFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { GAME } from '../lib/paths.mjs';
import { loadJson } from '../checks/vanilla_refs.mjs';

const HEADER = '# Generated by the ZIN content builder (vanilla removal).';

export async function vanillaTags(game = GAME) {
  const text = await readFile(path.join(game, 'common/country_tags/00_countries.txt'), 'latin1');
  return new Set([...text.matchAll(/^([A-Z][A-Z0-9]{2})\s*=/gm)].map(m => m[1]));
}

// Base game first, then integrated and purchasable DLC folders: they load at the same relative paths.
async function layers(game) {
  const out = [game];
  for (const l of ['integrated_dlc', 'dlc']) {
    const dir = path.join(game, l);
    if (!existsSync(dir)) continue;
    for (const e of (await readdir(dir, { withFileTypes: true })).filter(e => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name, 'en'))) out.push(path.join(dir, e.name));
  }
  return out;
}

// A file is written for one vanilla country when a vanilla tag stands alone in its name: GER_naval.txt,
// goals_ENG.txt, 00_SOV_names.txt, LaR_FRA_operations.txt, GER.txt.
export const namesVanillaTag = (name, tags) => name.replace(/\.txt$/, '').split(/[_.\s-]+/).some(part => tags.has(part));

export async function silencedFiles({ game = GAME, data } = {}) {
  data ??= await loadJson('silenced.json');
  const tags = await vanillaTags(game), out = [], missingExtras = [];
  for (const [folder, entry] of Object.entries(data.folders).sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const names = new Set();
    for (const base of await layers(game)) {
      const dir = path.join(base, folder);
      if (!existsSync(dir)) continue;
      for (const e of await readdir(dir, { withFileTypes: true })) if (e.isFile() && e.name.endsWith('.txt')) names.add(e.name);
    }
    for (const x of entry.extra ?? []) if (!names.has(x)) missingExtras.push(`${folder}/${x}`);
    for (const name of [...names].sort((a, b) => a.localeCompare(b, 'en'))) if (namesVanillaTag(name, tags) || (entry.extra ?? []).includes(name)) out.push({ rel: `${folder}/${name}`, reason: entry.reason });
  }
  if (missingExtras.length) throw new Error(`silenced.json names files the game does not have: ${missingExtras.join(', ')}`);
  return out;
}

export async function buildSilenced(staged) {
  const files = await silencedFiles();
  for (const f of files) staged.text(f.rel, `${HEADER}\n# Silenced: this vanilla file names vanilla countries, which do not exist in ZIN (${f.reason}).\n`);
  return { silenced: files.length };
}
