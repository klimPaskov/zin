// ------------------------------------------------------------------------------------------------ story dates
// paceDate comes from lib/story_dates.mjs (R2) when that library exists; the formula is the same: a date d becomes
// start + (d - start) * pace.
let storyDates;
try { storyDates = await import('../lib/story_dates.mjs'); } catch (e) { if (e.code !== 'ERR_MODULE_NOT_FOUND') throw e; }
const toDays = d => { const [y, m, day] = d.split('.').map(Number); return Date.UTC(y, m - 1, day) / 86400000; };
const fromDays = n => { const d = new Date(n * 86400000); return `${d.getUTCFullYear()}.${d.getUTCMonth() + 1}.${d.getUTCDate()}`; };
export function paceDate(date, pace) {
  if (storyDates?.paceDate) {
    const shifted = storyDates.paceDate(date, pace);
    if (typeof shifted !== 'string' || !/^\d{4}\.\d{1,2}\.\d{1,2}$/.test(shifted)) throw new Error(`paceDate(${date}, ${pace}) did not return a date such as 1750.1.1: ${JSON.stringify(shifted)}`);
    return shifted;
  }
  const start = toDays(START_DATE.split('.').slice(0, 3).join('.'));
  return fromDays(start + Math.round((toDays(date) - start) * pace));
}

