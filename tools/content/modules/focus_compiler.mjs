// ------------------------------------------------------------------------------------------------ compile context
// C: { tree, tags (name -> tag), codes, loc, owner: { id, nameKey, tips } }
function country(C, name) { return COUNTRY_TOKENS.includes(name) ? name : C.tags.get(name); }

function argValue(C, effectId, name, val) {
  if (typeof val === 'number') return num(val);
  if (typeof val === 'object') return val.variable;
  const decl = C.tree.scripted_effects?.[effectId]?.args?.[name];
  if (decl && decl !== 'number' && decl !== 'country') return String(decl.keyword[val]);
  if (decl === 'country') return country(C, val);
  const table = codesFor(C.codes, effectId, name);
  if (table && val in table) return String(table[val]);
  return country(C, val);
}

// ------------------------------------------------------------------------------------------------ conditions
function dateLines(op, date) {
  return block('OR', flat(PACES.map(p => block('AND', [`check_variable = { global.zin_story_pace = ${num(p)} }`, `date ${op} ${paceDate(date, p)}`]))));
}
export function conditionLines(c, C) {
  const [k] = Object.keys(c), v = c[k], tree = C.tree;
  switch (k) {
    case 'flag': return [`has_country_flag = ${v}`];
    case 'not_flag': return block('NOT', [`has_country_flag = ${v}`]);
    case 'global_flag': return [`has_global_flag = ${v}`];
    case 'exists': return [`country_exists = ${country(C, v)}`];
    case 'at_war': return [`has_war = ${v ? 'yes' : 'no'}`];
    case 'at_war_with': return [`has_war_with = ${country(C, v)}`];
    case 'after': return dateLines('>', v);
    case 'before': return dateLines('<', v);
    case 'focus_done': return [`has_completed_focus = ${focusId(tree, v)}`];
    case 'spirit': return [`has_idea = ${spiritId(tree, v)}`];
    case 'ideology': return [`has_government = ${IDEOLOGY_KEYS[v]}`];
    case 'people': return [`has_country_flag = zin_people_${v}`];
    case 'rule': return block('has_game_rule', [`rule = ${v.name}`, `option = ${v.option}`]);
    case 'is_subject': return [`is_subject = ${v ? 'yes' : 'no'}`];
    case 'subject_of': return [`is_subject_of = ${country(C, v)}`];
    case 'country': return [`original_tag = ${country(C, v)}`];
    case 'region': {
      const tags = C.roster.filter(r => r.scan === v).map(r => r.tag).sort();
      return tags.length === 1 ? [`original_tag = ${tags[0]}`] : block('OR', tags.map(t => `original_tag = ${t}`));
    }
    case 'stability_above': return [`stability > ${num(v)}`];
    case 'variable': {
      const op = 'above' in v ? ['>', v.above] : 'below' in v ? ['<', v.below] : ['=', v.equals];
      return [`check_variable = { ${v.name} ${op[0]} ${num(op[1])} }`];
    }
    case 'check': return [`${v} = yes`];
    case 'not': return block('NOT', flat(v.map(x => conditionLines(x, C))));
    case 'or': return block('OR', flat(v.map(x => conditionLines(x, C))));
    case 'and': return block('AND', flat(v.map(x => conditionLines(x, C))));
    case 'raw': return rawLines(v, C);
    default: throw new Error(`unknown condition ${k}`);
  }
}
const conds = (list, C) => flat((list ?? []).map(c => conditionLines(c, C)));

function rawLines(src, C) {
  const lines = src.replace(/\r\n?/g, '\n').split('\n').map(l => l.replace(/\s+$/, ''));
  while (lines.length && !lines[0].trim()) lines.shift();
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  const indent = Math.min(...lines.filter(l => l.trim()).map(l => l.match(/^\s*/)[0].length));
  C.raw++;
  return lines.map(l => l.slice(indent).replace(/^\s+/, s => '\t'.repeat(s.replace(/\t/g, '    ').length >> 2)));
}

// ------------------------------------------------------------------------------------------------ effects
const SIMPLE = {
  political_power: v => `add_political_power = ${num(v)}`, stability: v => `add_stability = ${num(v)}`, war_support: v => `add_war_support = ${num(v)}`,
  army_experience: v => `army_experience = ${num(v)}`, navy_experience: v => `navy_experience = ${num(v)}`, air_experience: v => `air_experience = ${num(v)}`,
  manpower: v => `add_manpower = ${v}`,
};
const eventCall = (id, days) => days === undefined ? [`country_event = ${id}`] : block('country_event', [`id = ${id}`, `days = ${days}`]);
const DOCTRINE = /_doctrine$/;
const COASTAL = new Set(['coastal_bunker', 'naval_base', 'dockyard']);

function buildingLines(b, C) {
  const inner = [`type = ${b.type}`, `level = ${b.level}`, 'instant_build = yes'];
  if (PROVINCE_BUILDINGS.includes(b.type)) {
    // A province building goes into the provinces of the chosen state that fit it: coastal ones for coastal_bunker and
    // naval_base, victory-point provinces (the cities) for a bunker.
    inner.push(...block('province', ['all_provinces = yes', b.type === 'bunker' ? 'limit_to_victory_point = yes' : 'limit_to_coastal = yes']));
  }
  const build = block('add_building_construction', inner);
  if (b.where === 'capital') return block('capital_scope', build);
  const limit = [];
  if (b.where === 'random_coastal' || COASTAL.has(b.type)) limit.push('is_coastal = yes');
  if (b.where.startsWith('region:')) limit.push(`zin_is_region_${b.where.slice(7)} = yes`);
  else if (!['random_owned', 'random_coastal'].includes(b.where)) limit.push(`zin_is_site_${b.where} = yes`);
  return block('random_owned_state', [...(limit.length ? block('limit', limit) : []), ...build]);
}

function researchLines(r, C) {
  const name = C.owner.nameKey;
  const out = [];
  for (const c of r.categories.filter(x => DOCTRINE.test(x))) out.push(...block('add_doctrine_cost_reduction', [`name = ${name}`, `cost_reduction = ${num(r.bonus)}`, `uses = ${r.uses}`, `category = ${c}`]));
  const tech = r.categories.filter(x => !DOCTRINE.test(x));
  if (tech.length) out.push(...block('add_tech_bonus', [`name = ${name}`, `bonus = ${num(r.bonus)}`, `uses = ${r.uses}`, ...tech.map(c => `category = ${c}`)]));
  return out;
}

function callLines(e, C) {
  const args = e.args ?? {};
  if (e.call === 'zin_aenor_event_for_parim') {
    // An event id cannot sit in a variable: the Aenor effect saves the global event target, the event follows (F7).
    const id = eventRef(C, args.event);
    return [`${e.call} = yes`, ...block('event_target:zin_aenor_parim_realm', eventCall(id, args.days))];
  }
  return [...Object.entries(args).map(([name, val]) => `set_temp_variable = { zin_arg_${name} = ${argValue(C, e.call, name, val)} }`), `${e.call} = yes`];
}

function eventRef(C, ref) { return ref.includes('.') ? ref : eventId(C.tree, ref, C.numbers); }
const opinionRef = (C, ref) => opinionId(C.tree, ref);

export function effectLines(e, C) {
  if ('call' in e) return callLines(e, C);
  const [k] = Object.keys(e), v = e[k], tree = C.tree;
  if (k in SIMPLE) return [SIMPLE[k](v)];
  switch (k) {
    case 'add_spirit': return [`add_ideas = ${spiritId(tree, v)}`];
    case 'remove_spirit': return [`remove_ideas = ${spiritId(tree, v)}`];
    case 'swap_spirit': return block('swap_ideas', [`remove_idea = ${spiritId(tree, v[0])}`, `add_idea = ${spiritId(tree, v[1])}`]);
    case 'timed_spirit': return block('add_timed_idea', [`idea = ${spiritId(tree, v.key)}`, `days = ${v.days}`]);
    case 'event': return typeof v === 'string' ? eventCall(eventRef(C, v)) : eventCall(eventRef(C, v.key), v.days);
    case 'event_for': return block(country(C, v.country), eventCall(eventRef(C, v.key), v.days));
    case 'flag': return typeof v === 'string' ? [`set_country_flag = ${v}`] : block('set_country_flag', [`flag = ${v.name}`, `days = ${v.days}`]);
    case 'clear_flag': return [`clear_country_flag = ${v}`];
    case 'global_flag': return [`set_global_flag = ${v}`];
    case 'variable': return 'add' in v ? [`add_to_variable = { ${v.name} = ${num(v.add)} }`] : [`set_variable = { ${v.name} = ${num(v.set)} }`];
    case 'popularity': return block('add_popularity', [`ideology = ${IDEOLOGY_KEYS[v.ideology]}`, `popularity = ${num(v.value)}`]);
    case 'government': return block('set_politics', [`ruling_party = ${IDEOLOGY_KEYS[v]}`]);
    case 'building': return buildingLines(v, C);
    case 'research': return researchLines(v, C);
    case 'equipment': return block('add_equipment_to_stockpile', [`type = ${v.type}`, `amount = ${v.amount}`]);
    case 'annex': return block('annex_country', [`target = ${country(C, v)}`, 'transfer_troops = yes']);
    case 'puppet': return [`puppet = ${country(C, v)}`];
    case 'wargoal': return block('create_wargoal', [`type = ${v.type}`, `target = ${country(C, v.target)}`]);
    case 'claims_on': return block(country(C, v), block('every_owned_state', ['add_claim_by = PREV.PREV']));
    case 'cores_on': return block(country(C, v), block('every_owned_state', ['add_core_of = PREV.PREV']));
    case 'guarantee': return [`give_guarantee = ${country(C, v)}`];
    case 'non_aggression': return block('diplomatic_relation', [`country = ${country(C, v)}`, 'relation = non_aggression_pact', 'active = yes']);
    case 'opinion': {
      const id = opinionRef(C, v.modifier), t = country(C, v.target);
      return [...block('add_opinion_modifier', [`target = ${t}`, `modifier = ${id}`]), ...(v.both_ways ? block('reverse_add_opinion_modifier', [`target = ${t}`, `modifier = ${id}`]) : [])];
    }
    case 'faction': return [`create_faction_from_template = zin_faction_${v}`];
    case 'invite': return [`add_to_faction = ${country(C, v)}`];
    case 'join_faction_of': return block(country(C, v), ['add_to_faction = PREV']);
    case 'for_country': return block(country(C, v.country), effects(v.effects, C));
    case 'if': return [...block('if', [...block('limit', conds(v.limit, C)), ...effects(v.then, C)]), ...(v.else ? block('else', effects(v.else, C)) : [])];
    case 'tooltip': {
      const key = `${C.owner.tipBase}_tip_${++C.owner.tips}`;
      C.loc[key] = v;
      return [`custom_effect_tooltip = ${key}`];
    }
    case 'raw': return rawLines(v, C);
    default: throw new Error(`unknown effect ${k}`);
  }
}
const effects = (list, C) => flat((list ?? []).map(e => effectLines(e, C)));

// ------------------------------------------------------------------------------------------------ AI
function aiLines(head, ai, C, fallback) {
  if (!ai) return fallback ? block(head, [`factor = ${fallback}`]) : [];
  const mods = (ai.modifiers ?? []).map(m => block('modifier', [`${'factor' in m ? 'factor' : 'add'} = ${num(m.factor ?? m.add)}`, ...conds(m.if, C)]));
  return block(head, [`factor = ${num(ai.base ?? 1)}`, ...flat(mods)]);
}

// ------------------------------------------------------------------------------------------------ one tree
function focusLines(f, closure, C) {
  const tree = C.tree, id = focusId(tree, f.key);
  C.owner = { id, nameKey: id, tipBase: id, tips: 0 };
  const L = [`id = ${id}`];
  if (typeof f.icon === 'string') L.push(`icon = ${SPRITE.focus(f.icon)}`);
  else {
    L.push(...block('icon', [...flat((f.icon.after ?? []).map(a => block(SPRITE.focus(a.icon), [`has_global_flag = ${a.global_flag}`]))), `${SPRITE.focus(f.icon.default)} = yes`]), 'dynamic = yes');
  }
  if (f.relative_to !== undefined) L.push(`relative_position_id = ${focusId(tree, f.relative_to)}`);
  L.push(`x = ${f.x}`, `y = ${f.y}`);
  for (const g of f.prerequisite ?? []) L.push(...block('prerequisite', g.map(k => `focus = ${focusId(tree, k)}`)));
  const ex = [...closure.get(f.key)];
  if (ex.length) L.push(...block('mutually_exclusive', ex.map(k => `focus = ${focusId(tree, k)}`)));
  if (f.filters?.length) L.push(`search_filters = { ${f.filters.map(x => FILTER_TOKENS[x]).join(' ')} }`);
  L.push(`cost = ${f.days / 7}`);
  if (f.available?.length) L.push(...block('available', conds(f.available, C)));
  if (f.bypass?.length) L.push(...block('bypass', conds(f.bypass, C)));
  if (f.allow_branch?.length) L.push(...block('allow_branch', conds(f.allow_branch, C)));
  L.push(...aiLines('ai_will_do', f.ai, C, 1));
  C.loc[id] = f.name; C.loc[`${id}_desc`] = f.desc;
  const reward = effects(f.effects, C);
  if (reward.length) L.push(...block('completion_reward', reward));
  return block('focus', L);
}

function spiritLines(key, s, C) {
  const tree = C.tree, id = spiritId(tree, key);
  C.loc[id] = s.name; C.loc[`${id}_desc`] = s.desc;
  const L = [`picture = zin_${spiritIcon(tree, key)}`, 'allowed = { always = no }', 'allowed_civil_war = { always = yes }', 'removal_cost = -1'];
  if (s.cancel?.length) L.push(...block('cancel', conds(s.cancel, C)));
  const kv = o => Object.entries(o).map(([k, x]) => `${k} = ${typeof x === 'boolean' ? (x ? 'yes' : 'no') : num(x)}`);
  if (s.modifier) L.push(...block('modifier', kv(s.modifier)));
  if (s.research_bonus) L.push(...block('research_bonus', kv(s.research_bonus)));
  if (s.equipment_bonus) L.push(...block('equipment_bonus', flat(Object.entries(s.equipment_bonus).map(([type, o]) => block(type, kv(o))))));
  return block(id, L);
}

function eventLines(key, ev, C) {
  const tree = C.tree, id = eventId(tree, key, C.numbers);
  const options = ev.options.map((o, i) => {
    const nameKey = `${id}.${LETTERS[i]}`;
    C.owner = { id, nameKey, tipBase: nameKey, tips: 0 };
    const L = [];
    if (!ev.hidden) { C.loc[nameKey] = o.name; L.push(`name = ${nameKey}`); }
    if (o.ai_chance) L.push(...aiLines('ai_chance', o.ai_chance, C));
    L.push(...effects(o.effects, C));
    return L;
  });
  const L = [`id = ${id}`];
  if (ev.hidden) L.push('hidden = yes');
  else {
    C.loc[`${id}.t`] = ev.title; C.loc[`${id}.d`] = ev.desc;
    L.push(`title = ${id}.t`, `desc = ${id}.d`, `picture = ${ev.news ? SPRITE.news(ev.picture) : SPRITE.evt(ev.picture)}`);
  }
  L.push('is_triggered_only = yes', `timeout_days = ${EVENT_TIMEOUT_DAYS}`);
  if (ev.hidden) L.push(...block('immediate', options[0]));
  else options.forEach(o => L.push(...block('option', o)));
  return block(ev.news && !ev.hidden ? 'news_event' : 'country_event', L);
}

function strategyLines(s, i, C) {
  const tree = C.tree, name = `${prefixOf(tree)}ai_${i + 1}`;
  const actors = s.country === 'all' ? tree.countries : [s.country];
  const tags = actors.map(n => C.tags.get(n)).sort();
  const target = ['area_priority'].includes(s.type) ? s.target : C.tags.get(s.target);
  const allowed = tags.length === 1 ? [`original_tag = ${tags[0]}`] : block('OR', tags.map(t => `original_tag = ${t}`));
  return block(name, [
    ...block('allowed', allowed), ...block('enable', s.if?.length ? conds(s.if, C) : ['always = yes']),
    'abort_when_not_enabled = yes', ...block('ai_strategy', [`type = ${s.type}`, `id = ${target}`, `value = ${s.value}`]),
  ]);
}

// The generated opinion helper (contract pattern zin_<tree>_opinion): zin_arg_who, zin_arg_modifier (the 1-based
// position of the modifier in the block), zin_arg_both.
function opinionHelper(tree) {
  const keys = Object.keys(tree.opinion_modifiers);
  const one = (k, i) => block('if', [
    ...block('limit', [`check_variable = { zin_arg_modifier = ${i + 1} }`]),
    ...block('add_opinion_modifier', ['target = var:zin_arg_who', `modifier = ${opinionId(tree, k)}`]),
    ...block('if', [...block('limit', ['check_variable = { zin_arg_both = 1 }']), ...block('reverse_add_opinion_modifier', ['target = var:zin_arg_who', `modifier = ${opinionId(tree, k)}`])]),
  ]);
  return ['# Arguments: zin_arg_who (country), zin_arg_modifier (1-based position in the opinion_modifiers block), zin_arg_both (1 for both ways).', ...block(helperId(tree), flat(keys.map(one)))];
}

// Compiles one effective tree. Returns { files: Map path -> text, loc: { key: text }, stats }.
export function compileTree(tree, ctx) {
  const C = { tree, roster: ctx.roster, tags: new Map(ctx.roster.map(c => [c.name, c.tag])), codes: ctx.codes, loc: {}, raw: 0, numbers: eventNumbers(tree), owner: { id: '', nameKey: '', tipBase: '', tips: 0 } };
  const id = tree.id, head = HEADER(`${id}.json`), files = new Map();
  const closure = exclusiveClosure(tree);
  const { pos } = absolutePositions(tree);
  const tags = tree.countries.map(n => C.tags.get(n)).sort();
  const first = tree.focuses.find(f => !(f.prerequisite ?? []).length) ?? tree.focuses[0];
  const maxY = Math.max(...[...pos.values()].map(p => p.y));
  const focuses = tree.focuses.map(f => focusLines(f, closure, C));
  files.set(`common/national_focus/zin_${id}.txt`, text([head, ...block('focus_tree', [
    `id = zin_${id}`,
    // One modifier per country (shared-tree spec): the tree scores 10 for each original tag it serves, 0 for the rest.
    ...block('country', ['factor = 0', ...flat(tags.map(t => block('modifier', ['add = 10', `original_tag = ${t}`])))]),
    `initial_show_position = { focus = ${focusId(tree, first.key)} }`,
    `continuous_focus_position = { x = 50 y = ${Math.max(1000, (maxY + 2) * 130)} }`,
    ...flat(focuses),
  ])]));
  const spirits = Object.entries(tree.spirits ?? {});
  if (spirits.length) files.set(`common/ideas/zin_focus_${id}.txt`, text([head, ...block('ideas', block('country', flat(spirits.map(([k, s]) => spiritLines(k, s, C)))))]));
  const events = Object.entries(tree.events ?? {});
  if (events.length) files.set(`events/zin_${id}.txt`, text([head, `add_namespace = ${namespaceOf(tree)}`, '', ...flat(events.map(([k, ev]) => [...eventLines(k, ev, C), '']))].slice(0, -1)));
  const declared = Object.entries(tree.scripted_effects ?? {});
  const withHelper = Object.keys(tree.opinion_modifiers ?? {}).length > 0;
  if (declared.length || withHelper) {
    const body = declared.map(([eid, se]) => {
      C.owner = { id: eid, nameKey: eid, tipBase: eid, tips: 0 };
      const argNote = se.args && Object.keys(se.args).length ? [`# Arguments: ${Object.entries(se.args).map(([n, kind]) => `zin_arg_${n} (${kind === 'number' || kind === 'country' ? kind : `keyword ${Object.entries(kind.keyword).map(([w, c]) => `${w} ${c}`).join(', ')}`})`).join('; ')}.`] : [];
      return [...argNote, ...block(eid, effects(se.effects, C))];
    });
    if (withHelper) body.push(opinionHelper(tree));
    files.set(`common/scripted_effects/zin_${id}.txt`, text([head, ...flat(body.map((b, i) => (i ? ['', ...b] : b)))]));
  }
  const triggers = Object.entries(tree.scripted_triggers ?? {});
  if (triggers.length) files.set(`common/scripted_triggers/zin_${id}.txt`, text([head, ...flat(triggers.map(([tid, t]) => block(tid, conds(t.conditions, C))))]));
  const opinions = Object.entries(tree.opinion_modifiers ?? {});
  if (opinions.length) {
    files.set(`common/opinion_modifiers/zin_${id}.txt`, text([head, ...block('opinion_modifiers', flat(opinions.map(([k, m]) => {
      C.loc[opinionId(tree, k)] = m.name ?? titleCase(k);
      return block(opinionId(tree, k), [`value = ${m.value}`, ...(m.decay ? [`decay = ${num(m.decay)}`] : []), ...(m.months ? [`months = ${m.months}`] : []), ...(m.trade ? ['trade = yes'] : [])]);
    })))]));
  }
  if (tree.ai_strategies?.length) files.set(`common/ai_strategy/zin_${id}.txt`, text([head, ...flat(tree.ai_strategies.map((s, i) => strategyLines(s, i, C)))]));
  return { files, loc: C.loc, stats: { focuses: tree.focuses.length, spirits: spirits.length, events: events.length, raw: C.raw, effects: declared.length, triggers: triggers.length, opinions: opinions.length, strategies: tree.ai_strategies?.length ?? 0 } };
}

