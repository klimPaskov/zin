// ------------------------------------------------------------------------------------------------ loading and building
// The tree ids the tiers spec expects (tier A table, tier B and C lists).
export async function expectedTreeIds(file = TIERS_SPEC) {
  if (!existsSync(file)) return [];
  const md = await readFile(file, 'utf8'), ids = new Set();
  for (const line of md.split('\n')) {
    const cells = line.split('|').map(s => s.trim());
    if (cells.length >= 7 && /^\d+$/.test(cells[3]) && /^`[a-z0-9_]+`$/.test(cells[5])) ids.add(cells[5].slice(1, -1));
  }
  for (const [, id] of md.matchAll(/`((?:regional|shared)_[a-z0-9_]+)`/g)) ids.add(id);
  return [...ids].sort();
}

// Reads, validates and expands all tree files. Returns { entries, trees: Map id -> effective tree, problems }.
export function prepareTrees(entries, roster) {
  const problems = [], vctx = { countries: new Set(roster.map(c => c.name)), regions: new Set(roster.map(c => c.scan)), people: new Set(Object.keys(PEOPLES)) };
  const valid = [];
  for (const e of entries) {
    if (e.error) { problems.push(problem('schema', e.name, `${e.name}.json: ${e.error}`)); continue; }
    const errs = validateTree(e.data, vctx);
    for (const x of errs) problems.push(problem('schema', e.name, `${x.path} ${x.message}`));
    if (!errs.length) {
      if (e.data.id !== e.name) problems.push(problem('schema', e.name, `$.id ${JSON.stringify(e.data.id)} must equal the file name ${e.name}`));
      else valid.push(e.data);
    }
  }
  const ids = new Set();
  for (const t of valid) { if (ids.has(t.id)) problems.push(problem('collision_tree', t.id, `F3: tree id ${t.id} is used twice`)); ids.add(t.id); }
  const { trees, problems: copyProblems } = expandCopies(valid);
  for (const p of copyProblems) problems.push(problem('copy', p.tree, p.message));
  return { trees, problems };
}

async function loadRoster() { return JSON.parse(await readFile(new URL('../data/countries.json', import.meta.url), 'utf8')).countries; }

// Validates, expands and checks the tree entries ({ name, data } or { name, error }). Returns the effective trees, the
// shared context and every problem; nothing is staged. opts: countries, registry, catalog, codes, retired, tierRanges
// (null disables the range check), expected (tree ids that make the roster complete), game, isValidModifier.
export async function analyseTrees(entries, staged, opts = {}) {
  const roster = opts.countries ?? await loadRoster();
  const { trees, problems } = prepareTrees(entries, roster);
  const registry = opts.registry ?? (await loadRegistry()).merge(scanStaged(staged));
  const ctx = {
    roster, trees, registry, catalog: opts.catalog ?? await loadCatalog(), codes: opts.codes ?? await loadArgCodes(),
    retired: opts.retired ?? await loadRetired(), tierRanges: opts.tierRanges, game: opts.game, isValidModifier: opts.isValidModifier,
  };
  const list = [...trees.values()];
  problems.push(...await checkTrees(list, ctx));
  // Every country has exactly one tree: the missing-country half waits until every tree of the tiers spec is present.
  const expected = opts.expected ?? await expectedTreeIds();
  const complete = expected.length > 0 && expected.every(id => trees.has(id));
  problems.push(...checkCoverage(list, roster, { requireAll: complete }));
  const layout = layoutFile();
  problems.push(...checkLayoutRefresh(list, opts.layout ?? layout));
  return { roster, trees, list, ctx, problems, layout, complete, expected };
}

// buildFocusTrees(staged, opts): reads docs/design/focus/*.json (opts.dir), throws one Error listing every failed
// check, otherwise stages every file and returns the counts. Zero tree files stage nothing.
export async function buildFocusTrees(staged, opts = {}) {
  const warn = opts.warn ?? (m => process.stderr.write(`focus compiler: ${m}
`));
  const entries = await readTreeFiles(opts.dir ?? TREE_DIR);
  if (!entries.length) return { trees: 0, focuses: 0, spirits: 0, events: 0, raw: 0, files: 0, warnings: 0 };
  const a = await analyseTrees(entries, staged, opts);
  assertClean(a.problems);
  if (!a.complete) warn(`${a.list.length} of ${a.expected.length || '?'} trees present; the check that every country has a tree waits for the rest`);
  const total = { trees: a.list.length, focuses: 0, spirits: 0, events: 0, raw: 0, files: 0, warnings: 0 };
  for (const tree of a.list) {
    for (const w of gateWarnings(tree, a.ctx)) { warn(w); total.warnings++; }
    const out = compileTree(tree, a.ctx);
    for (const [rel, body] of out.files) { staged.text(rel, body); total.files++; }
    staged.loc(`zin_focus_${tree.id}`, out.loc); total.files++;
    total.focuses += out.stats.focuses; total.spirits += out.stats.spirits; total.events += out.stats.events; total.raw += out.stats.raw;
    if (out.stats.raw) warn(`${tree.id}: ${out.stats.raw} raw block${out.stats.raw === 1 ? '' : 's'}`);
  }
  staged.text(LAYOUT_FILE, a.layout); total.files++;
  return total;
}
