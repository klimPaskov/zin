const num = n => Number.isInteger(n) ? String(n) : String(Number(n.toFixed(3)));
const block = (head, lines) => [`${head} = {`, ...lines.map(l => `\t${l}`), '}'];
const flat = lists => lists.flat();
const text = lines => `${lines.join('\n')}\n`;
