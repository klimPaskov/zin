// The one ZIN defines file (docs/specs/00_foundation/05_defines_and_rules.md): common/defines/zin_defines.lua.
// Rows come from data/defines.json; `$START_DATE` and `$END_DATE` read lib/calendar.mjs. The engine ignores an unknown
// define silently, so every row is checked against the installed 00_defines.lua (category and key).
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GAME } from '../lib/paths.mjs';
import { loadJson } from '../checks/vanilla_refs.mjs';
import { START_DATE, END_DATE } from '../lib/calendar.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const HEADER = '-- Generated by the ZIN content builder (defines spec). Do not edit by hand.';
const SYMBOLS = { $START_DATE: START_DATE, $END_DATE: END_DATE };

// Category blocks of the vanilla file: `NGame = {` at depth 1 of `NDefines = {`, closed by `},` at the same depth.
export function vanillaCategories(text) {
  const out = new Map(), re = /^\t?(N[A-Za-z0-9_]+)\s*=\s*\{/gm;
  const starts = [...text.matchAll(re)].map(m => ({ name: m[1], at: m.index + m[0].length }));
  starts.forEach((s, i) => out.set(s.name, text.slice(s.at, i + 1 < starts.length ? starts[i + 1].at : text.length)));
  return out;
}

export function assertDefinesExist(rows, text) {
  const cats = vanillaCategories(text), bad = [];
  for (const r of rows) {
    const body = cats.get(r.category);
    if (!body) { bad.push(`${r.category}.${r.key} (no such category)`); continue; }
    if (!new RegExp(`\\b${r.key}\\s*=`).test(body)) bad.push(`${r.category}.${r.key} (no such define)`);
  }
  if (bad.length) throw new Error(`Defines the game does not have: ${bad.join(', ')}`);
}

const literal = v => typeof v === 'string' ? JSON.stringify(v) : Number.isInteger(v) ? String(v) : String(v);
const resolve = v => (typeof v === 'string' && v in SYMBOLS ? SYMBOLS[v] : v);

// The rows in effect at a stage: for one key the highest fromStage not above the stage wins.
export function rowsInEffect(rows, stage) {
  const best = new Map();
  for (const r of rows) {
    if (r.fromStage > stage) continue;
    const k = `${r.category}.${r.key}`, prev = best.get(k);
    if (!prev || r.fromStage >= prev.fromStage) best.set(k, r);
  }
  return [...best.values()].sort((a, b) => `${a.category}.${a.key}`.localeCompare(`${b.category}.${b.key}`, 'en'));
}

export async function buildDefines(staged, { countries }) {
  const data = JSON.parse(await readFile(path.join(here, '../data/defines.json'), 'utf8')), disp = await loadJson('dispositions.json');
  assertDefinesExist(data.rows, await readFile(`${GAME}/common/defines/00_defines.lua`, 'utf8'));
  const rows = rowsInEffect(data.rows, disp.currentStage);
  // The observer define needs a ZIN tag; Verde has no story role (spec 3.4, proposed).
  const handsOff = countries.find(c => c.name === 'Verde') ?? countries[0];
  const lines = [HEADER, `-- Rows in effect at stage ${disp.currentStage}; the table is tools/content/data/defines.json.`,
    ...rows.map(r => `NDefines.${r.category}.${r.key} = ${literal(resolve(r.value))} -- ${r.why}`),
    `NDefines.NGame.HANDS_OFF_START_TAG = "${handsOff.tag}" -- ${handsOff.name}: the tag for -hands_off runs`];
  staged.text('common/defines/zin_defines.lua', lines.join('\n'));
  return { defines: rows.length + 1, handsOff: handsOff.tag };
}
