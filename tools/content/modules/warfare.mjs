// ------------------------------------------------------------------------------------------------ tactics
export function transformTactics(source, text, uniqueUnits = new Set(['zin_support_sappers'])) {
  const re = /^(tactic_[a-z_0-9]+) = \{/gm, idx = [];
  let m;
  while ((m = re.exec(source))) idx.push([m[1], m.index]);
  const firstStart = idx[0][1];
  const head = source.slice(0, firstStart);
  const phases = head.match(/phases = \{[\s\S]*?\n\}/)?.[0] ?? err('warfare: no phases block in the installed tactics');
  const kept = [], dropped = [];
  idx.forEach(([id, at], i) => {
    const body = source.slice(at, i + 1 < idx.length ? idx[i + 1][1] : source.length).replace(/\s+$/, '');
    if (/only_show_for|\btag = /.test(body) || text.dropTactics.includes(id)) { dropped.push(id); return; }
    kept.push({ id, body });
  });
  const keptIds = new Set(kept.map(k => k.id));
  const out = kept.map(({ id, body }) => {
    let b = body.replace(/has_trait = (\w+)/g, (all, t) => `has_trait = ${text.traitMap[t] ?? t}`);
    b = b.replace(/has_unit_type = (engineer|pioneer_support)/g, 'has_unit_type = zin_support_sappers');
    b = b.replace(/^\s*countered_by = (tactic_\w+)\s*$/gm, (all, t) => (keptIds.has(t) ? all : ''));
    b = b.replace(/^[ \t]*OWNER = \{ NOT = \{ has_tactic = (tactic_\w+) \} \}[^\n]*$/gm, (all, t) => (keptIds.has(t) ? all : ''));
    return b;
  });
  for (const o of out) for (const t of o.match(/tactic_[a-z_0-9]+/g) ?? []) if (!keptIds.has(t)) err(`warfare: a kept tactic names the dropped ${t}`);
  return { text: `# Generated by the ZIN content builder: the engine's combat tactics without the single-country ones and with Erdae trait and unit names.\n${phases}\n\n${out.join('\n\n')}\n`, kept: [...keptIds], dropped };
}
function writeTactics(staged, model) {
  const source = readFileSync(`${GAME}/common/combat_tactics.txt`, 'utf8');
  const r = transformTactics(source, model.raw.text);
  staged.text('common/combat_tactics.txt', r.text);
  model.tactics = r;
  for (const t of r.kept) if (!model.raw.text.tactics[t]) err(`warfare: kept tactic ${t} has no Erdae name`);
}

