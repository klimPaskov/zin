// Bare hull stats: total / (1 + sum multipliers) - sum added, from the default modules.
function hullBase(h, v, modules) {
  const d = v.defaults, ids = [d.propulsion, d.protection, d.crew, ...d.armament].filter(Boolean);
  const total = { ...h.t };
  for (const [k, val] of Object.entries(v.delta ?? {})) total[k] = (total[k] ?? 0) + val;
  const adds = {}, mults = {};
  for (const id of ids) {
    const m = modules.find(x => x.id === id);
    for (const [k, val] of Object.entries(m.add ?? {})) adds[k] = (adds[k] ?? 0) + val;
    for (const [k, val] of Object.entries(m.mult ?? {})) mults[k] = (mults[k] ?? 0) + val;
  }
  const base = {};
  for (const [k, t] of Object.entries(total)) {
    if (k === 'manpower') { base[k] = t; continue; }
    base[k] = Math.max(0, round3(t / (1 + (mults[k] ?? 0)) - (adds[k] ?? 0)));
  }
  return base;
}
