function peopleOf(model, culture) { return model.raw.cultureDefs.cultures[culture]?.people; }
function cultureTags(model) {
  const by = new Map();
  for (const c of model.cultureRows) { if (!by.has(c.culture)) by.set(c.culture, []); by.get(c.culture).push(c.tag); }
  return by;
}
function nounOf(model, culture, people) { return model.raw.names.cultureNouns[culture] ?? model.raw.names.nouns[people]; }

const mixPlaces = (target, n, seed, kinds) => {
  const per = kinds.map((k, i) => placeNames(target, k, Math.ceil(n / kinds.length), { seed: `${seed}${k}:` }));
  const out = [];
  for (let i = 0; out.length < n && i < per[0].length; i++) for (const p of per) if (p[i] && out.length < n) out.push(p[i].text);
  return [...new Set(out)];
};

