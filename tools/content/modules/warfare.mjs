function unitFileOf(u) {
  const id = u.id;
  if (u.great) return 'great';
  if (id === 'zin_support_pack_train' || id === 'zin_elves_wardsingers') return 'camp';
  if (id.startsWith('zin_support_')) return ['catapults', 'ballistae', 'scorpions'].some(x => id.endsWith(x)) ? 'siege' : 'camp';
  if (id.startsWith('zin_siege_')) return 'siege';
  if (id.startsWith('zin_men_')) return 'men';
  if (id.startsWith('zin_elves_')) return 'elves';
  if (id.startsWith('zin_sun_elves_')) return 'sun_elves';
  if (id.startsWith('zin_orcs_') || id.startsWith('zin_ogres_') || id === 'zin_abyss_folk') return 'orcs';
  if (id.startsWith('zin_trolls_') || id.startsWith('zin_giants_') || id.startsWith('zin_ents_') || id.startsWith('zin_yeti_')) return 'kin';
  if (id.startsWith('zin_demons_')) return 'demons';
  if (id.startsWith('zin_the_dead_') || id.startsWith('zin_dead_') || id.startsWith('zin_zol_')) return 'dead';
  return err(`warfare: no unit file for ${id}`);
}

function writeUnits(staged, model) {
  const byFile = new Map(Object.keys(LAND_FILES).map(k => [k, []]));
  for (const u of model.landUnits) byFile.get(unitFileOf(u)).push(landUnitBlock(u, model));
  for (const s of model.raw.units.ships) byFile.get('ships').push(shipBlock(s, model));
  for (const s of model.raw.units.air) byFile.get('air').push(airBlock(s));
  for (const [k, file] of Object.entries(LAND_FILES)) {
    if (!byFile.get(k).length) err(`warfare: ${file} would be empty`);
    staged.text(`common/units/${file}`, `${HEADER}\n# ${file}\nsub_units = {\n${byFile.get(k).join('\n\n')}\n}\n`);
  }
}

