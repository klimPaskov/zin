export function ordinalWord(n) {
  if (n < 20) return ORDINALS[n - 1];
  const t = Math.floor(n / 10), o = n % 10;
  return o === 0 ? TENS_TH[t] : `${TENS[t]}-${ORDINALS[o - 1].toLowerCase()}`;
}

// The equipment type ids and their stats. `a` is an archetype row of warfare_equipment.json.
export function variantStats(a, v) {
  const d = v.n - a.b, set = v.set ?? {};
  if (a.kindAir) {
    const out = {};
    for (const [k, base] of Object.entries(a.base)) out[k] = round3(base * (1 + (a.g?.[k] ?? 0) * d));
    return { ...out, ...set };
  }
  const gr = k => a.g?.[k] ?? 0, st = {};
  for (const k of ['sa', 'ha', 'def', 'brk']) st[k] = Math.max(0, round3(a.base[k] * (1 + gr(k) * d)));
  st.ap = Math.max(0, round3(a.base.ap + (a.apStep ?? 0) * d + (set.apPlus ?? 0)));
  st.arm = Math.max(0, round3(a.base.arm + (a.armStep ?? 0) * d));
  st.hard = a.base.hard;
  if (a.base.air !== undefined) st.air = round3(a.base.air * (1 + gr('air') * d));
  for (const k of ['sa', 'ha', 'def', 'brk', 'ap', 'arm', 'hard', 'air']) if (set[k] !== undefined) st[k] = set[k];
  return st;
}
export const variantId = (a, v) => v.id ?? `${a.id}_${v.n}`;
const variantResources = (a, v) => (a.resLate && v.n >= a.resLate.from) ? { ...a.res, ...a.resLate.res } : (a.res ?? {});

// Baseline stats of an archetype: its baseline variant.
export function baselineOf(a) {
  const v = a.variants.find(x => x.n === a.b) ?? a.variants[0];
  return variantStats(a, v);
}

// Solve one sub-unit: factors that put the blended equipment stats on the spec target.
export function solveUnit(u, eqBase) {
  const needs = Object.entries(u.needs), total = needs.reduce((s, [, n]) => s + n, 0);
  const blend = k => needs.reduce((s, [id, n]) => s + n * ((eqBase.get(id) ?? err(`${u.id}: no equipment ${id}`))[k] ?? 0), 0) / total;
  const [org, hp, sa, ha, def, brk, arm, prc, spd, width, mp, days] = u.s;
  const target = { sa, ha, def, brk, arm, ap: prc, hard: u.hard ?? 0 };
  const factors = {}, blended = {};
  for (const k of Object.keys(target)) {
    const b = blend(k), t = target[k];
    blended[k] = round3(b);
    if (Math.abs(b - t) < 1e-9) continue;
    if ((k === 'arm' && Math.abs(b - t) <= 1.01) || (k === 'hard' && Math.abs(b - t) < 0.12)) continue; // within the tolerance of the model
    if (b === 0) { if (t === 0) continue; err(`${u.id}: target ${k} ${t} but its equipment gives 0`); }
    factors[k] = round3(t / b - 1);
  }
  const speedFactor = round3(spd / SPEED - 1);
  return { org, hp, width, mp, days, spd, target, blended, factors, speedFactor };
}

// Division piercing as the spec states it: the blend of the best and the average sub-unit piercing (ARMOR_VS_AVERAGE 0.4).
export const ARMOR_VS_AVERAGE = 0.4;
export function divisionPiercing(prcs) {
  if (!prcs.length) return 0;
  const avg = prcs.reduce((s, x) => s + x, 0) / prcs.length, best = Math.max(...prcs);
  return ARMOR_VS_AVERAGE * avg + (1 - ARMOR_VS_AVERAGE) * best;
}
// Which technologies a people (or a named realm, `country:<name>`) can research: a technology's `who` list, or that of the
// technology it requires when it has none. A `who` entry may be a group of the technology data, a people, a country, or a
// people with a region (`men+region:east_lands`), which counts for the people.
export function techReaches(techs, key, who) {
  const byKey = new Map(techs.technologies.map(t => [t.key, t]));
  let t = byKey.get(key);
  while (t && !t.who && t.requires?.length) t = byKey.get(t.requires[0]);
  if (!t?.who) return true;
  const entries = t.who.flatMap(w => w.startsWith('group:') ? techs.groups[w.slice(6)] : [w]);
  return entries.some(e => who.includes(e.split('+')[0]));
}
// The best variant of every archetype that a people can have by `year`.
export function bestVariants(model, who, year) {
  const best = new Map();
  for (const t of model.raw.techs.technologies) {
    if (t.year > year || !techReaches(model.raw.techs, t.key, who)) continue;
    for (const e of t.unlocks?.equipment ?? []) {
      const a = [...model.archById.values()].find(x => x.variants.some(v => (v.id ?? `${x.id}_${v.n}`) === e));
      if (!a) continue;
      const v = a.variants.find(x => (x.id ?? `${a.id}_${x.n}`) === e);
      if (!best.has(a.id) || v.n > best.get(a.id).n) best.set(a.id, v);
    }
  }
  return best;
}
// The piercing of a sub-unit with the best variant of every archetype that `who` can have by `year` (everyone, when `who` is empty).
export function unitPiercing(model, unitId, year, who = null) {
  const u = model.unitById.get(unitId);
  const needs = Object.entries(u.needs), total = needs.reduce((s, [, n]) => s + n, 0);
  const best = who ? bestVariants(model, who, year) : null;
  let blend = 0;
  for (const [id, n] of needs) {
    const a = model.archById.get(id), vs = a.variants.filter(v => v.year <= year);
    let v = best ? (best.get(id) ?? (a.granted ? a.variants[0] : a.variants[0])) : (vs.length ? vs.reduce((m, x) => (x.n > m.n ? x : m)) : a.variants[0]);
    blend += n * variantStats(a, v).ap;
  }
  blend /= total;
  const f = model.solved.get(unitId)?.factors?.ap ?? 0;
  return blend * (1 + f);
}

