export function locEntries(data) {
  const out = {
    zin_se_window_title: '[zin_loc_super_event_title]',
    zin_se_window_date: '[GetDateText]',
    zin_se_window_desc: '[zin_loc_super_event_desc]',
    zin_se_window_quote: '[zin_loc_super_event_quote]',
    zin_se_window_button: '[zin_loc_super_event_button]',
    zin_se_window_button_tip: 'Close this page of the chronicle and return to the realm.',
    zin_se_window_queue: 'More news of the age waits to be told: [?zin_se_queue^num|0]',
    zin_se_music_on: 'Music: on',
    zin_se_music_on_tip: 'Each great moment of the age plays its own music. Click to silence it for the great moments still to come. The game\'s music volume also applies.',
    zin_se_music_off: 'Music: off',
    zin_se_music_off_tip: 'The great moments of the age play no music for you. Click to hear this one and those still to come.',
  };
  for (const e of data.events) {
    // The song's title in the music player (vanilla keys a song title by the song name); the recording's own title replaces it when it ships.
    out[song(e)] = e.title;
    out[locKey(e, 't')] = e.title;
    out[locKey(e, 'd')] = e.desc.join('\n\n');
    out[locKey(e, 'q')] = `${e.quote}\n- ${e.attribution}`;
    out[locKey(e, 'a')] = e.button;
  }
  return out;
}

export async function buildSuperEvents(staged, { data } = {}) {
  data ??= await loadSuperEvents();
  staged.text(FILES.gui, guiText(data));
  staged.text(FILES.gfx, `${HEAD}# The super-event pictures (700 x 500). Pending art: docs/plans/zin-art/pending_from_integration.md, section Super-event pictures.\n${gfxText(data)}`);
  staged.text(FILES.sgui, scriptedGuiText());
  staged.text(FILES.effects, effectsText(data));
  staged.text(FILES.sloc, scriptedLocText(data));
  staged.text(FILES.constants, constantsText(data));
  staged.text(FILES.events, eventsText(data));
  staged.text(FILES.music, musicText(data));
  staged.loc('zin_super_events', locEntries(data));
  return { data, counts: { superEvents: data.events.length, sprites: data.events.length, songs: data.events.length } };
}

// ---- the hooks ---------------------------------------------------------------------------------------------------------------------
// Insert `zin_super_event_<key> = yes` after every `set_global_flag = <hook>` of the finished script tree (comments ignored). Every hook flag
// must be set somewhere; a flag that no file sets stops the build, because its super event could never be shown.
export function hookSuperEvents(staged, data) {
  const sites = new Map(data.events.map(e => [e.hook, []]));
  const byFlag = new Map(data.events.map(e => [e.hook, e]));
  const re = /^([ \t]*)set_global_flag = ([a-z0-9_]+)[ \t]*(#.*)?$/;
  for (const [rel, bytes] of [...staged.files].sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (!/^(common|events|history)\/.+\.txt$/.test(rel) || rel === FILES.effects) continue;
    const text = bytes.toString('utf8');
    if (!/set_global_flag = /.test(text)) continue;
    const lines = text.split('\n');
    let changed = false;
    const out = [];
    for (const [i, line] of lines.entries()) {
      out.push(line);
      const m = re.exec(line.replace(/\r$/, ''));
      if (!m || !byFlag.has(m[2])) continue;
      const e = byFlag.get(m[2]);
      out.push(`${m[1]}${effect(e)} = yes # super event ${e.id} (modules/super_events.mjs)`);
      sites.get(e.hook).push(`${rel}:${i + 1}`);
      changed = true;
    }
    if (changed) staged.files.set(rel, Buffer.from(out.join('\n')));
  }
  const missing = [...sites].filter(([, s]) => !s.length).map(([f]) => f);
  if (missing.length) throw new Error(`super events: no staged file sets ${missing.join(', ')}; their super events could never be shown (data/super_events.json hook)`);
  return Object.fromEntries([...sites].map(([f, s]) => [byFlag.get(f).key, s]));
}
