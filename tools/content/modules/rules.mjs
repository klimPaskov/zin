// The foundation's game rules (docs/specs/00_foundation/05_defines_and_rules.md section 2, "Implementation"):
//   await buildRules(staged)   after the mechanic slices, whose own rule files the generated triggers read
// Writes common/game_rules/zin_game_rules.txt (the foundation rules and the rows the owner specs supply), the wrapper triggers
// common/scripted_triggers/zin_rules.txt (zin_rules_is_historical, zin_rules_is_free, zin_rules_ai_branch_<power>_<option> for every
// per-power rule, zin_rules_ai_random_<power> for the rules with RANDOM), the start-up block common/on_actions/zin_rules.txt that sets
// global.zin_story_pace, and the rule text (localisation/english/zin_game_rules_l_english.yml; the group name RULE_GROUP_ZIN stays in
// vanilla_removal.mjs's zin_rules file). Data: tools/content/data/game_rules.json. No rule carries an icon until the rule icons exist
// (docs/plans/zin-art/pending_from_integration.md).
import { readFile } from 'node:fs/promises';
import { parse, scriptText } from '../lib/clausewitz.mjs';

const HEADER = '# Generated by the ZIN content builder (modules/rules.mjs, docs/specs/00_foundation/05_defines_and_rules.md). Do not edit; change tools/content/data/game_rules.json.';
const PATH_OPTIONS = ['HISTORICAL', 'PLAUSIBLE', 'FREE'];
const textKey = id => `ZIN_RULE_${id.replace(/^zin_rule_/, '').toUpperCase()}`;
const ruleTest = (rule, option) => `has_game_rule = { rule = ${rule} option = ${option} }`;

export async function loadRules() {
  return JSON.parse(await readFile(new URL('../data/game_rules.json', import.meta.url), 'utf8'));
}

// Rule definitions and options of the staged rule files (the owners' rules read by the branch triggers).
function stagedRules(staged) {
  const out = new Map();
  for (const [rel, bytes] of staged.files) {
    if (!rel.startsWith('common/game_rules/') || !rel.endsWith('.txt')) continue;
    for (const e of parse(scriptText(bytes))) if (e.k && Array.isArray(e.v)) out.set(e.k, e.v.filter(o => o.k === 'option' || o.k === 'default').map(o => o.v.find(x => x.k === 'name')?.v));
  }
  return out;
}

export function checkRules(data) {
  const problems = [], seen = new Set();
  for (const r of data.rules) {
    if (!/^zin_rule_[a-z_]+$/.test(r.id)) problems.push(`${r.id}: not a zin_rule_ name`);
    if (seen.has(r.id)) problems.push(`${r.id}: defined twice`); seen.add(r.id);
    if (!r.options?.length) problems.push(`${r.id}: no options`);
    if (r.perPower && r.options[0].key !== 'DEFAULT') problems.push(`${r.id}: a per-power rule opens with DEFAULT (R1)`);
    const keys = new Set(r.options.map(o => o.key));
    for (const [path, option] of Object.entries(r.branch ?? {})) {
      if (!PATH_OPTIONS.includes(path)) problems.push(`${r.id}: branch key ${path} is not a path option`);
      if (!keys.has(option)) problems.push(`${r.id}: branch option ${option} is not an option`);
    }
    for (const t of [r.name, r.desc, ...r.options.flatMap(o => [o.name, o.desc])]) if (/\b(Afrit|Eindil|Hidden Council)\b/.test(t ?? '')) problems.push(`${r.id}: the rule text names a secret: ${t}`);
    for (const o of r.options) if (!o.name || !o.desc) problems.push(`${r.id}.${o.key}: missing text`);
  }
  return problems;
}

function branchTriggers(rule, power, options, branch) {
  const out = [];
  for (const option of options.filter(o => o !== 'DEFAULT' && o !== 'RANDOM')) {
    const paths = PATH_OPTIONS.filter(p => branch[p] === option);
    const viaDefault = paths.length ? `\n\t\tAND = {\n\t\t\t${ruleTest(rule, 'DEFAULT')}\n\t\t\t${paths.length === 1 ? ruleTest('zin_rule_historical_path', paths[0]) : `OR = { ${paths.map(p => ruleTest('zin_rule_historical_path', p)).join(' ')} }`}\n\t\t}` : '';
    out.push(`# ${rule} forces ${option}${paths.length ? `, or it is DEFAULT and the path rule is ${paths.join(' or ')}` : ''}. RANDOM makes it false.\nzin_rules_ai_branch_${power}_${option.toLowerCase()} = {\n\tOR = {\n\t\t${ruleTest(rule, option)}${viaDefault}\n\t}\n}`);
  }
  if (options.includes('RANDOM')) out.push(`# ${rule} is RANDOM: its owner draws once at the start and reads the draw.\nzin_rules_ai_random_${power} = {\n\t${ruleTest(rule, 'RANDOM')}\n}`);
  return out;
}

export async function buildRules(staged, { data } = {}) {
  data ??= await loadRules();
  const problems = checkRules(data);
  const owners = stagedRules(staged);
  for (const r of data.ownerRules ?? []) {
    const options = owners.get(r.id);
    if (!options) { problems.push(`${r.id}: the owner's rule file is not staged`); continue; }
    if (options[0] !== 'DEFAULT') problems.push(`${r.id}: a per-power rule opens with DEFAULT (R1)`);
    for (const option of Object.values(r.branch ?? {})) if (!options.includes(option)) problems.push(`${r.id}: branch option ${option} is not one of the owner's options`);
  }
  for (const r of data.rules) if (owners.has(r.id)) problems.push(`${r.id}: already defined by another module's rule file`);
  if (problems.length) throw new Error(`Game rules (data/game_rules.json):\n  ${problems.join('\n  ')}`);

  const loc = {};
  const blocks = data.rules.map(r => {
    const K = textKey(r.id);
    loc[K] = r.name; loc[`${K}_DESC`] = r.desc;
    const opts = r.options.map((o, i) => {
      loc[`${K}_${o.key}`] = o.name; loc[`${K}_${o.key}_DESC`] = o.desc;
      return `\t${i === 0 ? 'default' : 'option'} = {\n\t\tname = ${o.key}\n\t\ttext = "${K}_${o.key}"\n\t\tdesc = "${K}_${o.key}_DESC"\n\t}`;
    });
    // No rule-level desc: the game reads desc only on an option ("Unexpected token: desc" otherwise; vanilla 00_game_rules.txt has none).
    return `${r.id} = {\n\tname = "${K}"\n\tgroup = "${data.group}"\n${opts.join('\n')}\n}`;
  });
  staged.text('common/game_rules/zin_game_rules.txt', `${HEADER}\n# Every per-power rule opens with DEFAULT, which follows ${data.path_rule} (decision R1). Rules never act on a player's country.\n${blocks.join('\n')}\n`);

  const triggers = [
    `# The path rule (06_historical_path_and_ai.md): PLAUSIBLE is neither historical nor free.\nzin_rules_is_historical = {\n\t${ruleTest(data.path_rule, 'HISTORICAL')}\n}`,
    `zin_rules_is_free = {\n\t${ruleTest(data.path_rule, 'FREE')}\n}`,
  ];
  for (const r of data.rules.filter(x => x.perPower)) triggers.push(...branchTriggers(r.id, r.power, r.options.map(o => o.key), r.branch ?? {}));
  for (const r of data.ownerRules ?? []) triggers.push(...branchTriggers(r.id, r.power, owners.get(r.id), r.branch ?? {}));
  staged.text('common/scripted_triggers/zin_rules.txt', `${HEADER}\n# Wrappers over has_game_rule, so a rule rename touches one file.\n${triggers.join('\n')}\n`);

  const pace = data.rules.find(r => r.id === 'zin_rule_story_pace');
  const [first, ...rest] = pace.options;
  const paceBlock = [...rest.map((o, i) => `\t\t\t${i === 0 ? 'if' : 'else_if'} = {\n\t\t\t\tlimit = { ${ruleTest(pace.id, o.key)} }\n\t\t\t\tset_variable = { global.zin_story_pace = ${o.pace} }\n\t\t\t}`), `\t\t\telse = {\n\t\t\t\tset_variable = { global.zin_story_pace = ${first.pace} }\n\t\t\t}`].join('\n');
  staged.text('common/on_actions/zin_rules.txt', `${HEADER}\n# on_startup is not run on a country: the story pace is set once for the whole world.\non_actions = {\n\ton_startup = {\n\t\teffect = {\n${paceBlock}\n\t\t}\n\t}\n}\n`);
  staged.loc('zin_game_rules', loc);
  return { counts: { rules: data.rules.length, triggers: triggers.length, keys: Object.keys(loc).length } };
}
