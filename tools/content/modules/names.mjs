// Character names for every ZIN country: given names and surnames built from the syllables of the drawn
// labels of the country's own sheet, so each region has its own sound. Without these the game cannot name the
// characters it generates for ZIN countries.
import { rng, ascii } from '../lib/core.mjs';

const STOP = new Set(['the', 'of', 'and', 'lands', 'land', 'sea', 'ocean', 'islands', 'island', 'forest', 'forests', 'mountains', 'mountain', 'great', 'north', 'south', 'east', 'west', 'river', 'lake', 'hills', 'desert', 'border', 'borders', 'isles', 'gate', 'mistake', 'cold', 'dark', 'giant', 'magic', 'magical', 'cursed', 'lost', 'king', 'kingdom', 'old', 'new', 'fire', 'red', 'black', 'white', 'green', 'sky', 'end', 'light', 'stone', 'peace', 'heaven', 'dream', 'god', 'gods', 'sun', 'sunny', 'yeti', 'dead', 'deadlands']);
const BANNED = ['rush', 'klinti', 'sunhot', 'edvoid', 'zol', 'volgan', 'afrit', 'hell', 'dead', 'death', 'devil', 'demon', 'god', 'sex', 'ass', 'tit', 'cum', 'dick', 'cock', 'kill', 'rape', 'slut', 'piss', 'shit', 'fuck', 'nazi'];
const syllables = w => w.match(/[^aeiouy]*[aeiouy]+[^aeiouy]*?(?=[^aeiouy][aeiouy]|$)/g) ?? [];

function bankFor(words) {
  const open = [], end = [];
  for (const w of words) { const s = syllables(w); if (s.length < 2) continue; open.push(s[0]); end.push(s.at(-1)); }
  return { open, end };
}

// Female names favour vowel endings; surnames use longer stems with regional endings.
function makeName(bank, r, kind) {
  const o = bank.open[Math.floor(r() * bank.open.length)];
  let e = bank.end[Math.floor(r() * bank.end.length)];
  if (kind === 'female' && !/[aeiy]$/.test(e)) e = e.replace(/[^aeiouy]+$/, '') + ['a', 'e', 'ia', 'iel', 'ra', 'wen'][Math.floor(r() * 6)];
  let n = o + e;
  if (kind === 'surname' && r() < 0.5) n += bank.end[Math.floor(r() * bank.end.length)];
  return n;
}
const ok = n => n.length >= 3 && n.length <= (12) && (n.match(/[aeiouy]/g) ?? []).length >= 1 && !/(.)\1\1|[^aeiouy]{4}/.test(n) && !BANNED.some(b => n.includes(b));
const cap = s => s[0].toUpperCase() + s.slice(1);

export function buildNames(staged, countries, labels) {
  const wordsByScan = new Map();
  for (const l of labels) for (const w of ascii(l.name).toLowerCase().split(/[^a-z]+/)) if (w.length >= 3 && !STOP.has(w)) (wordsByScan.get(l.scan) ?? wordsByScan.set(l.scan, new Set()).get(l.scan)).add(w);
  const all = [...new Set([...wordsByScan.values()].flatMap(s => [...s]))].sort();
  const pools = new Map();
  const poolFor = scan => {
    if (pools.has(scan)) return pools.get(scan);
    const words = [...(wordsByScan.get(scan) ?? [])].sort(), bank = bankFor(words.length >= 12 ? words : [...words, ...all]), known = new Set(all);
    const r = rng('zin-names:' + scan), take = (kind, n) => { const out = new Set(); for (let i = 0; out.size < n && i < n * 400; i++) { const v = makeName(bank, r, kind); if (ok(v) && !known.has(v)) out.add(cap(v)); } return [...out].sort(); };
    const pool = { male: take('male', 60), female: take('female', 50), surnames: take('surname', 90) };
    pools.set(scan, pool); return pool;
  };
  const block = (key, p) => `${key} = {\n\tmale = {\n\t\tnames = { ${p.male.join(' ')} }\n\t}\n\tfemale = {\n\t\tnames = { ${p.female.join(' ')} }\n\t}\n\tsurnames = { ${p.surnames.join(' ')} }\n\tcallsigns = { ${p.surnames.slice(0, 12).map(s => `"${s}"`).join(' ')} }\n}`;
  // The default pool, from the labels of all Erdae, names every tag without its own list: the 75 dynamic tags of
  // civil wars, whose party leaders the engine generates at load (300 failed names without it).
  const blocks = [block('default', poolFor('zin:all-erdae')), ...countries.map(c => block(c.tag, poolFor(c.scan)))];
  staged.text('common/names/zin_names.txt', `# Generated by the ZIN content builder: character names by region.\n${blocks.join('\n')}\n`);
  return pools;
}
