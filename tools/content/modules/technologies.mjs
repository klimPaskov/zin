const FALLBACK_TEXTURE = 'gfx/interface/zin/frame.dds';
function spriteFile(title, entries) {
  const L = [HEADER, `# ${title}`, '# A sprite points at its own DDS when the art step has shipped it, and at the ZIN frame texture until then (interim: no vanilla texture, no missing-sprite line).', 'spriteTypes = {'];
  for (const [name, tex] of entries) L.push('\tspriteType = {', `\t\tname = "${name}"`, `\t\ttexturefile = "${tex}"`, '\t}');
  L.push('}');
  return L.join('\n');
}
const textureFor = (dir, key) => existsSync(`${ZIN}/${dir}/${key}.dds`) ? `${dir}/${key}.dds` : FALLBACK_TEXTURE;

export function technologyIconKeys(model) { return model.techs.filter(t => !t.grantOnly).map(t => `GFX_${t.key}_medium`).sort(); }
export function doctrineIconKeys(model) {
  const d = model.doctrines, keys = [];
  for (const g of d.grand) keys.push(`GFX_${g.key}_medium`);
  for (const s of [...d.subs, d.hidden]) keys.push(`GFX_${s.key}_medium`);
  for (const t of d.tracks) keys.push(`GFX_${t.key}_bg`, `GFX_${t.key}_icon`);
  for (const f of d.folders) keys.push(`GFX_zin_doctrine_${f.key}_ledger`, `GFX_zin_doctrine_${f.key}_tab`, `GFX_zin_doctrine_decor_${f.key}`);
  return keys.sort();
}

async function localisation(staged, model) {
  const e = {};
  const set = (k, v) => { if (e[k] !== undefined) throw new Error(`Duplicate localisation key ${k}`); if (!WINDOWS_1252.test(v)) throw new Error(`Text of ${k} has characters the game font does not draw`); e[k] = v; };
  for (const f of model.folders.values()) { set(f.key, f.name); set(`${f.key}_desc`, f.desc); }
  for (const c of model.categories.values()) { set(c.key, c.name); set(`${c.key}_research`, `${c.name} Research`); }
  for (const t of model.techs) { set(t.key, t.name); set(`${t.key}_desc`, t.desc); }
  for (const g of model.gates) { set(g.key, g.name); set(`${g.key}_desc`, g.desc); }
  for (const [y, caption] of Object.entries(model.bandCaptions)) set(`zin_techtree_year_${y}`, caption);
  set('zin_techtree_year_start', '1 Thaw 4A 1748');
  const d = model.doctrines;
  for (const f of d.folders) { set(`zin_doctrine_folder_${f.key}`, f.name); set(`zin_doctrine_folder_${f.key}_desc`, f.desc); }
  for (const t of d.tracks) { set(t.key, t.name); }
  for (const g of d.grand) { set(g.key, g.name); set(`${g.key}_desc`, g.desc); }
  for (const s of [...d.subs, d.hidden]) { set(s.key, s.name); set(`${s.key}_desc`, s.desc); for (const r of s.rewards) { set(`${s.key}_${r.key}`, r.name); set(`${s.key}_${r.key}_desc`, r.desc); } }
  if (!model.externalSharing) {
    for (const g of model.sharing.groups) { set(`${g.id}_name`, g.name); set(`${g.id}_desc`, g.desc); }
    set(`${model.sharing.league.id}_name`, model.sharing.league.name); set(`${model.sharing.league.id}_desc`, model.sharing.league.desc);
  }
  const vanilla = await vanillaLocKeys();
  const own = {}, replace = {};
  for (const [k, v] of Object.entries(e)) (vanilla.has(k) ? replace : own)[k] = v;
  staged.loc('zin_technologies', own);
  if (Object.keys(replace).length) staged.add('localisation/replace/zin_technologies_l_english.yml', yml(replace));
  return { keys: Object.keys(e).length, replaced: Object.keys(replace).length };
}

// ---------- the build ----------
export async function buildTechnologies(staged, ctx) {
  const model = await prepareModel(ctx);
  // technology files
  const byFolder = new Map();
  for (const t of model.techs) { if (!byFolder.has(t.folder)) byFolder.set(t.folder, []); byFolder.get(t.folder).push(t); }
  const order = (a, b) => {
    const sa = model.layout.folders[a.folder].tiles.find(x => x.key === a.key), sb = model.layout.folders[b.folder].tiles.find(x => x.key === b.key);
    return sa.y - sb.y || sa.x - sb.x || a.key.localeCompare(b.key, 'en');
  };
  for (const [folder, file] of Object.entries(FOLDER_FILES)) {
    const list = (byFolder.get(folder) ?? []).sort(order);
    staged.text(`common/technologies/${file}`, [HEADER, `# ${model.folders.get(folder).name}: ${list.length} technologies (docs/specs/03_gameplay).`, 'technologies = {', ...list.map(t => technologyBlock(t, model)), '}'].join('\n'));
  }
  staged.text('common/technologies/zin_gates.txt', [HEADER, '# Seven grant-only technologies keep unused vanilla buildings locked. None is researched, granted or shown.', 'technologies = {', ...model.gates.map(gateBlock), '}'].join('\n'));
  staged.text('common/technology_tags/zin_technology_tags.txt', tagsFile(model));
  staged.text('common/ai_focuses/zin_ai_focuses.txt', aiFocusFile(model));
  // With ctx.externalSharing the diplomacy module owns common/technology_sharing and the groups' text; this module keeps the sync effect.
  if (!model.externalSharing) staged.text('common/technology_sharing/zin_tech_sharing.txt', sharingFile(model));
  staged.text('common/scripted_triggers/zin_technologies.txt', scriptedTriggers(model));
  staged.text('common/scripted_effects/zin_technologies.txt', scriptedEffectsSharing(model));
  staged.text('common/scripted_effects/zin_naval_air.txt', scriptedEffectsAir());
  staged.text('common/on_actions/zin_technologies.txt', onActions());
  // doctrines
  staged.text(DOCTRINE_FILES.folders, doctrineFolders(model));
  staged.text(DOCTRINE_FILES.tracks, doctrineTracks(model));
  staged.text(DOCTRINE_FILES.grand, grandDoctrines(model));
  for (const f of ['land', 'naval', 'air', 'special_forces']) staged.text(DOCTRINE_FILES[f], subdoctrines(model, f));
  // sprites
  staged.text('interface/zin_technologies.gfx', spriteFile('Technology tile icons, GFX_<technology>_medium.', model.techs.filter(t => !t.grantOnly).map(t => [`GFX_${t.key}_medium`, textureFor('gfx/interface/technologies/zin', t.key)]).sort(([a], [b]) => a.localeCompare(b, 'en'))));
  const dEntries = [];
  const d = model.doctrines;
  for (const g of d.grand) dEntries.push([`GFX_${g.key}_medium`, textureFor('gfx/interface/doctrines/zin', g.key)]);
  for (const s of [...d.subs, d.hidden]) dEntries.push([`GFX_${s.key}_medium`, textureFor('gfx/interface/doctrines/zin', s.key)]);
  for (const t of d.tracks) dEntries.push([`GFX_${t.key}_bg`, textureFor('gfx/interface/doctrines/zin', `${t.key}_bg`)], [`GFX_${t.key}_icon`, textureFor('gfx/interface/doctrines/zin', `${t.key}_icon`)]);
  for (const f of d.folders) dEntries.push([`GFX_zin_doctrine_${f.key}_ledger`, textureFor('gfx/interface/doctrines/zin', `${f.key}_ledger`)], [`GFX_zin_doctrine_${f.key}_tab`, textureFor('gfx/interface/doctrines/zin', `${f.key}_tab`)], [`GFX_zin_doctrine_decor_${f.key}`, textureFor('gfx/interface/doctrines/zin', `decor_${f.key}`)]);
  staged.text('interface/zin_doctrines.gfx', spriteFile('Doctrine icons, track art and folder tabs.', dEntries.sort(([a], [b]) => a.localeCompare(b, 'en'))));
  const loc = await localisation(staged, model);
  // published data for the folder windows (interface step) and the politics step
  const packages = technologyPackages(model);
  const layoutOut = { origin: ORIGIN, slot: SLOT, rows: model.bands.map(b => b.y), rowCaptions: model.bandCaptions, folders: Object.fromEntries(Object.entries(model.layout.folders).map(([f, v]) => [f, { rows: v.rows, width: v.width, height: v.height, gridboxes: v.gridboxes.map(g => ({ name: g.name, px: g.px, py: g.py, width: g.width, height: g.height, slotsize: g.slotsize, format: g.format })), tiles: v.tiles.map(t => ({ key: t.key, x: t.x, y: t.y, rx: t.rx, ry: t.ry, root: t.root, sprite: `GFX_${t.key}_medium` })) }])) };
  staged.text('docs/design/technology/layout.json', canonicalJson(layoutOut));
  const starts = {};
  for (const c of model.countries) { const people = model.assignment?.get(c.tag) ?? defaultPeople(c); starts[c.name] = { people, ...startFor(model, packages, c, people) }; }
  staged.text('docs/design/technology/start_packages.json', canonicalJson({ packages, countries: starts }));
  return {
    technologies: model.techs.length, gates: model.gates.length, folders: model.folders.size, categories: model.categories.size,
    grandDoctrines: d.grand.length, subdoctrines: d.subs.length + 1, tracks: d.tracks.length, sharingGroups: model.externalSharing ? model.externalSharing.length : model.sharing.groups.length + 1, packages: Object.keys(packages).length, localisationKeys: loc.keys,
  };
}
