// ---------- writers: doctrines ----------
function whoCondition(clauses, model, depth) { return clauses.length ? whoLines(clauses, model, depth) : [`${tab(depth)}always = yes`]; }

function doctrineFolders(model) {
  const L = [HEADER, '# Doctrine folders (docs/specs/03_gameplay/09_naval_air_doctrines.md section 5).'];
  for (const f of model.doctrines.folders) L.push(`${f.key} = {`, '\tallowed = {', ...condLines(f.allowed, 2), '\t}', `\tname = zin_doctrine_folder_${f.key}`, `\tledger = ${f.ledger}`, `\tledger_gfx = GFX_zin_doctrine_${f.key}_ledger`, `\ttab_gfx = GFX_zin_doctrine_${f.key}_tab`, `\tcolor_frame = ${f.colorFrame}`, `\tsound = ${f.sound}`, '}', '');
  return L.join('\n').trimEnd();
}

function doctrineTracks(model) {
  const L = [HEADER, '# Doctrine tracks and their mastery sources.'];
  for (const t of model.doctrines.tracks) {
    L.push(`${t.key} = {`, `\tname = ${t.key}`, `\tbackground = GFX_${t.key}_bg`, `\ticon = GFX_${t.key}_icon`, `\ticon_frame = GFX_zin_doctrine_decor_${t.folder}`);
    if (t.active) L.push('\tactive = {', ...condLines(t.active, 2), '\t}');
    L.push('\tmastery = {', `\t\tmultiplier = ${num(t.mastery.multiplier)}`);
    if (t.mastery.categories?.length) L.push(`\t\tcategories = { ${t.mastery.categories.join(' ')} }`);
    if (t.mastery.subUnits?.length) L.push(`\t\tsub_units = { ${t.mastery.subUnits.join(' ')} }`);
    if (t.mastery.equipment?.length) L.push(`\t\tequipment = { ${t.mastery.equipment.join(' ')} }`);
    L.push('\t}', '}', '');
  }
  return L.join('\n').trimEnd();
}

function grandAvailable(g, model, depth) {
  const body = [];
  if (g.availableRaw) body.push(...rawLines(g.availableRaw, depth));
  else body.push(...whoCondition(g.whoClauses, model, depth));
  if (g.visibleRaw) body.push(...rawLines(g.visibleRaw, depth));
  if (g.hideForClauses.length) body.push(`${tab(depth)}NOT = {`, ...whoLines(g.hideForClauses, model, depth + 1), `${tab(depth)}}`);
  return body;
}
function grandVisible(g, model, depth) {
  const body = grandAvailable(g, model, depth);
  if (g.folder === 'air') body.push(`${tab(depth)}zin_rules_skies_present = yes`);
  return body;
}
function homeAi(entry, model, depth, base = 1, boost = 10) {
  const L = [`${tab(depth)}ai_will_do = {`, `${tab(depth + 1)}base = ${base}`];
  const homeBody = [];
  if (!entry.homeAll && entry.homeClauses.length) homeBody.push(...whoLines(entry.homeClauses, model, depth + 2));
  if (entry.homeNotClauses?.length) homeBody.push(`${tab(depth + 2)}NOT = {`, ...whoLines(entry.homeNotClauses, model, depth + 3), `${tab(depth + 2)}}`);
  if (entry.homeAll || entry.homeClauses.length) L.push(`${tab(depth + 1)}modifier = {`, `${tab(depth + 2)}factor = ${boost}`, ...homeBody, `${tab(depth + 1)}}`);
  L.push(`${tab(depth)}}`);
  return L;
}

function grandDoctrines(model) {
  const d = model.doctrines, L = [HEADER, '# Grand doctrines: ten for the land, three for the sea, two for the air.'];
  const xp = { land: 'army', naval: 'navy', air: 'air' };
  for (const g of d.grand) {
    L.push(`${g.key} = {`, `\tfolder = ${g.folder}`, `\tname = ${g.key}`, `\tdescription = ${g.key}_desc`, `\ticon = GFX_${g.key}_medium`,
      '\tavailable = {', ...grandAvailable(g, model, 2), '\t}', '\tvisible = {', ...grandVisible(g, model, 2), '\t}',
      '\txp_cost = 100', `\txp_type = ${xp[g.folder]}`, ...homeAi(g, model, 1, 1, 10), `\ttracks = { ${g.tracks.join(' ')} }`);
    L.push(...activationLines(g.act, 1));
    L.push('\tmilestones = {');
    for (const m of g.milestones) L.push('\t\t{', ...activationLines(m, 3), '\t\t}');
    L.push('\t}', '}', '');
  }
  return L.join('\n').trimEnd();
}

function subdoctrines(model, folder) {
  const d = model.doctrines, subs = folder === 'special_forces' ? [d.hidden] : d.subs.filter(s => s.folder === folder);
  const L = [HEADER, `# ${folder} subdoctrines with three rewards each; the third reward needs 150 mastery.`];
  for (const s of subs) {
    const hidden = s === d.hidden;
    L.push(`${s.key} = {`, `\ttrack = ${s.track}`, `\tname = ${s.key}`, `\tdescription = ${s.key}_desc`, `\ticon = GFX_${s.key}_medium`, '\txp_cost = 100', `\txp_type = ${s.xpType}`);
    if (hidden) L.push('\tavailable = {', '\t\talways = no', '\t}', '\tvisible = {', '\t\talways = no', '\t}', '\tai_will_do = {', '\t\tbase = 0', '\t}');
    else {
      L.push('\tavailable = {', ...whoCondition(s.availClauses, model, 2), '\t}', '\tvisible = {', ...whoCondition(s.availClauses, model, 2), '\t}');
      L.push(...homeAi({ homeAll: s.homeAll, homeClauses: s.homeClauses }, model, 1, 1, 10));
    }
    if (s.xor?.length) L.push(`\txor = { ${s.xor.join(' ')} }`);
    L.push(...activationLines(s.act, 1));
    L.push('\trewards = {');
    s.rewards.forEach((r, i) => { L.push(`\t\t${r.key} = {`); if (i === 2) L.push('\t\t\tmastery = 150'); L.push(...activationLines(r, 3), '\t\t}'); });
    L.push('\t}', '}', '');
  }
  return L.join('\n').trimEnd();
}

