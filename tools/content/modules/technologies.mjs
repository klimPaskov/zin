// ---------- game documentation (cached) ----------
let docCache;
export async function gameDocs() {
  if (docCache) return docCache;
  const mod = await readFile(`${GAME}/documentation/modifiers_documentation.md`, 'utf8');
  const modifiers = new Set([...mod.matchAll(/^## ([a-z0-9_]+)$/gm)].map(m => m[1]));
  // Dynamic families: "## <span id=...></span>local_resources_<Resource>_factor" followed by "Modified types: a, b, c".
  const lines = mod.split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^##\s+<span[^>]*><\/span>([a-zA-Z0-9_<>]+)$/);
    if (!m || !/<[A-Za-z]+>/.test(m[1])) continue;
    for (let j = i + 1; j < Math.min(i + 12, lines.length); j++) {
      const t = lines[j].match(/Modified types\*{0,2}:\s*(.+)$/);
      if (t) { for (const type of t[1].split(',').map(s => s.trim()).filter(Boolean)) modifiers.add(m[1].replace(/<[A-Za-z]+>/, type)); break; }
      if (lines[j].startsWith('## ')) break;
    }
  }
  const trig = await readFile(`${GAME}/documentation/triggers_documentation.md`, 'utf8');
  const triggers = new Set([...trig.matchAll(/^## ([A-Za-z0-9_]+)$/gm)].map(m => m[1]));
  const eff = await readFile(`${GAME}/documentation/effects_documentation.md`, 'utf8');
  const effects = new Set([...eff.matchAll(/^## ([A-Za-z0-9_]+)$/gm)].map(m => m[1]));
  const unitTags = new Set();
  for (const e of parse(scriptText(await readFile(`${GAME}/common/unit_tags/00_categories.txt`)))) if (e.k === 'sub_unit_categories' && Array.isArray(e.v)) for (const c of e.v) if (c.k === null) unitTags.add(c.v);
  const aiFocusKeys = new Set();
  for (const f of await readdir(`${GAME}/common/ai_focuses`)) if (f.endsWith('.txt')) for (const e of parse(scriptText(await readFile(`${GAME}/common/ai_focuses/${f}`)))) if (e.k && !/_[A-Z]{3}$/.test(e.k)) aiFocusKeys.add(e.k);
  docCache = { modifiers, triggers, effects, unitTags, aiFocusKeys };
  return docCache;
}

