let vanillaNameCache;
export async function vanillaNames() {
  if (vanillaNameCache) return vanillaNameCache;
  const out = { techs: new Set(), folders: new Set(), categories: new Set(), doctrines: new Set(), sharing: new Set() };
  const roots = [GAME];
  for (const sub of ['dlc', 'integrated_dlc']) { try { for (const d of await readdir(`${GAME}/${sub}`)) roots.push(`${GAME}/${sub}/${d}`); } catch { /* none */ } }
  const files = async dir => { try { return (await readdir(dir, { recursive: true })).filter(f => f.endsWith('.txt')).map(f => `${dir}/${f}`); } catch { return []; } };
  for (const root of roots) {
    for (const f of await files(`${root}/common/technologies`)) for (const e of parse(scriptText(await readFile(f)))) if (e.k === 'technologies' && Array.isArray(e.v)) for (const t of e.v) if (t.k) out.techs.add(t.k);
    for (const f of await files(`${root}/common/technology_tags`)) for (const e of parse(scriptText(await readFile(f)))) {
      if (e.k === 'technology_categories' && Array.isArray(e.v)) for (const c of e.v) if (c.k === null) out.categories.add(c.v);
      if (e.k === 'technology_folders' && Array.isArray(e.v)) for (const c of e.v) if (c.k) out.folders.add(c.k);
    }
    for (const sub of ['grand_doctrines', 'subdoctrines', 'tracks', 'folders']) for (const f of await files(`${root}/common/doctrines/${sub}`)) for (const e of parse(scriptText(await readFile(f)))) if (e.k) out.doctrines.add(e.k);
    for (const f of await files(`${root}/common/technology_sharing`)) for (const e of parse(scriptText(await readFile(f)))) if (e.k === 'technology_sharing_group' && Array.isArray(e.v)) for (const c of e.v) if (c.k === 'id') out.sharing.add(c.v);
  }
  vanillaNameCache = out;
  return out;
}

let vanillaLocCache;
// Every localisation key of the installed game (base and DLC, English). A ZIN value for such a key cannot sit in
// localisation/english (duplicate key), so it goes to localisation/replace/.
export async function vanillaLocKeys() {
  if (vanillaLocCache) return vanillaLocCache;
  const keys = new Set(), roots = [GAME];
  for (const sub of ['dlc', 'integrated_dlc']) { try { for (const d of await readdir(`${GAME}/${sub}`)) roots.push(`${GAME}/${sub}/${d}`); } catch { /* none */ } }
  for (const root of roots) {
    const dir = `${root}/localisation/english`;
    let files = [];
    try { files = (await readdir(dir)).filter(f => f.endsWith('.yml')); } catch { continue; }
    for (const f of files) for (const m of (await readFile(`${dir}/${f}`, 'utf8')).matchAll(/^ ([A-Za-z0-9_.\-]+):\d*\s/gm)) keys.add(m[1]);
  }
  vanillaLocCache = keys;
  return keys;
}

// ---------- who: clauses ----------
// A "who" string is a clause: a people key, country:<name>, region:<key>, group:<name>, joined with + for AND.
// A list of strings is an OR. An empty or missing list admits everyone.
export function parseWho(list, ctx, problems, where) {
  const out = [];
  for (const raw of list ?? []) {
    if (raw.startsWith('group:')) {
      const g = ctx.groups[raw.slice(6)];
      if (!g) { problems.push(`${where}: unknown who group ${raw}`); continue; }
      out.push(...parseWho(g, ctx, problems, where));
      continue;
    }
    const clause = {};
    for (const part of raw.split('+')) {
      if (part.startsWith('country:')) {
        const name = part.slice(8);
        if (!ctx.tags.has(name)) problems.push(`${where}: country ${name} is not in the roster`);
        clause.country = name;
      } else if (part.startsWith('region:')) {
        const r = part.slice(7);
        if (!ctx.ids.regionFlags.includes(r)) problems.push(`${where}: unknown region flag ${r}`);
        clause.region = r;
      } else {
        if (!PEOPLES[part]) problems.push(`${where}: unknown people ${part}`);
        clause.people = part;
      }
    }
    out.push(clause);
  }
  return out;
}

// ---------- the model ----------
// prepareModel validates every row of the data files and returns everything the writers and the tests need. `raw` can replace
// any loaded file (the tests plant bad rows there).
export async function loadRaw() {
  const [civil, warfare, doctrines, packages, ids] = await Promise.all(['technologies.json', 'technologies_warfare.json', 'technologies_doctrines.json', 'technologies_packages.json', 'technologies_ids.json'].map(readJson));
  return { civil, warfare, doctrines, packages, ids };
}

export async function prepareModel({ countries, assignment, externalSharing }, raw0) {
  const raw = raw0 ?? await loadRaw();
  const docs = await gameDocs();
  const problems = [];
  const P = m => problems.push(m);
  const ids = raw.ids;
  const tags = new Map(countries.map(c => [c.name, c.tag]));
  const peopleOfName = name => { const c = countries.find(x => x.name === name); return c ? (assignment?.get(c.tag) ?? defaultPeople(c)) : undefined; };
  const ctx = { groups: raw.warfare.groups ?? {}, tags, ids };

  // folders and categories
  const folders = new Map(), categories = new Map();
  for (const f of raw.civil.folders) { if (folders.has(f.key)) P(`duplicate folder ${f.key}`); folders.set(f.key, f); }
  for (const c of raw.civil.categories) { if (categories.has(c.key)) P(`duplicate category ${c.key}`); categories.set(c.key, c); }
  const lines = new Map();
  for (const l of [...raw.civil.lines, ...raw.warfare.lines]) {
    if (lines.has(l.key)) P(`duplicate line ${l.key}`);
    if (!folders.has(l.folder)) P(`line ${l.key}: unknown folder ${l.folder}`);
    for (const c of l.categories) if (!categories.has(c)) P(`line ${l.key}: unknown category ${c}`);
    for (const s of l.specialization ?? []) if (!ids.specializations.includes(s)) P(`line ${l.key}: unknown specialisation ${s}`);
    lines.set(l.key, l);
  }

  // no vanilla object is reused except the engine keys the spec keeps on purpose
  const vanilla = await vanillaNames();
  for (const k of folders.keys()) if (vanilla.folders.has(k) && !KEPT_FOLDERS.has(k)) P(`folder ${k} is a vanilla folder key`);
  for (const k of categories.keys()) if (vanilla.categories.has(k) && !KEPT_CATEGORIES.has(k)) P(`category ${k} is a vanilla category`);
  for (const g of raw.civil.gates) if (vanilla.techs.has(`${PREFIX}gate_${g.key}`)) P(`gate ${g.key} is a vanilla technology`);
  const rowsAll = [...raw.civil.technologies, ...raw.warfare.technologies];
  for (const r of rowsAll) if (vanilla.techs.has(fullKey(r.key ?? '')) || vanilla.techs.has(r.key ?? '')) P(`technology ${r.key} is a vanilla technology name`);

  // rows
  const rows = [...raw.civil.technologies.map(t => ({ ...t, source: 'civil' })), ...raw.warfare.technologies.map(t => ({ ...t, source: 'warfare' }))];
  const techs = [], byKey = new Map();
  const knownFields = new Set(['key', 'name', 'desc', 'line', 'year', 'cost', 'x', 'requires', 'needs', 'xor', 'modifiers', 'blocks', 'unlocks', 'who', 'allow', 'allowRaw', 'allowBranchRaw', 'completeRaw', 'completeLimitRaw', 'locked', 'grantOnly', 'specialization', 'ai', 'categories', 'inventory', 'source']);
  for (const r of rows) {
    const where = `technology ${r.key}`;
    for (const k of Object.keys(r)) if (!knownFields.has(k)) P(`${where}: unknown field ${k}`);
    if (!/^[a-z0-9_]+$/.test(shortKey(r.key ?? ''))) P(`${where}: bad key`);
    const key = fullKey(r.key);
    if (byKey.has(key)) { P(`duplicate technology ${key}`); continue; }
    const line = lines.get(r.line);
    if (!line) { P(`${where}: unknown line ${r.line}`); continue; }
    if (!Number.isInteger(r.year) || r.year < 1500 || r.year > 1790) P(`${where}: year ${r.year} is outside 1500 to 1790`);
    if (!r.name || !r.desc) P(`${where}: name and desc are required`);
    for (const t of [r.name, r.desc]) if (t && !WINDOWS_1252.test(t)) P(`${where}: text has characters the game font does not draw`);
    const t = {
      key, short: shortKey(key), name: r.name, desc: r.desc, line: r.line, folder: line.folder, year: r.year, source: r.source,
      cost: r.cost ?? ruleCost(r.year, raw.civil.costRule), costExplicit: r.cost !== undefined,
      x: r.x, requires: (r.requires ?? []).map(fullKey), needs: (r.needs ?? []).map(fullKey), xor: (r.xor ?? []).map(fullKey),
      modifiers: r.modifiers ?? {}, blocks: r.blocks ?? [], unlocks: r.unlocks ?? {},
      whoRaw: r.who, allowRaw: r.allowRaw, allowBranchRaw: r.allowBranchRaw, completeRaw: r.completeRaw, completeLimitRaw: r.completeLimitRaw,
      locked: !!r.locked, grantOnly: !!r.grantOnly, ai: r.ai ?? line.ai, extraCategories: r.categories ?? [],
    };
    t.categories = [...new Set([...line.categories, ...t.extraCategories])];
    t.specialization = r.specialization ?? line.specialization ?? [];
    techs.push(t); byKey.set(key, t);
  }
  // who, prerequisites
  for (const t of techs) {
    const where = `technology ${t.short}`;
    t.whoOwn = parseWho(t.whoRaw, ctx, problems, where);
  }
  const effWho = new Map();
  const eff = t => {
    if (effWho.has(t.key)) return effWho.get(t.key);
    let w;
    if (t.whoOwn.length) w = t.whoOwn;
    else if (t.requires.length && byKey.get(t.requires[0])) w = eff(byKey.get(t.requires[0]));
    else w = [];
    effWho.set(t.key, w);
    return w;
  };
  for (const t of techs) t.who = eff(t);
  const dependsOn = new Map();
  for (const t of techs) {
    const where = `technology ${t.short}`;
    if (t.requires.length > 1) P(`${where}: two path parents (a second path parent breaks the gridbox)`);
    for (const p of t.requires) {
      const parent = byKey.get(p);
      if (!parent) { P(`${where}: path parent ${shortKey(p)} does not exist`); continue; }
      if (parent.line !== t.line) P(`${where}: path parent ${parent.short} is in another line (${parent.line}); use needs`);
      if (parent.year > t.year) P(`${where}: path parent ${parent.short} (${parent.year}) is later than the technology (${t.year})`);
      if (!whoCovered(t.who, parent.who, peopleOfName)) P(`${where}: visible to someone who cannot see its path parent ${parent.short}`);
    }
    for (const n of t.needs) {
      const need = byKey.get(n);
      if (!need) { P(`${where}: needs ${shortKey(n)}, which does not exist`); continue; }
      if (need.year > t.year) P(`${where}: needs ${need.short} (${need.year}), which is later than the technology (${t.year})`);
      if (!whoCovered(t.who, need.who, peopleOfName)) P(`${where}: visible to someone who cannot research its dependency ${need.short}`);
    }
    for (const x of t.xor) {
      const other = byKey.get(x);
      if (!other) { P(`${where}: XOR names ${shortKey(x)}, which does not exist`); continue; }
      if (!other.xor.includes(t.key)) P(`${where}: XOR with ${other.short} is written on one side only`);
    }
    dependsOn.set(t.key, [...t.requires, ...t.needs]);
  }
  // cycles
  const state = new Map();
  const visit = (k, trail) => {
    if (state.get(k) === 2) return;
    if (state.get(k) === 1) { P(`technology cycle: ${[...trail, k].map(shortKey).join(' > ')}`); return; }
    state.set(k, 1);
    for (const d of dependsOn.get(k) ?? []) if (byKey.has(d)) visit(d, [...trail, k]);
    state.set(k, 2);
  };
  for (const t of techs) visit(t.key, []);

  // effects, unlocks, triggers
  const checkTrigger = (snippet, where) => {
    let entries;
    try { entries = parse(snippet); } catch (e) { P(`${where}: trigger text does not parse (${e.message})`); return; }
    const walk = es => { for (const e of es) {
      if (e.k === null) continue;
      if (LOGIC.has(e.k)) { if (Array.isArray(e.v)) walk(e.v); continue; }
      if (e.k === 'modifier') { if (Array.isArray(e.v)) walk(e.v.filter(c => !['factor', 'add', 'base'].includes(c.k))); continue; }
      if (!docs.triggers.has(e.k) && !/^zin_(rules_skies_present|rules_skies_beasts|tech_not_zol|tech_people_[a-z_]+)$/.test(e.k)) P(`${where}: unknown trigger ${e.k}`);
    } };
    walk(entries);
    for (const m of snippet.matchAll(/has_global_flag\s*=\s*([A-Za-z0-9_]+)/g)) if (!ids.globalFlags.includes(m[1])) P(`${where}: global flag ${m[1]} is not in the id list`);
    for (const m of snippet.matchAll(/has_tech\s*=\s*([A-Za-z0-9_]+)/g)) if (!byKey.has(m[1])) P(`${where}: has_tech names ${m[1]}, which does not exist`);
  };
  const checkBlocks = (blocks, where) => {
    for (const b of blocks ?? []) {
      const t = b.target ?? '';
      const okTarget = ids.subUnits.includes(t) || ids.zinCategories.includes(t) || docs.unitTags.has(t);
      if (!okTarget) P(`${where}: unit block target ${t} is neither a sub-unit nor a unit category`);
      for (const [s, v] of Object.entries(b.stats ?? {})) { if (!UNIT_STATS.has(s)) P(`${where}: ${s} is not a unit stat the game reads here${s === 'ap_attack' ? ' (piercing is closed to technologies and doctrines: the deathless invariant)' : ''}`); if (typeof v !== 'number') P(`${where}: ${s} must be a number`); }
      for (const [terr, st] of Object.entries(b.terrain ?? {})) { if (!TERRAINS.has(terr)) P(`${where}: unknown terrain ${terr}`); for (const k of Object.keys(st)) if (!TERRAIN_STATS.has(k)) P(`${where}: ${terr} stat ${k} is not attack, defence or movement`); }
    }
  };
  const checkModifiers = (mods, where) => { for (const [k, v] of Object.entries(mods ?? {})) { if (!docs.modifiers.has(k)) P(`${where}: unknown modifier ${k}`); else if (MODERN_MODIFIER.test(k)) P(`${where}: modifier ${k} belongs to a system Erdae does not have`); if (k === 'ap_attack') P(`${where}: piercing is closed to technologies (the deathless invariant)`); if (typeof v !== 'number') P(`${where}: modifier ${k} must be a number`); } };
  const checkEquipment = (id, where) => {
    const m = id.match(/^(.+)_(\d)$/);
    if (!m || !ids.archetypes.includes(m[1])) { P(`${where}: equipment ${id} is not a variant of a known archetype`); return; }
  };
  const FORBIDDEN_BUILDINGS = new Set(ids.buildings.filter(b => !['radar_station', 'anti_air_building', 'stronghold_network', 'air_base'].includes(b)));
  for (const t of techs) {
    const where = `technology ${t.short}`;
    checkModifiers(t.modifiers, where);
    checkBlocks(t.blocks, where);
    for (const e of t.unlocks.equipment ?? []) checkEquipment(e, where);
    for (const s of t.unlocks.subunits ?? []) if (!ids.subUnits.includes(s)) P(`${where}: sub-unit ${s} is not in the id list`);
    for (const m of t.unlocks.modules ?? []) if (!ids.modules.includes(m)) P(`${where}: ship module ${m} is not in the id list`);
    for (const b of t.unlocks.buildings ?? []) {
      if (!ids.buildings.includes(b.building)) P(`${where}: building ${b.building} is not in the id list`);
      if (FORBIDDEN_BUILDINGS.has(b.building)) P(`${where}: ${b.building} must stay locked (only the gate technologies list it)`);
      if (!Number.isInteger(b.level) || b.level < 1 || b.level > 10) P(`${where}: building level ${b.level}`);
    }
    for (const c of t.categories) if (!categories.has(c)) P(`${where}: unknown category ${c}`);
    for (const s of t.specialization) if (!ids.specializations.includes(s)) P(`${where}: unknown specialisation ${s}`);
    for (const f of ['allowRaw', 'allowBranchRaw', 'completeLimitRaw']) if (t[f]) checkTrigger(t[f], `${where} ${f}`);
    if (t.completeRaw) { try { parse(t.completeRaw); } catch (e) { P(`${where}: completeRaw does not parse`); } for (const e of parse(t.completeRaw)) if (e.k && !docs.effects.has(e.k)) P(`${where}: unknown effect ${e.k}`); }
    checkTrigger(t.ai.modifiers ? t.ai.modifiers.map(m => m.trigger).join(' ') : '', `${where} ai`);
    if (typeof t.ai.base !== 'number') P(`${where}: ai base must be a number`);
    if (t.grantOnly) P(`${where}: grantOnly belongs to the gate technologies only (use locked for a visible row nobody researches)`);
    if (t.x !== undefined && !Number.isInteger(t.x)) P(`${where}: x must be an integer`);
  }
  // gates
  const gates = [];
  for (const g of raw.civil.gates) {
    const where = `gate ${g.key}`;
    if (!ids.buildings.includes(g.building)) P(`${where}: building ${g.building} is not in the id list`);
    if (!g.name || !g.desc) P(`${where}: name and desc are required`);
    gates.push({ key: `${PREFIX}gate_${g.key}`, short: `gate_${g.key}`, building: g.building, name: g.name, desc: g.desc });
  }

  // layout
  const placed = techs.filter(t => !t.grantOnly);
  const layout = layoutFolders(placed, lines, raw.civil.bands);
  for (const p of layout.problems) P(`layout: ${p.replace(new RegExp(PREFIX, 'g'), '')}`);
  for (const t of techs) if (!folders.has(t.folder)) P(`technology ${t.short}: unknown folder ${t.folder}`);

  // AI focuses: nine engine keys, every category in at least one
  const aiFocuses = raw.civil.aiFocuses;
  for (const k of Object.keys(aiFocuses)) { if (!docs.aiFocusKeys.has(k)) P(`AI focus ${k} is not an engine AI focus`); for (const c of Object.keys(aiFocuses[k])) if (!categories.has(c)) P(`AI focus ${k} names unknown category ${c}`); }
  for (const k of docs.aiFocusKeys) if (!aiFocuses[k]) P(`engine AI focus ${k} has no ZIN entry`);
  for (const c of categories.keys()) if (!Object.values(aiFocuses).some(f => c in f)) P(`category ${c} appears in no AI focus (the AI would never research it)`);

  const model = { vanilla, raw, docs, ids, tags, countries, assignment, peopleOfName, folders, categories, lines, techs, byKey, gates, layout, aiFocuses, externalSharing: externalSharing ?? null, bands: raw.civil.bands, costRule: raw.civil.costRule, bandCaptions: raw.civil.bandCaptions, problems };
  prepareDoctrines(model, raw, P);
  prepareSharing(model, raw, P);
  if (problems.length) throw new Error(`Technology data is invalid (${problems.length} problems):\n  ${problems.slice(0, 60).join('\n  ')}`);
  return model;
}

// ---------- doctrines ----------
function prepareDoctrines(model, raw, P) {
  const d = raw.doctrines, ids = model.ids, docs = model.docs;
  const trackKeys = new Set(d.tracks.map(t => t.key)), folderKeys = new Set(d.folders.map(f => f.key));
  const xpOf = { land: 'army', naval: 'navy', air: 'air', special_forces: 'army' };
  const resolveTrigger = (name, where) => { if (name && !['always', 'never'].includes(name) && !/^zin_rules_skies_(present|beasts)$/.test(name)) P(`${where}: unknown trigger ${name}`); };
  const checkEffects = (o, where) => {
    for (const k of Object.keys(o?.modifiers ?? {})) { if (!docs.modifiers.has(k)) P(`${where}: unknown modifier ${k}`); else if (MODERN_MODIFIER.test(k)) P(`${where}: modifier ${k} belongs to a system Erdae does not have`); if (k === 'ap_attack') P(`${where}: piercing is closed to doctrines (the deathless invariant)`); }
    for (const [k, v] of Object.entries(o?.modifiers ?? {})) if (typeof v !== 'number') P(`${where}: modifier ${k} must be a number`);
    for (const b of o?.blocks ?? []) {
      const ok = ids.subUnits.includes(b.target) || ids.zinCategories.includes(b.target) || docs.unitTags.has(b.target);
      if (!ok) P(`${where}: block target ${b.target} is neither a sub-unit nor a unit category`);
      for (const s of Object.keys(b.stats ?? {})) if (!UNIT_STATS.has(s)) P(`${where}: ${s} is not a unit stat${s === 'ap_attack' ? ' (piercing is closed to doctrines: the deathless invariant)' : ''}`);
      for (const [terr, st] of Object.entries(b.terrain ?? {})) { if (!TERRAINS.has(terr)) P(`${where}: unknown terrain ${terr}`); for (const k of Object.keys(st)) if (!TERRAIN_STATS.has(k)) P(`${where}: ${terr} stat ${k}`); }
    }
  };
  for (const f of d.folders) { resolveTrigger(f.allowed, `folder ${f.key}`); if (!f.name || !f.desc) P(`folder ${f.key}: name and desc required`); }
  for (const t of d.tracks) {
    const where = `track ${t.key}`;
    if (!folderKeys.has(t.folder)) P(`${where}: unknown folder ${t.folder}`);
    if (!t.name) P(`${where}: name required`);
    resolveTrigger(t.active, where);
    for (const c of t.mastery.categories ?? []) if (!docs.unitTags.has(c) && !ids.zinCategories.includes(c)) P(`${where}: mastery category ${c} is not a unit category`);
    for (const e of t.mastery.equipment ?? []) if (!ids.equipmentTypes.includes(e)) P(`${where}: mastery equipment type ${e} is not known`);
    for (const s of t.mastery.subUnits ?? []) if (!ids.subUnits.includes(s)) P(`${where}: mastery sub-unit ${s} is not in the id list`);
    if (!(t.mastery.categories?.length || t.mastery.equipment?.length || t.mastery.subUnits?.length)) P(`${where}: no mastery source (the track would never gain mastery)`);
  }
  for (const f of d.folders) if (model.vanilla.doctrines.has(f.key) && !KEPT_DOCTRINE_FOLDERS.has(f.key)) P(`doctrine folder ${f.key} is a vanilla key`);
  for (const o of [...d.tracks, ...d.grand, ...d.subs, d.hidden]) if (model.vanilla.doctrines.has(o.key)) P(`doctrine object ${o.key} is a vanilla key`);
  const keys = new Set();
  const dupe = (k, where) => { if (keys.has(k)) P(`${where}: duplicate doctrine key ${k}`); keys.add(k); };
  const tracksUsed = new Map();
  for (const g of d.grand) {
    const where = `grand doctrine ${g.key}`;
    dupe(g.key, where);
    if (!folderKeys.has(g.folder)) P(`${where}: unknown folder ${g.folder}`);
    if (!g.name || !g.desc) P(`${where}: name and desc required`);
    for (const t of g.tracks) { if (!trackKeys.has(t)) P(`${where}: unknown track ${t}`); tracksUsed.set(t, (tracksUsed.get(t) ?? 0) + 1); }
    for (const t of g.tracks) { const tr = d.tracks.find(x => x.key === t); if (tr && tr.folder !== g.folder) P(`${where}: track ${t} belongs to folder ${tr.folder}`); }
    if (g.milestones.length !== g.tracks.length) P(`${where}: ${g.milestones.length} milestones for ${g.tracks.length} tracks (the doctrine screen breaks)`);
    checkEffects(g.act, where);
    g.milestones.forEach((m, i) => checkEffects(m, `${where} milestone ${i + 1}`));
    const ctx = { groups: raw.warfare.groups ?? {}, tags: model.tags, ids };
    const pr = [];
    g.whoClauses = parseWho(g.who, ctx, pr, where); pr.forEach(P);
    g.homeClauses = (g.home ?? []).filter(x => x !== '*').flatMap(x => parseWho([x], ctx, pr, where));
    g.homeAll = (g.home ?? []).includes('*');
    g.homeNotClauses = parseWho(g.homeNot ?? [], ctx, pr, where);
    g.hideForClauses = parseWho(g.hideFor ?? [], ctx, pr, where);
    pr.forEach(P);
    for (const f of ['availableRaw', 'visibleRaw']) if (g[f]) { try { parse(g[f]); } catch { P(`${where}: ${f} does not parse`); } }
  }
  const subKeys = new Set(d.subs.map(s => s.key));
  for (const s of [...d.subs, d.hidden]) {
    const hidden = s === d.hidden;
    const where = `subdoctrine ${s.key}`;
    dupe(s.key, where);
    if (!trackKeys.has(s.track)) P(`${where}: unknown track ${s.track} (the doctrine screen breaks)`);
    const tr = d.tracks.find(x => x.key === s.track);
    s.folder = tr?.folder;
    if (!hidden && !d.grand.some(g => g.tracks.includes(s.track))) P(`${where}: track ${s.track} is in no grand doctrine`);
    if (!s.name || !s.desc) P(`${where}: name and desc required`);
    if (s.rewards.length !== 3) P(`${where}: ${s.rewards.length} rewards, three are required`);
    checkEffects(s.act, where);
    const rk = new Set();
    for (const r of s.rewards) { if (rk.has(r.key)) P(`${where}: duplicate reward ${r.key}`); rk.add(r.key); if (!r.name || !r.desc) P(`${where} reward ${r.key}: name and desc required`); checkEffects(r, `${where} reward ${r.key}`); }
    for (const x of s.xor ?? []) { if (!subKeys.has(x)) P(`${where}: XOR names ${x}, which does not exist`); else if (!(d.subs.find(o => o.key === x).xor ?? []).includes(s.key)) P(`${where}: XOR with ${x} is written on one side only`); }
    const ctx = { groups: raw.warfare.groups ?? {}, tags: model.tags, ids };
    const pr = [];
    s.availClauses = parseWho(s.available, ctx, pr, where);
    s.homeClauses = (s.home ?? []).filter(x => x !== '*').flatMap(x => parseWho([x], ctx, pr, where));
    s.homeAll = (s.home ?? []).includes('*');
    pr.forEach(P);
    s.xpType = xpOf[s.folder] ?? 'army';
  }
  for (const t of d.tracks) if (!tracksUsed.get(t.key) && t.key !== 'zin_track_hidden_special') P(`track ${t.key} is in no grand doctrine`);
  model.doctrines = d;
}

function prepareSharing(model, raw, P) {
  const s = raw.packages.sharing;
  for (const g of s.groups) {
    if (!model.tags.has(g.leader)) P(`sharing group ${g.id}: leader ${g.leader} is not in the roster`);
    if (!g.name || !g.desc) P(`sharing group ${g.id}: name and desc required`);
  }
  if (!(s.bonus > 0 && s.bonus <= 0.5)) P('sharing bonus outside 0..0.5 (MAX_TECH_SHARING_BONUS)');
  for (const g of [...s.groups, s.league]) if (model.vanilla.sharing.has(g.id)) P(`sharing group ${g.id} is a vanilla group`);
  model.sharing = s;
}

// ---------- start packages ----------
function admitted(model, t, profile) { return whoAdmits(t.who, profile); }

// Turns the rule lists of technologies_packages.json into closed lists of technology keys (without the zin_tech_ prefix).
export function technologyPackages(model) {
  const out = {};
  const problems = [];
  for (const pkg of model.raw.packages.packages) {
    const profile = { ...pkg.profile };
    const chosen = new Set();
    const addKey = (k, why) => {
      const t = model.byKey.get(fullKey(k));
      if (!t) { problems.push(`package ${pkg.key}: ${k} does not exist`); return; }
      if (!admitted(model, t, profile)) { problems.push(`package ${pkg.key}: ${k} is not open to ${JSON.stringify(profile)} (${why})`); return; }
      chosen.add(t.key);
    };
    for (const rule of pkg.rules) {
      if (rule.keys) { for (const k of rule.keys) addKey(k, 'named'); continue; }
      for (const t of model.techs) {
        if (rule.maxYear !== undefined && t.year > rule.maxYear) continue;
        if (rule.folders && !rule.folders.includes(t.folder)) continue;
        if (rule.lines && !rule.lines.includes(t.line)) continue;
        if (!rule.folders && !rule.lines) continue;
        if (t.locked || t.xor.length || /has_global_flag/.test(`${t.allowRaw ?? ''}${t.allowBranchRaw ?? ''}`)) continue;
        if (!admitted(model, t, profile)) continue;
        chosen.add(t.key);
      }
    }
    // closure under prerequisites
    const queue = [...chosen];
    while (queue.length) {
      const t = model.byKey.get(queue.pop());
      for (const p of [...t.requires, ...t.needs]) {
        const pt = model.byKey.get(p);
        if (chosen.has(p)) continue;
        if (!admitted(model, pt, profile)) { problems.push(`package ${pkg.key}: ${t.short} needs ${pt.short}, which is not open to ${JSON.stringify(profile)}`); continue; }
        if (pt.locked || pt.xor.length) { problems.push(`package ${pkg.key}: ${t.short} needs ${pt.short}, which a package may not grant`); continue; }
        chosen.add(p); queue.push(p);
      }
    }
    for (const k of chosen) { const t = model.byKey.get(k); if (t.xor.length) problems.push(`package ${pkg.key}: grants the exclusive root ${t.short}`); }
    out[pkg.key] = { name: pkg.name, profile, technologies: [...chosen].map(shortKey).sort() };
  }
  if (problems.length) throw new Error(`Start packages are invalid:\n  ${problems.join('\n  ')}`);
  return out;
}

// The package, technologies and doctrines one country starts with (the politics step and warfare.mjs read this).
export function startFor(model, packages, country, people) {
  const a = model.raw.packages.assign, sd = model.raw.packages.startDoctrines;
  let key = a.named[country.name];
  if (!key && a.byPeople[people]) key = a.byPeople[people];
  if (!key && people === 'men') {
    for (const r of a.men) {
      if (r.scan && !r.scan.includes(country.scan)) continue;
      if (r.maxStates !== undefined && !(country.states <= r.maxStates)) continue;
      if (r.minStates !== undefined && !(country.states >= r.minStates)) continue;
      key = r.package; break;
    }
  }
  key ??= a.theDeadOther;
  const techs = new Set(packages[key].technologies);
  for (const e of a.extras[country.name] ?? []) techs.add(e);
  // closure over prerequisites for the extras
  const queue = [...techs];
  while (queue.length) { const t = model.byKey.get(fullKey(queue.pop())); for (const p of [...t.requires, ...t.needs]) { const s = shortKey(p); if (!techs.has(s)) { techs.add(s); queue.push(s); } } }
  const land = sd.landNamed[country.name] ?? sd.landByPeople[people] ?? null;
  const naval = sd.navalNamed[country.name] ?? sd.navalRegion[country.scan] ?? sd.navalDefault;
  return { package: key, technologies: [...techs].sort(), landGrandDoctrine: land, navalGrandDoctrine: naval[0], navalSubDoctrine: naval[1] };
}

// ---------- writers: conditions ----------
function whoLines(clauses, model, depth) {
  const one = c => {
    const parts = [];
    if (c.people) parts.push(`zin_tech_people_${c.people} = yes`);
    if (c.country) parts.push(`original_tag = ${model.tags.get(c.country)}`);
    if (c.region) parts.push(`has_country_flag = zin_region_${c.region}`);
    return parts;
  };
  const items = clauses.map(c => one(c));
  if (items.length === 1) return items[0].map(p => `${tab(depth)}${p}`);
  const lines = [`${tab(depth)}OR = {`];
  for (const parts of items) {
    if (parts.length === 1) lines.push(`${tab(depth + 1)}${parts[0]}`);
    else { lines.push(`${tab(depth + 1)}AND = {`); parts.forEach(p => lines.push(`${tab(depth + 2)}${p}`)); lines.push(`${tab(depth + 1)}}`); }
  }
  lines.push(`${tab(depth)}}`);
  return lines;
}

function printEntries(entries, depth) {
  const lines = [];
  for (const e of entries) {
    const val = v => (e.quoted ? JSON.stringify(v) : v);
    if (e.k === null && !Array.isArray(e.v)) { lines.push(`${tab(depth)}${val(e.v)}`); continue; }
    if (e.k === null) { lines.push(`${tab(depth)}{`, ...printEntries(e.v, depth + 1), `${tab(depth)}}`); continue; }
    if (Array.isArray(e.v)) {
      if (e.v.length && e.v.every(c => c.k === null && !Array.isArray(c.v))) lines.push(`${tab(depth)}${e.k} ${e.op} { ${e.v.map(c => c.v).join(' ')} }`);
      else lines.push(`${tab(depth)}${e.k} ${e.op} {`, ...printEntries(e.v, depth + 1), `${tab(depth)}}`);
    } else lines.push(`${tab(depth)}${e.k} ${e.op} ${val(e.v)}`);
  }
  return lines;
}
const rawLines = (snippet, depth) => printEntries(parse(snippet), depth);

// A trigger block body for a doctrine or folder condition name.
const condLines = (name, depth) => name === 'never' ? [`${tab(depth)}always = no`] : name === 'always' ? [`${tab(depth)}always = yes`] : [`${tab(depth)}${name} = yes`];

// ---------- writers: technologies ----------
function aiLines(ai, depth, zero) {
  const lines = [`${tab(depth)}ai_will_do = {`, `${tab(depth + 1)}factor = ${zero ? 0 : num(ai.base)}`];
  if (!zero) for (const m of ai.modifiers ?? []) lines.push(`${tab(depth + 1)}modifier = {`, `${tab(depth + 2)}factor = ${num(m.factor)}`, ...rawLines(m.trigger, depth + 2), `${tab(depth + 1)}}`);
  lines.push(`${tab(depth)}}`);
  return lines;
}

function statBlock(b, depth) {
  const lines = [`${tab(depth)}${b.target} = {`];
  for (const k of Object.keys(b.stats ?? {})) lines.push(`${tab(depth + 1)}${k} = ${num(b.stats[k])}`);
  for (const terr of Object.keys(b.terrain ?? {})) { lines.push(`${tab(depth + 1)}${terr} = {`); for (const k of Object.keys(b.terrain[terr])) lines.push(`${tab(depth + 2)}${k} = ${num(b.terrain[terr][k])}`); lines.push(`${tab(depth + 1)}}`); }
  lines.push(`${tab(depth)}}`);
  return lines;
}
// Blocks with the same target are merged, so a doctrine never writes one key twice.
function mergedBlocks(blocks) {
  const by = new Map();
  for (const b of blocks ?? []) {
    const cur = by.get(b.target) ?? { target: b.target, stats: {}, terrain: {} };
    Object.assign(cur.stats, b.stats ?? {});
    for (const [t, st] of Object.entries(b.terrain ?? {})) cur.terrain[t] = { ...(cur.terrain[t] ?? {}), ...st };
    by.set(b.target, cur);
  }
  return [...by.values()];
}
const activationLines = (o, depth) => {
  const lines = [];
  for (const k of Object.keys(o?.modifiers ?? {})) lines.push(`${tab(depth)}${k} = ${num(o.modifiers[k])}`);
  for (const b of mergedBlocks(o?.blocks)) lines.push(...statBlock(b, depth));
  return lines;
};

export function technologyBlock(t, model) {
  const zol = [...t.who].some(c => c.country === 'Zol');
  const d = 2, L = [`${tab(d - 1)}${t.key} = {`];
  const push = (...l) => L.push(...l);
  for (const k of Object.keys(t.modifiers)) push(`${tab(d)}${k} = ${num(t.modifiers[k])}`);
  for (const b of mergedBlocks(t.blocks)) push(...statBlock(b, d));
  const u = t.unlocks;
  if (u.equipment?.length) push(`${tab(d)}enable_equipments = { ${[...u.equipment].sort().join(' ')} }`);
  if (u.modules?.length) push(`${tab(d)}enable_equipment_modules = { ${[...u.modules].sort().join(' ')} }`);
  if (u.subunits?.length) push(`${tab(d)}enable_subunits = { ${[...u.subunits].sort().join(' ')} }`);
  for (const b of u.buildings ?? []) push(`${tab(d)}enable_building = {`, `${tab(d + 1)}building = ${b.building}`, `${tab(d + 1)}level = ${b.level}`, `${tab(d)}}`);
  if (t.completeRaw) {
    if (t.completeLimitRaw) push(`${tab(d)}on_research_complete_limit = {`, ...rawLines(t.completeLimitRaw, d + 1), `${tab(d)}}`);
    push(`${tab(d)}on_research_complete = {`, ...rawLines(t.completeRaw, d + 1), `${tab(d)}}`);
  }
  for (const c of model.techs.filter(x => x.requires.includes(t.key)).sort((a, b) => a.key.localeCompare(b.key, 'en'))) push(`${tab(d)}path = {`, `${tab(d + 1)}leads_to_tech = ${c.key}`, `${tab(d + 1)}research_cost_coeff = 1`, `${tab(d)}}`);
  const slot = model.layout.folders[t.folder].tiles.find(x => x.key === t.key);
  push(`${tab(d)}research_cost = ${num(t.cost)}`, `${tab(d)}start_year = ${t.year}`);
  push(`${tab(d)}folder = {`, `${tab(d + 1)}name = ${t.folder}`, `${tab(d + 1)}position = { x = ${slot.rx} y = ${slot.ry} }`, `${tab(d)}}`);
  push(`${tab(d)}force_use_small_tech_layout = yes`);
  // researchable?
  const allowBody = [];
  if (t.locked) allowBody.push(`${tab(d + 1)}always = no`);
  else if (t.allowRaw) allowBody.push(...rawLines(t.allowRaw, d + 1));
  if (allowBody.length) push(`${tab(d)}allow = {`, ...allowBody, `${tab(d)}}`);
  // visible? roots and rows with an explicit restriction write allow_branch; inherited rows are hidden by their path parent
  const isRoot = !t.requires.length;
  const branch = [];
  if ((isRoot || t.whoOwn.length || t.allowBranchRaw) && !zol) branch.push(`${tab(d + 1)}zin_tech_not_zol = yes`);
  if ((isRoot || t.whoOwn.length) && t.whoOwn.length) branch.push(...whoLines(t.whoOwn, model, d + 1));
  else if (isRoot && t.who.length) branch.push(...whoLines(t.who, model, d + 1));
  if (t.allowBranchRaw) branch.push(...rawLines(t.allowBranchRaw, d + 1));
  if (t.folder === 'zin_skies_folder' && !t.allowBranchRaw) branch.push(`${tab(d + 1)}zin_rules_skies_present = yes`);
  if (branch.length) push(`${tab(d)}allow_branch = {`, ...branch, `${tab(d)}}`);
  push(...aiLines(t.ai, d, t.locked));
  push(`${tab(d)}categories = { ${t.categories.join(' ')} }`);
  if (t.specialization.length) push(`${tab(d)}special_project_specialization = { ${t.specialization.join(' ')} }`);
  if (t.needs.length) push(`${tab(d)}dependencies = {`, ...t.needs.map(n => `${tab(d + 1)}${n} = 1`), `${tab(d)}}`);
  if (t.xor.length) push(`${tab(d)}XOR = { ${t.xor.join(' ')} }`);
  push(`${tab(d - 1)}}`);
  return L.join('\n');
}

function gateBlock(g) {
  return [`\t${g.key} = {`, '\t\tallow = {', '\t\t\talways = no', '\t\t}', '\t\tenable_building = {', `\t\t\tbuilding = ${g.building}`, '\t\t\tlevel = 1', '\t\t}', '\t\tresearch_cost = 1', '\t\tstart_year = 1790', '\t\tai_will_do = {', '\t\t\tfactor = 0', '\t\t}', '\t}'].join('\n');
}

