// ------------------------------------------------------------------------------------------------ text variants
// A text is a string or [{ key?, if?, text }, ..., { text }]. Returns the variants with their loc keys and fills `loc`.
function variants(spec, base, keyBase, W, loc) {
  if (typeof spec === 'string') { loc[keyBase] = spec; return [{ plain: keyBase }]; }
  const out = [];
  spec.forEach((v, i) => {
    const key = !v.if && !v.key ? keyBase : `${keyBase}_${v.key ?? i + 1}`;
    loc[key] = v.text;
    out.push({ key, cond: v.if ?? null });
  });
  if (out.filter(o => !o.cond).length !== 1 || out.at(-1).cond) W.problems.push(`${keyBase}: a variant text needs exactly one default variant, last`);
  return out;
}
function variantLines(field, vs, W) {
  if (vs.length === 1 && vs[0].plain) return [`${field} = ${vs[0].plain}`];
  const conds = vs.map(v => v.cond ? trigger(v.cond, W) : null);
  return vs.flatMap((v, i) => {
    const earlier = conds.slice(0, i).filter(Boolean), lines = [];
    if (conds[i]) lines.push(...conds[i]);
    if (earlier.length) lines.push(...block('NOT', earlier.length === 1 ? earlier[0] : block('OR', earlier.flatMap(c => (c.length === 1 ? c : block('AND', c))))));
    return block(field, [`text = ${v.key}`, ...(lines.length ? block('trigger', lines) : [])]);
  });
}

// ------------------------------------------------------------------------------------------------ one event
export const eventKind = ev => ev.hidden ? 'hidden' : ev.news ? 'news' : 'country';

// sched: { test: trigger lines, seen: flag } added by the lore scheduler. Returns lines.
export function renderEvent(ns, ev, W, loc, sched) {
  const eid = idOf(ns, ev.id), kind = eventKind(ev);
  const title = ev.title === undefined ? '(hidden)' : typeof ev.title === 'string' ? ev.title : ev.title.at(-1).text;
  const note = [ev.to ? `to: ${ev.to}` : '', ev.hist ? `hist: ${ev.hist}` : '', ev.checkpoint ? `checkpoint ${ev.checkpoint}` : ''].filter(Boolean).join('; ');
  const comment = [`# ${title}`, ...(note ? [`# ${note}`] : [])];
  const L = [`id = ${eid}`];
  if (kind === 'hidden') L.push('hidden = yes');
  else {
    const titles = variants(ev.title, 't', `${eid}.t`, W, loc), descs = variants(ev.desc, 'd', `${eid}.d`, W, loc);
    L.push(...variantLines('title', titles, W), ...variantLines('desc', descs, W), `picture = GFX_zin_${kind === 'news' ? 'news' : 'evt'}_${ev.picture}`);
    if (kind === 'news') L.push('major = yes');
  }
  if (ev.mtth) L.push(...block('mean_time_to_happen', Object.entries(ev.mtth).map(([k, v]) => `${k} = ${v}`)));
  else L.push('is_triggered_only = yes');
  if (ev.once) L.push('fire_only_once = yes');
  if (kind !== 'hidden') L.push(`timeout_days = ${TIMEOUT_DAYS}`);
  const trig = [...trigger(ev.trigger, W), ...(sched?.test ?? [])];
  if (trig.length) L.push(...block('trigger', trig));
  const seen = sched?.seen ?? (ev.seen ? ev.seen : null);
  const imm = [...(seen ? [`set_country_flag = ${seen}`] : []), ...effectsPlain(ev.immediate, W)];
  if (imm.length) L.push(...block('immediate', imm));
  if (kind !== 'hidden') {
    const hasHist = ev.options.some(o => o.hist);
    ev.options.forEach((o, i) => {
      const key = `${eid}.${LETTERS[i]}`;
      loc[key] = o.name;
      const body = [`name = ${key}`];
      if (o.if) body.push(...block('trigger', trigger(o.if, W)));
      body.push(...aiChance(o, hasHist, W));
      if (o.tip) { loc[`${key}_tip`] = o.tip; body.push(`custom_effect_tooltip = ${key}_tip`); }
      body.push(...effects(o.effects, W));
      L.push(...block('option', body));
    });
  }
  return [...comment, ...block(kind === 'news' ? 'news_event' : 'country_event', L)];
}

// ------------------------------------------------------------------------------------------------ recipients of the scheduler and the runners
// who: [{ names?, any?, all?, not_names?, share? }] -> clause tests
function clauseTest(c, W) {
  if (typeof c === 'string') c = c.startsWith('group:') ? { all: [c] } : { names: [c] };
  const L = [];
  if (c.names) L.push(...trigger([{ names: c.names }], W));
  if (c.any) L.push(...block('OR', trigger(c.any, W)));
  if (c.all) L.push(...trigger(c.all, W));
  if (c.not_names) L.push(...block('NOT', trigger([{ names: c.not_names }], W)));
  if (c.not) L.push(...block('NOT', trigger(c.not, W)));
  return L.length ? L : ['always = yes'];
}
export function whoTest(who, W) {
  const tests = who.map(c => clauseTest(c, W));
  return tests.length === 1 ? tests[0] : block('OR', tests.flatMap(t => block('AND', t)));
}
const withShare = (call, share) => !share || share >= 100 ? call : block('random_list', [...block(String(share), call), ...block(String(100 - share), [])]);
const call = (kind, id, o) => {
  const extra = ['hours', 'days', 'random_days'].filter(k => o[k] !== undefined && !(k !== 'hours' && o[k] === 0 && k === 'random_days')).map(k => `${k} = ${o[k]}`);
  return extra.length ? block(kind, [`id = ${id}`, ...extra]) : [`${kind} = ${id}`];
};

