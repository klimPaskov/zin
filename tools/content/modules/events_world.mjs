// ------------------------------------------------------------------------------------------------ loading
export async function loadWorldData(dir = DATA_DIR) {
  const files = (await readdir(dir)).filter(f => /^events_world.*\.json$/.test(f)).sort();
  const data = { meta: null, sets: [] };
  for (const f of files) {
    const j = JSON.parse(await readFile(path.join(dir, f), 'utf8'));
    j.file = f;
    if (j.kind === 'meta') { if (data.meta) throw new Error(`two meta files: ${f}`); data.meta = j; } else if (j.kind === 'events') data.sets.push(j); else throw new Error(`${f}: kind must be meta or events`);
  }
  if (!data.meta) throw new Error('data/events_world.json (kind meta) is missing');
  return data;
}
