// Lastwar runner: zin_story_tick_lastwar (spec 03, C6). Every block is inside the guard has_global_flag = zin_war_of_last_crowns.
// A runner entry is { if, to, days?, random_days?, key?, set? }; `to` is a recipient (fire notation), "news", or { who, once }: every
// country that passes `who` (once: and has not seen the event yet; the event sets its own seen flag).
export function lastwarRunner(events, meta, W) {
  const items = [];
  for (const ev of events.filter(e => e.runner)) {
    const eid = idOf('zin_lastwar', ev.id);
    W.used.events.add(eid);
    for (const r of [].concat(ev.runner)) {
      const key = r.key ?? String(ev.id), done = `zin_story_done_lastwar_${key}`, seen = `zin_story_seen_lastwar_${ev.id}`;
      const targets = [].concat(r.to ?? 'self'), onceOnly = targets.some(t => typeof t === 'object' && t.once);
      const timing = { days: r.days, random_days: r.random_days };
      const sends = targets.flatMap(t => {
        if (t === 'news') return call('news_event', eid, timing);
        if (typeof t === 'string') return fire(eid, { ...timing, to: t }, W);
        const limit = [...trigger(t.who, W), ...(t.once ? [`NOT = { has_country_flag = ${seen} }`] : [])];
        return block('every_country', [...block('limit', limit.length ? limit : ['always = yes']), ...call('country_event', eid, timing)]);
      });
      const when = trigger(r.if, W);
      const guard = onceOnly ? when : [`NOT = { has_global_flag = ${done} }`, ...when];
      items.push([`# zin_lastwar.${ev.id} ${typeof ev.title === 'string' ? ev.title : ev.title.at(-1).text}`,
        ...block('if', [...block('limit', guard.length ? guard : ['always = yes']), ...(onceOnly ? [] : [`set_global_flag = ${done}`]), ...effectsPlain(r.set, W), ...sends])]);
    }
  }
  const prelude = effectsPlain(meta.lastwar.prelude, W);
  const runnerBody = block('if', [...block('limit', ['has_global_flag = zin_war_of_last_crowns']), ...prelude, ...items.flatMap(l => ['', ...l])]).map(l => `\t${l}`).join('\n');
  return `${HEADER}
# The story runner of the War of the Last Crowns (event convention C6, R5). zin_story_tick calls it once a month; it fires each
# story event of zin_lastwar once, when its conditions hold, and sets zin_story_done_lastwar_<id>. Events that every qualifying country
# sees once set the country flag zin_story_seen_lastwar_<id> themselves. No event here starts a war. The runner runs in any country
# scope: it uses only global flags, tags and iterators.

zin_story_tick_lastwar = {
${runnerBody}
}
`;
}

