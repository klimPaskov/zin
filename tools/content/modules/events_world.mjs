// ------------------------------------------------------------------------------------------------ build
export async function renderAll(data, countries) {
  const W = await makeWorld(data, countries), meta = data.meta;
  const files = new Map(), locs = {}, ev = {}, counts = {};
  for (const ns of NAMESPACES) {
    ev[ns] = eventsOf(data, ns);
    const loc = locs[ns] = {};
    const sched = new Map();
    if (ns === 'zin_lore') {
      for (const e of ev[ns]) if (e.window && e.who && !e.opening) {
        const seen = `zin_lore_seen_${e.id}`;
        sched.set(e.id, { seen: e.repeatable ? null : seen, test: [...whoTest(e.who, W), ...(e.repeatable ? [] : [`NOT = { has_country_flag = ${seen} }`])] });
      } else if (e.story) {
        const seen = `zin_lore_seen_${e.id}`;
        sched.set(e.id, { seen, test: [...whoTest(e.who, W), `NOT = { has_country_flag = ${seen} }`] });
      } else if (e.opening) sched.set(e.id, { seen: `zin_lore_seen_${e.id}`, test: [] });
    }
    if (ns === 'zin_lastwar') for (const e of ev[ns]) if ([].concat(e.runner ?? []).some(r => [].concat(r.to ?? []).some(t => typeof t === 'object' && t.once))) e.seen ??= `zin_story_seen_lastwar_${e.id}`;
    const text = [HEADER, `add_namespace = ${ns}`, ''];
    for (const e of ev[ns]) text.push(...renderEvent(ns, e, W, loc, sched.get(e.id)), '');
    files.set(`events/${ns}.txt`, text.slice(0, -1).join('\n') + '\n');
    counts[ns] = ev[ns].length;
  }
  files.set('common/scripted_triggers/zin_events_world.txt', triggersFile(meta, W));
  files.set('common/scripted_effects/zin_eindil_events.txt', eindilEffectsFile(meta, W));
  files.set('common/scripted_effects/zin_lastwar_story.txt', lastwarRunner(ev.zin_lastwar, meta, W));
  files.set('common/ai_strategy/zin_lastwar.txt', strategiesFile(meta.lastwar.strategies, W));
  files.set('common/ideas/zin_lastwar.txt', ideasFile(meta.lastwar.ideas, 'The marches hold: the timed idea of zin_lastwar.41.', W));
  files.set('common/opinion_modifiers/zin_lastwar.txt', opinionsFile(meta.lastwar.opinions, 'Opinion modifiers of the War of the Last Crowns.'));
  files.set('common/scripted_effects/zin_lore.txt', loreScheduler(ev.zin_lore, W));
  files.set('common/scripted_effects/zin_lore_story.txt', loreRunner(ev.zin_lore, W));
  files.set('common/scripted_triggers/zin_lore_flavour.txt', `${HEADER}\n# The coast list of the island-fishermen events (spec 05): every realm with a state on the coast of the Kusmeel, never Zol itself.\n\nzin_is_zol_coast_country = {\n\tNOT = { zin_is_zol = yes }\n\tany_owned_state = { zin_is_site_ocean_of_zol_coast = yes }\n}\n`);
  files.set('common/on_actions/zin_lore.txt', loreStartup(meta));
  files.set('common/ideas/zin_lore.txt', ideasFile(meta.lore.ideas, 'Timed ideas of the flavour events.', W));
  files.set('common/opinion_modifiers/zin_lore.txt', opinionsFile(meta.lore.opinions, 'Opinion modifiers of the flavour events (zin_lore). The Eindil events\' own modifiers are the journey module\'s.'));
  for (const [rel, text] of files) files.set(rel, text.replace(/[ 	]+$/gm, ''));
  // localisation: the three event files, plus ideas and opinion modifiers
  const names = { zin_eindil: 'zin_eindil_story', zin_lastwar: 'zin_lastwar', zin_lore: 'zin_lore' };
  for (const [key, def] of Object.entries({ ...meta.lastwar.ideas, ...meta.lore.ideas })) { const ns = key.startsWith('zin_lastwar') ? 'zin_lastwar' : 'zin_lore'; locs[ns][key] = def.name; locs[ns][`${key}_desc`] = def.desc; }
  for (const [key, d] of Object.entries({ ...meta.lastwar.opinions })) locs.zin_lastwar[key] = d.name;
  for (const [key, d] of Object.entries({ ...meta.lore.opinions })) locs.zin_lore[key] = d.name;
  return { files, locs, names, W, counts, events: ev };
}

export async function buildEventsWorld(staged, ctx) {
  const { check } = await import('../lib/ew_check.mjs');
  const data = await loadWorldData();
  const out = await renderAll(data, ctx.countries);
  const problems = await check(data, out, ctx);
  if (problems.length) throw new Error(`Story events break the rules (${problems.length}):\n  ${problems.slice(0, 40).join('\n  ')}`);
  for (const d of [...Object.values(data.meta.lastwar.ideas), ...Object.values(data.meta.lore.ideas)]) await assertModifiers('events_world idea', d.modifier);
  for (const [rel, text] of out.files) staged.text(rel, text);
  for (const [ns, loc] of Object.entries(out.locs)) staged.loc(out.names[ns], loc);
  return { events: out.counts, files: out.files.size + Object.keys(out.locs).length, keys: Object.values(out.locs).reduce((n, l) => n + Object.keys(l).length, 0) };
}
