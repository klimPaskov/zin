// Economy, military and intelligence windows (UI overhaul lane W4, docs/plans/ui_overhaul/02_plan.md phase 2; design system
// docs/specs/07_interface/07_design_system.md §1.2, §1.3, §7; K69, K70: production, construction, trade, logistics, recruitment and the
// military views are Banner Hall, the intelligence agency and the intelligence ledger are Chancery).
//
//   buildMilitaryUi(staged, { read })  -> { overrides, counts }
//
// The Banner Hall windows need no override: the C1 reskin already gives them one material, and the icons whose sockets were empty are
// reskin rows (data/ui/w4_icons.json, sheets icons-w4-*, rules in lib/ui_plan.mjs). The two intelligence windows share vanilla textures with
// the Banner Hall views, so each draws the Chancery sprites of lane W2 (interface/zin_chancery.gfx, built by modules/ui_chancery.mjs before
// this module) instead: the override is the installed vanilla file with sprite names swapped (whole words, every element name and position
// kept) and the two section titles that sit on a dark Chancery band set in the label face with the gold heading colour (vanilla drew them in the
// typewriter face, which the C2 colours make dark reading ink, on paper).
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { GAME } from '../lib/paths.mjs';
import { swapSpriteNames, loadChancery } from './ui_chancery.mjs';

export const MILITARY_UI_FILE = fileURLToPath(new URL('../data/ui/military_ui.json', import.meta.url));
export const loadMilitaryUi = (file = MILITARY_UI_FILE) => JSON.parse(readFileSync(file, 'utf8'));
const HEAD = file => `# ${file}: generated by the ZIN content builder (modules/ui_military.mjs, UI overhaul lane W4) from the installed vanilla file.\n# Shared chrome sprites are swapped for the Chancery sprites of interface/zin_chancery.gfx; every element name and position is vanilla.\n`;

// The own text of an element from its name line to its closing brace (the first line that closes the block at the depth of its name).
function ownEnd(text, from) {
  let depth = 0;
  for (let i = from; i < text.length; i++) { const c = text[i]; if (c === '{') depth++; else if (c === '}' && --depth < 0) return i; }
  return text.length;
}

// Adds `key = value` to the own lines of the first element named `name` (right after its name line); throws when the element is missing
// or already sets the key.
export function setElementKey(text, name, key, value) {
  const re = new RegExp(`(\\n([\\t ]*)name\\s*=\\s*"${name}"[^\\n]*)`);
  const m = re.exec(text);
  if (!m) throw new Error(`military ui: no element ${name}`);
  const own = text.slice(m.index, ownEnd(text, m.index));
  if (new RegExp(`\\n\\s*${key}\\s*=`).test(own)) throw new Error(`military ui: ${name} already sets ${key}`);
  return text.slice(0, m.index) + `${m[1]}\n${m[2]}${key} = "${value}"` + text.slice(m.index + m[1].length);
}

// Replaces the value of `key` in the own lines of the first element named `name`; throws when the element or the key is missing.
export function replaceElementKey(text, name, key, value) {
  const m = new RegExp(`\\n[\\t ]*name\\s*=\\s*"${name}"`).exec(text);
  if (!m) throw new Error(`military ui: no element ${name}`);
  const own = text.slice(m.index, ownEnd(text, m.index));
  const k = new RegExp(`(\\n[\\t ]*${key}\\s*=\\s*)("[^"]*"|\\S+)`).exec(own);
  if (!k) throw new Error(`military ui: ${name} sets no ${key}`);
  const at = m.index + k.index;
  return text.slice(0, at) + k[1] + `"${value}"` + text.slice(at + k[0].length);
}

export function militaryOverrides(spec = loadMilitaryUi(), chancery = loadChancery(), read = f => readFileSync(`${GAME}/${f}`, 'latin1')) {
  const swaps = { ...chancery.swaps, ...spec.swaps };
  for (const k of Object.keys(chancery.emblemSwaps ?? {})) delete swaps[k];
  const files = new Map(), counts = {};
  for (const [rel, o] of Object.entries(spec.overrides)) {
    const r = swapSpriteNames(read(rel), swaps, o.windows);
    const n = Object.values(r.counts).reduce((a, b) => a + b, 0);
    if (n < o.min) throw new Error(`military ui: ${rel} swapped ${n} sprites, expected at least ${o.min}`);
    let text = r.text;
    for (const [name, values] of Object.entries(o.set ?? {})) for (const [k, v] of Object.entries(values)) text = setElementKey(text, name, k, v);
    for (const [name, values] of Object.entries(o.replace ?? {})) for (const [k, v] of Object.entries(values)) text = replaceElementKey(text, name, k, v);
    files.set(rel, HEAD(rel) + text);
    counts[rel] = r.counts;
  }
  return { files, counts };
}

export function buildMilitaryUi(staged, { spec = loadMilitaryUi(), read } = {}) {
  const { files, counts } = militaryOverrides(spec, loadChancery(), read);
  for (const [rel, text] of files) staged.add(rel, Buffer.from(text, 'latin1'));
  return { overrides: [...files.keys()], swapCounts: counts, counts: { overrides: files.size } };
}
