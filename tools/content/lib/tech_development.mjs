// Ways of life and development tiers of the technology tree (owner decision K58, docs/specs/03_gameplay/07_industry_and_electronics_techs.md
// sections 3.5 and 3.6). Called by modules/technologies.mjs.
//
// Ways of life: data/technologies.json `ways` groups cultures (data/cultures_game.json keys) by how their realms live (riders of the steppe,
// peoples of the sand, sea-kings, island folk and so on). A technology whose `who` names way:<key> is seen and researched only by the realms
// whose dominant culture is in that way (scripted trigger zin_way_<key>, which reads the cultures module's zin_is_culture_<culture>).
//
// Development tiers: data/technologies.json `development`. Every realm takes a tier at the start from its start package (learned, settled
// or of custom). The common technologies of the campaign era and later carry the category cat_zin_advanced; the dynamic modifier
// zin_development raises their research cost by the tier's `cost` (the engine's <category>_cost_factor, vanilla precedent
// cat_battlefield_support_cost_factor in common/ideas/GER.txt), and their AI weight is scaled by the tier's `ai`. A realm rises one tier for
// every `step` points of learning: one point for each scholarship technology of `learnFrom` and for each of the two decisions (students sent
// to a learned neighbour or league partner, a house of learning endowed). Every tuning value is written to
// common/script_constants/zin_development.txt; the decision costs and cooldowns are static engine fields written from the same data.
import { readFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ZIN } from './paths.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const HEADER = '# Generated by the ZIN content builder (tools/content/lib/tech_development.mjs, owner decision K58). Do not edit by hand.';
const FALLBACK_TEXTURE = 'gfx/interface/zin/frame.dds';
export const ADVANCED_CATEGORY = 'cat_zin_advanced';
export const DEVELOPMENT_EFFECTS = new Set(['zin_development_learn']);
export const DEVELOPMENT_FILES = {
  constants: 'common/script_constants/zin_development.txt', modifier: 'common/dynamic_modifiers/zin_development.txt', effects: 'common/scripted_effects/zin_development.txt',
  decisions: 'common/decisions/zin_development.txt', category: 'common/decisions/categories/zin_development.txt', sprites: 'interface/zin_development.gfx',
};
const TIER_KEYS = ['learned', 'settled', 'customary'];
const tab = n => '\t'.repeat(n);
const num = v => (Number.isInteger(v) ? String(v) : String(Number(v.toFixed(3))));

// The culture keys of the game layer (data/cultures_game.json).
let culturesCache;
export async function gameCultures() {
  culturesCache ??= new Set(Object.keys(JSON.parse(await readFile(path.join(here, '../data/cultures_game.json'), 'utf8')).cultures));
  return culturesCache;
}

// The ways of life, checked: unique keys, known cultures, no culture in two ways. `has` serves parseWho.
export function prepareWays(list, cultures, P) {
  const byKey = new Map(), byCulture = new Map();
  for (const w of list) {
    if (!/^[a-z_]+$/.test(w.key ?? '')) P(`way ${w.key}: bad key`);
    if (byKey.has(w.key)) P(`duplicate way ${w.key}`);
    if (!w.name || !w.cultures?.length) P(`way ${w.key}: a name and at least one culture are required`);
    for (const c of w.cultures ?? []) {
      if (!cultures.has(c)) P(`way ${w.key}: culture ${c} is not in data/cultures_game.json`);
      if (byCulture.has(c)) P(`way ${w.key}: culture ${c} is already in way ${byCulture.get(c)}`);
      byCulture.set(c, w.key);
    }
    byKey.set(w.key, w);
  }
  return { list, byKey, byCulture, has: k => byKey.has(k) };
}

// The development block, checked against the packages, the categories and the technology rows.
export function prepareDevelopment(dev, raw, categories, P) {
  const tiers = dev.tiers ?? [];
  if (tiers.map(t => t.key).join() !== TIER_KEYS.join()) P(`development: tiers must be ${TIER_KEYS.join(', ')} in that order`);
  tiers.forEach((t, i) => {
    if (t.value !== i + 1) P(`development: tier ${t.key} must have the value ${i + 1}`);
    if (!(t.cost >= 0 && t.cost <= 2)) P(`development: tier ${t.key} cost ${t.cost} is outside 0 to 2`);
    if (!(t.ai > 0 && t.ai <= 1)) P(`development: tier ${t.key} AI factor ${t.ai} is outside (0, 1]`);
    if (!t.name) P(`development: tier ${t.key} needs a name`);
  });
  for (let i = 1; i < tiers.length; i++) if (!(tiers[i].cost > tiers[i - 1].cost && tiers[i].ai < tiers[i - 1].ai)) P(`development: tier ${tiers[i].key} must cost more and weigh less than ${tiers[i - 1].key}`);
  if (!Number.isInteger(dev.step) || dev.step < 1) P('development: step must be a positive integer');
  if (!Number.isInteger(dev.advancedFrom)) P('development: advancedFrom must be a year');
  for (const p of raw.packages.packages) if (!dev.packageTier?.[p.key]) P(`development: package ${p.key} has no tier`);
  for (const [k, v] of Object.entries(dev.packageTier ?? {})) if (v !== 'none' && !TIER_KEYS.includes(v)) P(`development: package ${k} has the unknown tier ${v}`);
  if (!categories.has(ADVANCED_CATEGORY)) P(`development: the category ${ADVANCED_CATEGORY} is not defined`);
  for (const k of dev.learnFrom ?? []) {
    const row = raw.civil.technologies.find(t => t.key === k);
    if (!row) P(`development: learnFrom names ${k}, which does not exist`);
    else if (!/zin_development_learn = yes/.test(row.completeRaw ?? '')) P(`development: ${k} does not call zin_development_learn`);
  }
  const d = dev.decisions ?? {};
  for (const k of ['scholars', 'endow']) if (!(Number.isInteger(d[k]?.cost) && Number.isInteger(d[k]?.days))) P(`development: decision ${k} needs an integer cost and cooldown`);
  if (!(Number.isInteger(d.endow?.factories) && d.endow.factories > 0)) P('development: decision endow needs a positive factory count');
}

// The AI weight of an advanced technology: the line's weight, scaled down for the less developed tiers.
export function developmentAi(ai, dev) {
  return { ...ai, modifiers: [...(ai.modifiers ?? []), ...dev.tiers.filter(t => t.ai !== 1).map(t => ({ factor: t.ai, trigger: `zin_development_${t.key} = yes` }))] };
}

// Scripted triggers: zin_way_<key> (the realm's dominant culture is in the way) and zin_development_<tier>.
export function wayAndTierTriggers(model) {
  const L = [];
  for (const w of model.ways?.list ?? []) L.push('', `zin_way_${w.key} = {`, '\tOR = {', ...w.cultures.map(c => `\t\tzin_is_culture_${c} = yes`), '\t}', '}');
  for (const t of model.development?.tiers ?? []) L.push('', `zin_development_${t.key} = {`, `\tcheck_variable = { zin_dev_tier = ${t.value} }`, '}');
  return L;
}

const textureFor = key => (existsSync(`${ZIN}/gfx/interface/technologies/zin/${key}.dds`) ? `gfx/interface/technologies/zin/${key}.dds` : FALLBACK_TEXTURE);
export const DEVELOPMENT_SPRITES = ['GFX_zin_development_modifier', 'GFX_decision_category_zin_dev_learning', 'GFX_decision_cat_picture_zin_dev_learning', 'GFX_decision_zin_dev_send_scholars', 'GFX_decision_zin_dev_endow_learning'];

export async function writeDevelopment(staged, model, starts) {
  const dev = model.development;
  if (!dev) return;
  const tier = k => dev.tiers.find(t => t.key === k);
  const learned = tier('learned').value;
  // constants
  const C = [HEADER, '# Development tiers (owner decision K58): the extra research cost of advanced learning per tier, and the learning that lifts a realm.', 'zin_development = {', '\tschema = {', '\t\tany_key = yes', '\t\tdata = fixed_point', '\t}', ''];
  for (const t of dev.tiers) C.push(`\t${t.key}_cost = ${num(t.cost)}`);
  C.push(`\tstep = ${dev.step}`, '\tlearn_points = 1', '}');
  staged.text(DEVELOPMENT_FILES.constants, C.join('\n'));
  // dynamic modifier
  staged.text(DEVELOPMENT_FILES.modifier, [HEADER, `# The extra research cost of the advanced common technologies (category ${ADVANCED_CATEGORY}); the variable is set by zin_development_apply.`,
    'zin_development = {', '\ticon = GFX_zin_development_modifier', '\tenable = { always = yes }', `\t${ADVANCED_CATEGORY}_cost_factor = zin_dev_advanced_cost`, '}'].join('\n'));
  // effects
  const tagsOf = k => Object.entries(starts).filter(([, s]) => s.development === k).map(([name]) => model.tags.get(name)).filter(Boolean).sort();
  const orTags = (tags, d) => [`${tab(d)}OR = {`, ...tags.map(t => `${tab(d + 1)}original_tag = ${t}`), `${tab(d)}}`];
  const none = tagsOf('none');
  const E = [HEADER, '# zin_development_init: the start tier of a country (from its start package), once. zin_development_apply: the cost of the tier.',
    '# zin_development_learn: one point of learning; every `step` points lift the tier by one (the scholarship technologies and the decisions call it).', 'zin_development_init = {', '\tif = {', '\t\tlimit = {', '\t\t\tNOT = { has_variable = zin_dev_tier }'];
  if (none.length) E.push('\t\t\tNOT = {', ...orTags(none, 4), '\t\t\t}');
  E.push('\t\t}');
  const lower = dev.tiers.filter(t => t.value !== learned).reverse();
  lower.forEach((t, i) => E.push(`\t\t${i === 0 ? 'if' : 'else_if'} = {`, '\t\t\tlimit = {', ...orTags(tagsOf(t.key), 4), '\t\t\t}', `\t\t\tset_variable = { zin_dev_tier = ${t.value} }`, '\t\t}'));
  E.push('\t\telse = {', `\t\t\tset_variable = { zin_dev_tier = ${learned} }`, '\t\t}', '\t\tset_variable = { zin_dev_progress = 0 }', '\t\tzin_development_apply = yes', '\t}', '}', '', 'zin_development_apply = {');
  dev.tiers.forEach((t, i) => E.push(`\t${i === 0 ? 'if' : 'else_if'} = {`, `\t\tlimit = { zin_development_${t.key} = yes }`, `\t\tset_variable = { zin_dev_advanced_cost = constant:zin_development.${t.key}_cost }`, '\t}'));
  E.push('\tif = {', '\t\tlimit = {', '\t\t\tNOT = { has_dynamic_modifier = { modifier = zin_development } }', '\t\t}', '\t\tadd_dynamic_modifier = { modifier = zin_development }', '\t}', '\tforce_update_dynamic_modifier = yes', '}', '',
    'zin_development_learn = {', '\tif = {', '\t\tlimit = {', `\t\t\tcheck_variable = { zin_dev_tier > ${learned} }`, '\t\t}', '\t\tadd_to_variable = { zin_dev_progress = constant:zin_development.learn_points }', '\t\tcustom_effect_tooltip = zin_development_learn_tt',
    '\t\tset_temp_variable = { zin_dev_step = constant:zin_development.step }', '\t\tif = {', '\t\t\tlimit = {', '\t\t\t\tcheck_variable = { var = zin_dev_progress value = zin_dev_step compare = greater_than_or_equals }', '\t\t\t}',
    '\t\t\tsubtract_from_variable = { zin_dev_progress = zin_dev_step }', '\t\t\tsubtract_from_variable = { zin_dev_tier = 1 }', '\t\t\tzin_development_apply = yes', '\t\t\tcustom_effect_tooltip = zin_development_rise_tt', '\t\t}', '\t}', '}');
  staged.text(DEVELOPMENT_FILES.effects, E.join('\n'));
  // decisions
  const d = dev.decisions;
  staged.text(DEVELOPMENT_FILES.category, [HEADER, 'zin_dev_learning = {', '\ticon = zin_dev_learning', '\tpicture = GFX_decision_cat_picture_zin_dev_learning', '\tpriority = 15', '\tallowed = { always = yes }',
    '\tvisible = {', `\t\tcheck_variable = { zin_dev_tier > ${learned} }`, '\t}', '}'].join('\n'));
  const decision = (key, available, cost, days, aiFactor) => [`\t${key} = {`, `\t\ticon = ${key}`, '\t\tallowed = { always = yes }', '\t\tvisible = {', `\t\t\tcheck_variable = { zin_dev_tier > ${learned} }`, '\t\t}', '\t\tavailable = {', ...available.map(l => `\t\t\t${l}`), '\t\t}',
    `\t\tcost = ${cost}`, `\t\tdays_re_enable = ${days}`, '\t\tcomplete_effect = {', '\t\t\tzin_development_learn = yes', '\t\t}', '\t\tai_will_do = {', `\t\t\tfactor = ${aiFactor}`, '\t\t\tmodifier = {', '\t\t\t\tfactor = 0', '\t\t\t\thas_war = yes', '\t\t\t}', '\t\t}', '\t}'];
  staged.text(DEVELOPMENT_FILES.decisions, [HEADER, '# The learning a less developed realm buys with political power (owner decision K58): students sent to a learned neighbour or league', '# partner, and a house of learning endowed once the realm keeps libraries and workshops. Each adds one point of learning.', 'zin_dev_learning = {',
    ...decision('zin_dev_send_scholars', ['OR = {', '\tany_neighbor_country = { zin_development_learned = yes }', '\tany_country = {', '\t\tis_in_faction_with = ROOT', '\t\tzin_development_learned = yes', '\t}', '}'], d.scholars.cost, d.scholars.days, 3),
    ...decision('zin_dev_endow_learning', ['has_tech = zin_tech_libraries', `num_of_civilian_factories > ${d.endow.factories - 1}`], d.endow.cost, d.endow.days, 2), '}'].join('\n'));
  // text
  const tiersText = dev.tiers.map(t => `${t.name}: ${t.cost ? `advanced crafts cost ${Math.round(t.cost * 100)} per cent more research` : 'no extra cost'}`).join('; ');
  staged.loc('zin_development', {
    zin_development: 'Learning of the Realm',
    zin_development_desc: 'How far the realm\'s scholars, schools and workshops reach. A realm with less learning pays more research for the advanced crafts of the age until its learning grows.',
    [`${ADVANCED_CATEGORY}_cost_factor`]: 'Advanced Learning Research Cost',
    zin_dev_learning: 'Learning of the Realm',
    zin_dev_learning_desc: `The standing of the realm's learning decides what the advanced crafts cost it. ${tiersText}. Each library, university, conclave of scholars and royal academy researched, each band of students sent abroad and each house of learning endowed adds to the realm's learning, and every ${dev.step} such steps raise it one standing.`,
    zin_dev_send_scholars: 'Send Students to Learned Lands',
    zin_dev_send_scholars_desc: 'Young scholars go to study in a learned neighbour or league partner and come home with books, methods and friends.',
    zin_dev_endow_learning: 'Endow a House of Learning',
    zin_dev_endow_learning_desc: 'The crown endows a house where scholars teach the crafts of the libraries and workshops, and pays its masters for years to come.',
    zin_development_learn_tt: 'The realm\'s learning grows.',
    zin_development_rise_tt: 'The realm rises to a higher standing of learning, and the advanced crafts cost it less research.',
  });
  // sprites
  const S = [HEADER, '# The development sprites; each points at its own DDS once the art step ships it and at the ZIN frame until then.', 'spriteTypes = {'];
  const keyOf = { GFX_zin_development_modifier: 'zin_development_modifier', GFX_decision_category_zin_dev_learning: 'decision_category_zin_dev_learning', GFX_decision_cat_picture_zin_dev_learning: 'decision_cat_picture_zin_dev_learning', GFX_decision_zin_dev_send_scholars: 'decision_zin_dev_send_scholars', GFX_decision_zin_dev_endow_learning: 'decision_zin_dev_endow_learning' };
  for (const s of DEVELOPMENT_SPRITES) S.push('\tspriteType = {', `\t\tname = "${s}"`, `\t\ttexturefile = "${textureFor(keyOf[s])}"`, '\t}');
  S.push('}');
  staged.text(DEVELOPMENT_FILES.sprites, S.join('\n'));
}
