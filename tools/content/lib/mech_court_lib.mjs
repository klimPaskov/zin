// ------------------------------------------------------------------------------------------------- text shaping
// Script text is written loosely (template literals with the indentation of the JS source) and indented once, at the end, from
// the braces by format(). dedent() only drops the blank first and last line and the leading blanks of each line.
export function dedent(text) {
  return String(text).replace(/^\n/, '').replace(/\n[\t ]*$/, '').split('\n').map(l => l.trim()).join('\n');
}
export const ind = text => String(text);
// Re-indents a script from its braces: one tab per open brace; a closing brace at the start of a line steps back first.
export function format(text) {
  let depth = 0;
  return String(text).split('\n').map(raw => {
    const line = raw.trim();
    if (!line) return '';
    const code = line.startsWith('#') ? '' : line.replace(/"[^"]*"/g, '');
    const opens = (code.match(/\{/g) ?? []).length, closes = (code.match(/\}/g) ?? []).length;
    const lead = (code.match(/^\}+/) ?? [''])[0].length;
    const here = Math.max(0, depth - lead);
    depth = Math.max(0, depth + opens - closes);
    return '\t'.repeat(here) + line;
  }).join('\n');
}
export const blk = (name, body) => `${name} = {\n${ind(dedent(body))}\n}`;
export const list = (...parts) => parts.flat().filter(x => x !== undefined && x !== null && x !== '').join('\n');
export const num = v => (Number.isInteger(v) ? String(v) : String(Number(Number(v).toFixed(4))));

// A scripted-effect call with arguments (decision E1): temporary variables zin_arg_<name>, then the call.
export function call(effect, args = {}) {
  const set = Object.entries(args).map(([k, v]) => `set_temp_variable = { zin_arg_${k} = ${typeof v === 'number' ? num(v) : v} }`);
  return list(set, `${effect} = yes`);
}
// A scripted effect that reads zin_arg_<name>: copies each into a local temp and clears the argument.
export const takeArgs = (...names) => names.map(n => `set_temp_variable = { zin_${n} = zin_arg_${n} }\nclear_variable = zin_arg_${n}`).join('\n');

// ------------------------------------------------------------------------------------------------- story dates
// Erdae has no leap days (Paradox wiki, Event modding). Date d moves to start + (d - start) * pace for pace 1.0, 1.5, 0.75.
const MONTH_DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const serial = ([y, m, d]) => y * 365 + MONTH_DAYS.slice(0, m - 1).reduce((a, b) => a + b, 0) + d - 1;
const unserial = n => {
  const y = Math.floor(n / 365); let rest = n - y * 365, m = 0;
  while (rest >= MONTH_DAYS[m]) { rest -= MONTH_DAYS[m]; m++; }
  return [y, m + 1, rest + 1];
};
export const START = [1748, 3, 1];
export const parseDate = s => s.split('.').map(Number);
export const fmtDate = d => d.join('.');
export function paceDate(date, pace) {
  const a = serial(START), b = serial(parseDate(date));
  return fmtDate(unserial(a + Math.round((b - a) * pace)));
}
export const PACES = { standard: 1, slow: 1.5, fast: 0.75 };
// "On or after" test. The standard date is the first day the trigger is true; `date >` is true after the given day.
const before = d => fmtDate(unserial(serial(parseDate(d)) - 1));
export function dateTrigger(name, date, note = '') {
  const when = pace => `date > ${before(paceDate(date, pace))}`;
  const pv = 'global.zin_story_pace';
  const L = [];
  if (note) L.push(`# ${note}`);
  L.push(`${name} = {`, '\tOR = {',
    '\t\tAND = {', `\t\t\tcheck_variable = { ${pv} > 1.25 }`, `\t\t\t${when(PACES.slow)}`, '\t\t}',
    '\t\tAND = {', `\t\t\tcheck_variable = { ${pv} > 0 }`, `\t\t\tcheck_variable = { ${pv} < 0.875 }`, `\t\t\t${when(PACES.fast)}`, '\t\t}',
    '\t\tAND = {', '\t\t\tOR = {', `\t\t\t\tcheck_variable = { ${pv} = 0 }`,
    '\t\t\t\tAND = {', `\t\t\t\t\tcheck_variable = { ${pv} > 0.875 }`, `\t\t\t\t\tcheck_variable = { ${pv} < 1.25 }`, '\t\t\t\t}', '\t\t\t}',
    `\t\t\t${when(PACES.standard)}`, '\t\t}', '\t}', '}');
  return L.join('\n');
}

// ------------------------------------------------------------------------------------------------- sprites
// Every picture is a catalog icon (gfx/interface/ideas/zin/<key>.dds). Names are GFX_decision_<icon>, GFX_decision_category_<id>,
// GFX_decision_cat_picture_<id>, GFX_modifiers_<id> and the GFX_zin_mech_* sprites of the panels. No texture is invented.
export class Sprites {
  constructor(catalogKeys, extraTextures = {}) { this.keys = new Set(catalogKeys); this.map = new Map(); this.extra = extraTextures; this.frames = new Map(); }
  use(name, art) {
    if (!this.keys.has(art) && !this.extra[art]) throw new Error(`Sprite ${name}: art key ${art} is not in the icon catalog`);
    if (this.map.has(name) && this.map.get(name) !== art) throw new Error(`Sprite ${name} bound to two pictures (${this.map.get(name)}, ${art})`);
    this.map.set(name, art);
    return name;
  }
  has(name) { return this.map.has(name); }
  text(header) {
    const body = [...this.map].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, art]) => `\tspriteType = {\n\t\tname = "${name}"\n\t\ttexturefile = "${this.extra[art] ?? `gfx/interface/ideas/zin/${art}.dds`}"${this.frames.get(name) ? `\n\t\tnoOfFrames = ${this.frames.get(name)}` : ''}\n\t}`);
    return `${header}\nspriteTypes = {\n${body.join('\n')}\n}\n`;
  }
  get size() { return this.map.size; }
}

// ------------------------------------------------------------------------------------------------- events
// One event definition: { id, kind: country|news|hidden, title, desc, picture, requires, trigger, mtth, immediate, options, checkpoint,
// fireOnce, major }. Text goes to `loc`; the keys are <ns>.<id>.t / .d / .<option>. `desc` may be an array of { trigger, text }.
export function writeEvent(ns, e, loc, opts = {}) {
  const id = `${ns}.${e.id}`;
  const hidden = e.kind === 'hidden';
  const head = [`id = ${id}`];
  if (!hidden) {
    loc.set(`${id}.t`, e.title);
    head.push(`title = ${id}.t`);
    if (Array.isArray(e.desc)) {
      e.desc.forEach((d, i) => loc.set(`${id}.desc${i ? i : ''}`, d.text));
      head.push(...e.desc.map((d, i) => `desc = {\n\ttext = ${id}.desc${i ? i : ''}${d.trigger ? `\n\ttrigger = {\n${ind(dedent(d.trigger), 2)}\n\t}` : ''}\n}`));
    } else { loc.set(`${id}.desc`, e.desc); head.push(`desc = ${id}.desc`); }
    const pic = e.kind === 'news' ? `GFX_zin_news_${e.picture}` : `GFX_zin_evt_${e.picture}`;
    head.push(`picture = ${pic}`);
  } else head.push('hidden = yes');
  if (e.kind === 'news') head.push('major = yes');
  if (e.fireOnce) head.push('fire_only_once = yes');
  if (e.trigger || e.mtth) {
    if (e.trigger) head.push(blk('trigger', e.trigger));
    if (e.mtth) head.push(blk('mean_time_to_happen', e.mtth));
  } else head.push('is_triggered_only = yes');
  if (!hidden) head.push(`timeout_days = ${e.timeout ?? 30}`);
  if (e.showMajor) head.push(blk('show_major', e.showMajor));
  if (e.immediate) head.push(blk('immediate', e.immediate));
  const options = (e.options ?? [{ key: 'a', text: hidden ? (opts.hiddenOk ?? 'The month turns.') : (opts.okText ?? 'So it stands.') }]).map(o => {
    const key = `${id}.${o.key}`;
    loc.set(key, o.text);
    const parts = [`name = ${key}`];
    if (o.trigger) parts.push(blk('trigger', o.trigger));
    if (o.ai !== undefined) parts.push(typeof o.ai === 'number' ? `ai_chance = { base = ${o.ai} }` : blk('ai_chance', o.ai));
    if (o.effect) parts.push(dedent(o.effect));
    return blk('option', parts.join('\n'));
  });
  const verb = e.kind === 'news' ? 'news_event' : 'country_event';
  return { id, text: `${verb} = {\n${ind(head.join('\n'))}\n\n${ind(options.join('\n\n'))}\n}`, meta: { ...e, full: id } };
}

// ------------------------------------------------------------------------------------------------- decisions
// { id, icon, visible, available, allowed, cost (PP), costTrigger, costText, days (days_remove), cooldown, once, effect, remove,
//   target (trigger text with FROM), targets, root, ai, title, desc, tooltip }
export function writeDecision(d, loc, sprites) {
  loc.set(d.id, d.title);
  if (d.desc) loc.set(`${d.id}_desc`, d.desc);
  const out = [];
  out.push(`icon = ${d.icon}`);
  sprites?.use(`GFX_decision_${d.icon}`, d.art ?? d.icon);
  if (d.picture) out.push(`picture = ${d.picture}`);
  out.push(blk('allowed', d.allowed ?? 'always = yes'));
  if (d.rootTrigger) out.push(blk('target_root_trigger', d.rootTrigger));
  if (d.targets) out.push(`targets = { ${d.targets.join(' ')} }`);
  if (d.targetsDynamic) out.push('targets_dynamic = yes');
  if (d.stateTarget) out.push(`state_trigger = ${d.stateTarget}`);
  if (d.target) out.push(blk('target_trigger', d.target));
  if (d.onMap) out.push('on_map_mode = map_and_decisions_view');
  if (d.visible) out.push(blk('visible', d.visible));
  if (d.available) out.push(blk('available', d.available));
  if (d.cost !== undefined) out.push(`cost = ${num(d.cost)}`);
  if (d.costTrigger) { out.push(blk('custom_cost_trigger', d.costTrigger)); loc.set(`${d.id}_cost_tt`, d.costText); out.push(`custom_cost_text = ${d.id}_cost_tt`); }
  if (d.days) out.push(`days_remove = ${d.days}`);
  if (d.cooldown) out.push(`days_re_enable = ${d.cooldown}`);
  if (d.once) out.push('fire_only_once = yes');
  if (d.cancel) out.push(blk('cancel_trigger', d.cancel));
  if (d.effect) out.push(blk('complete_effect', d.effect));
  if (d.remove) out.push(blk('remove_effect', d.remove));
  if (d.timeoutEffect) out.push(blk('timeout_effect', d.timeoutEffect));
  out.push(d.ai === undefined ? 'ai_will_do = {\n\tbase = 0\n}' : blk('ai_will_do', d.ai));
  return blk(d.id, out.join('\n'));
}
export const category = (id, o, loc, sprites) => {
  loc.set(id, o.title);
  loc.set(`${id}_desc`, o.desc);
  sprites.use(`GFX_decision_category_${id}`, o.art);
  const out = [`icon = ${id}`, o.picture ? `picture = GFX_decision_cat_picture_${id}` : '', `priority = ${o.priority ?? 30}`, blk('allowed', o.allowed ?? 'always = yes'), blk('visible', o.visible ?? 'always = yes')];
  if (o.picture) sprites.use(`GFX_decision_cat_picture_${id}`, o.picture);
  if (o.scriptedGui) out.push(`scripted_gui = ${o.scriptedGui}`);
  return blk(id, list(out));
};

