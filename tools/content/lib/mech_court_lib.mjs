// A tooltip helper for option effects: shows one line of plain text and hides the arithmetic behind it. Keys are <prefix>_tt_<slug>.
export function tipper(prefix, loc) {
  return (text, ...body) => {
    const key = `${prefix}_tt_${text.toLowerCase().replace(/\+/g, ' plus ').replace(/-/g, ' minus ').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 56)}`;
    loc.set(key, text);
    return `custom_effect_tooltip = ${key}\nhidden_effect = {\n${list(body)}\n}`;
  };
}
