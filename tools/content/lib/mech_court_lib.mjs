// Words that name the secret. A key is public unless it carries one of the private suffixes; the scan skips those.
export const SECRET_WORDS = /\bAfrit\b|Hidden Council|\bdemon\b|poisoner|murder|\bplot\b/i;
export function secrecyLeaks(entries, isPrivate = k => /(_hub|_true|_revealed|_private)$/.test(k)) {
  const hits = [];
  for (const [k, v] of Object.entries(entries)) { if (isPrivate(k)) continue; const m = SECRET_WORDS.exec(readable(v)); if (m) hits.push(`${k}: ${m[0]}`); }
  return hits;
}
export async function wordProblems(entries) {
  const rules = await loadBanned(), hits = [];
  for (const [key, value] of Object.entries(entries)) { const t = readable(value); for (const r of rules) { const m = r.re.exec(t); if (m) hits.push(`${key}: ${m[0]} (${r.id})`); } }
  return hits;
}
