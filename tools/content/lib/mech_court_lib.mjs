// Every command key inside effect and trigger positions must be documented, a control word, a variable name or one of `mine`.
export async function unknownCommands(scriptText, mine = new Set()) {
  const v = await gameVocabulary();
  const all = new Set([...v.effects, ...v.triggers, ...v.modifiers]);
  const unknown = new Set();
  const visit = list => {
    for (const e of list) {
      if (e.k && !all.has(e.k) && !CONTROL.has(e.k) && !mine.has(e.k) && !/[@:.]|^[A-Z0-9]{2,4}$|^zin_|^GFX_|^var$|^[A-Z][A-Za-z0-9_]+$/.test(e.k) && !/^\d+$/.test(e.k) && !/^(democratic|fascism|communism|neutrality)$/.test(e.k)) unknown.add(e.k);
      if (Array.isArray(e.v)) visit(e.v);
    }
  };
  visit(parse(scriptText));
  return [...unknown].sort();
}

