/**
 * Source indentation becomes tabs: a level is one tab or two spaces, so a fragment that is already tab-indented can be
 * embedded in a template. `depth` tabs are added in front. Blank lines stay empty.
 */
export function fmt(text, depth = 0) {
  return String(text).replace(/^\n+/, '').replace(/\s+$/, '').split('\n').map(line => {
    if (!line.trim()) return '';
    const lead = /^[\t ]*/.exec(line)[0];
    const tabs = (lead.match(/\t/g) ?? []).length, spaces = (lead.match(/ /g) ?? []).length;
    if (spaces % 2) throw new Error(`Odd indentation (${spaces} spaces) in: ${line.trim().slice(0, 60)}`);
    return '\t'.repeat(depth + tabs + spaces / 2) + line.slice(lead.length);
  }).join('\n');
}
/** Adds `n` tabs in front of every non-empty line of an already tab-indented fragment. */
export const ind = (n, text) => String(text).split('\n').map(l => (l.trim() ? '\t'.repeat(n) + l : l)).join('\n');
export const num = v => (Number.isInteger(v) ? String(v) : String(Number(Number(v).toFixed(4))));
export const HEADER = (module, spec) => `# Generated by the ZIN content builder (modules/${module}.mjs, spec ${spec}). Do not edit by hand.`;
/** The call convention of decision E1: one temporary variable per argument, then the effect. Values are numbers or script text. */
export function call(effect, args = {}) {
  return [...Object.entries(args).map(([k, v]) => `set_temp_variable = { zin_arg_${k} = ${typeof v === 'number' ? num(v) : v} }`), `${effect} = yes`].join('\n');
}
/** Joins fragments with newlines, dropping the empty ones. */
export const join = (...parts) => parts.flat().filter(p => p !== undefined && p !== null && p !== false && String(p).trim() !== '').join('\n');

// ------------------------------------------------------------------------------------------------ the roster
/** Resolves country names to their roster rows; with `scan`, the roster region must match. */
export function resolveCountries(countries, names, scan) {
  const byName = new Map(countries.map(c => [c.name, c]));
  const out = new Map();
  for (const n of names) {
    const c = byName.get(n);
    if (!c) throw new Error(`The data names ${n}, which is not in the roster`);
    if (scan && c.scan !== scan) throw new Error(`The data names ${n} as a ${scan} country, but the roster puts it in ${c.scan}`);
    out.set(n, c);
  }
  return out;
}

// ------------------------------------------------------------------------------------------------ story dates
const MONTH_DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const YEAR_DAYS = 365;
const [START_Y, START_M, START_D] = START_DATE.split('.').map(Number);
const monthStart = m => MONTH_DAYS.slice(0, m - 1).reduce((a, b) => a + b, 0);
/** Days from the start date (1 Thaw 4A 1748) to y.m.d; the engine year has no leap days. */
export const dayOf = (y, m, d) => (y - START_Y) * YEAR_DAYS + monthStart(m) + d - (monthStart(START_M) + START_D);
export function dateOfDay(n) {
  const total = n + monthStart(START_M) + START_D - 1 + START_Y * YEAR_DAYS;   // zero-based day number since year 0
  const y = Math.floor(total / YEAR_DAYS);
  let rest = total - y * YEAR_DAYS, m = 0;
  while (rest >= MONTH_DAYS[m]) { rest -= MONTH_DAYS[m]; m++; }
  return [y, m + 1, rest + 1];
}
export const PACES = { standard: 1, slow: 1.5, fast: 0.75 };
/** The engine date a story date takes at a story pace (decision V4: start + (date - start) x pace), as y.m.d. */
export function paceDate(y, m, d, pace) {
  const [py, pm, pd] = dateOfDay(Math.round(dayOf(y, m, d) * pace));
  return `${py}.${pm}.${pd}`;
}
/**
 * A scripted trigger that is true after a story date at every story pace. The pace is the global variable zin_story_pace
 * (1, 1.5 or 0.75, set by the rules); while it is unset the standard date applies.
 */
export function dateTrigger(id, y, m, d, note = '') {
  const std = paceDate(y, m, d, PACES.standard), slow = paceDate(y, m, d, PACES.slow), fast = paceDate(y, m, d, PACES.fast);
  const pace = c => `check_variable = { global.zin_story_pace ${c} }`;
  return fmt(`
${note ? `# ${note}\n` : ''}${id} = {
  OR = {
    AND = { ${pace('> 1.25')} date > ${slow} }
    AND = { ${pace('> 0.9')} ${pace('< 1.25')} date > ${std} }
    AND = { ${pace('> 0.5')} ${pace('< 0.9')} date > ${fast} }
    AND = { ${pace('< 0.5')} date > ${std} }
  }
}`);
}

// ------------------------------------------------------------------------------------------------ text guards
let rules;
/** Fails the build on a banned word (error severity) or a character the game font cannot draw. */
export async function assertCleanText(where, entries) {
  rules ??= compileBanned(await loadRuleSet({ glossary: await loadGlossary() }));
  const hits = [];
  for (const [key, value] of Object.entries(entries)) for (const h of findBanned(readable(value), rules, ['error'])) hits.push(`${key}: "${h.word}" (${h.id})`);
  const bad = notCp1252(entries).map(b => `font ${b}`);
  if (hits.length || bad.length) throw new Error(`${where}: text problems\n  ${[...hits, ...bad].slice(0, 20).join('\n  ')}`);
}

// ------------------------------------------------------------------------------------------------ renderers
const aiBlock = (ai, depth) => {
  if (ai === undefined || ai === null) return '';
  if (typeof ai === 'number') return `${'\t'.repeat(depth)}base = ${num(ai)}`;
  const lines = [`base = ${num(ai.base ?? 0)}`];
  for (const m of ai.mods ?? []) lines.push(`modifier = {\n${m.factor !== undefined ? `\tfactor = ${num(m.factor)}` : `\tadd = ${num(m.add)}`}\n${ind(1, fmt(m.when))}\n}`);
  return ind(depth, lines.join('\n'));
};
const inner = text => ind(1, fmt(text));

/**
 * One event block. kind is country_event (default) or news_event. The texts come from T by convention: <id>.t, <id>.d (or
 * <id>.d_<key> for the descVariants { key, trigger }) and <id>.<option key>. Every shown event carries timeout_days = 30
 * (E2): a timed-out event takes its first option. Hidden events have no texts and no options, only an immediate block.
 */
export function renderEvent(e, T) {
  const kind = e.kind ?? 'country_event';
  const L = [`id = ${e.id}`];
  if (e.hidden) L.push('hidden = yes');
  else {
    L.push(`title = ${T.use(`${e.id}.t`)}`);
    if (e.descVariants) for (const v of e.descVariants) L.push(`desc = {\n\ttext = ${T.use(`${e.id}.d_${v.key}`)}${v.trigger ? `\n\ttrigger = {\n${ind(2, fmt(v.trigger))}\n\t}` : ''}\n}`);
    else L.push(`desc = ${T.use(`${e.id}.d`)}`);
    if (!e.picture) throw new Error(`Event ${e.id} has no picture`);
    L.push(`picture = ${e.picture}`);
  }
  if (kind === 'news_event' || e.major) L.push('major = yes');
  if (e.show_major) L.push(`show_major = {
${inner(e.show_major)}
}`);
  if (e.fire_only_once) L.push('fire_only_once = yes');
  if (!e.mtth && !e.auto) L.push('is_triggered_only = yes');
  if (e.trigger) L.push(`trigger = {\n${inner(e.trigger)}\n}`);
  if (e.mtth) L.push(`mean_time_to_happen = {\n${inner(e.mtth)}\n}`);
  if (!e.hidden) L.push('timeout_days = 30');
  if (e.immediate) L.push(`immediate = {\n${inner(e.immediate)}\n}`);
  if (!e.hidden) {
    if (!e.options?.length) throw new Error(`Event ${e.id} has no option`);
    for (const o of e.options) {
      const parts = [`name = ${T.use(`${e.id}.${o.key}`)}`];
      if (o.trigger) parts.push(`trigger = {\n${inner(o.trigger)}\n}`);
      if (o.ai !== undefined) parts.push(`ai_chance = {\n${aiBlock(o.ai, 1)}\n}`);
      if (o.effect) parts.push(fmt(o.effect));
      L.push(`option = {\n${ind(1, parts.join('\n'))}\n}`);
    }
  } else if (e.options?.length) throw new Error(`Hidden event ${e.id} has options`);
  return `${kind} = {\n${ind(1, L.join('\n'))}\n}`;
}

const DECISION_ORDER = ['icon', 'priority', 'allowed', 'target_root_trigger', 'targets', 'targets_dynamic', 'target_array', 'state_target', 'target_trigger', 'on_map_mode', 'visible', 'available', 'cancel_trigger', 'cost', 'custom_cost_trigger', 'custom_cost_text', 'ai_hint_pp_cost', 'days_re_enable', 'days_remove', 'days_mission_timeout', 'fire_only_once', 'fixed_random_seed', 'war_with_target_on_complete', 'modifier', 'highlight_states', 'complete_effect', 'remove_effect', 'timeout_effect', 'cancel_effect'];
const SCALAR_KEYS = new Set(['icon', 'priority', 'targets_dynamic', 'state_target', 'on_map_mode', 'cost', 'custom_cost_text', 'ai_hint_pp_cost', 'days_re_enable', 'days_remove', 'days_mission_timeout', 'fire_only_once', 'fixed_random_seed', 'war_with_target_on_complete', 'target_array']);
/** One decision or mission. Block keys take script text, scalar keys a value, targets a list of tags. Texts <id> and <id>_desc come from T. */
export function renderDecision(d, T) {
  T.use(d.id); T.use(`${d.id}_desc`);
  for (const k of d.extraText ?? []) T.use(k);
  const L = [];
  for (const key of DECISION_ORDER) {
    const v = d[key];
    if (v === undefined || v === null || v === false) continue;
    if (key === 'targets') L.push(`targets = { ${v.join(' ')} }`);
    else if (SCALAR_KEYS.has(key)) L.push(`${key} = ${typeof v === 'number' ? num(v) : v === true ? 'yes' : v}`);
    else L.push(`${key} = {\n${inner(v)}\n}`);
  }
  if (d.ai !== undefined) L.push(`ai_will_do = {\n${aiBlock(d.ai, 1)}\n}`);
  return `${d.id} = {\n${ind(1, L.join('\n'))}\n}`;
}
export function renderCategory(c, T) {
  T.use(c.id); T.use(`${c.id}_desc`);
  const L = [];
  if (c.icon) L.push(`icon = ${c.icon}`);
  if (c.priority) L.push(`priority = ${c.priority}`);
  if (c.picture) L.push(`picture = ${c.picture}`);
  if (c.visible_when_empty) L.push('visible_when_empty = yes');
  if (c.allowed) L.push(`allowed = {\n${inner(c.allowed)}\n}`);
  if (c.visible) L.push(`visible = {\n${inner(c.visible)}\n}`);
  if (c.scripted_gui) L.push(`scripted_gui = ${c.scripted_gui}`);
  return `${c.id} = {\n${ind(1, L.join('\n'))}\n}`;
}
/** A national spirit; its modifier keys are checked against the modifier documentation (or by `check`). Texts <id>, <id>_desc. */
export async function renderIdea(i, T, check = assertModifiers) {
  await check(`idea ${i.id}`, i.modifier);
  T.use(i.id); T.use(`${i.id}_desc`);
  const mods = Object.entries(i.modifier).map(([k, v]) => `${k} = ${num(v)}`).join('\n');
  const head = join('allowed = { always = no }', 'allowed_civil_war = { always = yes }', `removal_cost = ${i.removal ?? -1}`, i.cancel ? `cancel = {\n${inner(i.cancel)}\n}` : '', `picture = ${i.picture}`, `modifier = {\n${ind(1, mods)}\n}`);
  return `${i.id} = {\n${ind(1, head)}\n}`;
}
/** A dynamic modifier whose values are variables (or numbers). Text <id>, and <id>_desc when the data has it. */
export async function renderDynamicModifier(m, T, check = assertModifiers) {
  await check(`dynamic modifier ${m.id}`, m.modifier);
  T.use(m.id);
  if (T.has(`${m.id}_desc`)) T.use(`${m.id}_desc`);
  const mods = Object.entries(m.modifier).map(([k, v]) => `${k} = ${typeof v === 'number' ? num(v) : v}`).join('\n');
  const head = join(m.icon ? `icon = ${m.icon}` : '', 'enable = { always = yes }', m.remove ? `remove_trigger = {\n${inner(m.remove)}\n}` : '', mods);
  return `${m.id} = {\n${ind(1, head)}\n}`;
}
export function renderOpinion(o, T) {
  T.use(o.id);
  return `${o.id} = {\n${ind(1, join(`value = ${o.value}`, o.decay ? `decay = ${num(o.decay)}` : ''))}\n}`;
}

