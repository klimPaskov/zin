let vocab;
/** Names the installed documentation lists: effects, triggers, modifiers. */
export async function gameVocabulary() {
  vocab ??= (async () => {
    const names = async f => new Set([...(await readFile(`${GAME}/documentation/${f}`, 'utf8')).matchAll(/^## ([A-Za-z0-9_]+)\s*$/gm)].map(m => m[1]));
    return { effects: await names('effects_documentation.md'), triggers: await names('triggers_documentation.md'), modifiers: await names('modifiers_documentation.md') };
  })();
  return vocab;
}
/** Every keyed entry of a script text. */
export function keysOf(text) {
  const out = [];
  walk(parse(text), (e, a) => { if (e.k) out.push({ k: e.k, line: e.line, depth: a.length, parent: a.length ? a[a.length - 1].k : null, block: Array.isArray(e.v), v: e.v }); });
  return out;
}
