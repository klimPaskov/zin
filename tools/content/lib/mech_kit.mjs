let pictureKeys, ideaKeys;
/** Event and news picture sprites of the icon catalog. */
export async function knownPictures() {
  if (!pictureKeys) {
    const cells = JSON.parse(await readFile(new URL('../data/presentation-cells.json', import.meta.url), 'utf8'));
    pictureKeys = new Set(cells.events.flatMap(e => [`GFX_zin_evt_${e.key}`, ...(e.crop !== 'standard' ? [`GFX_zin_news_${e.key}`] : [])]));
  }
  return pictureKeys;
}
/** Idea and decision icon sprites of the catalog (GFX_idea_zin_<key>). */
export async function knownIcons() {
  ideaKeys ??= new Set((await loadCatalogKeys()).map(k => `GFX_idea_zin_${k}`));
  return ideaKeys;
}

