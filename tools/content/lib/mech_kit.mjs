/** The text of one mechanic: a flat key -> value map from its data file. Keys are read through get() or use(), so the output holds exactly the keys the script uses. */
export class Texts {
  constructor(map) { this.map = new Map(Object.entries(map)); this.used = new Set(); }
  get(key) {
    if (!this.map.has(key)) throw new Error(`The data file has no text for ${key}`);
    this.used.add(key);
    return this.map.get(key);
  }
  has(key) { return this.map.has(key); }
  /** Gives `key` the text of `source` (a second decision that shares a name and a description with the first). */
  alias(key, source) { if (!this.map.has(source)) throw new Error(`No text to alias: ${source}`); this.map.set(key, this.map.get(source)); }
  /** Marks a key used and returns the key (for script that names a localisation key). */
  use(key) { this.get(key); return key; }
  entries() { return Object.fromEntries([...this.used].sort((a, b) => a.localeCompare(b, 'en')).map(k => [k, this.map.get(k)])); }
  unused() { return [...this.map.keys()].filter(k => !this.used.has(k)).sort(); }
}

