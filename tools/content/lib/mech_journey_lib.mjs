// Returns the keys of a parsed script that are not engine effects or triggers, scope switches, structure or an allowed
// name. `parse` is lib/clausewitz.mjs's reader; `known` lists the scripted effects and triggers, characters, tokens that
// this slice or another declares. Statement context is decided by the container, so parameter blocks are not read as script.
export function unknownKeys(entries, vocab, known, found = new Set(), mode = 'statement') {
  for (const e of entries) {
    const k = e.k;
    if (k === null) continue;
    const isBlock = Array.isArray(e.v);
    if (/^\d+(\.\d+)?$/.test(k) && isBlock) { unknownKeys(e.v, vocab, known, found, 'statement'); continue; }   // random_list weights
    if (STRUCTURE.has(k)) {
      if (!isBlock) continue;
      if (k === 'mean_time_to_happen') continue;
      if (k === 'text' || k === 'tooltip' || k === 'meta_effect' || k === 'meta_trigger') continue;
      unknownKeys(e.v, vocab, known, found, 'statement');
      continue;
    }
    if (vocab.effects.has(k) || vocab.triggers.has(k)) {
      if (!isBlock) continue;
      if (LEAF.has(k) || LEAF_TRIGGER.has(k)) { if (BODY.has(k)) unknownKeys(e.v.filter(x => x.k && !['array', 'value', 'start', 'end', 'break', 'iterations', 'index', 'compare', 'distinct'].includes(x.k)), vocab, known, found); continue; }
      unknownKeys(e.v, vocab, known, found, 'statement');
      continue;
    }
    if (known.has(k)) { if (isBlock && !LEAF.has(k)) unknownKeys(e.v, vocab, known, found); continue; }
    if (SCOPE_KEY.test(k) || ITER.test(k) || known.has('scope:' + k)) { if (isBlock) unknownKeys(e.v, vocab, known, found); continue; }
    found.add(k);
  }
  return found;
}

// Lints a script item (kind: trigger, effect, event, decision, on_action) and returns the unknown keys. Events and decisions are
// unwrapped first: their own header fields are structure, their blocks are script.
export function lintScript(item, parse, vocab, known) {
  const tree = parse(item.text);
  const found = new Set();
  if (item.kind === 'event' || item.kind === 'decision') for (const e of tree) { if (Array.isArray(e.v)) unknownKeys(e.v, vocab, known, found); }
  else unknownKeys(tree, vocab, known, found);
  found.delete(item.where);
  return found;
}

