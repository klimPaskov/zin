// Shared helpers of the journey-slice mechanic modules (modules/mech_eindil.mjs, mech_yeldenne.mjs, mech_crossing.mjs):
// script indentation, story-pace dates, event and idea writers, localisation collection, and the offline vocabulary
// check that proves every engine key a script uses exists in the installed game's documentation.
// Notes: docs/design/stage2/mech_journey.md. Nothing here writes a file; the modules stage everything through `Staged`.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
