export const callWith = (effect, args = {}) => [...Object.entries(args).map(([k, v]) => `set_temp_variable = { zin_arg_${k} = ${v} }`), `${effect} = yes`];

// ------------------------------------------------------------------------------------------------ events
// An event definition (data) -> script lines. `ev` fields:
//   ns, id, kind ('country' | 'news'), hidden, title (key), desc (key, or [{ trigger: lines, key }] with a last key without trigger),
//   picture (sprite name), trigger (lines), immediate (lines), options: [{ key, name (loc key), trigger, effects, ai (number | lines), tooltip }]
//   fireOnce, timeout (default 30 for shown events)
export function eventLines(ev) {
  const kind = ev.kind === 'news' ? 'news_event' : 'country_event';
  const out = [`${kind} = {`, `id = ${ev.ns}.${ev.id}`];
  if (ev.hidden) out.push('hidden = yes');
  else {
    out.push(`title = ${ev.title}`);
    if (Array.isArray(ev.desc)) for (const d of ev.desc) out.push(d.trigger ? L('desc', L('trigger', d.trigger), `text = ${d.key}`) : L('desc', `text = ${d.key}`));
    else out.push(`desc = ${ev.desc}`);
    out.push(`picture = ${ev.picture}`);
    if (ev.kind === 'news') out.push('major = no');
  }
  out.push('is_triggered_only = yes');
  if (ev.fireOnce) out.push('fire_only_once = yes');
  if (!ev.hidden) out.push(`timeout_days = ${ev.timeout ?? 30}`);
  if (ev.trigger?.length) out.push(L('trigger', ev.trigger));
  if (ev.immediate?.length) out.push(L('immediate', ev.immediate));
  for (const o of ev.options ?? []) {
    const body = [`name = ${o.name}`];
    if (o.trigger?.length) body.push(L('trigger', o.trigger));
    if (o.tooltip) body.push(`custom_effect_tooltip = ${o.tooltip}`);
    body.push(...flat(o.effects ?? []));
    if (o.ai !== undefined) body.push(typeof o.ai === 'number' ? L('ai_chance', `base = ${o.ai}`) : L('ai_chance', o.ai));
    out.push(L('option', body));
  }
  out.push('}');
  return out;
}

// The scripted-effect text of a list of definitions: `name = { body }`.
export const defineBlocks = defs => defs.map(d => render(L(d.name, d.body))).join('\n\n');

// Collects script and its kind for the vocabulary check and the dependency list.
export class ScriptSet {
  constructor() { this.items = []; this.depends = new Map(); }
  add(where, kind, lines) { this.items.push({ where, kind, text: render(lines) }); }
  depend(name, kind, owner) { if (!this.depends.has(name)) this.depends.set(name, { name, kind, owner }); }
}

// An if / else_if / else chain on the story pace for effects: branch(pace) returns the lines for that pace.
export function paceChoose(branch) {
  return [L('if', `limit = { ${SLOW} }`, branch(PACES[1])), L('else_if', `limit = { ${FAST.join(' ')} }`, branch(PACES[2])), L('else', branch(PACES[0]))];
}
