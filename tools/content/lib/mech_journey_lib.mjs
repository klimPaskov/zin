const here = path.dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = path.join(here, '../data');
export const HEADER = '# Generated by the ZIN content builder (the journey-slice mechanic modules). Do not edit; change the module data in tools/content/data/mech_journey_*.json.';
const TAB = '\t';

// ------------------------------------------------------------------------------------------------ script text
// Script is written as flat lines without indentation; braces decide the depth (the diplomacy module's convention).
const flat = a => (Array.isArray(a) ? a.flat(Infinity) : [a]);
export function indentLines(lines, depth = 0) {
  const out = [];
  let d = depth;
  for (const rawLine of flat(lines)) {
    for (const piece of String(rawLine).split('\n')) {
      const line = piece.trim();
      if (!line) continue;
      if (line.startsWith('#')) { out.push(TAB.repeat(d) + line); continue; }
      let lead = 0;
      while (line[lead] === '}') lead++;
      out.push(TAB.repeat(Math.max(d - lead, 0)) + line);
      const code = line.replace(/"[^"]*"/g, '');
      d += (code.match(/\{/g) ?? []).length - (code.match(/\}/g) ?? []).length;
    }
  }
  if (d !== depth) throw new Error(`Unbalanced braces in generated script (depth ${d - depth}):\n${flat(lines).join('\n').slice(0, 400)}`);
  return out;
}
export const render = (lines, depth = 0) => indentLines(lines, depth).join('\n');
export const L = (name, ...body) => [`${name} = {`, ...flat(body), '}'];
export const M = (name, obj) => L(name, cw(obj).split('\n').map(l => l.trim()).filter(Boolean));
export const fileText = (...parts) => `${HEADER}\n${parts.filter(Boolean).join('\n')}\n`;
export const comment = text => text.split('\n').map(l => `# ${l}`).join('\n');
export const yes = v => (v ? 'yes' : 'no');
export const num = v => (Number.isInteger(v) ? String(v) : String(Number(Number(v).toFixed(3))));

// ------------------------------------------------------------------------------------------------ data files
