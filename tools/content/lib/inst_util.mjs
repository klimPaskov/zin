const here = path.dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = path.join(here, '../data');
export const HEADER = '# Generated by the ZIN content builder (modules/institutions.mjs, spec 03_gameplay/08_institutions.md).';

const cache = new Map();
export async function loadData(name) {
  if (!cache.has(name)) cache.set(name, JSON.parse(await readFile(path.join(DATA_DIR, name), 'utf8')));
  return cache.get(name);
}
// The five data files of this module, in one object.
export async function loadAllData() {
  const [core, traits, intrigue, craft] = await Promise.all(['institutions.json', 'institutions_traits.json', 'institutions_intrigue.json', 'institutions_craft.json'].map(loadData));
  return { core, traits, intrigue, craft };
}

export const tab = (n, s) => String(s).split('\n').map(l => (l.trim() ? '\t'.repeat(n) + l : l)).join('\n');
// A raw Clausewitz fragment written one tab deeper per level; keeps the generated files readable.
export const block = (name, body, depth = 0) => `${'\t'.repeat(depth)}${name} = {\n${tab(depth + 1, body)}\n${'\t'.repeat(depth)}}`;
export const num = v => (Number.isInteger(v) ? String(v) : String(Number(v.toFixed(4))));
export const lines = (...parts) => parts.flat().filter(x => x !== undefined && x !== null && x !== '').join('\n');
export const sortedEntries = o => Object.entries(o).sort(([a], [b]) => a.localeCompare(b, 'en'));
// "a = 1" lines of a flat modifier object, in the order given.
export const modLines = (o, n = 0) => Object.entries(o).map(([k, v]) => `${'\t'.repeat(n)}${k} = ${typeof v === 'object' ? `{ ${Object.entries(v).map(([a, b]) => `${a} = ${num(b)}`).join(' ')} }` : num(v)}`).join('\n');

// ------------------------------------------------------------------------------------------------ localisation
export class Loc {
  constructor() { this.map = new Map(); }
  set(key, value) {
    if (typeof value !== 'string' || !value.trim()) throw new Error(`Empty localisation value for ${key}`);
    if (/[\r\t]/.test(value)) throw new Error(`Control character in localisation value of ${key}`);
    if (this.map.has(key) && this.map.get(key) !== value) throw new Error(`Localisation key ${key} defined twice with different text`);
    this.map.set(key, value);
  }
  entries() { return Object.fromEntries([...this.map].sort(([a], [b]) => a.localeCompare(b, 'en'))); }
  bytes() { return yml(this.entries()); }
  get size() { return this.map.size; }
}

// ------------------------------------------------------------------------------------------------ sprites
// Every picture this module names is a sprite defined in interface/zz_zin_institutions.gfx. The art is the icon
// catalog's (data/presentation-cells.json): ideas use gfx/interface/ideas/zin/<key>.dds, so no texture is invented
// here and no vanilla picture can show. A later art pass swaps a sprite's `art` key for its own file.
export class Sprites {
  constructor(catalogKeys) { this.keys = new Set(catalogKeys); this.map = new Map(); }
  use(name, art) {
    if (!this.keys.has(art)) throw new Error(`Sprite ${name}: art key ${art} is not in the icon catalog`);
    if (this.map.has(name) && this.map.get(name) !== art) throw new Error(`Sprite ${name} bound to two pictures (${this.map.get(name)}, ${art})`);
    this.map.set(name, art);
    return name;
  }
  text() {
    const body = [...this.map].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, art]) => `\tspriteType = {\n\t\tname = "${name}"\n\t\ttexturefile = "gfx/interface/ideas/zin/${art}.dds"\n\t}`);
    return `${HEADER}\n# Sprites of the institutions: traits, abilities, operations, phases, upgrades, agencies, workshops, spells.\n# Each shows a picture of the icon catalog until the art pass draws its own. Loaded after the vanilla files (zz_).\nspriteTypes = {\n${body.join('\n')}\n}\n`;
  }
  get size() { return this.map.size; }
}
export async function loadCatalogKeys() {
  const cells = await loadData('presentation-cells.json');
  return cells.icons.flatMap(s => s.keys);
}

// ------------------------------------------------------------------------------------------------ banned words
let bannedCache;
export async function loadBanned() {
  if (!bannedCache) {
    const d = await loadData('banned_words.json');
    bannedCache = d.rules.filter(r => r.severity === 'error').map(r => ({ id: r.id, re: new RegExp(`(?<![\\p{L}\\p{N}'])(?:${r.pattern})(?![\\p{L}\\p{N}'])`, r.caseSensitive ? 'u' : 'iu') }));
  }
  return bannedCache;
}
// What a player reads: colour codes, icon codes, $..$ and [..] calls and line breaks removed (banned_words.json "matching").
export const readable = v => String(v).replace(/§./g, '').replace(/£\w+(\|\w+)?/g, '').replace(/\$[^$]*\$/g, '').replace(/\[[^\]]*\]/g, '').replace(/\\n/g, ' ').normalize('NFKC');
export async function bannedIn(entries) {
  const rules = await loadBanned(), hits = [];
  for (const [key, value] of Object.entries(entries)) {
    const text = readable(value);
    for (const r of rules) { const m = r.re.exec(text); if (m) hits.push({ key, rule: r.id, word: m[0] }); }
  }
  return hits;
}
// Windows-1252 only: the game font draws nothing else. Returns "key: character" for every character it cannot draw.
const CP1252_EXTRA = new Set([0x20ac, 0x201a, 0x0192, 0x201e, 0x2026, 0x2020, 0x2021, 0x02c6, 0x2030, 0x0160, 0x2039, 0x0152, 0x017d, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, 0x02dc, 0x2122, 0x0161, 0x203a, 0x0153, 0x017e, 0x0178]);
export function notCp1252(entries) {
  const bad = [];
  for (const [k, v] of Object.entries(entries)) for (const ch of String(v)) { const c = ch.codePointAt(0); if (c > 0xff && !CP1252_EXTRA.has(c)) bad.push(`${k}: ${ch}`); }
  return bad;
}

// ------------------------------------------------------------------------------------------------ roster
// Tier tables of 05_focus_trees/01_tiers_and_coverage.md (names, resolved against the roster).
export function tierOf(core, countries) {
  const byName = new Map(countries.map(c => [c.name, c]));
  const resolve = names => names.map(n => { const c = byName.get(n); if (!c) throw new Error(`Tier table names ${n}, which is not in the roster`); return c; });
  return { a: resolve(core.tiers.a), b: resolve(core.tiers.b) };
}
