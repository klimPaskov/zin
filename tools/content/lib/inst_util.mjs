export const pickFrom = (arr, r) => arr[Math.floor(r() * arr.length)];

// ------------------------------------------------------------------------------------------------ modifier checks
// A modifier key is valid when the installed modifier documentation lists it, when it belongs to a family the engine
// generates (an operation's risk, cost and outcome, a resource, a mission), or when an installed vanilla trait, ability
// or sub-unit file uses it as a unit modifier (the documentation omits some unit-only keys).
const DYNAMIC = [/^(operation_[a-z_]+|target_sabotage)_(risk|cost|outcome)$/, /^country_resource_[a-z_]+$/, /^[a-z_]+_mission_factor$/];
const MOD_BLOCKS = new Set(['modifier', 'non_shared_modifier', 'field_marshal_modifier', 'corps_commander_modifier', 'unit_modifiers', 'deployed_leader_modifiers']);
let vanillaUnitKeys;
async function loadVanillaUnitKeys() {
  const keys = new Set();
  for (const dir of ['common/unit_leader', 'common/abilities', 'common/units']) {
    for (const f of (await readdir(`${GAME}/${dir}`)).filter(n => n.endsWith('.txt'))) {
      const entries = parse(scriptText(await readFile(`${GAME}/${dir}/${f}`)));
      const walkBlock = (list, inside) => { for (const e of list) { if (Array.isArray(e.v)) walkBlock(e.v, inside || MOD_BLOCKS.has(e.k)); else if (inside && e.k) keys.add(e.k); } };
      walkBlock(entries, false);
    }
  }
  return keys;
}
export async function checkMods(where, mods) {
  vanillaUnitKeys ??= await loadVanillaUnitKeys();
  const rest = {};
  for (const [k, v] of Object.entries(mods)) { if (typeof v === 'object') continue; if (DYNAMIC.some(re => re.test(k)) || vanillaUnitKeys.has(k)) continue; rest[k] = v; }
  await assertModifiers(where, rest);
}
