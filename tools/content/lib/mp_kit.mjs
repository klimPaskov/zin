// Shared kit of the power mechanics (docs/design/stage2/mech_powers.md): the elves and the Wall, Lerendor and the Narrow
// Strait, Volgan and the Southern Dominion. Script is authored as plain text with any indentation and re-indented here by
// brace depth; every definition is registered (one id, one definition), every localisation key is collected, every event
// and decision takes its words from the text file of its mechanic, so tuning and text never touch the code.
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Loc } from './inst_util.mjs';
import { START_DATE } from './calendar.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const DATA = path.join(here, '../data');
export const HEADER = '# Generated by the ZIN content builder (modules/mech_elves.mjs, mech_lerendor.mjs, mech_volgan.mjs; docs/design/stage2/mech_powers.md). Do not edit by hand.';
export const EVENT_TIMEOUT_DAYS = 30;

export async function loadMech(file) { return JSON.parse(await readFile(path.join(DATA, file), 'utf8')); }

// ------------------------------------------------------------------------------------------------ formatting
// Re-indents a script fragment by brace depth. Braces inside quotes or after # are ignored.
export function fmt(text, depth = 0) {
  const out = [];
  let d = depth;
  for (const raw of String(text).split('\n')) {
    const line = raw.trim();
    if (!line) { out.push(''); continue; }
    let lead = 0;
    while (line[lead] === '}') lead++;
    let open = 0, close = 0, inStr = false;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (c === '"') inStr = !inStr;
      else if (!inStr && c === '#') break;
      else if (!inStr && c === '{') open++;
      else if (!inStr && c === '}') close++;
    }
    d -= lead;
    out.push('\t'.repeat(Math.max(0, d)) + line);
    d += open - (close - lead);
  }
  if (d !== depth) throw new Error(`Unbalanced braces in script fragment:\n${String(text).slice(0, 400)}`);
  return out.join('\n');
}
export const num = v => (Number.isInteger(v) ? String(v) : String(Number(Number(v).toFixed(4))));
export const join = (...parts) => parts.flat().filter(p => p !== undefined && p !== null && p !== false && String(p).trim() !== '').join('\n');

// ------------------------------------------------------------------------------------------------ conditions and calls
// check_variable in its long form (the short forms do not offer >= or <=).
const cmp = (op, v, n) => `check_variable = { var = ${v} value = ${typeof n === 'number' ? num(n) : n} compare = ${op} }`;
export const ge = (v, n) => cmp('greater_than_or_equals', v, n);
export const gt = (v, n) => cmp('greater_than', v, n);
export const le = (v, n) => cmp('less_than_or_equals', v, n);
export const lt = (v, n) => cmp('less_than', v, n);
export const eq = (v, n) => cmp('equals', v, n);
// Add to a variable and clamp it.
export const bump = (v, delta, min, max) => `add_to_variable = { ${v} = ${typeof delta === 'number' ? num(delta) : delta} }\nclamp_variable = { var = ${v} min = ${num(min)} max = ${num(max)} }`;
// A call: the temporary argument variables are set just before the call (decision E1).
export const call = (effect, args = {}) => [...Object.entries(args).map(([k, v]) => `set_temp_variable = { zin_arg_${k} = ${typeof v === 'number' ? num(v) : v} }`), `${effect} = yes`].join('\n');
export const anyOf = conds => `OR = {\n${conds.join('\n')}\n}`;
export const allOf = conds => `AND = {\n${conds.join('\n')}\n}`;
export const not = cond => `NOT = { ${cond.includes('\n') ? `\n${cond}\n` : cond} }`;
// Weighted AI block: base plus modifiers [{ add|factor, when }].
export function ai(base, mods = []) {
  const L = [`base = ${num(base)}`];
  for (const m of mods) L.push(`modifier = {\n${m.factor !== undefined ? `factor = ${num(m.factor)}` : `add = ${num(m.add)}`}\n${m.when}\n}`);
  return L.join('\n');
}

// ------------------------------------------------------------------------------------------------ story dates
// A date d becomes start + (d - start) * pace (decision V4). lib/story_dates.mjs is used when it exists.
export const PACES = [1, 1.5, 0.75];
let storyDates;
try { storyDates = await import('./story_dates.mjs'); } catch (e) { if (e.code !== 'ERR_MODULE_NOT_FOUND') throw e; }
const toDays = d => { const [y, m, day] = d.split('.').map(Number); return Date.UTC(y, m - 1, day) / 86400000; };
const fromDays = n => { const d = new Date(n * 86400000); return `${d.getUTCFullYear()}.${d.getUTCMonth() + 1}.${d.getUTCDate()}`; };
export function paceDate(date, pace) {
  if (storyDates?.paceDate) return storyDates.paceDate(date, pace);
  const start = toDays(START_DATE.split('.').slice(0, 3).join('.'));
  return fromDays(start + Math.round((toDays(date) - start) * pace));
}
// A scripted trigger that is true after the pace-shifted date; one block per zin_story_pace value (1, 1.5, 0.75).
export function afterDateTrigger(name, date) {
  const body = PACES.map(p => `AND = {\ncheck_variable = { global.zin_story_pace = ${num(p)} }\ndate > ${paceDate(date, p)}\n}`).join('\n');
  return `${name} = {\n${fmt(`OR = {\n${body}\n}`, 1)}\n}`;
}

// ------------------------------------------------------------------------------------------------ the kit
export class Kit {
  // slice: 'elves' | 'leren' | 'dominion'; data: the mechanic's data file; text: its text file
  constructor(slice, data, text) {
    this.slice = slice; this.D = data; this.T = text;
    this.loc = new Loc();
    this.defs = new Map();       // kind -> Set of ids
    this.used = { events: new Set(), decisions: new Set(), ideas: new Set(), categories: new Set(), misc: new Set() };
    this.sprites = new Map();    // sprite name -> catalog art key
    this.files = new Map();      // rel -> [parts]
  }
  N(key) {
    const v = key.split('.').reduce((o, k) => (o == null ? o : o[k]), this.D.numbers);
    if (v === undefined) throw new Error(`${this.slice}: number ${key} is not in the data file`);
    return v;
  }
  def(kind, id) {
    const set = this.defs.get(kind) ?? this.defs.set(kind, new Set()).get(kind);
    if (set.has(id)) throw new Error(`${this.slice}: ${kind} ${id} is defined twice`);
    set.add(id);
    return id;
  }
  has(kind, id) { return this.defs.get(kind)?.has(id) ?? false; }
  add(rel, text) { (this.files.get(rel) ?? this.files.set(rel, []).get(rel)).push(text); }
  // free-standing text (tooltips, custom cost text, scripted localisation)
  misc(key) { const v = this.T.misc?.[key]; if (v === undefined) throw new Error(`${this.slice}: misc text ${key} is missing`); this.used.misc.add(key); this.loc.set(key, v); return key; }
  art(name, key) {
    if (this.sprites.has(name) && this.sprites.get(name) !== key) throw new Error(`sprite ${name} bound to two pictures`);
    this.sprites.set(name, key); return name;
  }

  // ---------------------------------------------------------------------------------------- effects and triggers
  effect(name, body, note) { this.def('effect', name); return `${note ? `# ${note}\n` : ''}${name} = {\n${fmt(body, 1)}\n}`; }
  trigger(name, body, note) { this.def('trigger', name); return `${note ? `# ${note}\n` : ''}${name} = {\n${fmt(body, 1)}\n}`; }

  // ---------------------------------------------------------------------------------------- ideas
  // spec: { id, picture, mods:{}, on_add?, on_remove? } (picture is an idea icon key of the catalog)
  idea(spec) {
    const t = this.T.ideas?.[spec.id];
    if (!t) throw new Error(`${this.slice}: no text for idea ${spec.id}`);
    this.def('idea', spec.id); this.used.ideas.add(spec.id);
    this.loc.set(spec.id, t.n); this.loc.set(`${spec.id}_desc`, t.d);
    const mods = Object.entries(spec.mods).map(([k, v]) => `${k} = ${num(v)}`).join('\n');
    return fmt(`${spec.id} = {\nallowed = { always = no }\nallowed_civil_war = { always = yes }\npicture = ${spec.picture}\nremoval_cost = -1\n${spec.on_add ? `on_add = {\n${spec.on_add}\n}\n` : ''}${spec.on_remove ? `on_remove = {\n${spec.on_remove}\n}\n` : ''}modifier = {\n${mods}\n}\n}`, 2);
  }

  // ---------------------------------------------------------------------------------------- opinion modifiers
  opinion(id, value, { decay, trade } = {}) {
    this.def('opinion', id);
    const lines = [`value = ${num(value)}`];
    if (decay !== undefined) lines.push(`decay = ${num(decay)}`);
    if (trade) lines.push('trade = yes');
    return `${id} = {\n${fmt(lines.join('\n'), 1)}\n}`;
  }

  // ---------------------------------------------------------------------------------------- events
  // spec: { id, kind: 'country'|'news'|'hidden', pic, trigger, mtth, fire_only_once, immediate, options:[{effect, ai, trigger}], descs:[{key, trigger}] }
  event(spec) {
    const { id } = spec;
    this.def('event', id); this.used.events.add(id);
    const hidden = spec.kind === 'hidden';
    const t = this.T.events?.[id];
    const L = [`id = ${id}`];
    if (hidden) {
      if (t) throw new Error(`${id} is hidden and must not carry text`);
      L.push('hidden = yes');
    } else {
      if (!t) throw new Error(`${this.slice}: no text for event ${id}`);
      if (!Array.isArray(t.o) || t.o.length !== spec.options.length) throw new Error(`${id}: ${spec.options.length} options need ${spec.options.length} option names`);
      this.loc.set(`${id}.t`, t.t); this.loc.set(`${id}.d`, t.d);
      const sprite = spec.kind === 'news' ? `GFX_zin_news_${spec.pic}` : `GFX_zin_evt_${spec.pic}`;
      const variants = (spec.descs ?? []).map(v => {
        const text = t.v?.[v.key];
        if (!text) throw new Error(`${id}: description variant ${v.key} has no text`);
        this.loc.set(`${id}.d_${v.key}`, text);
        return `desc = {\ntext = ${id}.d_${v.key}\ntrigger = {\n${v.trigger}\n}\n}`;
      });
      if (t.v) for (const k of Object.keys(t.v)) if (!(spec.descs ?? []).some(v => v.key === k)) throw new Error(`${id}: text variant ${k} is never used`);
      L.push(`title = ${id}.t`, ...(variants.length ? [...variants, `desc = {\ntext = ${id}.d\n}`] : [`desc = ${id}.d`]), `picture = ${sprite}`);
      if (spec.major) L.push('major = yes');
    }
    // An event is fired by script unless it has a mean time to happen; a trigger is also checked when a fired event arrives.
    if (spec.fire_only_once) L.push('fire_only_once = yes');
    if (!spec.mtth) L.push('is_triggered_only = yes');
    if (spec.trigger) L.push(`trigger = {\n${spec.trigger}\n}`);
    if (spec.mtth) L.push(`mean_time_to_happen = {\n${spec.mtth}\n}`);
    L.push(`timeout_days = ${EVENT_TIMEOUT_DAYS}`);
    if (hidden) L.push(`immediate = {\n${spec.immediate}\n}`);
    else {
      if (spec.immediate) L.push(`immediate = {\n${spec.immediate}\n}`);
      spec.options.forEach((o, i) => {
        const letter = 'abcdefghij'[i];
        this.loc.set(`${id}.${letter}`, t.o[i]);
        const body = [`name = ${id}.${letter}`];
        if (o.trigger) body.push(`trigger = {\n${o.trigger}\n}`);
        if (o.ai !== undefined) body.push(`ai_chance = {\n${o.ai}\n}`);
        if (o.effect) body.push(o.effect);
        L.push(`option = {\n${body.join('\n')}\n}`);
      });
    }
    return fmt(`${hidden || spec.kind === 'country' ? 'country_event' : 'news_event'} = {\n${L.join('\n')}\n}`, 0);
  }

  // ---------------------------------------------------------------------------------------- decisions
  // spec: { id, icon (catalog art key), allowed, visible, available, cost (number or variable name), custom_cost:{trigger,text}, cooldown,
  //         days_remove, complete, remove, ai, fire_only_once, modifier, cancel_trigger, targeted:{root, trigger} }
  decision(spec) {
    const t = this.T.decisions?.[spec.id];
    if (!t) throw new Error(`${this.slice}: no text for decision ${spec.id}`);
    this.def('decision', spec.id); this.used.decisions.add(spec.id);
    this.loc.set(spec.id, t.n); this.loc.set(`${spec.id}_desc`, t.d);
    this.art(`GFX_decision_${spec.id}`, spec.icon);
    const L = [`icon = ${spec.id}`, `allowed = {\n${spec.allowed ?? 'always = yes'}\n}`];
    // The decision key is state_target ("Unexpected token: state_trigger"; vanilla writes state_target = yes for every state).
    if (spec.state_trigger) L.push(`state_target = ${spec.state_trigger === 'any' ? 'yes' : spec.state_trigger}`);
    if (spec.targeted) {
      L.push(`target_root_trigger = {\n${spec.targeted.root ?? 'always = yes'}\n}`);
      L.push(`target_trigger = {\n${spec.targeted.trigger}\n}`);
    }
    L.push(`visible = {\n${spec.visible ?? 'always = yes'}\n}`);
    L.push(`available = {\n${spec.available ?? 'always = yes'}\n}`);
    if (spec.custom_cost) {
      const base = spec.custom_cost.text;
      L.push(`custom_cost_trigger = {\n${spec.custom_cost.trigger}\n}`, `custom_cost_text = ${base}`);
      if (!t.cost) throw new Error(`${spec.id}: custom cost needs text.cost`);
      this.loc.set(base, t.cost); this.loc.set(`${base}_blocked`, `§R${t.cost}§!`); this.loc.set(`${base}_tooltip`, t.cost_tt ?? t.d);
      if (spec.ai_hint_pp_cost) L.push(`ai_hint_pp_cost = ${spec.ai_hint_pp_cost}`);
    } else if (spec.cost !== undefined) L.push(`cost = ${spec.cost}`);
    if (spec.cooldown) L.push(`days_re_enable = ${spec.cooldown}`);
    if (spec.days_remove !== undefined) L.push(`days_remove = ${spec.days_remove}`);
    if (spec.fire_only_once) L.push('fire_only_once = yes');
    if (spec.modifier) L.push(`modifier = {\n${spec.modifier}\n}`);
    if (spec.cancel_trigger) L.push(`cancel_trigger = {\n${spec.cancel_trigger}\n}`);
    if (spec.complete) L.push(`complete_effect = {\n${spec.complete}\n}`);
    if (spec.remove) L.push(`remove_effect = {\n${spec.remove}\n}`);
    if (spec.ai !== undefined) L.push(`ai_will_do = {\n${spec.ai}\n}`);
    return fmt(`${spec.id} = {\n${L.join('\n')}\n}`, 1);
  }
  category(id, art, { visible = 'always = yes', priority = 20 } = {}) {
    const t = this.T.categories?.[id];
    if (!t) throw new Error(`${this.slice}: no text for category ${id}`);
    this.def('category', id); this.used.categories.add(id);
    this.loc.set(id, t.n); this.loc.set(`${id}_desc`, t.d);
    this.art(`GFX_decision_category_${id}`, art); this.art(`GFX_decision_cat_picture_${id}`, art);
    return fmt(`${id} = {\nicon = ${id}\npicture = GFX_decision_cat_picture_${id}\npriority = ${priority}\nallowed = { always = yes }\nvisible = {\n${visible}\n}\n}`, 0);
  }

  // ---------------------------------------------------------------------------------------- output
  stage(staged) {
    for (const [rel, parts] of [...this.files].sort(([a], [b]) => a.localeCompare(b, 'en'))) staged.text(rel, `${HEADER}\n${parts.join('\n\n')}\n`);
  }
  // Sprite file text for decisions and categories (ideas and event pictures are the presentation module's).
  spriteText(title) {
    const body = [...this.sprites].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([name, art]) => `\tspriteType = {\n\t\tname = "${name}"\n\t\ttexturefile = "gfx/interface/ideas/zin/${art}.dds"\n\t}`);
    return `${HEADER}\n# ${title}\nspriteTypes = {\n${body.join('\n')}\n}\n`;
  }
}
