// Author commands of the Chronicle of Aoaz (docs/specs/07_interface/04_chronicle_codex.md section 11). The build runs the checks itself.
//   node tools/content/chronicle.mjs check [--file entries/<category>.json] [--warnings]   every builder check; exit 1 on an error
//   node tools/content/chronicle.mjs stamp                 writes the vault section hashes into every paragraph's sources
//   node tools/content/chronicle.mjs ids                   gives every realm of the regional histories a stable id (never renumbers)
//   node tools/content/chronicle.mjs index                 writes docs/design/chronicle/source_index.json
//   node tools/content/chronicle.mjs status                writes docs/design/chronicle/canon_status.json
//   node tools/content/chronicle.mjs uncovered             lists in-scope vault sections no paragraph cites and coverage.json does not exclude
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadChronicle, chronicleProblems, indexVault, vaultFilesFrom, CHR_DATA, REGIONS, sectionOf } from './modules/chronicle.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const ZIN = path.join(here, '../..');
const [cmd, ...args] = process.argv.slice(2);
const arg = k => { const i = args.indexOf(k); return i < 0 ? null : args[i + 1]; };
const json = o => `${JSON.stringify(o, null, 2)}\n`;

if (cmd === 'ids') {
  const file = path.join(CHR_DATA, 'realm_ids.json');
  const cur = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : { about: '', next: 20001, ids: {} };
  cur.about = 'Stable ids of the Roots and Signs entries of the Chronicle (one per realm of tools/content/data/world/history/*.json, keyed region/name). Ids are never reused or renumbered, because saves store them; a new realm takes the next id (node tools/content/chronicle.mjs ids).';
  let added = 0;
  for (const [f] of REGIONS) for (const c of JSON.parse(readFileSync(path.join(here, 'data/world/history', `${f}.json`), 'utf8')).countries) {
    const k = `${f}/${c.name}`;
    if (!cur.ids[k]) { cur.ids[k] = cur.next++; added++; }
  }
  writeFileSync(file, json(cur));
  console.log(`${added} ids added, ${Object.keys(cur.ids).length} in all`);
  process.exit(0);
}

const vault = indexVault(vaultFilesFrom(null));

if (cmd === 'stamp') {
  let n = 0, miss = 0;
  for (const f of readdirSync(path.join(CHR_DATA, 'entries')).filter(f => f.endsWith('.json'))) {
    const file = path.join(CHR_DATA, 'entries', f), j = JSON.parse(readFileSync(file, 'utf8'));
    for (const e of j.entries) for (const p of e.parts) for (const q of p.paragraphs) for (const s of q.sources ?? []) {
      const note = vault.get(s.note), sec = note?.sections.get(sectionOf(note, s));
      if (!sec) { miss++; continue; }
      if (s.sha256 !== sec.sha256) { s.sha256 = sec.sha256; n++; }
    }
    writeFileSync(file, json(j));
  }
  console.log(`${n} hashes written, ${miss} sources not found in the vault`);
  process.exit(0);
}

if (cmd === 'index') {
  mkdirSync(path.join(ZIN, 'docs/design/chronicle'), { recursive: true });
  const out = [...vault.values()].sort((a, b) => a.path.localeCompare(b.path)).map(n => ({ note: n.path, status: n.status, sections: [...n.sections.values()].map(s => ({ heading: s.heading, level: s.level, sha256: s.sha256, length: s.length })) }));
  writeFileSync(path.join(ZIN, 'docs/design/chronicle/source_index.json'), json({ about: 'Generated by node tools/content/chronicle.mjs index: the lore vault parsed into notes and sections (normalised text hashed with sha256).', notes: out }));
  console.log(`${out.length} notes`);
  process.exit(0);
}

const data = loadChronicle();

if (cmd === 'status') {
  const per = data.entries.filter(e => !e.generated).map(e => ({ id: e.id, key: e.key, paragraphs: e.parts.flatMap((p, i) => p.paragraphs.map((q, j) => ({ part: i + 1, paragraph: j + 1, when: p.when, status: q.status, note: q.note, sources: q.sources.map(s => `${s.note} § ${s.section}`) }))) }));
  const all = per.flatMap(e => e.paragraphs), tally = k => all.filter(p => p.status === k).length;
  mkdirSync(path.join(ZIN, 'docs/design/chronicle'), { recursive: true });
  writeFileSync(path.join(ZIN, 'docs/design/chronicle/canon_status.json'), json({ about: 'Generated by node tools/content/chronicle.mjs status: every authored paragraph of the Chronicle with its status and vault sources, for the owner’s review. Generated realm entries (Roots and Signs) take their status from the regional histories.', totals: { established: tally('established'), proposed: tally('proposed'), mixed: tally('mixed') }, entries: per }));
  console.log(JSON.stringify({ established: tally('established'), proposed: tally('proposed'), mixed: tally('mixed') }));
  process.exit(0);
}

if (cmd === 'check' || cmd === 'uncovered') {
  const file = arg('--file');
  const only = file ? (e => path.resolve(CHR_DATA, e.file) === path.resolve(file) || path.resolve(ZIN, file) === path.resolve(CHR_DATA, e.file)) : null;
  const { errors, warnings } = await chronicleProblems(data, { vault, only });
  if (cmd === 'uncovered') { for (const w of warnings.filter(w => w.startsWith('coverage:'))) console.log(w); process.exit(0); }
  for (const e of errors) console.log(`error ${e}`);
  if (args.includes('--warnings')) for (const w of warnings) console.log(`warning ${w}`);
  console.log(`${data.entries.length} entries (${data.entries.filter(e => !e.generated).length} authored), ${errors.length} errors, ${warnings.length} warnings (${data.uncovered ?? 0} vault sections uncovered)`);
  process.exit(errors.length ? 1 : 0);
}

console.error('usage: node tools/content/chronicle.mjs check|stamp|ids|index|status|uncovered');
process.exit(2);
